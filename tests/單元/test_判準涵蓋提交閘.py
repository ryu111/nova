"""判準要涵蓋提交閘那幾條，**而且測試涵蓋不准縮水**。

## 現在的洞

三個判準階段跑的是 `載體/判準.py` 的 `預設判準指令 = ("uv", "run", "pytest", "-q")`。
它跑全部測試，但 ruff／mypy／繁中／機密／文件事實**一條都不跑**——那幾條只在
提交閘與 CI 上。於是工作流自己宣布「全綠」，人一 commit 就被提交閘擋下來，
整輪重做。

## 為什麼不是直接換成 `nova 閘 提交`

提交閘的 `pytest-unit` **只跑 `tests/單元`**（規則表自己標了
`涵蓋於="pytest-parallel"`，全測試由 CI 那條負責）。直接換過去的話，
判準的測試涵蓋會從「全部」縮成「只有單元」——而且縮水的樣子是**更快變綠**，
看起來像改善。`test_測試涵蓋不准比全跑窄` 就是釘這一格的。

要的是**聯集**：提交閘那幾條 ＋ 現在這份全測試。

## 為什麼清單要從 `規則表` 推導

手抄一份代碼清單的話，新增一條閘規則時判準不會跟上，這個洞會靜靜長回來。
所以斷言的右手邊一律是 `建規則表()` 現算出來的。
"""

from pathlib import Path

import pytest

from nova.契約.工作流 import 任務, 判準終局
from nova.載體 import 判準 as 判準模組
from nova.載體.判準 import 建預設判準, 預設判準指令, 預設判準步驟們
from nova.載體.規則表 import 建規則表
from nova.載體.閘鎖 import 佔不到

#: 建表本身不碰硬碟，所以根目錄給一個不存在的路徑就夠了（同 `test_規則表.py`）。
_不碰硬碟的根 = Path("/不存在也沒關係/建表時不該碰硬碟")


def _提交閘規則代碼(根目錄: Path = _不碰硬碟的根) -> frozenset[str]:
    """提交閘上掛著哪些規則。**現算，不手抄。**"""
    return frozenset(條.代碼 for 條 in 建規則表(根目錄) if "提交" in 條.閘點)


def _判準涵蓋的規則代碼(根目錄: Path = _不碰硬碟的根) -> frozenset[str]:
    """預設判準宣稱自己涵蓋到哪些規則。"""
    涵蓋: set[str] = set()
    for 步 in 預設判準步驟們(根目錄):
        涵蓋 |= set(步.涵蓋規則)
    return frozenset(涵蓋)


class Test判準涵蓋提交閘:
    def test_判準涵蓋提交閘的每一條規則(self) -> None:
        """提交閘擋得下來的，判準也要擋得下來。

        少一條就代表：工作流說綠、提交閘說紅，而中間隔著一整輪模型。
        """
        提交閘的 = _提交閘規則代碼()
        # 先確認題目本身不是空的——空集合會讓下面那條斷言恆真（假綠）。
        assert 提交閘的, "規則表上一條提交閘規則都沒有，這支測試在測空氣"

        漏掉的 = 提交閘的 - _判準涵蓋的規則代碼()
        assert not 漏掉的, f"判準沒涵蓋到提交閘的這幾條規則：{sorted(漏掉的)}"

    def test_測試涵蓋不准比全跑窄(self) -> None:
        """**這是最容易寫錯的一格。**

        提交閘的 `pytest-unit` 只跑 `tests/單元`。判準要是換成跑閘就收工，
        測試涵蓋會從「全部」縮成「只有單元」，而症狀是**變綠變快**，
        沒有人會覺得那是退化。所以原本那條全跑的指令必須原樣還在步驟裡。
        """
        指令們 = {步.指令 for 步 in 預設判準步驟們(_不碰硬碟的根)}
        assert 預設判準指令 in 指令們, (
            f"判準步驟裡找不到全跑的 {預設判準指令}，測試涵蓋縮水了：{sorted(指令們)}"
        )

    def test_佔不到鎖是跑不起來不是紅(self) -> None:
        """**佔不到鎖代表判準根本沒跑。**

        回紅的話工作流會退回實作重做一輪——而它一件事都沒驗過。
        退出碼四值語意：3 是「不知道做了沒」，不准重跑
        （`_子命令_閘` 佔不到就是回 3）。

        組合判準也要守這一條，不能只有 `建判準` 守：所有子程序都得走
        同一把機器鎖，這條斷言順便釘住「有走」。
        """

        def _佔不住(名稱: str, **_: object) -> object:
            訊息 = f"等了很久還是佔不到 {名稱}——判準沒有跑"
            raise 佔不到(訊息)

        with pytest.MonkeyPatch.context() as 換:
            換.setattr(判準模組, "佔住", _佔不住)
            收場, 證據 = 建預設判準()(任務(描述="隨便", 工作目錄=Path.cwd()))

        assert 收場 is 判準終局.跑不起來, f"佔不到鎖被判成 {收場}，工作流會白跑一輪實作"
        assert "沒跑" in 證據 or "忙" in 證據
