"""`nova 線` 的單元測試。純函式排版與退出碼翻譯。"""

import pytest

from nova.契約.成果 import 成果
from nova.契約.遮罩 import 已經遮過了
from nova.載體.線 import 排版, 線資料


def _造線資料(**覆寫: object) -> 線資料:
    預設: dict[str, object] = {
        "名字": "測試線",
        "在跑嗎": False,
        "跑多久": None,
        "啟動時間": None,
        "目前階段": None,
        "上一次": None,
        "護欄原因": None,
        "未提交檔案數": 0,
        "基底落後數": 0,
    }
    預設.update(覆寫)
    return 線資料(**預設)  # type: ignore[arg-type]


@pytest.mark.parametrize(
    ("退出碼", "護欄原因", "預期片段"),
    [
        (0, None, "退出碼 0：成功"),
        (1, None, "退出碼 1：確定失敗"),
        (3, None, "退出碼 3：結果未知（不准重跑）"),
        (4, "預算用完", "退出碼 4：護欄生效（不是壞了）；護欄原因：預算用完"),
        (4, None, "退出碼 4：護欄生效（不是壞了）；護欄原因：查不到（現有帳本沒有記錄護欄原因）"),
        (99, None, "查不到（未定義的退出碼 99）"),
    ],
)
def test_上一次收場人話翻譯(退出碼: int, 護欄原因: str | None, 預期片段: str) -> None:
    成果紀錄 = 成果(
        執行識別碼="20260831T000000Z-測試",
        任務=已經遮過了("測試任務", 因為="單元測試"),
        收場="測試",
        退出碼=退出碼,
        起="",
        迄="",
        走了幾階=0,
        總token=0,
    )
    線 = _造線資料(上一次=成果紀錄, 護欄原因=護欄原因)
    輸出 = 排版((線,))
    assert 預期片段 in 輸出


def test_沒有工作樹時回傳查不到() -> None:
    assert 排版(()) == "線：查不到（沒有 worktree）\n"


def test_多條線排版用空行隔開() -> None:
    線甲 = _造線資料(名字="線甲")
    線乙 = _造線資料(名字="線乙")
    輸出 = 排版((線甲, 線乙))
    assert "\n\n線：線乙" in 輸出
