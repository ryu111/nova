"""重排的前提：**同一種護欄、而且有前進**，兩個條件都成立才准再排一輪。

`最多輪次 = 3` 只答得出「最多幾輪」，答不出「這一輪值不值得排」。
少了這道判準，一件工作可以連撞三種不同的護欄還照樣被排回收件匣——
而**原因換了就代表題目本身有問題**（第一輪收在測試檔護欄、第二輪收在步數，
修法完全不同），再排一輪只是換一面牆撞。

守的是 `_也許接著排` 這個真的會排票的出口，不是旁邊某支算得出理由卻沒人呼叫的
helper：判準只要還停在「碼 == 護欄碼」，這三支就得紅。

上一輪長什麼樣**只認成果帳**：`狀態.json` 15 分鐘就被蓋掉，拿它當上一輪的來源
等於拿一個會自己消失的東西當證據。所以這裡把上一輪那筆成果直接寫成帳上的 JSON。

進展的定義只認機械證據：**階段代碼走得比上一輪後面**才算前進。
模型講了什麼不算——那是它自己的輸出，讓它算數等於讓被評的人改分數。

比照 Kubernetes Job 的 back-off：計數是「成功完成才重置」，
不是「時間到就重置」；沒進展就不再多給一次。
"""

import json
from pathlib import Path

from nova.契約.工作流 import 步驟結果, 結束, 結束代碼, 階段代碼
from nova.契約.模型回應 import 終局
from nova.契約.護欄 import 護欄原因
from nova.契約.退出碼 import 護欄碼
from nova.載體.命令列 import _也許接著排, _醒來
from nova.載體.收件 import 丟一件, 你敲, 收下一件, 收件單
from nova.迴圈.工作流 import 工作流結果

_題目 = "把某件事做完"


def _收下一張票(匣: Path) -> 收件單:
    丟一件(_題目, 來源=你敲, 目錄=匣)
    單 = 收下一件(匣)
    assert 單 is not None
    return 單


def _上一輪落在成果帳(已處理: Path, *, 原因: 護欄原因, 最後階段: 階段代碼) -> None:
    """把上一輪那一筆寫進成果帳，鍵用落盤的 ASCII 欄名（跨程序 schema 就是這組字）。"""
    已處理.mkdir(parents=True, exist_ok=True)
    (已處理 / "上一輪.json").write_text(
        json.dumps(
            {
                "run_id": "上一輪",
                "task": _題目,
                "outcome": 結束代碼.護欄.value,
                "exit_code": 護欄碼,
                "guardrail_reason": 原因.value,
                "last_stage": 最後階段.value,
            },
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )


def _這一輪(*, 原因: 護欄原因, 最後階段: 階段代碼) -> 工作流結果:
    return 工作流結果(
        結束=結束(代碼=結束代碼.護欄, 原因="撞到上限停下來", 護欄原因=原因),
        軌跡=(步驟結果(階段=最後階段, 終局=終局.成功, 判準綠=False, 證據="走到這裡"),),
    )


class Test原因換了就不再排:
    def test_上一輪測試檔護欄這一輪步數就不排(self, tmp_path: Path) -> None:
        """**原因序列 A→B ＝ 題目有問題**，不是同一面牆多撞一次就過得去的。

        理由要同時講出兩個原因：只寫「跳開」的話，人回頭看帳
        還是得自己去翻上一輪才知道換了什麼牆。
        """
        匣 = tmp_path / "收件"
        已處理 = tmp_path / "已處理"
        單 = _收下一張票(匣)
        _上一輪落在成果帳(已處理, 原因=護欄原因.動了測試, 最後階段=階段代碼.測試)
        這次 = _醒來()

        _也許接著排(
            單,
            果=_這一輪(原因=護欄原因.步數, 最後階段=階段代碼.驗證紅),
            識別="這一輪",
            碼=護欄碼,
            這次=這次,
            已處理目錄=已處理,
        )

        assert 收下一件(匣) is None, "原因換了還排＝換一面牆撞"
        assert 護欄原因.動了測試 in 這次.理由, 這次.理由
        assert 護欄原因.步數 in 這次.理由, 這次.理由


class Test同原因看有沒有前進:
    def test_同原因而且階段往後走就照舊排(self, tmp_path: Path) -> None:
        """**有進展才續命**：同一種護欄、這一輪走到比上一輪後面的階段，那是在前進。"""
        匣 = tmp_path / "收件"
        已處理 = tmp_path / "已處理"
        單 = _收下一張票(匣)
        _上一輪落在成果帳(已處理, 原因=護欄原因.步數, 最後階段=階段代碼.實作)

        _也許接著排(
            單,
            果=_這一輪(原因=護欄原因.步數, 最後階段=階段代碼.審查),
            識別="這一輪",
            碼=護欄碼,
            這次=_醒來(),
            已處理目錄=已處理,
        )

        下一輪 = 收下一件(匣)
        assert 下一輪 is not None, "同原因又往前走還不排＝把有進展的那件也掐掉"
        assert 下一輪.輪次 == 2

    def test_同原因但停在同一階就不排(self, tmp_path: Path) -> None:
        """**原地打轉不給下一輪**：同一種護欄、最後到達的階段跟上一輪一樣，就是沒進展。"""
        匣 = tmp_path / "收件"
        已處理 = tmp_path / "已處理"
        單 = _收下一張票(匣)
        _上一輪落在成果帳(已處理, 原因=護欄原因.步數, 最後階段=階段代碼.實作)
        這次 = _醒來()

        _也許接著排(
            單,
            果=_這一輪(原因=護欄原因.步數, 最後階段=階段代碼.實作),
            識別="這一輪",
            碼=護欄碼,
            這次=這次,
            已處理目錄=已處理,
        )

        assert 收下一件(匣) is None, "沒前進還排＝每 15 分鐘重撞同一面牆"
        assert "沒進展" in 這次.理由, 這次.理由
        assert 階段代碼.實作 in 這次.理由, 這次.理由
