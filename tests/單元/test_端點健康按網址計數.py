"""不同本地網址的端點健康計數要分開。"""

from nova.契約.模型回應 import 回應, 失敗代碼, 用量, 終局
from nova.契約.角色 import 呼叫選項, 預設選項
from nova.載體.模型 import 接力 as 接力模組
from nova.載體.模型.接力 import 接力腦

_網址甲 = "http://127.0.0.1:11434/v1"
_網址乙 = "http://127.0.0.1:22434/v1"
_原文 = "Model 'Qwen3.8-27B-8bit' is busy; unload is pending"


def _四〇九(網址: str) -> 回應:
    return 回應(
        文字=f"{網址} 回 HTTP 409：{_原文}",
        終局=終局.確定失敗,
        失敗代碼=失敗代碼.上游,
        原始結束碼=409,
        對話識別碼=None,
        用量=用量(輸入token=0, 輸出token=0),
    )


def _成功() -> 回應:
    return 回應(
        文字="備援接手",
        終局=終局.成功,
        失敗代碼=失敗代碼.無,
        原始結束碼=0,
        對話識別碼=None,
        用量=用量(輸入token=1, 輸出token=1),
    )


class 同名假端點:
    """兩個網址都掛在 `local` 家族，只有網址能分辨它們。"""

    def __init__(self, 網址: str) -> None:
        """建立指定網址的假端點。"""
        self.網址 = 網址
        self.次數 = 0

    @property
    def 名稱(self) -> str:
        return "local"

    def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
        del 提示, 選項
        self.次數 += 1
        return _四〇九(self.網址)


class 永遠成功的備援:
    名稱 = "agy"

    def __init__(self) -> None:
        """建立永遠成功的備援假腦。"""
        self.次數 = 0

    def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
        del 提示, 選項
        self.次數 += 1
        return _成功()


def test_不同網址不能共用連續失敗計數() -> None:
    """同一家族的兩個端點各失敗一次，不得湊成一個端點的 N 次。"""
    上限 = 接力模組.連續失敗上限
    共享健康 = 接力模組.新端點健康表()
    端點甲 = 同名假端點(_網址甲)
    端點乙 = 同名假端點(_網址乙)
    備援甲 = 永遠成功的備援()
    備援乙 = 永遠成功的備援()
    鏈甲 = 接力腦(名稱="甲鏈", 腦們=(端點甲, 備援甲), 端點健康=共享健康)
    鏈乙 = 接力腦(名稱="乙鏈", 腦們=(端點乙, 備援乙), 端點健康=共享健康)

    for 回合 in range(上限 - 1):
        assert 鏈甲.詢問(f"甲端點第 {回合 + 1} 次").終局 is 終局.成功
        assert 鏈乙.詢問(f"乙端點第 {回合 + 1} 次").終局 is 終局.成功

    最後 = 鏈甲.詢問("甲端點達到上限")

    assert 最後.終局 is 終局.確定失敗
    assert 端點甲.次數 == 上限
    assert 備援甲.次數 == 上限 - 1
    assert 端點乙.次數 == 上限 - 1
    assert 備援乙.次數 == 上限 - 1
    assert _網址甲 in 最後.文字
    assert _原文 in 最後.文字
