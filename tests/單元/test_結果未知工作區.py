"""結果未知時，工作流要先交出工作區的唯讀證據。"""

from pathlib import Path

from nova.契約.工作流 import 任務, 步驟結果, 結束代碼, 階段代碼, 階段定義
from nova.契約.模型回應 import 終局
from nova.迴圈.工作流 import 跑工作流


def test_實作逾時要回報工作區綠與尚未執行階段但不得往下跑(tmp_path: Path) -> None:
    """逾時後可以查證，但查證不是把結果未知變成下一階的通行證。"""
    工作區 = tmp_path / "工作區"
    工作區.mkdir()
    一件事 = 任務(描述="完成一個逾時中的實作", 工作目錄=工作區)
    查詢紀錄: list[tuple[Path, 階段代碼]] = []
    執行過的階段: list[階段代碼] = []

    def 執行一步(定義: 階段定義, _: 任務, __: tuple[步驟結果, ...]) -> 步驟結果:
        執行過的階段.append(定義.代碼)
        return 步驟結果(
            階段=定義.代碼,
            終局=終局.結果未知,
            判準綠=None,
            證據="實作逾時，可能已經做了一半",
        )

    def 唯讀判定(工作: 任務, 階段: 階段代碼) -> str:
        查詢紀錄.append((工作.工作目錄, 階段))
        return "工作區綠：pytest、ruff；尚未執行：驗證綠、重構、驗證重構、審查"

    結果 = 跑工作流(
        一件事,
        執行一步=執行一步,
        起點=階段代碼.實作,
        結果未知判定=唯讀判定,
    )

    assert 查詢紀錄 == [(工作區, 階段代碼.實作)]
    assert "工作區綠：pytest、ruff" in 結果.結束.原因
    assert "尚未執行：驗證綠、重構、驗證重構、審查" in 結果.結束.原因
    assert 結果.結束.代碼 is 結束代碼.護欄
    assert 執行過的階段 == [階段代碼.實作]
    assert 結果.軌跡[0].終局 is 終局.結果未知
