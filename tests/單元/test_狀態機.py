def test_本線負控的刀紅認代碼就退回測試員() -> None:
    """守：`registered-mutation-diff` 紅了第一次就送測試員，不管證據裡有沒有 `src/` 的路徑。

    刀紅的修法**依定義**在 `tests/` 底下（改該紅那支測試，或改 `登記們/` 那把刀的錨點），
    但它的證據天生同時點名 `tests/` 的測試與刀動的目標檔 `src/…`。
    套那條「路徑要全在 `tests/` 底下」的判準就會把這種紅退回一個不准碰測試的角色，
    而下場是它伸手動測試、收 4。所以這條走的是認代碼的那組例外。
    """
    那一步 = _提交閘紅那一步(本線負控刀紅的證據)

    assert 閘只紅在測試檔的哪幾處(那一步) == ("registered-mutation-diff",), (
        "刀紅要認得出來，而且只回規則代碼——路徑那一格對這條規則不成立"
    )
    assert 下一步(查階段(階段代碼.驗證綠), 那一步) is 階段代碼.測試, (
        "刀紅第一次就該送測試員，不等連紅第二次"
    )
    assert "registered-mutation-diff" in _給測試員的段落((那一步,)), (
        "接手的測試員要看得出紅在哪條規則"
    )


def test_lint連紅三輪工作區沒變就收護欄() -> None:
    """守：lint 紅也要有穩定的「這一批是誰」的鍵，同一批連紅三輪且工作區沒動就停。

    lint 紅一行 `FAILED` 都沒有。連紅計數只認 `FAILED` nodeid 的話，
    每一輪都被當成「這批是空的」而歸零，於是新開的那條回頭邊
    （測試 → 全綠了嗎 lint 紅 → 測試 → …）永遠不會被護欄停下來。
    """
    一輪 = _提交閘紅那一步(測試檔E501紅證據)
    同一份雜湊 = "工作區雜湊甲"

    assert 卡住了((一輪,) * 卡住門檻, 工作區雜湊們=(同一份雜湊,) * 卡住門檻) is not None, (
        "同一份 lint 紅連三輪、工作區沒動，這就是無進展"
    )
    assert 卡住了((一輪,) * (卡住門檻 - 1), 工作區雜湊們=(同一份雜湊,) * (卡住門檻 - 1)) is None, (
        "門檻要真的是門檻：差一輪還不准停"
    )


