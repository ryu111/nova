def _提交閘紅那一步(證據: str) -> 步驟結果:
    """全測試綠、紅在提交閘的一步「全綠了嗎」。"""
    return 步驟結果(
        階段=階段代碼.驗證綠,
        終局=終局.成功,
        判準綠=False,
        證據=證據,
        動過的測試檔=這輪動過的測試檔,
    )


def _給測試員的段落(軌跡: tuple[步驟結果, ...]) -> str:
    """被退回來的那一輪，測試員多接到的那幾段。"""
    return "\n".join(
        _看階段才帶的段落(
            查階段(階段代碼.測試),
            任務(描述="把票做完", 工作目錄=Path("不會被讀的工作目錄")),
            軌跡,
        )
    )


def test_驗證綠紅在測試檔的ruff就退回測試員() -> None:
    """守：提交閘只紅在 `tests/` 底下的排版時，這一輪接測試員，並說得出是哪個檔哪條規則。

    實作員被明令禁止碰測試檔，唯一能讓這條閘變綠的動作它做不得；
    第一次紅就送，不等連紅第二次——這裡沒有「可能是實作員改壞的」那種模稜兩可。
    前情只列檔與規則，不整份倒證據。
    """
    那一步 = _提交閘紅那一步(測試檔排版紅證據)

    assert 下一步(查階段(階段代碼.驗證綠), 那一步) is 階段代碼.測試

    前情 = _給測試員的段落((那一步,))
    assert "tests/單元/test_甲.py" in 前情
    assert "ruff-format" in 前情
    assert "負責層" not in 前情, "只列 file:line rule，不准把整份證據倒給測試員"


