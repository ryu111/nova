"""表上讀不到的邊等於沒有圖。

`階段定義` 原本只宣告「綠」「紅」兩格出口，可是真正走過的邊有五種標籤——
另外三種（結果未知、確定失敗、審查沒給結論）藏在 `下一步()` 的 `if` 裡。
**表印得出來、`if` 印不出來**，所以那三條邊只有讀原始碼才知道存在，
規格把這個叫**隱式控制流程**。

這支測的不是「某一條路走對了沒」（那是 `test_狀態機.py` 的事），是**表本身**：

1. 每個階段對它**做得出來**的每一種出口都指名了去處——少一格是隱式的邊，
   多一格是走不到的假邊，兩種都在**建表當下**就炸。
2. `下一步()` 只是查表，沒有表上讀不到的分支。
3. `階段表` 參數真的是那張表——收了就丟的話，第二張表會被靜默忽略。
"""

from pathlib import Path

import pytest

from nova.契約.工作流 import (
    任務,
    停止條件,
    出口標籤,
    審查判定,
    必要出口,
    步驟結果,
    種類,
    結束,
    結束代碼,
    階段代碼,
    階段定義,
)
from nova.契約.模型回應 import 終局
from nova.迴圈.工作流 import 跑工作流
from nova.迴圈.狀態機 import TDD階段表, 下一步, 判出口

一件事 = 任務(描述="讓 X 變成 Y", 工作目錄=Path("/不存在但沒人會碰"))


def _結果(
    階段: 階段代碼,
    終: 終局 = 終局.成功,
    *,
    判準綠: bool | None = None,
    審查結論: 審查判定 | None = None,
) -> 步驟結果:
    return 步驟結果(階段=階段, 終局=終, 判準綠=判準綠, 證據="", 審查結論=審查結論)


def _走得到這條出口的結果(定義: 階段定義, 標籤: 出口標籤) -> 步驟結果:
    """造一個「會走到這條出口」的步驟結果。

    **造得出來 ＝ 這條邊真的走得到。** 表上列著一條沒有任何結果走得到的邊，
    是另一種說謊：讀表的人會以為模型做不出來時會看到「測試角色寫不出測試」，
    實際上他看到的是別句話。
    """
    if 標籤 is 出口標籤.結果未知:
        return _結果(定義.代碼, 終局.結果未知)
    if 標籤 is 出口標籤.確定失敗:
        return _結果(定義.代碼, 終局.確定失敗)
    if 定義.種類 is 種類.審查:
        判定 = {
            出口標籤.綠: 審查判定.通過,
            出口標籤.紅: 審查判定.要求修改,
            出口標籤.沒給結論: 審查判定.沒給結論,
        }[標籤]
        return _結果(定義.代碼, 審查結論=判定)
    if 定義.種類 is 種類.判準:
        期望 = 定義.期望綠
        assert 期望 is not None, f"{定義.代碼} 是判準階段卻沒有期望綠"
        return _結果(定義.代碼, 判準綠=期望 if 標籤 is 出口標籤.綠 else not 期望)
    return _結果(定義.代碼)  # 模型階段跑完就算綠


class Test每一種出口都要指名去處:
    def test_每個階段都指名了它做得出來的每一種出口(self) -> None:
        """少一格＝那條邊藏在函式裡（隱式控制流程）；多一格＝表上有走不到的假邊。"""
        for 定義 in TDD階段表:
            assert set(定義.出口) == 必要出口[定義.種類], 定義.代碼

    def test_每一種階段種類都登記了該有哪些出口(self) -> None:
        """新增一種階段種類卻沒回來補一格，那種階段的表就沒人守得住。"""
        assert set(必要出口) == set(種類)

    def test_少宣告一種出口就建不出階段定義(self) -> None:
        """**建表當下就炸**，不是跑到那一階才 `KeyError`——那時 token 已經花掉了。"""
        with pytest.raises(ValueError, match=出口標籤.結果未知.value):
            階段定義(
                代碼=階段代碼.測試,
                名稱="缺一格",
                種類=種類.模型,
                期望綠=None,
                出口={
                    出口標籤.綠: 階段代碼.驗證紅,
                    出口標籤.確定失敗: 結束(結束代碼.中止, "做不出來"),
                },
            )

    def test_多宣告一條走不到的出口也建不出來(self) -> None:
        """模型階段沒有「沒給結論」這種收場——列上去只會誤導讀表的人。"""
        with pytest.raises(ValueError, match=出口標籤.沒給結論.value):
            階段定義(
                代碼=階段代碼.測試,
                名稱="多一格",
                種類=種類.模型,
                期望綠=None,
                出口={
                    出口標籤.綠: 階段代碼.驗證紅,
                    出口標籤.結果未知: 結束(結束代碼.護欄, "未知"),
                    出口標籤.確定失敗: 結束(結束代碼.中止, "失敗"),
                    出口標籤.沒給結論: 結束(結束代碼.中止, "審查才有這格"),
                },
            )

    def test_出口表建好之後改不動(self) -> None:
        """表是模組層級共用的一份。改得動就等於執行到一半可以重接線。"""
        with pytest.raises(TypeError):
            TDD階段表[0].出口[出口標籤.綠] = 階段代碼.審查  # type: ignore[index]


class Test原本藏在函式裡的三條邊:
    """`結果未知 → 護欄`、`確定失敗 → 中止`、`審查沒給結論 → 中止`。

    這三條原本寫在 `下一步()` 的 `if` 裡，表上讀不到。行為不變，位置變了。
    """

    def test_結果未知在每個階段都是護欄(self) -> None:
        """at-most-once：不知道做了沒，往下走或退回重做都可能做第二次。"""
        for 定義 in TDD階段表:
            去處 = 定義.出口[出口標籤.結果未知]
            assert isinstance(去處, 結束), 定義.代碼
            assert 去處.代碼 is 結束代碼.護欄, 定義.代碼

    def test_確定失敗在每個階段都是中止(self) -> None:
        """**判準跑不起來是環境問題**，退回去再實作一次只會再跑不起來一次。"""
        for 定義 in TDD階段表:
            去處 = 定義.出口[出口標籤.確定失敗]
            assert isinstance(去處, 結束), 定義.代碼
            assert 去處.代碼 is 結束代碼.中止, 定義.代碼

    def test_審查沒給結論在表上就是中止(self) -> None:
        審查 = next(定義 for 定義 in TDD階段表 if 定義.種類 is 種類.審查)
        去處 = 審查.出口[出口標籤.沒給結論]
        assert isinstance(去處, 結束)
        assert 去處.代碼 is 結束代碼.中止

    def test_共用訊息裡的階段名不准跟表漂掉(self) -> None:
        """名稱寫兩份就會漂：改了 `名稱` 卻沒改訊息，使用者看到的是舊名字。"""
        for 定義 in TDD階段表:
            for 標籤 in (出口標籤.結果未知, 出口標籤.確定失敗, 出口標籤.沒給結論):
                去處 = 定義.出口.get(標籤)
                if isinstance(去處, 結束):
                    assert 定義.名稱 in 去處.原因, (定義.代碼, 標籤)


def test_下一步只是查表() -> None:
    """窮舉每個階段 × 每一種出口：判出來的標籤要對，去處要**就是表上那一格**。

    這支同時證明兩件事：表上沒有走不到的假邊（每一格都造得出結果），
    以及 `下一步()` 沒有表上讀不到的分支。
    """
    for 定義 in TDD階段表:
        for 標籤 in 必要出口[定義.種類]:
            結果 = _走得到這條出口的結果(定義, 標籤)
            assert 判出口(定義, 結果) is 標籤, (定義.代碼, 標籤)
            assert 下一步(定義, 結果) == 定義.出口[標籤], (定義.代碼, 標籤)


def _假執行(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> 步驟結果:
    del 任, 軌跡
    return 步驟結果(階段=定義.代碼, 終局=終局.成功, 判準綠=None, 證據="")


def _一步就完的表(去處: 階段代碼 | 結束) -> tuple[階段定義, ...]:
    return (
        階段定義(
            代碼=階段代碼.測試,
            名稱="自訂表的唯一一步",
            種類=種類.模型,
            期望綠=None,
            出口={
                出口標籤.綠: 去處,
                出口標籤.結果未知: 結束(結束代碼.護欄, "自訂表的唯一一步的結果未知"),
                出口標籤.確定失敗: 結束(結束代碼.中止, "自訂表的唯一一步確定失敗"),
            },
        ),
    )


class Test階段表真的是傳進來那一張:
    """`跑工作流(階段表=…)` 原本 `del 階段表`——傳第二張表會被**靜默忽略**。

    靜默是關鍵：呼叫端拿到的是一次照舊的 TDD 跑法，而且沒有任何訊號說它被忽略了。
    """

    def test_傳進去的表真的會被走(self) -> None:
        果 = 跑工作流(
            一件事,
            執行一步=_假執行,
            階段表=_一步就完的表(結束(結束代碼.完成, "自訂表走完了")),
            停止=停止條件(最多步數=3),
        )
        assert [步.階段 for 步 in 果.軌跡] == [階段代碼.測試]
        assert 果.結束.原因 == "自訂表走完了", 果.結束

    def test_表指到表外的階段就開跑前炸(self) -> None:
        """走到一半才 `KeyError` 的話，前面幾階的 token 已經花掉了。"""
        叫過: list[階段代碼] = []

        def 記一筆(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> 步驟結果:
            叫過.append(定義.代碼)
            return _假執行(定義, 任, 軌跡)

        with pytest.raises(ValueError, match=階段代碼.審查.value):
            跑工作流(一件事, 執行一步=記一筆, 階段表=_一步就完的表(階段代碼.審查))
        assert 叫過 == [], "炸之前不准先跑掉一階"

    def test_起點不在表上就開跑前炸(self) -> None:
        with pytest.raises(ValueError, match=階段代碼.重構.value):
            跑工作流(
                一件事,
                執行一步=_假執行,
                階段表=_一步就完的表(結束(結束代碼.完成, "走完了")),
                起點=階段代碼.重構,
            )
