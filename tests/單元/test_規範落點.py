"""CLAUDE.md 的規則與 typed 登記表必須保持同步。"""

from nova.載體.規範落點 import 檢查文件與登記, 規範狀態, 規範登記


def test_文件多一條規則但登記表沒跟上時會紅() -> None:
    """每個 `##` 標題是一條規則；文件多出的規則不能默默漏登記。"""
    文件 = """# CLAUDE.md

## 既有規則

這條規則已經在登記表裡。

## 新增規則

這條規則故意沒有加入登記表。
"""
    登記表 = (
        規範登記(
            識別="既有規則",
            狀態=規範狀態.還是懇求,
            理由="尚未有機械把關器。",
        ),
    )

    通過, 證據 = 檢查文件與登記(文件, 登記表)

    assert 通過 is False
    assert "新增規則" in 證據


def test_搬不動不能只靠替代方案出現canary關鍵字() -> None:
    """明確取消 canary 與人工驗收時，不能被關鍵字嗅探放行。"""
    文件 = """# CLAUDE.md

## 外部服務規則

這條規則沒有本機可決定的 oracle。
"""
    登記表 = (
        規範登記(
            識別="標題:2:1",
            狀態=規範狀態.搬不動,
            理由="本機沒有遠端服務的決定權。",
            替代方案="不做 canary，也不安排人工驗收。",
            到期日="2099-01-01",
        ),
    )

    通過, 證據 = 檢查文件與登記(文件, 登記表)

    assert 通過 is False
    assert "有效替代方案" in 證據


def test_搬不動到期日已過期時會紅() -> None:
    """搬不動的人工驗收或 canary 期限若已過期，登記檢查必須報紅。"""
    文件 = """# CLAUDE.md

## 外部服務規則

這條規則沒有本機可決定的 oracle。
"""
    登記表 = (
        規範登記(
            識別="標題:2:1",
            狀態=規範狀態.搬不動,
            理由="本機沒有遠端服務的決定權。",
            替代方案="用隔離 repo 的 scheduled canary 驗證；人工驗收期限 2020-01-01。",
            到期日="2020-01-01",
        ),
    )

    通過, 證據 = 檢查文件與登記(文件, 登記表)

    assert 通過 is False
    assert "到期日已過期" in 證據
