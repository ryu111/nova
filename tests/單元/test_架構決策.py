"""架構決策交給計畫員前的拒絕契約。"""

from dataclasses import replace

from nova.契約.架構決策 import (
    工作流代碼,
    未決實驗,
    架構決策,
    架構決策問題代碼,
    節點規格,
    驗證架構決策,
)
from nova.契約.節點 import (
    停止政策,
    節點識別碼,
    結果代碼,
    結構識別碼,
    證據項,
    邊識別碼,
)


def _非預設停止政策() -> 停止政策:
    return 停止政策(
        最多呼叫=17,
        最多token=34_001,
        最多秒=73.25,
        最多無進展=5,
        結果未知不重跑=False,
    )


def _研究來源() -> tuple[證據項, ...]:
    return (
        證據項(
            識別碼=邊識別碼("研究證據-非預設-001"),
            類型=結構識別碼("研究發現-v17"),
            摘要="研究來源的具名摘要",
        ),
    )


_完整出口 = tuple(結果代碼)
_預設節點 = 節點識別碼("架構節點-非預設")
_已知節點契約 = frozenset({_預設節點})
_預設停止 = _非預設停止政策()


def _節點規格(
    *,
    節點: str = "架構節點-非預設",
    停止: 停止政策 | None = _預設停止,
    允許結果: tuple[結果代碼, ...] = _完整出口,
) -> 節點規格:
    return 節點規格(
        節點=節點識別碼(節點),
        輸入結構=結構識別碼("架構輸入-v17"),
        輸出結構=結構識別碼("架構輸出-v23"),
        允許結果=允許結果,
        停止=停止,
        需要權限="read-only",
        可否扇出=False,
    )


def _架構決策(
    *,
    依據: tuple[證據項, ...] = _研究來源(),
    節點: tuple[節點規格, ...] = (_節點規格(),),
    未決: tuple[未決實驗, ...] = (),
) -> 架構決策:
    return 架構決策(
        依據=依據,
        工作流=工作流代碼("research"),
        節點=節點,
        出口表版本=23,
        未決=未決,
        風險=("研究證據仍需回放驗證",),
    )


def _驗證(
    決策: 架構決策,
    *,
    可用節點契約: frozenset[節點識別碼] = _已知節點契約,
) -> tuple[架構決策問題代碼, ...]:
    return tuple(問題.代碼 for 問題 in 驗證架構決策(決策, 可用節點契約=可用節點契約))


def _完整未決實驗() -> 未決實驗:
    return 未決實驗(
        問題="輸出結構是否需要版本升級",
        指令=("uv run pytest tests/單元/test_架構決策.py -q",),
        觀察="記錄驗證結果與輸出版本",
        勝負判準="新版本能通過所有契約測試",
        到期="下一次研究回放前",
        驗證方式="回放測試並比較版本化輸出",
    )


def test_沒有來源的決策不能交給計畫員() -> None:
    """架構師的輸出沒有研究來源時，必須在進計畫員前被拒絕。"""
    assert _驗證(_架構決策(依據=())) == (架構決策問題代碼.缺來源,)


def test_沒有停止政策的決策不能交給計畫員() -> None:
    """架構師的輸出沒有停止政策時，必須在進計畫員前被拒絕。"""
    assert _驗證(_架構決策(節點=(_節點規格(停止=None),))) == (架構決策問題代碼.缺停止政策,)


def test_不存在的節點契約要被拒絕() -> None:
    決策 = _架構決策(節點=(_節點規格(節點="不存在的節點契約"),))

    assert _驗證(決策) == (架構決策問題代碼.不存在節點契約,)


def test_出口必須窮舉四種終局() -> None:
    決策 = _架構決策(節點=(_節點規格(允許結果=_完整出口[:-1]),))

    assert _驗證(決策) == (架構決策問題代碼.出口未窮舉,)


def test_未決實驗要有到期與驗證方式() -> None:
    for 實驗 in (
        replace(_完整未決實驗(), 到期=""),
        replace(_完整未決實驗(), 驗證方式=""),
    ):
        決策 = _架構決策(未決=(實驗,))

        assert _驗證(決策) == (架構決策問題代碼.未決實驗不完整,)


def test_節點規格識別碼重複要被拒絕() -> None:
    決策 = _架構決策(
        節點=(
            _節點規格(),
            _節點規格(),
        ),
    )

    assert _驗證(決策) == (架構決策問題代碼.節點規格矛盾,)


def test_完全合法的決策通過驗證() -> None:
    決策 = _架構決策(未決=(_完整未決實驗(),))

    assert _驗證(決策) == ()


def test_同時犯多種錯時要全部報出來() -> None:
    決策 = _架構決策(
        依據=(),
        節點=(
            _節點規格(
                節點="不存在的節點契約",
                停止=None,
                允許結果=_完整出口[:-1],
            ),
            _節點規格(節點="不存在的節點契約"),
        ),
        未決=(replace(_完整未決實驗(), 驗證方式=""),),
    )

    assert set(_驗證(決策)) == {
        架構決策問題代碼.缺來源,
        架構決策問題代碼.缺停止政策,
        架構決策問題代碼.不存在節點契約,
        架構決策問題代碼.出口未窮舉,
        架構決策問題代碼.未決實驗不完整,
        架構決策問題代碼.節點規格矛盾,
    }
