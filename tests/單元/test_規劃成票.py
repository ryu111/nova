"""目標 → 分派單 → 票 這條鏈：驗證沒過不准落票，過了的票要四欄齊全。

這裡刻意不接 CLI、不寫收件匣：這一格要證明的是「規劃這件事機械化得起來」，
不是「從哪裡叫它」。計畫產生器（＝一次模型呼叫）在測試裡是注入的假貨，
所以整條鏈是確定性的。

硬規則二在這裡的樣子：**計畫員產出、`驗證分派單` 機械把關**，
不是同一個對話自寫自評。
"""

from dataclasses import replace
from pathlib import Path

import pytest

from nova.契約.分派 import 分派問題代碼, 分派單, 分派項目
from nova.契約.工作流 import 任務
from nova.契約.節點 import (
    停止政策,
    分支識別碼,
    執行識別碼,
    工作流識別碼,
    節點上下文,
    節點識別碼,
    結構識別碼,
    邊識別碼,
)
from nova.載體.收件 import 缺哪幾欄
from nova.載體.規劃成票 import 分派單不合格, 規劃成票
from nova.迴圈.計畫 import 執行限制, 工作現況, 規劃輸入, 計畫產生器

_目標 = "把規劃那一層接上收件匣"
_節點 = 節點識別碼("實作節點")
_結構 = 結構識別碼("輸入-文字")
_一項停止 = 停止政策(最多呼叫=1, 最多token=100, 最多秒=1.0, 最多無進展=1)
_總停止 = 停止政策(最多呼叫=4, 最多token=400, 最多秒=4.0, 最多無進展=1)

_限制 = 執行限制(
    停止=_總停止,
    允許網路=False,
    允許編輯=True,
    可用節點=(_節點,),
    可用結構=(_結構,),
    最大分支數=1,
)

_合格項目 = 分派項目(
    識別碼="項目-001",
    節點=_節點,
    輸入結構=_結構,
    前置項目=(),
    分支=None,
    必要=True,
    停止=_一項停止,
    驗收出口=("uv run pytest tests/單元 -q",),
    需要編輯=True,
    寫入範圍=("src/nova/迴圈/計畫.py",),
)

_第二項 = replace(
    _合格項目,
    識別碼="項目-002",
    前置項目=("項目-001",),
    驗收出口=("uv run nova 閘 提交",),
    寫入範圍=("tests/單元/test_規劃成票.py",),
)


def _現況() -> 工作現況:
    return 工作現況(
        工作目錄=Path("工作目錄"),
        已有工件=(),
        已有證據=(),
        目前節點=None,
        缺口=("規劃那一層零呼叫端",),
    )


def _上下文() -> 節點上下文:
    return 節點上下文(
        任務=任務(描述=_目標, 工作目錄=Path("工作目錄")),
        執行=執行識別碼("執行-001"),
        工作流=工作流識別碼("規劃-001"),
        節點=節點識別碼("計畫員"),
        分支=分支識別碼("根"),
        父邊=(邊識別碼("根輸入"),),
        嘗試=1,
        停止=_總停止,
    )


def _假產生器(項目們: tuple[分派項目, ...], 看到的: list[規劃輸入]) -> 計畫產生器:
    """回一張寫死的分派單，順便把收到的規劃輸入記下來。"""

    def 產生(輸入: 規劃輸入) -> 分派單:
        看到的.append(輸入)
        return 分派單(版本=1, 項目=項目們, 最大分支數=1, 總停止=_總停止)

    return 產生


def test_缺欄的分派單不准落票且訊息指名哪一項缺哪一欄() -> None:
    """模型講的分派單缺停止與驗收出口 → 一張票都不准生，而且要講是哪一項。"""
    缺欄的 = replace(_合格項目, 識別碼="項目-缺欄", 停止=None, 驗收出口=())
    看到的: list[規劃輸入] = []

    with pytest.raises(分派單不合格) as 抓到:
        規劃成票(
            _目標,
            現況=_現況(),
            限制=_限制,
            上下文=_上下文(),
            產生器=_假產生器((缺欄的,), 看到的),
        )

    問題們 = 抓到.value.問題們
    assert {問題.代碼 for 問題 in 問題們} == {
        分派問題代碼.缺停止政策,
        分派問題代碼.缺驗收條件,
    }
    assert {問題.項目 for 問題 in 問題們} == {"項目-缺欄"}
    訊息 = str(抓到.value)
    assert "項目-缺欄" in 訊息
    assert "停止" in 訊息
    assert "驗收" in 訊息


def test_合格的分派單轉出來的票過得了四欄檢查() -> None:
    """防「生出一張自己會擋下來的票」：轉出來的票要過 `收件.缺哪幾欄`。"""
    看到的: list[規劃輸入] = []

    票們 = 規劃成票(
        _目標,
        現況=_現況(),
        限制=_限制,
        上下文=_上下文(),
        產生器=_假產生器((_合格項目, _第二項), 看到的),
    )

    assert [輸入.目標 for 輸入 in 看到的] == [_目標]
    assert tuple(票.識別碼 for 票 in 票們) == ("項目-001", "項目-002")
    for 票 in 票們:
        assert 缺哪幾欄(票.內容) == ()
        for 欄 in ("輸入", "輸出", "驗收", "停止"):
            assert f"## {欄}" in 票.內容
    assert "uv run pytest tests/單元 -q" in 票們[0].內容
    assert "src/nova/迴圈/計畫.py" in 票們[0].內容
    assert "項目-001" in 票們[1].內容
