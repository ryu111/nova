"""「哪一階算例行、哪一階算推理」只准有一份。

原本是兩份拷貝各活各的：`載體/命令列.py` 的 `_階段的工作`（開跑前的資格檢查
拿它驗本地腦資格與熔斷）、`迴圈/角色工廠.py` 的 `建TDD角色藍圖`（實際派工時
逐階硬編 `怎麼派(工作種類.例行/推理)`）。兩份各自有測試把值釘死，**卻沒有
任何測試斷言兩份相等**——改一份、更新它自己的測試，另一份照樣綠。

症狀是「資格檢查驗的家」≠「真的被叫的家」：走散成甲說推理、乙派例行，
資格檢查就驗了一家沒被叫的（**靜默放行**）；反過來則可能**誤擋**。

這支測試守兩層：
1. `test_藍圖的工作種類是問來的不是硬編的`：藍圖不准自己知道哪一階算哪種，
   得問呼叫端傳進來的查詢。這一層是**機制**，它逼出「只有一份」。
2. `test_資格檢查算的家就是藍圖真的派的家`：把兩邊的結果直接接上比對。
   這一層是**行為**，也是負控要打的地方（把留下來那份的審查改成例行，它要紅）。

方向選的是「查詢當參數傳進去」，因為 `建TDD角色藍圖` **已經**吃 `怎麼派`
當參數，多收一個同型的查詢是最小改動。**知識落在迴圈**
（`迴圈/角色工廠.py` 的 `TDD階段的工作`），載體 import 過去讀：
架構閘只擋「迴圈 import 載體」，反向讀是允許的；若把知識留在載體，
`建TDD角色藍圖` 就連預設值都拿不到（那會逼出越界的 import）。
"""

import argparse

import pytest

from nova.契約.工作流 import 階段代碼
from nova.契約.派工 import 工作種類
from nova.載體.命令列 import _這次的TDD角色藍圖, _哪幾家
from nova.載體.派工表 import 怎麼派
from nova.迴圈.角色工廠 import 建TDD角色藍圖, 這階算哪種工作

#: TDD 四階與它該算哪一種工作。**這是規格不是現況的拓印**：
#: 測試／實作／重構是照現成樣子寫、對不對看得出來；審查要靠推理才看得出來。
四階該算哪種 = {
    階段代碼.測試: 工作種類.例行,
    階段代碼.實作: 工作種類.例行,
    階段代碼.重構: 工作種類.例行,
    階段代碼.審查: 工作種類.推理,
}


class 記下來的工作種類查詢:
    """假的「這一階算哪種」查詢：全部回推理，並記下被問過哪幾階。

    全部回推理是刻意的——硬編那份的三階是例行，所以只要藍圖偷懶不問，
    這支測試就會看到例行而當場紅。
    """

    def __init__(self) -> None:
        """開一本空的「被問過哪幾階」帳。"""
        self.問過: list[階段代碼] = []

    def __call__(self, 階段: 階段代碼) -> 工作種類:
        self.問過.append(階段)
        return 工作種類.推理


def _不給腦旗標的參數() -> argparse.Namespace:
    """沒給 `--用` 也沒給 `--審查用`，就是排程真正在跑的那條路。"""
    return argparse.Namespace(用=None, 審查用=None, 逾時=None, 模型=None)


def test_藍圖的工作種類是問來的不是硬編的() -> None:
    """`建TDD角色藍圖` 不准自己存一份「哪一階算哪種」。

    它要吃一個「階段 → 工作種類」的查詢，四階都得問過，而且拿問來的答案去
    決定派法。查詢全回推理時，四階的派法就都必須是推理那一列。
    """
    查詢 = 記下來的工作種類查詢()

    藍圖們 = 建TDD角色藍圖(怎麼派, 查詢)

    assert set(查詢.問過) == set(四階該算哪種), (
        f"藍圖沒有逐階去問工作種類，只問了 {查詢.問過}——沒問的那幾階就是還硬編著"
    )
    推理派法 = 怎麼派(工作種類.推理)
    for 藍圖 in 藍圖們:
        assert 藍圖.派法 == 推理派法, f"{藍圖.識別碼} 沒有照查詢的答案派，還是自己決定的"


def test_資格檢查算的家就是藍圖真的派的家() -> None:
    """開跑前驗的那幾家，必須就是那一階真的會被叫的那幾家。

    左邊是 `_哪幾家`（`_工作流前置檢查` 用它驗本地腦資格與熔斷），
    右邊是 `_這次的TDD角色藍圖`（真的拿去建腦派工）。兩邊走散的話，
    護欄驗的是一家沒人叫的腦——綠得很好看，什麼都沒守到。
    """
    藍圖們 = {藍圖.識別碼: 藍圖 for 藍圖 in _這次的TDD角色藍圖(_不給腦旗標的參數())}

    for 階段, 該算哪種 in 四階該算哪種.items():
        藍圖 = 藍圖們.get(階段.value)
        assert 藍圖 is not None, f"藍圖裡沒有 {階段.value} 這一階"
        資格檢查驗的 = _哪幾家(None, 階段)
        真的被叫的 = set(藍圖.派法.腦們)
        assert 資格檢查驗的 == 真的被叫的, (
            f"{階段.value}：資格檢查驗 {資格檢查驗的}、實際派 {真的被叫的}，兩份知識走散了"
        )
        assert 真的被叫的 == set(怎麼派(該算哪種).腦們), (
            f"{階段.value} 該算 {該算哪種.value}，卻派成了別種工作的腦鏈"
        )


def test_審查跟例行三階派的不是同一條鏈() -> None:
    """兩份合成一份之後仍然不准把審查併進例行——那等於自寫自評。"""
    藍圖們 = {藍圖.識別碼: 藍圖 for 藍圖 in _這次的TDD角色藍圖(_不給腦旗標的參數())}
    審查的家們 = set(藍圖們[階段代碼.審查.value].派法.腦們)
    for 階段 in (階段代碼.測試, 階段代碼.實作, 階段代碼.重構):
        assert 審查的家們 != set(藍圖們[階段.value].派法.腦們), (
            f"{階段.value} 跟審查派同一條鏈，審查就變成自己批改自己"
        )


