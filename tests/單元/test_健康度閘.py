"""健康度閘的行為契約：**二元**閘，紅了只擋推進票，維護票永遠放行。

這一格只測「算」的那一半——四個指標當參數收進來，不在函式裡自己去查
`gh`／git／檔案系統。查的那一半是載體的另一個入口，不在這裡測；
真去查的話，沒有 CI 的機器上這幾支就跑不動了。

**不測配額（90/10、40/60）**：中間那一檔會被拿來拖延，這裡只有綠與紅。
"""

from dataclasses import replace

import pytest

from nova.載體.健康度 import 健康度指標, 准生票嗎, 指標代碼, 票種

#: 四個指標全綠的基準。每一支測試從這裡 `replace` 出「只有一項不綠」的現場，
#: 才能確定擋下來的原因就是那一項。
全綠 = 健康度指標(main綠嗎=True, 卡住的線數=0, 沒收尾的件數=0, 壞掉的PR數=0)

#: （欄位名, 紅值, 對應的指標代碼）。四個指標各紅一次，一列都不能少：
#: 少一列就等於那個指標接上去之後沒人擋，而每一輪看起來都還是很努力。
四項 = (
    ("main綠嗎", False, 指標代碼.main的CI),
    ("卡住的線數", 2, 指標代碼.卡住的線),
    ("沒收尾的件數", 3, 指標代碼.沒收尾的收件),
    ("壞掉的PR數", 1, 指標代碼.壞掉的PR),
)

四項各自紅 = tuple(
    pytest.param(欄位, 紅值, 代碼, id=f"{代碼.value}是紅的") for 欄位, 紅值, 代碼 in 四項
)

#: 同樣四項，但值是「算不出來」（`None`）——`gh` 不通、離線、查不到 CI。
四項各自算不出來 = tuple(
    pytest.param(欄位, None, 代碼, id=f"{代碼.value}算不出來") for 欄位, _紅值, 代碼 in 四項
)


def test_四個指標全綠才放行推進票() -> None:
    """基準線：這一支綠的，下面那幾支才證明得了是「那一項」擋的。"""
    判定 = 准生票嗎(全綠, 票種=票種.推進)

    assert 判定.放行 is True
    assert 判定.紅項 == ()


@pytest.mark.parametrize(("欄位", "紅值", "該項"), 四項各自紅)
def test_任一指標紅就擋掉推進票並指名是哪一項(欄位: str, 紅值: bool | int, 該項: 指標代碼) -> None:
    """紅的時候要說**哪一項**紅、要收掉什麼才會轉綠。

    只說「系統不健康」等於沒說：那會讓下一個人跑去調閾值，
    而不是去把卡住的那條線收掉。
    """
    判定 = 准生票嗎(replace(全綠, **{欄位: 紅值}), 票種=票種.推進)

    assert 判定.放行 is False
    assert 判定.紅項 == (該項,)
    assert 該項.value in 判定.訊息
    # 綠的那三項不准出現在訊息裡——被指名的必須只有真的紅的那一項
    for 別項 in 指標代碼:
        if 別項 is not 該項:
            assert 別項.value not in 判定.訊息


@pytest.mark.parametrize(("欄位", "紅值", "該項"), 四項各自紅)
def test_紅的時候維護票照樣放行(欄位: str, 紅值: bool | int, 該項: 指標代碼) -> None:
    """反向保證：閘紅票、接續票這種「修理」不准被自己擋掉。

    少了這一條，系統一紅就永遠紅著——擋住推進的同時也擋住了唯一能轉綠的路。
    """
    指標 = replace(全綠, **{欄位: 紅值})

    assert 准生票嗎(指標, 票種=票種.維護).放行 is True
    # 同一份現場，推進票確實是被那一項擋下的，才證明放行不是因為閘根本沒紅
    擋推進 = 准生票嗎(指標, 票種=票種.推進)
    assert 擋推進.放行 is False
    assert 擋推進.紅項 == (該項,)


@pytest.mark.parametrize(("欄位", "空值", "該項"), 四項各自算不出來)
def test_指標算不出來時往安全那邊倒擋掉推進票(欄位: str, 空值: None, 該項: 指標代碼) -> None:
    """算不出來（`None`）不等於綠：不拿 0 頂替，也不當作 main 是綠的。

    往安全那邊倒＝擋推進。理由：算不出來的時候我們**不知道**修理跟不跟得上，
    這時多生一張推進票是拿看不見的東西下注；而擋掉的代價只是晚 15 分鐘再醒來一次。
    """
    指標 = replace(全綠, **{欄位: 空值})
    判定 = 准生票嗎(指標, 票種=票種.推進)

    assert 判定.放行 is False
    assert 該項.value in 判定.訊息
    # 維護票在「算不出來」時一樣不受影響，理由同上一支
    assert 准生票嗎(指標, 票種=票種.維護).放行 is True
