class Testtoken預算:
    """花多少也要有上限，不是只有走幾步有上限。

    規格 §5 把 token budget 列成必要邊界。`最多步數` 擋的是步數，不是花費——
    一步可以很貴，十二步的上限對成本沒有任何保證。

    預算是**累計式**的：每次回來加總，**下一次呼叫之前**擋下。
    擋不到「這一次會花多少」——那要等它回來才知道，所以最後一步一定會超出一點，
    這是誠實的上限而不是精準的上限。
    """

    def _貴的執行器(self, 每次: int) -> 執行器:
        人 = {
            "測試": 假角色("測試", _假回應(token=每次)),
            "實作": 假角色("實作", _假回應(token=每次)),
            "審查": 假角色("審查", _假回應(文字=過關的審查回覆, token=每次)),
        }
        return _執行器([False, True], 人)[0]

    def test_步驟結果記得下這一步花了多少(self) -> None:
        """沒有這一格，迴圈根本數不出自己花了多少。"""
        執行, _ = _執行器([False, True])
        果 = 跑工作流(一件事, 執行一步=執行)
        模型步 = [步 for 步 in 果.軌跡 if 步.階段 in (階段代碼.測試, 階段代碼.實作, 階段代碼.審查)]
        assert all(步.花費 is not None and 步.花費.總token > 0 for 步 in 模型步)
        判準步 = [步 for 步 in 果.軌跡 if 步.階段 in (階段代碼.驗證紅, 階段代碼.驗證綠)]
        assert all(步.花費 is None for 步 in 判準步), "判準不叫模型，不該假裝有花費"

    def test_超過預算就停(self) -> None:
        果 = 跑工作流(一件事, 執行一步=self._貴的執行器(1000), 停止=停止條件(最多token=1500))
        assert 果.結束.代碼 is 結束代碼.護欄
        assert "token" in 果.結束.原因 and "1500" in 果.結束.原因

    def test_擋在下一次呼叫之前不是事後補救(self) -> None:
        """累計超標之前就不准再發下一次呼叫。

        **這支的期望改過一次，改的是需求不是為了配合實作。**
        舊規則是「已經超了才停」：第一步用掉 1000／預算 1500，實作跑完累計 2000，
        第四步之前才停——那 500 是**跑完才發現**的超支。

        新規則用觀測到的成本事前擋：進實作之前已花 1000、上一個模型階段花了 1000，
        1000＋1000＞1500，所以**實作不准跑**。同一個上限，提早生效。
        理由與實測數字見 `Test預算要事前擋不是事後發現`。

        判準階段（第二步）不花錢，照樣要跑得到——擋掉免費的驗證是擋錯東西。
        """
        人 = {
            "測試": 假角色("測試", _假回應(token=1000)),
            "實作": 假角色("實作", _假回應(token=1000)),
            "審查": 假角色("審查", _假回應(文字=過關的審查回覆, token=1000)),
        }
        執行, _ = _執行器([False, True], 人)
        果 = 跑工作流(一件事, 執行一步=執行, 停止=停止條件(最多token=1500))
        assert [步.階段 for 步 in 果.軌跡] == [階段代碼.測試, 階段代碼.驗證紅]
        assert len(人["實作"].收到) == 0, "預估會超標還去叫實作，那事前擋等於沒有"
        assert len(人["審查"].收到) == 0, "超了預算還去叫審查，那預算等於沒有"

    def test_預算夠就照常走完(self) -> None:
        果 = 跑工作流(一件事, 執行一步=self._貴的執行器(1000), 停止=停止條件(最多token=99999))
        assert 果.結束.代碼 is 結束代碼.完成

    def test_預設就有上限不必記得傳(self) -> None:
        """忘了傳不能等於沒有上限——沒有預設的保證是懇求，不是保證。"""
