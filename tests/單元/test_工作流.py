class _偷動測試的假實作員(假角色):
    """走到實作那一階就（依序）去動一個測試檔；給 `None` 那次就乖乖不動。

    跟 `_寫測試的假測試員` 同一招：讓 `動過的測試檔` 是快照比對算出來的，
    不是測試自己塞進 `步驟結果`。
    """

    def __init__(
        self,
        工作區: _假工作區,
        每次動的檔: list[str | None],
        回: 回應 | None = None,
    ) -> None:
        super().__init__("實作", 回)
        self._工作區 = 工作區
        self._每次動的檔 = 每次動的檔

    def 做(self, 提示: str, *, 工作目錄: Path | None = None) -> 回應:
        次數 = len(self.收到)
        檔 = self._每次動的檔[min(次數, len(self._每次動的檔) - 1)]
        if 檔 is not None:
            self._工作區.寫(檔, 實作員偷寫的內容)
        return super().做(提示, 工作目錄=工作目錄)


