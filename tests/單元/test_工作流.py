class Test混合審查退回測試員之後那一輪的實作員:
    """審查同時開 `[test-design]` 與 `[impl]` 時，整包退給測試員——

    路由沒錯（`[test-design]` 實作員動不了），錯的是那些 `[impl]` 條目
    **沒有任何機制**走到兩階之後的實作員：它的上一步是 `驗證紅` 的 pytest 輸出，
    審查一個字都看不到。於是它順著紅做出反方向的最小綠，第二次審查再開同一批意見，
    兩輪撞上「審查意見連續要求修改 2 次」的護欄。

    「最近一次審查」的查找已經住在 `工作流` 組回顧那一段的那個私有函式；
    壞的不是怎麼找，是它只接給審查階。（私有函式的名字是實作的自由，
    這裡不抄——抄了它改名就得回頭動測試檔，那正是上一輪撞護欄的路。）
    """

    #: 一條 `[test-design]`（路由去測試員）＋ 一條 `[impl]`（沒人接得到）。
    混合審查全文 = (
        "ISSUE: [test-design] 邊界案例沒寫\nISSUE: [impl] 空輸入沒處理\nREVIEW: CHANGES-REQUESTED"
    )

    def _跑一輪混合審查(self) -> dict[str, 假角色]:
        """審查第一次開混合意見、第二次通過；回各角色收到的提示。"""
        人 = {
            "測試": 假角色("測試"),
            "實作": 假角色("實作"),
            "審查": 假角色(
                "審查",
                [
                    _假回應(文字=self.混合審查全文),
                    _假回應(文字=過關的審查回覆),
                ],
            ),
        }
        # 驗證紅紅、驗證綠綠、驗證重構綠 ＋ 退回測試員之後再一輪同樣三支。
        執行, 人 = _執行器([False, True, True, False, True, True], 人)
