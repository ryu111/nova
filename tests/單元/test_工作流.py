class Test預算要事前擋不是事後發現:
    """實測（2026-08-29，重構 `命令列.py` 那一輪）：

        refactor (agy)    498,053 token
        review   (codex)  555,433 token
        累計            1,053,486  ≥ 上限 800,000

    護欄在 review **跑完之後**才發現超支——多燒了 253,486 token。
    而那一階本來就跑不完：進去之前已花 498,053，剩下 301,947，
    **而上一個模型階段就花了 498,053**。用觀測到的成本，事前就擋得下來。

    **這不是把上限調高**（那是拆執法點），是把同一個上限**提早生效**。

    估計用「最近一次**非零**的花費」不是「上一階」：判準階段不叫模型、花費是 0，
    拿它當估計等於沒估。
    """

    def _固定花費(self, token: int) -> 執行器:
        def 執行一步(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> 步驟結果:
            del 任, 軌跡
            是判準 = 定義.種類 is 種類.判準
            return 步驟結果(
                階段=定義.代碼,
                終局=終局.成功,
                # 判準階段要回**它自己期望的那個顏色**，不然驗證紅永遠走紅邊、
                # 工作流在回頭邊上打轉到撞步數上限——那測到的是別的東西。
                判準綠=定義.期望綠 if 是判準 else None,
                證據=過關的審查回覆 if 定義.種類 is 種類.審查 else "做好了",
                審查結論=審查判定.通過 if 定義.種類 is 種類.審查 else None,
                花費=None if 是判準 else 用量(輸入token=token, 輸出token=0),
            )

        return 執行一步

    def test_下一階預估會超過就先停(self) -> None:
        # 每個模型階段花 60；上限 100。第一階跑完已花 60，
        # 60 + 60 = 120 > 100 → 第二個模型階段不准跑。
        果 = 跑工作流(
            一件事,
            執行一步=self._固定花費(60),
            停止=停止條件(最多步數=20, 最多token=100),
        )
        assert 果.結束.代碼 is 結束代碼.護欄
        模型步數 = len([步 for 步 in 果.軌跡 if 步.花費 is not None])
        assert 模型步數 == 1, f"第二個模型階段不該跑：{模型步數}"

    def test_訊息要說得出估計是怎麼來的(self) -> None:
        """「預算不夠」不可行動。要看得出已花多少、估多少、上限多少。"""
        果 = 跑工作流(
            一件事, 執行一步=self._固定花費(60), 停止=停止條件(最多步數=20, 最多token=100)
        )
        for 字 in ("60", "100", "預估"):
            assert 字 in 果.結束.原因, f"訊息裡沒有 {字}：{果.結束.原因}"

    def test_建議值等於已花加剩餘階數乘花費並向上取整(self) -> None:
        果 = 跑工作流(
            一件事, 執行一步=self._固定花費(60), 停止=停止條件(最多步數=20, 最多token=100)
        )
