class _假工作區:
    """記住每個檔案的內容，讓快照比對算得出「這一步動過哪幾個測試檔」。

    不碰硬碟：`拍快照`／`動到測試了嗎` 是 `跑工作流` 的參數，
    這裡給的兩支就是正式跑法（`拍工作區快照`／`動到測試了嗎`）的同形狀替身。
    """

    def __init__(self) -> None:
        self.檔們: dict[str, str] = {
            "tests/整合/test_閘不准吃快取.py": "基線",
            "tests/驗收/test_文件即事實.py": "基線",
        }

    def 拍快照(self, 工作目錄: Path) -> Mapping[str, str]:
        """回**唯讀映射**：快照只被拿去比對，沒有人該改它。

        型別寫 `Mapping` 不寫 `dict`，是因為窄型別的假物件會反過來把
        `跑工作流` 的邊界逼成具體 `dict`（見 `test_快照邊界是Mapping…`）。
        """
        del 工作目錄
        return MappingProxyType(dict(self.檔們))

    def 動到測試了嗎(self, 前: Mapping[str, str], 後: Mapping[str, str]) -> tuple[str, ...]:
        return tuple(sorted(檔 for 檔 in 後 if 前.get(檔) != 後[檔]))

    def 寫(self, 檔: str, 內容: str) -> None:
        self.檔們[檔] = 內容


class _寫測試的假測試員(假角色):
    """走到測試那一階就真的動一個測試檔。

    這樣 `動過的測試檔` 才是快照比對算出來的，不是測試自己塞進 `步驟結果` 的。
    """

    def __init__(self, 工作區: _假工作區, 每次動的檔: list[str]) -> None:
        super().__init__("測試")
        self._工作區 = 工作區
        self._每次動的檔 = 每次動的檔

    def 做(self, 提示: str, *, 工作目錄: Path | None = None) -> 回應:
        次數 = len(self.收到)
        檔 = self._每次動的檔[min(次數, len(self._每次動的檔) - 1)]
        self._工作區.寫(檔, f"第 {次數 + 1} 次寫的")
        return super().做(提示, 工作目錄=工作目錄)


