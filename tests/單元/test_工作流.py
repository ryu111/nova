def _假回應(終: 終局 = 終局.成功, 文字: str = "做好了", *, token: int = 2) -> 回應:
    """`token` 是這一次呼叫的總花費，輸入輸出各一半——預算測試要拿它當旋鈕。"""
    return 回應(
        文字=文字,
        終局=終,
        失敗代碼=失敗代碼.無 if 終 is 終局.成功 else 失敗代碼.逾時,
        原始結束碼=0,
        對話識別碼=None,
        用量=用量(輸入token=token // 2, 輸出token=token - token // 2),
    )


class 假角色:
    """記下自己被叫過幾次、收到什麼提示。

    `回` 可以給一串：**第 n 次被叫就回第 n 個，用完之後一直回最後一個**。
    不給序列就測不出「審查要求修改 → 再實作一輪 → 第二次才通過」這種組合行為——
    固定回同一個答案的假角色，只走得到第一輪。
    """

    def __init__(self, 名稱: str, 回: 回應 | list[回應] | None = None) -> None:
        """名稱只是給錯誤訊息看的；`回` 讓測試決定這個角色會回什麼。"""
        self.名稱 = 名稱
        序列 = 回 if isinstance(回, list) else [回 or _假回應()]
        if not 序列:
            訊息 = "假角色至少要有一個回應"
            raise ValueError(訊息)
        self._序列 = 序列
        self.收到: list[str] = []

    def 做(self, 提示: str, *, 工作目錄: Path | None = None) -> 回應:
        del 工作目錄
        self.收到.append(提示)
        return self._序列[min(len(self.收到) - 1, len(self._序列) - 1)]


def _執行器(
    判準序列: list[bool], 角色們: dict[str, 假角色] | None = None
) -> tuple[執行器, dict[str, 假角色]]:
    """判準依序回這些紅綠；角色一律成功。"""
    # **覆蓋不是取代**：呼叫端只給它在意的那幾個角色，其餘用預設。
    # 取代的話，每加一個角色就要回頭改每一支自訂角色的測試。
    人 = {
        "測試": 假角色("測試"),
        "實作": 假角色("實作"),
        "重構": 假角色("重構"),
        "審查": 假角色("審查", _假回應(文字=過關的審查回覆)),
        **(角色們 or {}),
    }
    剩 = list(判準序列)

    def 跑判準(_: 任務) -> tuple[判準終局, str]:
        綠 = 剩.pop(0) if 剩 else True
        return (判準終局.綠 if 綠 else 判準終局.紅), "假判準"

    執行 = 建TDD執行器(
        角色表={
            階段代碼.測試: 人["測試"],
            階段代碼.實作: 人["實作"],
            階段代碼.重構: 人["重構"],
            階段代碼.審查: 人["審查"],
        },
        跑判準=跑判準,
    )
    return 執行, 人


