            階段代碼.驗證紅,
            階段代碼.實作,
            階段代碼.驗證綠,
            階段代碼.重構,
            階段代碼.驗證重構,
            階段代碼.審查,
            階段代碼.實作,
            階段代碼.驗證綠,
            階段代碼.重構,
            階段代碼.驗證重構,
            階段代碼.審查,
