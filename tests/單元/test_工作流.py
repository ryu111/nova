class Test停止條件:
    def test_來回不停會撞到步數上限(self) -> None:
        """缺 stop rule 的不是迴圈，是成本漏洞（§3.2）。

        走「驗證綠一直是紅的 → 退回實作」這條邊：它的專屬計數（`卡住門檻`）要三次
        同樣的紅才發話，六步之內還輪不到，所以這一步真正擋下來的是步數上限本身。
        """
        # 驗證紅如期紅一次，之後驗證綠永遠是紅的 → 永遠退回實作。
        執行, _ = _執行器([False] * 50)
        果 = 跑工作流(一件事, 執行一步=執行, 停止=停止條件(最多步數=6))
        assert 果.結束.代碼 is 結束代碼.護欄
        assert "最多步數" in 果.結束.原因, 果.結束.原因
        assert 果.結束.護欄原因 is 護欄原因.步數
        assert len(果.軌跡) == 6

    def test_驗證紅一直是綠的會在燒完步數之前收線(self) -> None:
        """沒有紅可看的票要當場說清楚，不是拿步數上限把它耗完。

        `測試 → 驗證紅（竟然是綠的）→ 測試` 這條回頭邊本身不會自己停；擋它的是
        「連續判成綠」的計數，收線理由要指向切題的人，不是指向測試員。
        """
        執行, 人 = _執行器([True] * 50)  # 驗證紅永遠是綠的 → 永遠退回測試
        果 = 跑工作流(一件事, 執行一步=執行, 停止=停止條件(最多步數=20))
        assert 果.結束.代碼 is 結束代碼.護欄
        assert 果.結束.護欄原因 is 護欄原因.沒有紅可看
        assert "沒有紅可看" in 果.結束.原因, 果.結束.原因
        assert len(果.軌跡) == 4, "第二次綠就收，不該再退回測試員一次"
        assert [步.階段 for 步 in 果.軌跡] == [
            階段代碼.測試,
            階段代碼.驗證紅,
            階段代碼.測試,
            階段代碼.驗證紅,
        ]
        assert len(人["實作"].收到) == 0, "一路沒有紅，實作員不該被叫起來"

