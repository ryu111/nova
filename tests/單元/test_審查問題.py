"""`FOLLOW-UP:` 跟 `ISSUE:` 是兩個入口：後續發現不算退回，也不進連續審查護欄。

## 這支守什麼

審查員的視野是整份 diff，每一輪都挖得到下一層——那是它的本業，不是它的錯。
但今天它只有一個出口（`ISSUE:`），於是「範圍外但值得做」寫下去就是一次退回，
兩輪之後撞上 `連續審查要求修改門檻 = 2`，一條有進展的線被收成「無進展」。

分兩個入口之後，**退回這條路上 `FOLLOW-UP:` 等於不存在**：

- 剖析那一格：`讀審查問題列` 只認 `^ISSUE:`，`FOLLOW-UP:` 一條都吃不進去。
- 讀出那一格：`讀後續發現` 讀得出後續條目，識別碼跟內容綁定，重複的算同一個
  （多輪重講同一條只落一張票，靠的就是它）。
- 護欄那一格：連續要求修改的計數只數帶 `ISSUE:` 的那幾輪。

第三格是純函式，所以測得動；它不是唯一那道防線（建步驟結果時就把
「`CHANGES-REQUESTED` 卻 0 條 `ISSUE:`」收成 `沒給結論`），留著是為了不讓那一格變成唯一。

## 這支**不**守什麼

- 不碰 `讀審查判定`：判定的唯一來源仍然是最後一個 `REVIEW: X`，`FOLLOW-UP:` 影響不了它。
- 不把門檻調高。這張票治的是「數錯了東西」，不是「數得太嚴」。
- 不管後續條目的種類標籤——現在只有自由文字。

## 負控

把 `src/nova/契約/審查問題.py` 的 `_問題樣式` 放寬成也吃 `FOLLOW-UP:`
（兩個入口併回一個，也就是今天的病），「ISSUE 只算 ISSUE」那一格要紅。
登記在 `tests/負控/登記們/審查範圍.py`。
"""

from collections.abc import Callable

import pytest

from nova.契約.審查問題 import 問題數量上限, 問題種類, 讀審查問題列, 讀後續發現
from nova.契約.工作流 import 審查判定, 步驟結果, 終局, 階段代碼
from nova.迴圈.狀態機 import 連續審查要求修改

#: 一段同時帶退回條目與後續條目的審查回覆。兩種入口混在同一份回覆裡是常態。
_一份混著兩種條目的回覆 = (
    "REVIEW: CHANGES-REQUESTED\n"
    "ISSUE: [impl] 空輸入沒處理\n"
    "FOLLOW-UP: src/nova/載體/收件.py:118 讀出驗收與讀出範圍可以收成一個掃描器\n"
    "FOLLOW-UP: docs/設計/10-目標長什麼樣.md:42 四欄的說明該補一個範圍的例子\n"
)


def _ISSUE只算ISSUE() -> None:
    """`讀審查問題列` 一條 `FOLLOW-UP:` 都不准吃進去。"""
    問題列 = 讀審查問題列(_一份混著兩種條目的回覆)

    assert len(問題列) == 1, (
        f"`FOLLOW-UP:` 被算成退回條目了（讀出 {len(問題列)} 條）"
        "——兩個入口併回一個，範圍外的發現又變成一次退回"
    )
    assert 問題列[0].種類 is 問題種類.實作
    assert 問題列[0].證據 == "空輸入沒處理"


def _FOLLOW_UP讀得出來() -> None:
    """`讀後續發現` 讀得出後續條目，識別碼跟內容綁定、重複的算同一個。"""
    後續們 = 讀後續發現(_一份混著兩種條目的回覆)

    assert len(後續們) == 2, f"後續條目該讀出兩條，實際 {len(後續們)} 條"
    assert [一條.證據 for 一條 in 後續們] == [
        "src/nova/載體/收件.py:118 讀出驗收與讀出範圍可以收成一個掃描器",
        "docs/設計/10-目標長什麼樣.md:42 四欄的說明該補一個範圍的例子",
    ], "後續條目的證據要照原文順序原樣留著——file:line 是人回頭查的唯一線索"

    重講一次 = 讀後續發現(
        "FOLLOW-UP: src/nova/載體/收件.py:118 讀出驗收與讀出範圍可以收成一個掃描器\n"
        "FOLLOW-UP: 另一件事\n"
    )
    assert 重講一次[0].識別碼 == 後續們[0].識別碼, (
        "同一條後續在另一輪重講時識別碼變了——那樣同一件事會落成好幾張票"
    )
    assert 重講一次[1].識別碼 != 後續們[0].識別碼, "不同內容的後續識別碼不准撞在一起"


def _護欄不數FOLLOW_UP() -> None:
    """連兩輪要求修改、但一條 `ISSUE:` 都沒有時，連續審查護欄不准生效。"""
    只有後續的證據 = "REVIEW: CHANGES-REQUESTED\nFOLLOW-UP: 這一段之後可以抽成共用函式\n"
    一步 = 步驟結果(
        階段=階段代碼.審查,
        終局=終局.成功,
        判準綠=None,
        證據=只有後續的證據,
        審查結論=審查判定.要求修改,
    )

    assert 連續審查要求修改((一步, 一步)) is None, (
        "護欄把只帶 `FOLLOW-UP:` 的那幾輪也數進去了"
        "——一條有進展的線會被收成「無進展」，而範圍外的發現本來就不是退回"
    )


def _後續條目有上限() -> None:
    """一份回覆塞幾十條 `FOLLOW-UP:`，讀出來的仍然是有界的那麼多。

    上限跟 `ISSUE:` 同一個（`問題數量上限`），理由也同一條：**下游會照著落票**，
    一次落幾十張的收件匣等於沒有收件匣。
    """
    塞爆的回覆 = "\n".join(f"FOLLOW-UP: 第 {n} 條可以之後再做" for n in range(問題數量上限 * 3))

    後續們 = 讀後續發現(塞爆的回覆)

    assert len(後續們) == 問題數量上限, (
        f"後續條目沒有上限（讀出 {len(後續們)} 條，上限 {問題數量上限}）"
        "——一輪審查就把幾十張票倒進收件匣，人再也看不出哪張要緊"
    )


#: id 是 ASCII 的，**這不是隨手取的**：pytest 會把非 ASCII 的參數化 id 轉義成
#: `\uXXXX`，那樣負控登記就指不到「該紅的是哪一格」。
_三格: tuple[tuple[str, Callable[[], None]], ...] = (
    ("issue", _ISSUE只算ISSUE),
    ("followup", _FOLLOW_UP讀得出來),
    ("guard", _護欄不數FOLLOW_UP),
    ("limit", _後續條目有上限),
)


