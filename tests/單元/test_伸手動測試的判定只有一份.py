"""「這一步是不准動測試的階段動了測試檔嗎」這個判定只准有一份。

現在是兩份同名、簽章卻不同的拷貝各活各的：
`迴圈/狀態機.py` 的 `_伸手動了測試(定義, 結果)`（轉移用它決定要不要接回測試階）、
`迴圈/工作流.py` 的 `_伸手動了測試(階段, 動了)`（再犯計數 `_這輪之前伸手過`、
第二次收 4 的 `_動了測試就收護欄`、以及「這一步不算數」的提示遮蔽
`_濾掉伸手那幾步` 都問它）。兩份各自有測試把行為釘死，**卻沒有任何測試
斷言兩份是同一份**——改一份、更新它自己的測試，另一份照樣綠。

走散的後果不是紅燈而是**政策分岔**：譬如哪天 `不准動測試的階段` 或
「什麼叫動過」的判準在狀態機那份放寬了，工作流那份沒跟上，就會出現
「轉移不當它伸手（照原表往前走）、runner 卻算它再犯（收 4）」這種
兩邊各說各話的收場；反過來則是**靜默放行**：收 4 那條路永遠數不到第二次。

這支測試守三層：
1. `test_判定全樹只有一份定義而且住在狀態機`：**機制**——原始碼層只准有一個
   `def 伸手動了測試`。家選狀態機，因為 `不准動測試的階段` 這份知識本來就住在
   那裡，而 `迴圈/工作流.py` 已經 import 它；反向（判定住工作流、狀態機去讀）
   會讓狀態機 import runner，是個回頭的相依。
2. `test_兩個呼叫端手上的是同一個函式物件`：**接線**——工作流不准自己再包一份，
   要 import 狀態機那份來用。
3. `test_共用的判定認得出哪幾階不准動測試`：**行為**——這也是負控要打的地方
   （把留下來那份的 `不准動測試的階段` 縮成只有實作，它要紅）。

簽章取 `(階段代碼, 動過的測試檔)` 這個最小原料：狀態機那側手上是
`階段定義` 與 `步驟結果`、工作流那側是散的兩個值，只有拆到最小原料兩邊才餵得進去。
"""

import ast
from collections.abc import Callable
from pathlib import Path
from typing import cast

import pytest

import nova
from nova.契約.工作流 import 階段代碼
from nova.迴圈 import 工作流 as 工作流模組
from nova.迴圈 import 狀態機 as 狀態機模組

#: 判定的名字（去掉底線比對，免得「有沒有 `_`」這種瑣事擋住定義只有一份的斷言）。
判定名 = "伸手動了測試"

#: 判定該住的家，相對 `src/nova`。
該住的家 = Path("迴圈/狀態機.py")

#: 單元層只要一個檔名；真的 git 是整合測試的事。
被伸手動的測試檔 = "tests/單元/test_被伸手動的.py"


def _原始碼裡定義判定的地方() -> list[str]:
    """全 `src/nova` 掃一遍，回「定義了這個判定的檔:函式名」清單（相對路徑）。"""
    套件根 = Path(nova.__file__).parent
    定義處: list[str] = []
    for 檔 in sorted(套件根.rglob("*.py")):
        樹 = ast.parse(檔.read_text(encoding="utf-8"))
        定義處.extend(
            f"{檔.relative_to(套件根).as_posix()}:{節點.name}"
            for 節點 in ast.walk(樹)
            if isinstance(節點, (ast.FunctionDef, ast.AsyncFunctionDef))
            and 節點.name.lstrip("_") == 判定名
        )
    return 定義處


type 伸手判定 = Callable[[階段代碼, tuple[str, ...]], bool]


def _拿共用判定() -> 伸手判定:
    """從狀態機拿共用判定；還沒抽出來就當場紅，說清楚缺的是什麼。"""
    判定 = getattr(狀態機模組, 判定名, None)
    if not callable(判定):
        pytest.fail(
            f"`nova.迴圈.狀態機` 沒有公開的 `{判定名}`："
            "轉移與 runner 的再犯計數要問同一個純函式，它得有個跨模組叫得到的名字"
        )
    return cast(伸手判定, 判定)


def test_判定全樹只有一份定義而且住在狀態機() -> None:
    """`def 伸手動了測試` 在 `src/nova` 底下只准出現一次，而且在 `迴圈/狀態機.py`。"""
    定義處 = _原始碼裡定義判定的地方()
    assert len(定義處) == 1, (
        f"「不准動測試的階段動了測試檔嗎」只准有一份定義，現在有 {len(定義處)} 份："
        f"{'、'.join(定義處)}——兩份同名不同簽章，改一份改不到另一份"
    )
    檔, _, 函式名 = 定義處[0].partition(":")
    assert 檔 == 該住的家.as_posix(), (
        f"判定該住 `{該住的家.as_posix()}`（`不准動測試的階段` 在那裡），現在住在 `{檔}`"
    )
    assert not 函式名.startswith("_"), (
        f"`{函式名}` 是跨模組共用的判定（`迴圈/工作流.py` 要 import 它），不准掛私有名"
    )


def test_兩個呼叫端手上的是同一個函式物件() -> None:
    """工作流不准自己再包一份：它命名空間裡的判定要**就是**狀態機那個物件。"""
    共用判定 = _拿共用判定()
    工作流那份 = getattr(工作流模組, 判定名, None)
    assert 工作流那份 is 共用判定, (
        "`迴圈/工作流.py` 要 `from nova.迴圈.狀態機 import 伸手動了測試` 用同一份，"
        f"現在拿到的是 {工作流那份!r}"
    )


@pytest.mark.parametrize(
    ("階段", "動過的測試檔", "期望"),
    [
        (階段代碼.實作, (被伸手動的測試檔,), True),
        (階段代碼.重構, (被伸手動的測試檔,), True),
        (階段代碼.實作, (), False),
        (階段代碼.重構, (), False),
        (階段代碼.測試, (被伸手動的測試檔,), False),
        (階段代碼.審查, (被伸手動的測試檔,), False),
        (階段代碼.驗證綠, (被伸手動的測試檔,), False),
    ],
)
def test_共用的判定認得出哪幾階不准動測試(
    階段: 階段代碼,
    動過的測試檔: tuple[str, ...],
    期望: bool,
) -> None:
    """實作與重構動了就是伸手；測試員那一階的工作就是寫測試，動了不算伸手。"""
    共用判定 = _拿共用判定()
    assert 共用判定(階段, 動過的測試檔) is 期望, f"`{判定名}({階段}, {動過的測試檔})` 該是 {期望}"
