"""`結束.護欄原因` 那一格要標死列舉，不是任意字串。

**要擋的是這個反例**：列舉曾經住在 `契約.節點`，而 `契約.節點` 反過來
import `契約.工作流`，於是 `結束` 不敢 import 它（會繞成環），欄位只好弱化成
`str | None`。那樣拼錯值（`"stagantion"`、`"acceptance_failed"`）型別檢查一個字
都不會說，等它流到成果帳、流到 `nova 線` 的看板上，才變成一格讀不懂的原因——
而那時候已經沒人記得那一輪發生什麼事。

所以這組**跨層共用**的列舉住在不會繞回來的落點（`契約.護欄`：`契約.工作流` 與
`契約.節點` 都 import 得到它、它誰也不 import），`結束.護欄原因` 標的是它本人。
`契約.工作流` 沒有 `from __future__ import annotations`，註解是建類別時就求值的，
所以 `get_type_hints` 拿得到列舉本身，就等於那個 import 真的成立、環真的不在。

換落點不准改行為：識別字是中文、值是那組 ASCII，`結束` 身上放進去還是流得出
同一個字串（`StrEnum`），因為成果帳的 JSON 就是照這個字寫的。
"""

from typing import get_type_hints

from nova.契約.工作流 import 結束, 結束代碼
from nova.契約.護欄 import 護欄原因


def test_結束的護欄原因標的是列舉不是任意字串() -> None:
    提示 = get_type_hints(結束)

    assert 提示["護欄原因"] == 護欄原因 | None, (
        f"`結束.護欄原因` 標成 {提示['護欄原因']}：拼錯的值不會被型別檢查攔下來，"
        "帳上就會出現讀不懂的原因"
    )

    #: 搬家不准動序列化：放進去的是列舉成員，拿出來還是那組 ASCII 值。
    收場 = 結束(代碼=結束代碼.護欄, 原因="連三輪雜湊沒變", 護欄原因=護欄原因.無進展)
    assert 收場.護欄原因 == "stagnation"
    assert str(收場.護欄原因).isascii()
