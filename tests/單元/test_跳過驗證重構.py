@pytest.mark.parametrize("情境", list(_情境們.values()), ids=list(_情境們))
def test_跳過那一輪判準沒被叫到而且軌跡沒有verify_refactor(情境: _情境, tmp_path: Path) -> None:
    """守：跳過真的省下那一次判準、只在重構走綠出口時發生，而且去處照表查。

    工作目錄裡先放一個檔，`驗證綠` 綠掉時的那棵樹才是有內容的一棵；
    假重構員動不動它由腳本決定，所以「樹沒變」是結構上的事實，不是講出來的。

    五格各守一句：沒動過就跳；重構員掛了就照走中止那條邊，不准被那句自由文字蓋掉；
    改過又退乾淨也算沒變（比的是最近一次綠掉的 `驗證綠`，不是上一步）；
    **兩輪重構都沒動過樹時，跳過之後接著跑的是 `審查` 而不是任何護欄**——
    「退回去的模型階段零改動」只擋得下**判準**，跳過 `驗證重構` 之後目前那一階是模型階，
    沒有判準要跑，就沒有重播可擋；
    跳過的去處是 `驗證重構` 那一階在**這張表**上的綠出口。
    """
    (tmp_path / "本來就在的東西.py").write_text("原本的樹\n", encoding="utf-8")

    果, 判準跑過幾次, 跳過了哪幾階 = _跑一輪(情境, tmp_path)

    assert 果.結束.代碼 is 情境.期望結束, 果.結束.原因
    assert tuple(步.階段 for 步 in 果.軌跡) == 情境.期望軌跡, (
        "被跳過的那一階不准進軌跡，沒被跳過的一階也不准消失"
        "——`卡住了` 用軌跡索引去查工作區雜湊，錯位會讓它判錯人"
    )
    assert len(判準跑過幾次) == 情境.期望判準次數, (
        f"判準被叫了 {len(判準跑過幾次)} 次，期望 {情境.期望判準次數} 次"
        "——省下來的那一次全測試才是這張票的全部意義，只看軌跡看不出來"
    )
    assert tuple(跳過了哪幾階) == 情境.期望跳過, (
        "跳過一階要記一筆帳而且要指名跳的是哪一階；沒跳的時候更不准記"
        "——「沒跳過」與「跳了沒記」在帳本上長得一樣"
    )
