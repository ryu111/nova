@dataclass(frozen=True)
class _這一次的回應:
    """假角色被叫到第 n 次時給的東西：一句話、一種終局，外加它動不動工作目錄。"""

    文字: str
    終局: 終局 = 終局.成功
    動手改: Callable[[Path], None] | None = None


class _假角色:
    """照腳本回話的角色，腳本用完就一直回最後一句。零 LLM、零子程序、零 token。"""

    def __init__(self, 名稱: str, *腳本: _這一次的回應) -> None:
        self.名稱 = 名稱
        self.腳本 = 腳本 or (_這一次的回應("做好了"),)
        self.被叫過幾次 = 0

    def 做(self, 提示: str, *, 工作目錄: Path | None = None) -> 回應:
        del 提示
        這次 = self.腳本[min(self.被叫過幾次, len(self.腳本) - 1)]
        self.被叫過幾次 += 1
        if 這次.動手改 is not None and 工作目錄 is not None:
            這次.動手改(工作目錄)
        return 回應(
            文字=這次.文字,
            終局=這次.終局,
            失敗代碼=失敗代碼.無 if 這次.終局 is 終局.成功 else 失敗代碼.認證,
            原始結束碼=0 if 這次.終局 is 終局.成功 else 1,
            對話識別碼=None,
            用量=用量(輸入token=1, 輸出token=1),
        )


def _寫一個檔(檔名: str) -> Callable[[Path], None]:
    """重構員真的動了工作目錄：多一個檔，樹就不是驗過綠的那一棵了。"""

    def 動手(工作目錄: Path) -> None:
        (工作目錄 / 檔名).write_text("被重構員加進來的東西\n", encoding="utf-8")

    return 動手


def _刪掉那個檔(檔名: str) -> Callable[[Path], None]:
    """重構員把自己的改動退乾淨：樹回到 `驗證綠` 綠掉時的那一棵。"""

    def 動手(工作目錄: Path) -> None:
        (工作目錄 / 檔名).unlink(missing_ok=True)

    return 動手


_退乾淨用的檔 = "重構員的半成品.py"

#: 假表：`驗證重構` 的綠出口不是 `審查`。跳過的去處要照表查，寫死就會走到別人的邊。
_假表上的收工 = 結束(結束代碼.完成, "假表：驗證重構綠了就收工")


def _驗證重構綠了就收工的假表() -> tuple[階段定義, ...]:
    """把 `驗證重構` 的綠出口換成「當場收工」，其餘照舊——`跑工作流` 吃得下自訂表。"""
    return tuple(
        replace(定義, 出口={**定義.出口, 出口標籤.綠: _假表上的收工})
        if 定義.代碼 is 階段代碼.驗證重構
        else 定義
        for 定義 in TDD階段表
    )


@dataclass(frozen=True)
class _情境:
    """一輪假工作流：餵什麼腳本、走哪張表、該長出什麼樣的軌跡與帳。"""

    重構員腳本: tuple[_這一次的回應, ...]
    判準腳本: tuple[tuple[判準終局, str], ...]
    期望軌跡: tuple[階段代碼, ...]
    期望判準次數: int
    期望跳過: tuple[階段代碼, ...]
    期望結束: 結束代碼
    階段表: tuple[階段定義, ...] = field(default_factory=lambda: TDD階段表)


def _跑一輪(情境: _情境, 工作目錄: Path) -> tuple[工作流結果, list[判準終局], list[階段代碼]]:
    """用假角色與假判準跑一輪，回收「結果、判準被叫的每一次、跳過了哪幾階」。"""
    判準跑過幾次: list[判準終局] = []
    待跑 = list(情境.判準腳本)

    def 跑判準(_: 任務) -> tuple[判準終局, str]:
        終, 證據 = 待跑.pop(0) if 待跑 else (判準終局.綠, "假判準")
        判準跑過幾次.append(終)
        return 終, 證據

    執行 = 建TDD執行器(
        角色表={
            階段代碼.測試: _假角色("測試"),
            階段代碼.實作: _假角色("實作"),
            階段代碼.重構: _假角色("重構", *情境.重構員腳本),
            階段代碼.審查: _假角色("審查", _這一次的回應(_過關的審查回覆)),
        },
        跑判準=跑判準,
        篩選指定測試=可作指定pytest目標,
    )
    跳過了哪幾階: list[階段代碼] = []
    果 = 跑工作流(
        任務(描述="讓 X 變成 Y", 工作目錄=工作目錄),
        執行一步=執行,
        階段表=情境.階段表,
        記跳過=跳過了哪幾階.append,
    )
    return 果, 判準跑過幾次, 跳過了哪幾階


