"""重構員回報「無需重構」而且工作區雜湊沒變時，`驗證重構` 那一次不必再跑。

守的是三件事：

1. **判準要有結構證據。** 回報裡那句「無需重構」只是意圖聲明，模型可以一邊那樣寫
   一邊改了三個檔（提示裡的規矩是懇求，不是保證）。所以准跳的條件是
   **字串成立而且兩個雜湊都拿得到、而且相同**——雜湊那一半才是保證
   （CLAUDE.md 硬規則第 2 條：不得以「模型說完成了」當停止條件）。
2. **跳過只發生在重構真的走綠出口的時候。** 重構員掛掉（`確定失敗`）時那一句
   自由文字什麼都不代表，該走的是中止那條邊；跳過不准蓋掉別的收場。
3. **迴圈真的跳得過去，而且跳到表上的去處。** 省下來的是那一次全測試
   （約兩分鐘＋閘鎖排隊），所以要看到判準**少被叫一次**；只看軌跡看不出這件事。
   去處照 `階段表` 查（`驗證重構` 的綠出口），不寫死；被跳過的那一階不准進軌跡，
   而跳過這件事要記得下來。

跳過的是「這一次不用跑」，不是「這一階不需要存在」——重構員真的動了東西時它照跑。
"""

