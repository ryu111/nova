"""建構列一定要指名型號，不能靠 `/v1/models` 清單的順序。

`本地.py` 的 `_第一個型號()` 註解寫著「**不寫死型號**——寫死的話換一顆模型
就要改 nova 的原始碼」。出發點對，但它拿的是清單的**第一個**——

    Ornith-1.5-9B-MLX-4bit   ← 排第一，所以建構列實際拿到的是它
    Ornith-1.5-9B-MLX-8bit
    Qwen3.8-27B-4bit
    Qwen3.8-27B-8bit         ← 想要的是這顆
    Qwen3.8-27B-MTP-8bit

**「清單第一個」不是一個決定，是一個意外。** 端點多下載一顆模型、
或它換一個排序，nova 的建構列就靜靜地換了一顆腦，而帳本看不出來
（帳本只記家族名，不記型號）。

型號該在**派工表**裡指名，跟 `推理` 列指名 `codex高階模型` 是同一招：
它是**資料**不是程式碼，換模型改一行資料，不必動 `本地.py`。
"""

from nova.契約.派工 import 工作種類
from nova.載體.派工表 import 怎麼派


class Test建構列不准靠清單順序:
    def test_建構列一定要指名型號(self) -> None:
        """不指名＝拿到 `/v1/models` 的第一個，那是意外不是決定。"""
        assert 怎麼派(工作種類.建構).模型 is not None, (
            "建構列沒有指名型號——本地腦會拿到 /v1/models 清單的第一個，"
            "端點多下載一顆模型就會靜靜換腦，而帳本只記家族名看不出來"
        )

    def test_建構列指名的是27B那顆(self) -> None:
        """9B 撞回合上限 19 次燒掉 193 萬 token 零產出；27B 才是建構列要的。"""
        assert 怎麼派(工作種類.建構).模型 == "Qwen3.8-27B-8bit"


class Test指名不會汙染鏈上第二家:
    def test_建構列第一家是local(self) -> None:
        """型號只給鏈上第一家（`接力.py` 換家時清掉）。

        指名的型號屬於 local 的命名空間，所以它必須排第一——
        排第二的話 `agy` 會先拿到一個它不認得的型號名。
        """
        assert 怎麼派(工作種類.建構).腦們[0] == "local"
