from nova.迴圈.角色提示 import 實作員, 審查員, 測試員, 重構員


class 假腦:
    """只記住工廠交給它的派法；這支測試不應該真的呼叫模型。"""

    名稱 = "測試用假腦"

    def __init__(self, 派法: 派法) -> None:
        """記住建腦收到的派法。"""
        self.派法 = 派法

    def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
        訊息 = f"角色工廠測試不該呼叫模型：{提示}，選項={選項}"
        raise AssertionError(訊息)


def _建假腦(派法: 派法) -> 語言模型:
    return 假腦(派法)


def _取角色(角色表: Mapping[str, 角色], 識別碼: str) -> 固定提示角色:
    return cast(固定提示角色, 角色表[識別碼])


def test_研究角色不改變_TDD_角色表() -> None:
    """研究工作流換一組角色時，TDD 的身分、提示與派法仍維持原樣。"""
    派工描述欄位 = "什麼時候派我"
    TDD藍圖 = (
        角色藍圖(
            識別碼="測試",
            名稱="測試員",
            什麼時候派我="需求要先被寫成一支會紅的測試時",
            系統提示=測試員,
            派法=怎麼派(工作種類.例行),
            權限=權限.可編輯,
            逾時秒=1800.0,
        ),
        角色藍圖(
            識別碼="實作",
            名稱="實作員",
            什麼時候派我="已經看見紅測試、可以補最少實作時",
            系統提示=實作員,
            派法=怎麼派(工作種類.例行),
            權限=權限.可編輯,
            逾時秒=1800.0,
        ),
        角色藍圖(
            識別碼="重構",
            名稱="重構員",
            什麼時候派我="測試全綠、可以整理但不能改行為時",
            系統提示=重構員,
            派法=怎麼派(工作種類.例行),
            權限=權限.可編輯,
            逾時秒=1800.0,
        ),
        角色藍圖(
            識別碼="審查",
            名稱="審查員",
            什麼時候派我="重構再次驗證通過、需要另一顆腦挑毛病時",
            系統提示=審查員,
            派法=怎麼派(工作種類.推理),
            權限=權限.唯讀,
            逾時秒=1800.0,
        ),
    )
    研究藍圖 = (
        角色藍圖(
            識別碼="搜尋",
            名稱="搜尋員",
            什麼時候派我="需要找資料並留下可追溯出處時",
            系統提示="你是研究工作流裡的搜尋員。",
            派法=怎麼派(工作種類.例行),
            權限=權限.唯讀,
            逾時秒=1800.0,
        ),
        角色藍圖(
            識別碼="對抗",
            名稱="對抗員",
            什麼時候派我="需要主動找反例、漏洞與相反證據時",
            系統提示="你是研究工作流裡的對抗員。",
            派法=怎麼派(工作種類.推理),
            權限=權限.唯讀,
            逾時秒=1800.0,
        ),
        角色藍圖(
            識別碼="整合",
            名稱="整合員",
            什麼時候派我="各分支都有結果、需要整理成有來源的結論時",
            系統提示="你是研究工作流裡的整合員。",
            派法=怎麼派(工作種類.推理),
            權限=權限.唯讀,
            逾時秒=1800.0,
        ),
    )

    TDD角色表 = 建角色表(TDD藍圖, 建腦=_建假腦, 組角色=固定提示角色)
    研究角色表 = 建角色表(研究藍圖, 建腦=_建假腦, 組角色=固定提示角色)

    assert set(TDD角色表) == {"測試", "實作", "重構", "審查"}
    assert set(研究角色表) == {"搜尋", "對抗", "整合"}
    assert [_取角色(TDD角色表, 識別碼).系統提示 for 識別碼 in ("測試", "實作", "重構", "審查")] == [
        測試員,
        實作員,
        重構員,
        審查員,
    ]
    assert [_取角色(TDD角色表, 識別碼).名稱 for 識別碼 in ("測試", "實作", "重構", "審查")] == [
        "測試員",
        "實作員",
        "重構員",
        "審查員",
    ]
    assert [
        getattr(_取角色(TDD角色表, 識別碼), 派工描述欄位)
        for 識別碼 in ("測試", "實作", "重構", "審查")
    ] == [
        "需求要先被寫成一支會紅的測試時",
        "已經看見紅測試、可以補最少實作時",
        "測試全綠、可以整理但不能改行為時",
        "重構再次驗證通過、需要另一顆腦挑毛病時",
    ]
    assert [
        cast(假腦, _取角色(TDD角色表, 識別碼).腦).派法
        for 識別碼 in ("測試", "實作", "重構", "審查")
    ] == [藍圖.派法 for 藍圖 in TDD藍圖]
    assert [_取角色(研究角色表, 識別碼).系統提示 for 識別碼 in ("搜尋", "對抗", "整合")] == [
        "你是研究工作流裡的搜尋員。",
        "你是研究工作流裡的對抗員。",
        "你是研究工作流裡的整合員。",
    ]


def test_系統架構師只讀且不執行自己的決策() -> None:
    """架構師只能產出決策資料，不能寫 code 或越過 PlanWorker 執行它。"""
    角色表 = 建角色表(建系統架構師角色藍圖(怎麼派), 建腦=_建假腦, 組角色=固定提示角色)
    角色 = _取角色(角色表, "系統架構師")

    assert 角色.權限 is 權限.唯讀
    assert "不准寫 code" in 角色.系統提示
    assert "不准執行自己產的決策" in 角色.系統提示
    assert "PlanWorker" in 角色.什麼時候派我
    assert "只決定這次先做哪幾步" in 角色.什麼時候派我


def test_藍圖的模型與思考深度要傳進角色() -> None:
    """**這一支是負控逼出來的。**

    合併 #116（思考深度進派工表）之後，角色改走工廠這條路。
    把 `建角色` 裡的 `思考深度=藍圖.思考深度` 拿掉，**整套測試沒有一支紅**——
    因為既有的整合測試比對的是 CLI argv，而
    agy 的預設型號本來就叫 `gemini-3.7-flash-high`、
    codex 的預設推理強度本來就是 `max`，**兩家的預設剛好等於表裡的值**。

    所以那些測試證明得了「旗標有送到 CLI」，證明不了「送過去的值來自藍圖」。
    這一支在單元層直接比對，用的是**跟任何一家預設都不同的值**，
    所以拿掉接線它一定紅。
    """
    藍圖 = 角色藍圖(
        識別碼="測試",
        名稱="測試員",
        什麼時候派我="需求要先被寫成一支會紅的測試時",
        系統提示=測試員,
        派法=怎麼派(工作種類.例行),
        權限=權限.可編輯,
        逾時秒=1800.0,
        模型="某個不存在的型號",
        思考深度="xhigh",
    )

    角色 = cast(固定提示角色, 建角色(藍圖, 建腦=_建假腦, 組角色=固定提示角色))

    assert 角色.模型 == "某個不存在的型號"
    assert 角色.思考深度 == "xhigh", "藍圖說了深度，角色卻沒帶上——那一格等於不存在"
