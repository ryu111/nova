def _測試員這一輪動的樹(工作目錄: Path, 第幾次: int) -> None:
    """測試員每一輪各加一個檔：這兩輪之間的樹一定不一樣。"""
    (工作目錄 / f"測試員第{第幾次}輪.py").write_text(f"第 {第幾次} 批測試\n", encoding="utf-8")


def _實作員這一輪動的樹(工作目錄: Path, 第幾次: int) -> None:
    """前兩輪各加一個檔；第三輪把測試員第二輪加的檔收掉——樹回到上一次 `驗證綠` 那一棵。

    「雜湊回到舊值」是這支的前提：繞了一圈之後樹跟舊的一模一樣，
    可是中間的 `驗證紅` 真的跑過一次別的東西。
    """
    第三輪 = 3
    if 第幾次 < 第三輪:
        (工作目錄 / f"實作員第{第幾次}輪.py").write_text(f"第 {第幾次} 版實作\n", encoding="utf-8")
    else:
        (工作目錄 / "測試員第2輪.py").unlink()


def test_上上一步是別的判準時雜湊相等也不算重播(tmp_path: Path) -> None:
    """重播只認**緊鄰的回頭邊**：上上一步不是同一個判準時，雜湊相等照樣要跑那次判準。

    中間那個判準（`驗證紅`）是另一道指令、跑的是另一批測試，它拿到新的紅就是新資訊；
    「這棵樹上一次也紅過」不等於「這次判準跑不出新東西」。
    往回無限搜尋同一個判準會把這種繞路誤收成護欄，把一輪真的有進展的線攔在半路。
    """
    工作 = 任務(描述="繞一圈回到同一個判準", 工作目錄=tmp_path)
    既有測試的紅 = (
        "FAILED tests/單元/test_慣例.py::test_舊慣例\nFAILED tests/單元/test_慣例.py::test_舊介面"
    )
    驗證綠次數 = 0
    測試次數 = 0
    實作次數 = 0

    def 執行一步(
        定義: 階段定義,
        _任務: 任務,
        _軌跡: tuple[步驟結果, ...],
    ) -> 步驟結果:
        nonlocal 驗證綠次數, 測試次數, 實作次數
        del _任務, _軌跡
        if 定義.代碼 is 階段代碼.測試:
            測試次數 += 1
            _測試員這一輪動的樹(tmp_path, 測試次數)
        if 定義.代碼 is 階段代碼.實作:
            實作次數 += 1
            _實作員這一輪動的樹(tmp_path, 實作次數)
        if 定義.代碼 is 階段代碼.驗證紅:
            return 步驟結果(
                階段=定義.代碼,
                終局=終局.成功,
                判準綠=False,
                證據=f"FAILED tests/單元/test_新功能.py::test_第{測試次數}批",
            )
        if 定義.代碼 is 階段代碼.驗證綠:
            驗證綠次數 += 1
            # 前兩次紅在同一批既有測試 → 第二次退回測試員；第三次才是這支要守的那一次。
            綠了 = 驗證綠次數 >= 3  # noqa: PLR2004 —— 第三次 `驗證綠`
            return 步驟結果(
                階段=定義.代碼,
                終局=終局.成功,
                判準綠=綠了,
                證據="全綠" if 綠了 else 既有測試的紅,
            )
        return 步驟結果(
            階段=定義.代碼,
            終局=終局.成功,
            判準綠=None if 定義.種類 is 種類.模型 else 定義.期望綠,
            證據="這一階做完了",
        )

    結果 = 跑工作流(
        工作,
        執行一步=執行一步,
        停止=停止條件(最多步數=35, 最多token=10**9),
    )

    軌跡上的階段 = tuple(步.階段 for 步 in 結果.軌跡)
    assert 軌跡上的階段[:9] == (
        階段代碼.測試,
        階段代碼.驗證紅,
        階段代碼.實作,
        階段代碼.驗證綠,
        階段代碼.實作,
        階段代碼.驗證綠,
        階段代碼.測試,
        階段代碼.驗證紅,
        階段代碼.實作,
    ), "走位變了這支就沒在守原本那件事"
    assert 驗證綠次數 == 3, (  # noqa: PLR2004 —— 第三次 `驗證綠` 就是這支要守的那一次
        "上上一步是 `驗證紅`（另一個判準、另一批測試）不是同一個判準，"
        "這一次 `驗證綠` 不是重播，必須真的跑"
    )
    assert "重播" not in 結果.結束.原因


def _整棵樹的雜湊(工作目錄: Path) -> str:
    """把整棵樹（檔名＋內容）壓成一個字串，用來把「這段路上樹沒動過」寫成斷言。"""
    料 = sha256()
    for 檔 in sorted(工作目錄.rglob("*")):
        if 檔.is_file():
            料.update(str(檔.relative_to(工作目錄)).encode("utf-8"))
            料.update(檔.read_bytes())
    return 料.hexdigest()


