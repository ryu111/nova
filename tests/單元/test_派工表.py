"""派工表：哪一種工作派給誰，寫成資料而不是寫成提示。

使用者的策略原話是「多把工作交給 agy，需要動腦推理的給 sol max」。
**這句話寫在提示裡是懇求**——我會忘、會偷懶、會在趕時間的時候直接用手邊那顆。
寫成表加上會紅的測試，它才是保證。

判準（`docs/決策/0001-規則要住哪一層.md` 的第 ① 格）：這條寫得出會失敗的測試嗎？
寫得出來 → 它就不該待在提示裡。
"""

import pytest

from nova.契約.派工 import 工作種類
from nova.載體.模型.轉接 import codex高階模型, 家族, 高階模型們
from nova.載體.派工表 import 怎麼派


def test_每個工作種類都要有派法() -> None:
    """fail-closed：表裡沒有的種類不准猜一個預設出來。

    猜錯的代價是**每一次**都派錯家，而且沒有人會發現——
    輸出看起來一樣，只是慢、貴、或笨。
    """
    for 種 in 工作種類:
        assert 怎麼派(種).腦們, 種


def test_例行工作第一順位是agy() -> None:
    """使用者的策略：「多把工作交給 agy」。分擔 Claude 額度是這件事的目的。"""
    assert 怎麼派(工作種類.例行).腦們[0] == "agy"


def test_例行工作要有備援() -> None:
    """只有一顆的鏈不是接力，是單點故障。分擔額度的前提是「這顆不行換下一顆」。"""
    assert len(怎麼派(工作種類.例行).腦們) >= 2


def test_例行不准用高階模型() -> None:
    """高階模型慢又貴。拿它做例行工作是把「分擔額度」做成「加倍花錢」。"""
    assert 怎麼派(工作種類.例行).模型 not in 高階模型們


def test_推理工作要用sol() -> None:
    """使用者的策略：「需要動腦推理的給 sol max」。"""
    assert 怎麼派(工作種類.推理).模型 == codex高階模型


def test_推理一定要指名模型() -> None:
    """不指名就會拿到 codex 的預設（luna），等於這條策略沒生效——

    而且**看起來完全正常**：一樣會回答，只是沒有用到你要的那顆腦。
    """
    assert 怎麼派(工作種類.推理).模型 is not None


def test_推理走codex() -> None:
    """sol 只有 codex 有。鏈上放別家等於那條策略對它無效。"""
    assert 怎麼派(工作種類.推理).腦們[0] == "codex"


@pytest.mark.parametrize("種", list(工作種類))
def test_鏈上的家都是認得的(種: 工作種類) -> None:
    """打錯字的家名要當場紅，不要等真的去跑才 FileNotFoundError。"""
    認得的 = set(家族.__args__)  # type: ignore[attr-defined]
    assert set(怎麼派(種).腦們) <= 認得的


def test_工作種類的值是ASCII() -> None:
    """會出現在 CLI 旗標與帳本裡，跨程序。"""
    for 種 in 工作種類:
        assert 種.value.isascii(), 種


def test_例行與推理不准重疊() -> None:
    """**真跑才發現的約束。**

    工作流不給 `--用` 時兩邊都問派工表，而硬規則 5 的檢查是**保守的**：
    只要兩條鏈有任何一家重疊就擋下來（因為備援真的被叫到時，
    那一家就同時做了實作與審查）。

    原本例行的備援是 codex，而推理就是 codex——所以走派工表的工作流
    **一定**會被自己的護欄擋下，一步都跑不了。實測退出碼 2。

    備援改成 claude 之後四條既有策略全部保住，而且
    **codex 從此只做推理**——那正是「分擔額度」要的方向。
    """
    例行 = set(怎麼派(工作種類.例行).腦們)
    推理 = set(怎麼派(工作種類.推理).腦們)
    assert not (例行 & 推理), f"重疊的家：{例行 & 推理}——工作流會被自寫自評擋下"
