"""派工表：哪一種工作派給誰，寫成資料而不是寫成提示。

使用者的策略原話是「多把工作交給 agy，需要動腦推理的給 sol max」。
**這句話寫在提示裡是懇求**——我會忘、會偷懶、會在趕時間的時候直接用手邊那顆。
寫成表加上會紅的測試，它才是保證。

判準（`docs/決策/0001-規則要住哪一層.md` 的第 ① 格）：這條寫得出會失敗的測試嗎？
寫得出來 → 它就不該待在提示裡。
"""

import pytest

from nova.契約.派工 import 工作種類, 派法
from nova.載體.模型.轉接 import codex高階模型, 家族, 思考深度們, 高階模型們
from nova.載體.派工表 import 怎麼派


def test_每個工作種類都要有派法() -> None:
    """fail-closed：表裡沒有的種類不准猜一個預設出來。

    猜錯的代價是**每一次**都派錯家，而且沒有人會發現——
    輸出看起來一樣，只是慢、貴、或笨。
    """
    for 種 in 工作種類:
        assert 怎麼派(種).腦們, 種


def test_例行工作第一順位是claude() -> None:
    """**量到之後翻面的**：agy 便宜不成立，例行改 claude 打頭。

    2026-08-31 三格實驗（記在 `docs/負控紀錄.md` 旁的觀察）：agy 跑真任務單階
    375,061／410,294 input token，claude 同一份工作約 8,600——**46 倍**。
    原因不是 CLI 把工作區打包（空目錄 13,720 vs nova 目錄 13,726，只差 6 個），
    是模型自己在工具迴圈裡選擇讀滿 repo。

    在角色提示教會 agy 怎麼找之前，例行的第一順位是 claude。
    agy 留在備援，額度耗盡時仍然接得住。
    """
    assert 怎麼派(工作種類.例行).腦們[0] == "claude"


def test_例行工作要有備援() -> None:
    """只有一顆的鏈不是接力，是單點故障。分擔額度的前提是「這顆不行換下一顆」。"""
    assert len(怎麼派(工作種類.例行).腦們) >= 2


def test_例行不准用高階模型() -> None:
    """高階模型慢又貴。拿它做例行工作是把「分擔額度」做成「加倍花錢」。"""
    assert 怎麼派(工作種類.例行).模型 not in 高階模型們


def test_推理工作要用sol() -> None:
    """使用者的策略：「需要動腦推理的給 sol max」。"""
    assert 怎麼派(工作種類.推理).模型 == codex高階模型


def test_推理一定要指名模型() -> None:
    """不指名就會拿到 codex 的預設（luna），等於這條策略沒生效——

    而且**看起來完全正常**：一樣會回答，只是沒有用到你要的那顆腦。
    """
    assert 怎麼派(工作種類.推理).模型 is not None


def test_推理走codex() -> None:
    """sol 只有 codex 有。鏈上放別家等於那條策略對它無效。"""
    assert 怎麼派(工作種類.推理).腦們[0] == "codex"


@pytest.mark.parametrize("種", list(工作種類))
def test_鏈上的家都是認得的(種: 工作種類) -> None:
    """打錯字的家名要當場紅，不要等真的去跑才 FileNotFoundError。"""
    認得的 = set(家族.__args__)  # type: ignore[attr-defined]
    assert set(怎麼派(種).腦們) <= 認得的


def test_工作種類的值是ASCII() -> None:
    """會出現在 CLI 旗標與帳本裡，跨程序。"""
    for 種 in 工作種類:
        assert 種.value.isascii(), 種


def test_推理工作要有備援() -> None:
    """**燒掉三輪才發現的洞。**

    排程的 argv 是 `nova 工作流 --從收件匣`，兩個腦旗標都不帶，
    所以審查階段問派工表拿到推理那一列。那一列曾經是單鏈 `("codex",)`——
    codex 額度一耗盡，每一輪都會**照劇本**跑完前三階、燒掉幾十萬 token，
    然後死在 review。三輪 aborted 的死因都是這個，不是巧合。

    單點故障不會顯示成「設定錯了」，會顯示成「工作做到一半沒收尾」。

    家族名重疊**不是**擋下的理由（`#140`）：判準是對話不是家族名，
    三家不給續接時本來就都是新對話，`固定提示角色` 連續接欄位都沒有。
    """
    assert len(怎麼派(工作種類.推理).腦們) >= 2


def test_派法必須明確指定思考深度() -> None:
    """決策 0002：把「你必須記得的事」變成「你不得不傳的參數」。

    不給預設值，逼每一次定義派法都要想清楚這件事該動多少腦。
    """
    with pytest.raises(TypeError):
        派法(腦們=("agy",))  # type: ignore[call-arg]


def test_每一格都說得出思考深度() -> None:
    """每一種工作都要明確指定思考深度，不吃黑箱預設。"""
    for 種 in 工作種類:
        assert 怎麼派(種).思考深度 in 思考深度們, 種


def test_例行工作的思考深度是high() -> None:
    """使用者的策略：例行（agy 打頭、claude 備援）用 high。"""
    assert 怎麼派(工作種類.例行).思考深度 == "high"


def test_例行不准用max() -> None:
    """codex 預設是 max，例行用 max 會每一次都在用最貴的檔位。"""
    assert 怎麼派(工作種類.例行).思考深度 != "max"


def test_推理工作的思考深度是max() -> None:
    """使用者的策略：「需要動腦推理的給 sol max」。"""
    assert 怎麼派(工作種類.推理).思考深度 == "max"
