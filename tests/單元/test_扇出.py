def test_最大並行數限制同時進行中的分支數(monkeypatch: pytest.MonkeyPatch) -> None:
    工作 = (_工作("甲"), _工作("乙"), _工作("丙"))
    放行 = Event()
    第二顆已開始 = Event()
    第三顆已開始 = Event()
    鎖 = Lock()
    開始數 = 0
    目前同時數 = 0
    峰值同時數 = 0
    結果們: list[扇出結果[str]] = []
    錯誤們: list[Exception] = []

    def 開不限池(*, max_workers: int) -> 真執行池:
        del max_workers
        return 真執行池(max_workers=len(工作))

    monkeypatch.setattr("nova.迴圈.扇出.ThreadPoolExecutor", 開不限池)

    def 執行一顆(工作項: 分支工作[str, None], _: 節點上下文) -> 節點成功[str]:
        nonlocal 開始數, 目前同時數, 峰值同時數
        with 鎖:
            開始數 += 1
            目前同時數 += 1
            峰值同時數 = max(峰值同時數, 目前同時數)
            if 開始數 == 2:
                第二顆已開始.set()
            if 開始數 == 3:
                第三顆已開始.set()
        try:
            assert 放行.wait(timeout=2.0), "分支沒有被測試放行"
            return 節點成功(產出=工作項.輸入, 證據=(), 用量=None)
        finally:
            with 鎖:
                目前同時數 -= 1

    def 跑扇出() -> None:
        try:
            結果們.append(
                執行扇出(
                    工作,
                    執行一顆=執行一顆,
                    上下文=_上下文(),
                    政策=_政策(
                        必要分支=frozenset(工作項.分支 for 工作項 in 工作),
                        設定=_政策設定(
                            最大分支數=3,
                            最大並行數=2,
                            最少成功數=3,
                            階段最多token=300,
                            最多呼叫=3,
                        ),
                    ),
                )
            )
        except Exception as 錯:
            錯誤們.append(錯)

    執行緒 = Thread(target=跑扇出)
    執行緒.start()
    try:
        assert 第二顆已開始.wait(timeout=2.0), "第二個並行分支沒有開始"
        assert not 第三顆已開始.wait(timeout=0.05), "超過並行上限的第三顆已經開始"
        with 鎖:
            assert 峰值同時數 == 2
    finally:
        放行.set()
        執行緒.join(timeout=2.0)

    assert not 執行緒.is_alive(), "扇出 runner 沒有在分支放行後結束"
    assert 錯誤們 == []
    assert len(結果們) == 1
    assert 結果們[0].終局 is 結果代碼.成功
    assert 結果們[0].缺口 == ()


