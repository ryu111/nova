def _跑兩個分支(
    甲: 節點結果[str],
    乙: 節點結果[str],
) -> 扇出結果[str]:
    工作 = (_工作("甲"), _工作("乙"))
    回應 = {工作[0].分支: 甲, 工作[1].分支: 乙}

    def 執行一顆(工作項: 分支工作[str, None], _: 節點上下文) -> 節點結果[str]:
        return 回應[工作項.分支]

    return 執行扇出(
        工作,
        執行一顆=執行一顆,
        上下文=_上下文(),
        政策=_政策(必要分支=frozenset(回應)),
    )


def test_必要分支未全部回來前不呼叫整合() -> None:
    """屏障必須等所有必要分支回來，才把結果交給整合。"""
    工作 = (_工作("甲"), _工作("乙"))
    回來順序: list[分支識別碼] = []
    呼叫次數 = 0
    鎖 = Lock()
    第一顆回來 = Event()
    放行第二顆 = Event()
    整合收到: list[扇出結果[str]] = []

    def 執行一顆(工作項: 分支工作[str, None], _: 節點上下文) -> 節點成功[str]:
        nonlocal 呼叫次數
        with 鎖:
            呼叫次數 += 1
            是第二顆 = 呼叫次數 == 2
        if 是第二顆:
            assert 放行第二顆.wait(timeout=2.0), "第二個必要分支沒有被測試放行"
        回來順序.append(工作項.分支)
        第一顆回來.set()
        return 節點成功(產出=工作項.輸入, 證據=(), 用量=None)

    def 執行並整合() -> None:
        結果 = 執行扇出(
            工作,
            執行一顆=執行一顆,
            上下文=_上下文(),
            政策=_政策(必要分支=frozenset({工作[0].分支, 工作[1].分支})),
        )
        整合收到.append(結果)

    執行緒 = Thread(target=執行並整合)
    執行緒.start()
    try:
        assert 第一顆回來.wait(timeout=2.0), "第一個必要分支沒有回來"
        assert 整合收到 == [], "必要分支尚未全部回來就呼叫了整合"
    finally:
        放行第二顆.set()
        執行緒.join(timeout=2.0)

    assert not 執行緒.is_alive(), "扇出 runner 沒有在必要分支回來後結束"
    assert set(回來順序) == {工作[0].分支, 工作[1].分支}
    assert len(整合收到) == 1
    assert 整合收到[0].終局 is 結果代碼.成功
    assert {項.分支 for 項 in 整合收到[0].分支結果} == {
        工作[0].分支,
        工作[1].分支,
    }


def test_必要分支逾時時整階終局是結果未知() -> None:
    """逾時可能已經做過事，必要分支逾時要把整階標成結果未知。"""
    工作 = (_工作("甲"), _工作("乙"))
    結果 = _跑兩個分支(
        _結果未知(失敗代碼.逾時),
        節點成功(產出=工作[1].輸入, 證據=(), 用量=None),
    )

    assert 結果.終局 is 結果代碼.結果未知
    assert int(結果.終局) == 3
    assert 結果.缺口 == (工作[0].分支,)
    assert 結果.分支結果[0].分支 == 工作[0].分支
    assert isinstance(結果.分支結果[0].結果, 節點結果未知)
    assert 結果.分支結果[0].結果.錯誤.代碼 is 失敗代碼.逾時


