"""判準逾時要有**專屬計數**，而且**不看工作區雜湊**。

`判準.py` 的 docstring 說「逾時當紅，卡住偵測器會在第 3 次擋下來」，
但真實工作流一律走工作區雜湊那條路（`工作流.py` 把快照傳進 `卡住了`），
那條路上逾時**兩道都擋不住**：

1. 逾時證據裡沒有 `FAILED` 行，`_取失敗測試` 抓不到 → 連紅次數當場歸零；
2. 就算抓得到，兩次逾時之間實作員一定改過檔，工作區雜湊必變 → 比對永遠不成立。

**逾時不是回饋。** 機器過載時模型改再多 code 也改變不了逾時，
所以這條護欄的條件裡**不准出現工作區雜湊**——把雜湊當條件等於這條護欄不會生效。
這一支就是釘死這件事：雜湊各不相同，連續兩次逾時照樣要收。
"""

from pathlib import Path

from nova.契約.工作流 import 任務, 判準終局, 步驟結果, 階段代碼
from nova.契約.模型回應 import 終局
from nova.載體.判準 import 建判準
from nova.迴圈.狀態機 import 卡住了


def _真的逾時的證據(工作目錄: Path) -> str:
    """跑一次真的會逾時的判準，拿它**實際吐出來**的證據。

    不手寫證據字串：護欄認的必須是判準真的產生的那份文字，
    自己編一份的話，`判準.py` 改了措辭這支還是綠的。
    """
    收場, 證據 = 建判準(["sh", "-c", "sleep 5"], 逾時秒=0.2)(
        任務(描述="逾時的判準", 工作目錄=工作目錄)
    )
    assert 收場 is 判準終局.紅, f"逾時的收場變了（{收場}），這支測試的前提要重寫：{證據}"
    return 證據


def _判準紅步(證據: str) -> 步驟結果:
    return 步驟結果(階段=階段代碼.驗證綠, 終局=終局.成功, 判準綠=False, 證據=證據)


def _實作步() -> 步驟結果:
    return 步驟結果(階段=階段代碼.實作, 終局=終局.成功, 判準綠=None, 證據="又改了一輪")


def test_連續兩次逾時就算工作區雜湊都不同也要收護欄(tmp_path: Path) -> None:
    """**這一支釘的是「雜湊無關」。**

    軌跡是真實形狀：逾時 → 退回實作（實作員改了檔，雜湊變了）→ 又逾時。
    釘「雜湊未變」是最危險的寫法——它會為了錯的理由變綠，
    而「雜湊必變」正是這一格要修的 bug 的成因。
    """
    證據 = _真的逾時的證據(tmp_path)
    軌跡 = (_實作步(), _判準紅步(證據), _實作步(), _判準紅步(證據))
    # 每一步的雜湊都不一樣：實作員每一輪都真的動過工作區。
    工作區雜湊們 = ("雜湊甲", "雜湊乙", "雜湊丙", "雜湊丁")

    理由 = 卡住了(軌跡, 工作區雜湊們=工作區雜湊們)

    assert 理由 is not None, (
        "連續兩次判準逾時沒有收護欄——這正是每次紅都退回實作、一路燒到 token 或步數上限的那條路"
    )
    assert "逾時" in 理由, f"護欄理由要說得出是逾時，不能混進同一批測試連紅的說法：{理由}"


def test_只逾時一次不算卡住(tmp_path: Path) -> None:
    """門檻要是真的門檻：單次逾時可能只是機器剛好忙，不該當場收工作流。"""
    軌跡 = (_實作步(), _判準紅步(_真的逾時的證據(tmp_path)))

    assert 卡住了(軌跡, 工作區雜湊們=("雜湊甲", "雜湊乙")) is None


def test_一般的紅在工作區改過時仍然不算無進展() -> None:
    """逾時的專屬計數**不准**順手把一般紅的雜湊條件也拆掉。

    同一批測試連紅但工作區有改動，那是還在動，不是卡住——
    那條護欄的「雜湊未變」是它自己的條件，跟逾時這條是兩件事。
    """
    證據 = "FAILED tests/單元/test_功能.py::test_空輸入\n"
    軌跡 = (_實作步(), _判準紅步(證據), _實作步(), _判準紅步(證據))

    assert 卡住了(軌跡, 工作區雜湊們=("雜湊甲", "雜湊乙", "雜湊丙", "雜湊丁")) is None
