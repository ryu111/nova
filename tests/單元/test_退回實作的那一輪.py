"""從 `review`／`verify` 退回來的那一輪，實作員看得見它要修的那份紅。

## 現在的洞

`迴圈/角色提示.py` 的實作員提示寫死了「**不要自己跑全套測試**，
只跑跟這次改動直接相關的那幾支」。

第一次進 `impl` 時這條是對的：省 token，下一階 `verify-green` 會替它跑。
**但被退回來的那一輪不一樣**——它要修的正是「全測試的紅」，而它拿不到那份紅，
也不准自己跑。它在猜。

## 訊號從哪來

「這次是不是被退回來的」要從狀態機流過去，不是讓提示自己猜，也不是在提示裡
寫死一份「哪些階段會退回實作」的清單——那份清單會跟階段表分岔。
回頭邊的定義住在 `TDD階段表`：去處排在來源前面就是回頭邊。
"""

from nova.契約.工作流 import 階段代碼
from nova.迴圈.狀態機 import 是回頭邊
from nova.迴圈.角色提示 import 實作員, 實作員提示

#: 那條省 token 的禁令，原文照抄。
_禁令 = "**不要自己跑全套測試**"


class Test退回實作的那一輪:
    def test_第一次進實作維持禁令(self) -> None:
        """第一次進 `impl` 沒有東西可看，禁令是對的，不准順手拆掉。"""
        assert _禁令 in 實作員, "實作員常數裡的禁令不見了，這支測試失去了對照組"
        assert 實作員提示(被退回=False, 上一階證據="") == 實作員

    def test_被退回時拿得到紅的證據而且准自己跑全測試(self) -> None:
        """要修全測試的紅，就得看得到那份紅，也得跑得動那套測試。"""
        證據 = (
            "FAILED tests/單元/test_判準涵蓋提交閘.py::Test判準涵蓋提交閘"
            "::test_測試涵蓋不准比全跑窄 - AssertionError: 判準步驟裡找不到全跑的指令"
        )
        提示 = 實作員提示(被退回=True, 上一階證據=證據)

        assert 證據 in 提示, "被退回的那一輪拿不到上一階的紅，實作員只能用猜的"
        assert _禁令 not in 提示, "被退回還禁止跑全測試，它修的正是全測試的紅"
        assert "全測試" in 提示, "沒有明講准它自己跑全測試"
        # 放寬的只有那條禁令，本業規矩一條都不准鬆。
        assert "不准改測試" in 提示

    def test_退回訊號從狀態機的回頭邊來(self) -> None:
        """`驗證綠 → 實作`、`審查 → 實作` 是回頭邊；`驗證紅 → 實作` 是往前走。"""
        assert 是回頭邊(階段代碼.驗證綠, 階段代碼.實作)
        assert 是回頭邊(階段代碼.審查, 階段代碼.實作)
        assert not 是回頭邊(階段代碼.驗證紅, 階段代碼.實作), (
            "第一次進 impl 被當成退回，禁令會在該生效的那一輪失效"
        )
