def test_轉成字典再轉回來是同一筆() -> None:
    """帳要跨程序讀（寫的是 CLI，讀的是下一次的 CLI），來回不准掉東西。"""
    assert 字典轉成果(成果轉字典(_一筆)) == _一筆


def test_落盤的欄位名是ASCII() -> None:
    """跨程序的 schema 欄位名用 ASCII——CLAUDE.md 的例外清單第二項。

    給 python 呼叫端的是繁中屬性名，落盤的是 ASCII，兩邊由 `成果轉字典` 對齊。

    **餵的是欄位齊全的那一筆**：`None` 的欄位不落盤，所以拿預設值那筆來檢查
    會讓後加的欄位靜默不在檢查範圍內——加了新欄位這支照樣綠。
    """
    欄位 = set(成果轉字典(_欄位齊全))

    assert 欄位 == {
        "run_id",
        "task",
        "outcome",
        "exit_code",
        "started_at",
        "ended_at",
        "source",
        "steps",
        "tokens",
        "cost_usd",
        "policy_version",
        "rollback_point",
        "acceptance",
    }


def test_轉出來的字典是JSON可序列化的() -> None:
    """落盤走 json.dump，塞得進 dataclass 不代表塞得進 JSON。"""
    assert json.loads(json.dumps(成果轉字典(_一筆), ensure_ascii=False)) == 成果轉字典(_一筆)


def test_少欄位的舊紀錄不准把讀取端整個弄爆() -> None:
    """帳是 append-only 的歷史，**以前寫的那些不會回頭改**。

    欄位是之後加的話，舊紀錄就少那一格；讀取端當場炸掉等於整本帳都看不了。
    缺的補預設值，讓人至少看得到「哪一次、什麼收場」。
    """
    舊的 = {"run_id": "20260101T000000Z-old", "task": "很久以前", "outcome": "完成"}

    回來 = 字典轉成果(舊的)

    assert 回來.執行識別碼 == "20260101T000000Z-old"
    assert 回來.收場 == "完成"
    assert 回來.總token == 0


def test_成本帶得進成果也讀得回來() -> None:
    """成果帳本是給人看「這件事花了多少」的地方，成本掉了就只剩 token。"""
    有成本 = 成果(
        執行識別碼="20260830T091500Z-abc123",
        任務=已經遮過了("把程序收割做完", 因為="測試資料，裡面沒有祕密"),
        收場="完成",
        退出碼=0,
        起="2026-08-30T09:15:00Z",
        迄="2026-08-30T09:31:00Z",
        走了幾階=5,
        總token=48213,
        總成本美金=1.25,
    )

    assert 成果轉字典(有成本)["cost_usd"] == 1.25
    assert 字典轉成果(成果轉字典(有成本)) == 有成本


def test_給不出成本的那次不落盤那個欄位() -> None:
    """**不落盤，不是落成 null。**

    補 null 會讓「這次沒有人給成本」跟「成本是零」長得一樣，
    而那兩件事對看帳的人意義完全不同。跟事件帳本同一條規則
    （見 `契約.帳本.事件` 的 docstring）。
    """
    字 = 成果轉字典(_一筆)

    assert _一筆.總成本美金 is None
    assert "cost_usd" not in 字
    assert 字典轉成果(字).總成本美金 is None


