"""成果：一次做完的工作在帳上長什麼樣。

跟 `帳本` 的分工：帳本是**事件流**（一次執行裡每一次模型呼叫、每一階），
成果是**一次工作一筆**——「這件事做完了沒、結果是什麼」。
兩者答的問題不同，所以不是同一份資料的兩種格式。

純函式，不碰硬碟，所以住單元層。
"""

import json

from nova.契約.成果 import 字典轉成果, 成果, 成果轉字典

_一筆 = 成果(
    執行識別碼="20260830T091500Z-abc123",
    任務="把程序收割做完",
    收場="完成",
    退出碼=0,
    起="2026-08-30T09:15:00Z",
    迄="2026-08-30T09:31:00Z",
    走了幾階=5,
    總token=48213,
)


def test_轉成字典再轉回來是同一筆() -> None:
    """帳要跨程序讀（寫的是 CLI，讀的是下一次的 CLI），來回不准掉東西。"""
    assert 字典轉成果(成果轉字典(_一筆)) == _一筆


def test_落盤的欄位名是ASCII() -> None:
    """跨程序的 schema 欄位名用 ASCII——CLAUDE.md 的例外清單第二項。

    給 python 呼叫端的是繁中屬性名，落盤的是 ASCII，兩邊由 `成果轉字典` 對齊。
    """
    欄位 = set(成果轉字典(_一筆))

    assert 欄位 == {
        "run_id",
        "task",
        "outcome",
        "exit_code",
        "started_at",
        "ended_at",
        "steps",
        "tokens",
    }


def test_轉出來的字典是JSON可序列化的() -> None:
    """落盤走 json.dump，塞得進 dataclass 不代表塞得進 JSON。"""
    assert json.loads(json.dumps(成果轉字典(_一筆), ensure_ascii=False)) == 成果轉字典(_一筆)


def test_少欄位的舊紀錄不准把讀取端整個弄爆() -> None:
    """帳是 append-only 的歷史，**以前寫的那些不會回頭改**。

    欄位是之後加的話，舊紀錄就少那一格；讀取端當場炸掉等於整本帳都看不了。
    缺的補預設值，讓人至少看得到「哪一次、什麼收場」。
    """
    舊的 = {"run_id": "20260101T000000Z-old", "task": "很久以前", "outcome": "完成"}

    回來 = 字典轉成果(舊的)

    assert 回來.執行識別碼 == "20260101T000000Z-old"
    assert 回來.收場 == "完成"
    assert 回來.總token == 0
