"""繁體中文規則的機械化版本。

CLAUDE.md 說「一律繁體中文」，但那是提示詞——模型會忘、換模型就沒了。
這支測試釘住的是：簡體字與日文新字體都要被抓出來，而且要說出是哪一行哪個字。
"""

from nova.載體.語言 import 允許標記, 找非繁體字


def test_抓簡體字() -> None:
    命中 = 找非繁體字("第一行沒問題\n這行有問题")  # nova:允許非繁體
    assert [(行, 字) for 行, 字, _ in 命中] == [(2, "题")]  # nova:允許非繁體


def test_抓日文新字體() -> None:
    """我真的打錯過這個字：U+95D8 不是 U+9598。"""
    命中 = 找非繁體字("水闘門")  # nova:允許非繁體
    assert [字 for _, 字, _ in 命中] == ["闘"]  # nova:允許非繁體


def test_純繁體不誤判() -> None:
    assert 找非繁體字("閘門、載體、迴圈、契約、證據、驗收") == []


def test_英數與符號不誤判() -> None:
    assert 找非繁體字("uv run nova 閘 提交 --格式 json # ok") == []


def test_同一行多個字都要報() -> None:
    命中 = 找非繁體字("这个")  # nova:允許非繁體
    assert [字 for _, 字, _ in 命中] == ["这", "个"]  # nova:允許非繁體


def test_允許標記可以放行整行() -> None:
    """有時候就是要引用簡體原文（例如這個測試檔本身）。逃生門要存在且明確。"""
    文字 = f"引用原文：这个  # {允許標記}"  # nova:允許非繁體
    assert 找非繁體字(文字) == []


def test_命中要帶整行內容才好定位() -> None:
    命中 = 找非繁體字("前面\n中間有这個字\n後面")  # nova:允許非繁體
    行號, 字, 整行 = 命中[0]
    assert 行號 == 2
    assert 字 == "这"  # nova:允許非繁體
    assert 整行 == "中間有这個字"  # nova:允許非繁體


def test_emoji_與符號不誤判() -> None:
    """Big5 也編不動 emoji，但那不是語言問題。誤報會逼人整個關掉閘。"""
    assert 找非繁體字("✅ 通過 ⚠️ 注意 ❌ 失敗 ≥2 票 ——「引號」") == []
