#: 硬規則 4 自己說「同一個檔尾就是跨線衝突點」——教模型往單一檔尾 append
#: 等於這條線一邊立規矩一邊示範相反做法。主題名由開票那條線自己取，
#: 所以錨點只釘到目錄為止。
_登記落點 = "tests/負控/登記們/"


class _假腦:
    """記下真正送出去的那一整串提示。這支測試不該真的呼叫模型。"""

    名稱 = "測試用假腦"

    def __init__(self, 收到: list[str]) -> None:
        self._收到 = 收到

    def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
        del 選項
        self._收到.append(提示)
        return 回應(
            文字="做好了",
            終局=終局.成功,
            失敗代碼=失敗代碼.無,
            原始結束碼=0,
            對話識別碼=None,
            用量=用量(輸入token=1, 輸出token=1),
        )


def _送給這一階的(階段: 階段代碼, 任: 任務) -> str:
    """用真的藍圖、真的角色、真的執行器跑那一步，回腦收到的整份提示。"""
    收到: list[str] = []

    def 建腦(_: object) -> 語言模型:
        return _假腦(收到)

    依識別碼 = 建角色表(建TDD角色藍圖(怎麼派), 建腦=建腦, 組角色=固定提示角色)
    執行一步 = 建TDD執行器(
        角色表={階段代碼(識別碼): 角 for 識別碼, 角 in 依識別碼.items()},
        跑判準=lambda _: (判準終局.綠, "假判準"),
        篩選指定測試=可作指定pytest目標,
    )
    定義: 階段定義 = 查階段(階段)
    執行一步(定義, 任, ())
    assert len(收到) == 1, f"{階段.value} 那一階該剛好叫一次腦"
    return 收到[0]


class Test新增保證的票要在測試員那一階補負控登記:
    """一張「新增保證」型的票，測試員必須同時被指派去補 `tests/負控/登記.py`。"""

    def test_新增保證的票送出去的提示會指名登記檔補一列(self) -> None:
        """要指名檔案、指名「破壞什麼」與「該紅哪支測試」，不能只說一句「記得做負控」。"""
        一張新增保證的票 = 任務(
            描述="新增：截斷的回應要當場收成失敗，不准當成綠",
            工作目錄=_工作目錄,
            新增保證=True,
        )

        提示 = _送給這一階的(階段代碼.測試, 一張新增保證的票)

        assert _測試員身分錨點 in 提示, "測試員的身分規矩不該因為多了負控那段就被換掉"
        assert _登記落點 in 提示, (
            "送給測試員的提示沒有指名登記落點——模型會走到 impl 才想起來補、然後收在護欄"
        )
        assert "tests/負控/登記.py" not in 提示, (
            "提示教的是往 `登記.py` 檔尾 append——同一個檔尾就是跨線衝突點，"
            "慣例早就改成一線一檔的 `登記們/<主題>.py`"
        )
        assert "破壞" in 提示, "負控登記要指名『破壞什麼』，否則登記的那一列不可重播"
        assert "該紅" in 提示, "負控登記要指名『該紅哪支測試』，否則證明不了這支測試在守東西"

    def test_純重構或純文件的票不准被要求補負控(self) -> None:
        """不新增保證就不付這次成本——否則每張票都多繞一次負控。"""
        純重構的票 = 任務(
            描述="重構：把三處重複的階段判斷收成一個查詢，行為不變",
            工作目錄=_工作目錄,
            新增保證=False,
        )

        提示 = _送給這一階的(階段代碼.測試, 純重構的票)

        assert _測試員身分錨點 in 提示, "不補負控的票，測試員的身分規矩照樣要在"
        assert "負控" not in 提示, "純重構的票被要求補負控，等於每張票都多付一次成本"
        assert _登記落點 not in 提示, "沒有新增保證的票不該被指去動負控登記檔"

    def test_沒指名票種的舊呼叫端預設不補負控(self) -> None:
        """`任務` 沒填這一欄時是「不新增保證」——**預設不加成本**，

        否則所有既有呼叫端（`nova.__init__`、`載體.命令列`）一夜之間每張票都多繞一次負控。
        """
        沒指名的票 = 任務(描述="更新文件裡過期的路徑", 工作目錄=_工作目錄)

        提示 = _送給這一階的(階段代碼.測試, 沒指名的票)

        assert "負控" not in 提示, "沒指名票種就被當成新增保證，等於預設多付一次成本"

    def test_新增保證的票裡實作員仍然不准動測試檔(self) -> None:
        """負控那段只准落在測試員身上。

        接給實作員等於叫它去動 `tests/負控/登記.py`，那正是護欄要擋的那一步——
        這張票不准為了讓自己過而把護欄拆掉。
        """
        一張新增保證的票 = 任務(
            描述="新增：截斷的回應要當場收成失敗，不准當成綠",
            工作目錄=_工作目錄,
            新增保證=True,
        )

        提示 = _送給這一階的(階段代碼.實作, 一張新增保證的票)

        assert _實作員禁令 in 提示, "實作員的本業規矩被這張票改掉了"
        assert _登記落點 not in 提示, (
            "實作員被指去動負控登記檔——這一步一動測試檔就會收在護欄，等於教它去撞牆"
        )


class _不該被呼叫的腦:
    """門面那幾支只驗接線，走到這裡就代表測試真的去敲模型了。"""

    名稱 = "不該被呼叫的腦"

    def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
        del 提示, 選項
        訊息 = "這支測試只驗接線，不該真的呼叫模型"
        raise AssertionError(訊息)


def _攔下門面送出去的任務(monkeypatch: pytest.MonkeyPatch) -> list[任務]:
    """讓 `nova.派工` 跑到「造好任務、交給工作流」為止，把那個任務接下來。

    攔在 `跑工作流` 而不是更外面，是因為要驗的正是**門面造出來的那個 `任務` 物件**：
    欄位存在（契約）不等於有人填（可達性）。
    """
    收到: list[任務] = []

    def 假建腦(*參數: object, **具名: object) -> 語言模型:
        del 參數, 具名
        return _不該被呼叫的腦()

    def 假跑工作流(任: 任務, **其餘: object) -> 工作流結果:
        del 其餘
        收到.append(任)
        return 工作流結果(結束=結束(代碼=結束代碼.完成, 原因="這支測試沒有真的跑"), 軌跡=())

    monkeypatch.setattr(nova, "_建腦", 假建腦)
    monkeypatch.setattr(nova, "跑工作流", 假跑工作流)
    return 收到


class Test新增保證要從生產路徑傳得進去:
    """`任務.新增保證` 現在沒有任何生產呼叫端會填它。

    契約上有這一欄、迴圈裡也接了它，但 `nova.派工` 收不到這個意思——
    於是那段負控提示在真線上**永遠不會出現**。CLAUDE.md 判準第 3 條：
    有實作沒有呼叫端等於沒有；契約欄位證明的是形狀，不是可達性。
    """

    def test_門面把票上的新增保證帶進任務(self, monkeypatch: pytest.MonkeyPatch) -> None:
        """開票的人說這張票新增保證，工作流收到的 `任務` 就要是這個意思。"""
        收到 = _攔下門面送出去的任務(monkeypatch)

        nova.派工(
            "新增：截斷的回應要當場收成失敗，不准當成綠",
            用="codex",
            審查用="claude",
            工作目錄=_工作目錄,
            新增保證=True,
        )

        assert len(收到) == 1, "門面該把任務交給工作流剛好一次"
        assert 收到[0].新增保證 is True, (
            "門面收了「這張票新增保證」卻沒帶進任務——負控那段在真線上永遠接不上"
        )

    def test_門面沒指名時預設不新增保證(self, monkeypatch: pytest.MonkeyPatch) -> None:
        """既有呼叫端一個字都不改時不准變貴：沒指名就是不補負控。"""
        收到 = _攔下門面送出去的任務(monkeypatch)

        nova.派工("更新文件裡過期的路徑", 用="codex", 審查用="claude", 工作目錄=_工作目錄)

        assert len(收到) == 1, "門面該把任務交給工作流剛好一次"
        assert 收到[0].新增保證 is False, "沒指名票種就被當成新增保證，等於每張票都多付一次成本"
