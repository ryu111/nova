"""固定負控的登記要有一個合法的家：測試員那一階，而且要**真的接上派工**。

## 為什麼是這支

CLAUDE.md 硬規則 4：新增保證**要**做一次固定負控（故意破壞、看它紅、改回來）。
但七階裡沒有任何一階被告知要做這件事——`src/nova/迴圈/角色提示.py` 一次都沒提「負控」。
實際發生的事是模型走到 `impl`（「最少的程式碼讓它綠」）才想起要補 `tests/負控/登記.py`，
而那一階**不准動測試檔**，於是當場收在護欄：

    guardrail：「最少的程式碼讓它綠」這一步動了測試檔：
      tests/負控/test_登記的變異會被殺.py、tests/負控/執行器.py

護欄沒有錯，規則也沒有錯——錯在這件強制的事沒有合法的階段可以住。
CLAUDE.md 判準第 1 條：只以文件或 skill 形式存在的規範等於不存在。

## 這支守什麼

**負控登記歸測試員，而且斷言打在腦真正收到的那一整串上。** 抄
`test_退回實作接線.py` 的做法：用真的藍圖、真的角色表、真的執行器跑那一步，
把提示從假腦手上接下來。多一個 helper 函式而生產路徑沒採用它的話，
這支要紅——「函式對了」不等於「接上了」。

票的種類從**資料**來，不是從模型的自覺來：`任務.新增保證` 由開票的人填，
執行器據此決定要不要把負控那段接給測試員。造資料驗，不真的派線。

**還要守得到「有人填得了它」。** 契約上有這一欄不等於真線上會有值——
`Test新增保證要從生產路徑傳得進去` 攔在 `nova.派工` 交棒給 `跑工作流` 的那一刻，
驗門面造出來的 `任務` 真的帶著這個意思。有實作沒有呼叫端等於沒有。

登記的落點是 `tests/負控/登記們/<主題>.py`，**不是 `登記.py` 檔尾**：
硬規則 4 自己說同一個檔尾就是跨線衝突點，這條線的主題正是硬規則 4，
不能一邊立規矩一邊教相反的做法。

## 這支**不**守什麼

- 不碰護欄。實作員那一階仍然不准動任何測試檔，這支不給任何人開白名單——
  開了白名單就等於把「動測試檔算不算作弊」交回給執行者自己說了算。
  第三支測試反過來釘住這件事：同一張新增保證的票，實作員收到的提示裡
  不准出現「去補登記檔」這種指示。
- 不真的派線、不呼叫模型。
- 提示是懇求不是保證，這支守得到的是「那段話真的送到測試員眼前」（防退化、防沒接線）。

## 負控

把測試員提示裡的負控段落拿掉（或把執行器裡接它的那一行拔掉），
`test_新增保證的票送出去的提示會指名登記檔補一列` 要紅。

把 `nova.派工` 收下的 `新增保證` 不往 `任務` 傳（收了就丟），
`test_門面把票上的新增保證帶進任務` 要紅。
"""

