#: 測試員的**身分**每一輪都在，不因票的種類而變。拿它當「提示本體沒被換掉」的錨點。
_測試員身分錨點 = "只新增或修改測試檔"

#: 實作員的本業規矩，原文照抄。負控那段接錯地方時，這一條要能證明護欄沒被鬆掉。
_實作員禁令 = "不准改測試"

#: 負控登記的落點：**一線一檔**的 `登記們/<主題>.py`，不是 `登記.py` 檔尾。
