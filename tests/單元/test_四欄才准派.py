"""自主派工的票**四欄要齊**：輸入／輸出／驗收／停止，缺一欄就不准派。

今天收件匣只擋「自主來源沒帶驗收」（`test_驗收才准派.py`），
另外三欄完全沒有人檢查——`grep -rn 四欄 src/nova` 是空的。
於是 `10-目標長什麼樣.md` 的「完整的點」是一句懇求：漏一欄沒有人會發現，
而漏了的那張票會讓執行者不知道要讀什麼、寫到哪、撞到什麼該停。

## 為什麼還是劃在「自主 vs 人給」

跟驗收同一條理由，不是新規矩：**沒有人在現場**。
人敲的票缺一欄，他自己看得到；排程／協定生的票缺一欄，
下一輪直接接著做，那時候「做完了」跟「做了別的事」長得一模一樣。

所以這裡只加嚴自主來源，人手丟的維持寬鬆——
加嚴人手那邊只會讓他改走別條路進來，於是這道閘等於不存在。
"""

from pathlib import Path

import pytest

from nova.載體.收件 import 丟一件, 你敲, 協定, 待處理, 時鐘

#: 一張四欄齊全的票長什麼樣。**驗收那欄要放真的標記**，
#: 不然缺別欄的案例會被既有的「沒帶驗收」擋下，測不到新檢查。
_四欄 = {
    "輸入": "docs/設計/13-規格做到哪了.md",
    "輸出": "src/nova/載體/找下一個點.py",
    "驗收": "<!--nova:驗收 uv run pytest tests/單元 -q-->",
    "停止": "改超過三個檔就停下來回報",
}


def _一張票(缺哪欄: str = "") -> str:
    """組一張票，指定的那一欄整段拿掉。缺哪欄留空就是四欄齊全的那張。"""
    段落 = [f"## {欄}\n\n{內文}" for 欄, 內文 in _四欄.items() if 欄 != 缺哪欄]
    return "把 nova 空手時找下一個點做出來\n\n" + "\n\n".join(段落) + "\n"


class Test缺欄的自主票派不出去:
    """開跑前拒絕，不是等執行者做到一半才發現票是殘的。"""

    @pytest.mark.parametrize("缺哪欄", list(_四欄))
    @pytest.mark.parametrize("來源", [時鐘, 協定])
    def test_四欄缺任何一欄都不准派(self, 缺哪欄: str, 來源: str, tmp_path: Path) -> None:
        """**四欄各缺一次，每一次都要看到它擋下來。**

        錯誤訊息要講出缺的是哪一欄：只說「欄位不齊」的話，
        補票的人（多半是下一輪的 nova 自己）得自己猜是哪一欄，
        猜錯就再被擋一次，而每一次都燒一輪排程。
        """
        with pytest.raises(ValueError, match=缺哪欄):
            丟一件(_一張票(缺哪欄), 來源=來源, 目錄=tmp_path)

    @pytest.mark.parametrize("缺哪欄", list(_四欄))
    def test_被擋下的票不准留在收件匣(self, 缺哪欄: str, tmp_path: Path) -> None:
        """**拋了例外但檔案已經寫進去**是最陰的那種假綠。

        呼叫端多半會 `except ValueError: 記一筆` 然後往下走，
        於是那張殘票安安靜靜躺在佇列裡等下一輪撿走。
        """
        with pytest.raises(ValueError, match=缺哪欄):
            丟一件(_一張票(缺哪欄), 來源=時鐘, 目錄=tmp_path)
        assert 待處理(tmp_path) == []

    def test_四欄齊全的自主票派得出去(self, tmp_path: Path) -> None:
        """正控：檢查不能嚴到把合格的票也擋掉。

        那樣 nova 生得出的票只剩下零張，而測試照樣全綠。
        """
        落點 = 丟一件(_一張票(), 來源=時鐘, 目錄=tmp_path)
        assert 待處理(tmp_path) == [落點]

    @pytest.mark.parametrize("缺哪欄", list(_四欄))
    def test_人手丟的票缺欄照樣派(self, 缺哪欄: str, tmp_path: Path) -> None:
        """**這一格是刻意放行的**，不是漏掉的。人在現場，欄位是他自己看。

        缺驗收那一欄也一樣：`要驗收嗎(你敲)` 早就是 False。
        """
        落點 = 丟一件(_一張票(缺哪欄), 來源=你敲, 目錄=tmp_path)
        assert 待處理(tmp_path) == [落點]
