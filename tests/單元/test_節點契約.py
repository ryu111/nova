def test_成功產出必帶_schema_與_provenance() -> None:
    """成功結果只能交出帶結構版本與完整來源追溯的邊包。"""
    來源 = 證據來源(
        執行=執行識別碼("執行-001"),
        工作流=None,
        分支=分支識別碼("root"),
        節點=節點識別碼("測試節點"),
        嘗試=1,
        父邊=(邊識別碼("輸入邊-001"),),
    )
    內容 = {"答案": "完成"}
    產出 = 邊包(
        結構=結構識別碼("測試結果"),
        版本=1,
        內容=內容,
        來源=來源,
    )
    結果 = 節點成功(產出=產出, 證據=(), 用量=None)

    assert 結果.結果 is 結果代碼.成功
    assert int(結果.結果) == 0
    assert 結果.產出.結構 == 結構識別碼("測試結果")
    assert 結果.產出.版本 == 1
    assert 結果.產出.內容 == 內容
    assert 結果.產出.來源 is 來源
    assert 結果.產出.來源.執行 == 執行識別碼("執行-001")
    assert 結果.產出.來源.分支 == 分支識別碼("root")
    assert 結果.產出.來源.節點 == 節點識別碼("測試節點")
    assert 結果.產出.來源.嘗試 == 1
    assert 結果.產出.來源.父邊 == (邊識別碼("輸入邊-001"),)


def _來源() -> 證據來源:
    return 證據來源(
        執行=執行識別碼("執行-002"),
        工作流=工作流識別碼("工作流-002"),
        分支=分支識別碼("分支-002"),
        節點=節點識別碼("節點-002"),
        嘗試=2,
        父邊=(邊識別碼("父邊-002"),),
    )


def _產出() -> 邊包[dict[str, str]]:
    return 邊包(
        結構=結構識別碼("測試結果"),
        版本=2,
        內容={"答案": "完成"},
        來源=_來源(),
    )


def _錯誤() -> 節點錯誤:
    return 節點錯誤(
        代碼=失敗代碼.認證,
        診斷="呼叫者提供的診斷",
        可能已產生副作用=False,
    )


def _上下文() -> 節點上下文:
    return 節點上下文(
        任務=任務(描述="呼叫者提供的任務", 工作目錄=Path("呼叫者的工作目錄")),
        執行=執行識別碼("呼叫者-執行"),
        工作流=工作流識別碼("呼叫者-工作流"),
        節點=節點識別碼("呼叫者-節點"),
        分支=分支識別碼("呼叫者-分支"),
        父邊=(邊識別碼("呼叫者-父邊"),),
        嘗試=7,
        停止=停止政策(
            最多呼叫=11,
            最多token=2200,
            最多秒=33.5,
            最多無進展=4,
            結果未知不重跑=False,
        ),
    )


