def test_護欄原因六種且只有這六種() -> None:
    預期 = {
        護欄原因.預算: "budget",
        護欄原因.步數: "steps",
        護欄原因.逾時: "timeout",
        護欄原因.無進展: "stagnation",
        護欄原因.扇出超限: "fanout-limit",
        護欄原因.輸出不合約: "invalid-output",
    }

    assert len(護欄原因) == 6
    assert {原因: 原因.value for 原因 in 護欄原因} == 預期


def _不可變案例() -> tuple[tuple[str, object, str, object], ...]:
    停止 = 停止政策(最多呼叫=1, 最多token=2, 最多秒=3.0, 最多無進展=4)
    邊 = _產出()
    錯誤 = _錯誤()
    return (
        ("停止政策", 停止, "最多呼叫", 9),
        ("證據來源", _來源(), "嘗試", 9),
        ("邊包", 邊, "版本", 9),
        ("節點錯誤", 錯誤, "診斷", "不准改"),
        (
            "證據項",
            證據項(識別碼=邊識別碼("證據-002"), 類型=結構識別碼("類型"), 摘要="摘要"),
            "摘要",
            "不准改",
        ),
        ("節點成功", 節點成功(產出=邊, 證據=(), 用量=None), "用量", object()),
        ("節點確定失敗", 節點確定失敗(錯誤=錯誤, 證據=()), "證據", ()),
        ("節點結果未知", 節點結果未知(錯誤=錯誤, 已知證據=(), 用量=None), "用量", object()),
        ("節點護欄", 節點護欄(原因=護欄原因.預算, 已知證據=(), 用量=None), "原因", 護欄原因.步數),
        ("節點上下文", _上下文(), "嘗試", 8),
    )


_不可變案例們 = _不可變案例()


@pytest.mark.parametrize(
    ("類別", "物件", "欄位", "新值"),
    _不可變案例們,
    ids=[案例[0] for 案例 in _不可變案例們],
)
def test_節點契約資料類別不可變(類別: str, 物件: object, 欄位: str, 新值: object) -> None:
    try:
        setattr(物件, 欄位, 新值)
    except dataclasses.FrozenInstanceError:
        return

    pytest.fail(f"{類別} 沒有擋住欄位寫入")


class 形狀相同節點:
    """不繼承任何 nova 基底類別，只靠形狀符合節點 Protocol。"""

    def __init__(self) -> None:
        """建立記錄呼叫參數的最小節點。"""
        self.收到輸入: 邊包[dict[str, str]] | None = None
        self.收到上下文: 節點上下文 | None = None
        self.收到依賴: str | None = None

    @property
    def 識別碼(self) -> 節點識別碼:
        return 節點識別碼("形狀相同節點")

    def 執行(
        self,
        輸入: 邊包[dict[str, str]],
        *,
        上下文: 節點上下文,
        依賴: str,
    ) -> 節點成功[dict[str, str]]:
        self.收到輸入 = 輸入
        self.收到上下文 = 上下文
        self.收到依賴 = 依賴
        return 節點成功(產出=輸入, 證據=(), 用量=None)


def test_節點上下文每一格都由呼叫者明傳() -> None:
    一件任務 = 任務(描述="這是呼叫者的任務", 工作目錄=Path("這是呼叫者給的目錄"))
    停止 = 停止政策(
        最多呼叫=17,
        最多token=3400,
        最多秒=51.5,
        最多無進展=6,
        結果未知不重跑=False,
    )
    父邊 = (邊識別碼("呼叫者給的父邊-甲"), 邊識別碼("呼叫者給的父邊-乙"))
    上下文 = 節點上下文(
        任務=一件任務,
        執行=執行識別碼("呼叫者給的執行"),
        工作流=工作流識別碼("呼叫者給的工作流"),
        節點=節點識別碼("呼叫者給的節點"),
        分支=分支識別碼("呼叫者給的分支"),
        父邊=父邊,
        嘗試=13,
        停止=停止,
    )
    輸入 = _產出()
    依賴 = "呼叫者給的依賴"
    節點 = 形狀相同節點()

    結果 = 執行節點(節點, 輸入, 上下文=上下文, 依賴=依賴)

    assert isinstance(結果, 節點成功)
    assert 結果.產出 is 輸入
    assert 節點.收到輸入 is 輸入
    assert 節點.收到依賴 == 依賴
    收到 = 節點.收到上下文
    assert 收到 is 上下文
    assert 收到.任務 is 一件任務
    assert 收到.任務.描述 == "這是呼叫者的任務"
    assert 收到.任務.工作目錄 == Path("這是呼叫者給的目錄")
    assert 收到.執行 == 執行識別碼("呼叫者給的執行")
    assert 收到.工作流 == 工作流識別碼("呼叫者給的工作流")
    assert 收到.節點 == 節點識別碼("呼叫者給的節點")
    assert 收到.分支 == 分支識別碼("呼叫者給的分支")
    assert 收到.父邊 is 父邊
    assert 收到.嘗試 == 13
    assert 收到.停止 is 停止


def test_執行節點接受不繼承基底的形狀相同物件() -> None:
    節點 = 形狀相同節點()
    輸入 = _產出()

    結果 = 執行節點(節點, 輸入, 上下文=_上下文(), 依賴="依賴")

    assert isinstance(結果, 節點成功)
    assert 結果.結果 is 結果代碼.成功
    assert 結果.產出 is 輸入
