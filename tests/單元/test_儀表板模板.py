#: 拿破折號頂替一個沒接線的數字，畫面上看起來像「這次剛好沒有值」。
#: **那是第三種狀態的偽裝**：未接線、查不到、真的是 0，三件事要分得出來。
_破折號們 = frozenset({"—", "–", "-", "－"})


def _看得見的文字(節: _元素) -> str:
    """這個元素連同子樹的文字，**徽章自己的字不算**。

    不排掉的話，一個寫著「閘鎖的門檻」的徽章會被當成「門檻」那一格的標籤，
    於是「徽章擺在自己那一格裡」變成恆真——徽章擺在哪裡都算擺對。
    """
    if _是徽章(節):
        return ""
    return 節.文字 + "".join(_看得見的文字(子) for 子 in 節.子們)


def _有徽章(節: _元素) -> bool:
    """這一格（連同子樹）喊不喊得出「未接線」。"""
    return _是徽章(節) or any(_有徽章(子) for 子 in 節.子們)


def _元素與爸(子們: list[_元素], 爸: _元素 | None = None) -> list[tuple[_元素, _元素 | None]]:
    """整棵樹攤成 `(元素, 它的爸)`——「那一格」有時是標籤自己、有時是它的爸。"""
    出: list[tuple[_元素, _元素 | None]] = []
    for 子 in 子們:
        出.append((子, 爸))
        出.extend(_元素與爸(子.子們, 子))
    return 出


def _那一格的落點(原文: str, 錨: str) -> list[_元素]:
    """設計稿那一格的標籤所在的最小元素，連同它的爸。

    數字有時候跟標籤同一個元素（`今日合併 <span class="num">10</span>`），
    有時候是隔壁的兄弟（大數字一個 `<div>`、`件 · 例外用了` 一個 `<div>`），
    所以「那一格」＝標籤自己或它的爸。**再往上就是整個區塊了，不算釘住。**
    """
    出: list[_元素] = []
    for 節, 爸 in _元素與爸(_解析(原文)):
        if 錨 not in _看得見的文字(節):
            continue
        if any(錨 in _看得見的文字(子) for 子 in 節.子們):
            continue
        出.append(節)
        if 爸 is not None:
            出.append(爸)
    return 出


def _沒釘好的格子(原文: str) -> list[str]:
    """哪幾格的未接線徽章沒有釘在自己那一格上。回空的代表每一格都釘住了。"""
    出: list[str] = []
    for 格, 錨 in _未接線該釘在哪:
        落點 = _那一格的落點(原文, 錨)
        if not 落點:
            出.append(f"{格}：設計稿上「{錨}」那一格在模板上整個不見了")
        elif not any(_有徽章(節) for 節 in 落點):
            出.append(f"{格}：「{錨}」那一格裡沒有未接線徽章（徽章被搬去別的區塊了？）")
        elif any(_破折號頂替(節) for 節 in 落點):
            出.append(f"{格}：「{錨}」那一格擺了一個破折號——那是在裝「這次剛好沒有值」")
    return 出


def _破折號頂替(節: _元素) -> bool:
    """這一格裡有沒有拿破折號當數字的元素。"""
    if 節.文字.strip() in _破折號們 and 節.文字.strip():
        return True
    return any(_破折號頂替(子) for 子 in 節.子們)


def _樣式內容(原文: str) -> str:
    """`<style>` 裡面那段，去掉整段縮排之後的樣子。"""
    找到 = re.search(r"<style>\n(?P<內文>.*?)\n\s*</style>", 原文, re.DOTALL)
    assert 找到 is not None, "模板要有一段 `<style>`——設計稿的版面就住在那裡"
    return textwrap.dedent(找到["內文"]).strip()


