def _第一個不一樣(設計: list[tuple[int, str, str]], 模板: list[tuple[int, str, str]]) -> str:
    """兩份骨架第一個對不上的地方，連前後文一起講清楚。"""
    for 位 in range(max(len(設計), len(模板))):
        左 = 設計[位] if 位 < len(設計) else None
        右 = 模板[位] if 位 < len(模板) else None
        if 左 == 右:
            continue
        前文 = "\n".join(f"    {一個}" for 一個 in 設計[max(0, 位 - 3) : 位])
        return (
            f"模板的骨架跟設計稿去殼後對不上（第 {位} 個元素；"
            f"設計稿 {len(設計)} 個、模板 {len(模板)} 個）。\n"
            f"  前面幾個（兩邊一樣）：\n{前文}\n"
            f"  設計稿這裡是：{左}\n"
            f"  模板這裡是：  {右}\n"
            "  模板 body 要拿去殼原文逐元素照貼，只換數值文字與重複列，不准自己重組版面"
        )
    return ""


