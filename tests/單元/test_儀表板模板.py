@dataclass
class _元素:
    """一個 HTML 元素。比骨架只要標籤、class 與巢狀關係，比徽章落點時才會用到文字。"""

    標籤: str
    屬性: dict[str, str]
    子們: list["_元素"] = field(default_factory=list)
    文字: str = ""

    @property
    def 類名(self) -> str:
        return self.屬性.get("class", "")

    @property
    def 類名們(self) -> list[str]:
        return self.類名.split()


class _建樹(HTMLParser):
    """HTML → 元素樹。文字節點、行內樣式、屬性值全部丟掉，只留骨架。"""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.根 = _元素("#文件", {})
        self._堆: list[_元素] = [self.根]

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        節 = _元素(tag, {名: 值 or "" for 名, 值 in attrs})
        self._堆[-1].子們.append(節)
        if tag not in _空元素:
            self._堆.append(節)

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self._堆[-1].子們.append(_元素(tag, {名: 值 or "" for 名, 值 in attrs}))

    def handle_endtag(self, tag: str) -> None:
        for 位 in range(len(self._堆) - 1, 0, -1):
            if self._堆[位].標籤 == tag:
                del self._堆[位:]
                return

    def handle_data(self, data: str) -> None:
        self._堆[-1].文字 += data


def _解析(原文: str) -> list[_元素]:
    """整份文件的頂層元素們。"""
    建 = _建樹()
    建.feed(原文)
    建.close()
    return 建.根.子們


def _是徽章(節: _元素) -> bool:
    """純粹的未接線徽章——它擺在哪一格由 `Test未接線徽章釘在自己那一格` 釘，

    比骨架的時候不算一個版面元素：設計稿那一格擺的是手拼的數字，
    模板那一格擺的是徽章，**兩邊擺的是同一格**。
    """
    return 節.類名們 == ["未接線"]


def _算版面的類名(節: _元素) -> dict[str, str]:
    """把「那一刻的狀態」從 class 上拿掉，剩下的才是版面語彙。"""
    留下 = [一個 for 一個 in 節.類名們 if 一個 not in _不算版面的類名 and "$" not in 一個]
    if 留下 == 節.類名們:
        return 節.屬性
    return {**節.屬性, "class": " ".join(留下)}


def _正規化(子們: list[_元素]) -> list[_元素]:
    """把兩邊都攤成同一個座標系：去殼、就地展開重複列、還原線列那一處升級。

    這幾條**每一條都是票面白紙黑字允許的偏差**，除此之外一個元素都不准差。
    """
    出: list[_元素] = []
    for 子 in 子們:
        if 子.標籤 in _不算版面 or _是徽章(子):
            continue
        屬性 = _算版面的類名(子)
        if 子.標籤 in _外殼標籤:
            出.extend(_正規化(子.子們))
        elif 子.標籤 == "template":
            if 子.屬性.get("id", "") in _就地展開的片段:
                出.extend(_正規化(子.子們))
        elif 子.標籤 == "details" and 子.類名 == _線列升級後:
            出.append(_元素("div", {"class": "線列 列"}, _正規化(_摘要的子們(子))))
        else:
            出.append(_元素(子.標籤, 屬性, _正規化(子.子們), 子.文字))
    return 出


def _摘要的子們(節: _元素) -> list[_元素]:
    """`<details>` 的 `<summary>` 底下那幾個——線列升級之後，原本那一列住在這裡。"""
    return next((子.子們 for 子 in 節.子們 if 子.標籤 == "summary"), [])


def _指紋(節: _元素) -> tuple[object, ...]:
    """一個元素連同它整棵子樹的形狀。連續重複的兄弟就是靠它認出來的。"""
    return (節.標籤, 節.類名, tuple(_指紋(子) for 子 in 節.子們))


def _動態列的形狀(原文: str) -> frozenset[tuple[object, ...]]:
    """三種動態列**各自那一列**長什麼形狀，從模板的 `<template id="…">` 取。

    **只有這三種形狀准壓**：列數是那一天有幾條線、幾家、幾個失敗碼，不是版面。
    除此之外的連續同形兄弟——收件匣那排圖例、閘鎖那條的每一段、負控那四張卡——
    **每一個都是版面**：壓掉它們等於允許模板少畫幾格而沒有人看得出來。
    """
    return frozenset(
        _指紋(節)
        for 名, 內文 in _片段內文們(原文).items()
        if 名 in _就地展開的片段
        for 節 in _正規化(_解析(內文))
    )


def _壓掉重複列(子們: list[_元素], 形狀們: frozenset[tuple[object, ...]]) -> list[_元素]:
    """**只有三種動態列**的連續同形兄弟壓成一個。

    設計稿那 8 條線是 10:05 那一刻手拼的 8 列，模板只留一列在 `<template>` 裡；
    列數是那一天的資料，不是版面。**兩邊都壓、而且用同一份形狀表**，
    所以壓法本身不會偏袒誰。
    """
    出: list[_元素] = []
    for 子 in 子們:
        壓過的 = _元素(子.標籤, 子.屬性, _壓掉重複列(子.子們, 形狀們), 子.文字)
        指紋 = _指紋(壓過的)
        if 出 and 指紋 in 形狀們 and _指紋(出[-1]) == 指紋:
            continue
        出.append(壓過的)
    return 出


