    命中 = [節 for 節 in _全部節點(節們) if any(子 is 條 for 子 in 節.子們)]
    assert len(命中) == 1, f"「{說明裡有}」那條圖形該只有一個外框，找到 {len(命中)} 個"
    return 命中[0]


