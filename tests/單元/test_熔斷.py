class Test冷卻期惰性重置:
    def test_冷卻期內維持開路(self) -> None:
        """最後一次失敗距今 20 分鐘（< 30 分鐘冷卻期），維持開路。"""
        最後失敗時間 = "2026-08-29T12:00:00Z"
        歷史 = [
            _失敗("r3", "agy", 最後失敗時間),
            _失敗("r2", "agy", "2026-08-29T11:50:00Z"),
            _失敗("r1", "agy", "2026-08-29T11:40:00Z"),
        ]
        現在 = datetime(2026, 8, 29, 12, 20, 0, tzinfo=UTC)
        理由 = 該跳過嗎(歷史, "agy", 現在)
        assert 理由 is not None
        assert "agy" in 理由

    def test_超過冷卻期自動閉路(self) -> None:
        """最後一次失敗距今 31 分鐘（> 30 分鐘冷卻期），視為閉路回 None。"""
        最後失敗時間 = "2026-08-29T12:00:00Z"
        歷史 = [
            _失敗("r3", "agy", 最後失敗時間),
            _失敗("r2", "agy", "2026-08-29T11:50:00Z"),
            _失敗("r1", "agy", "2026-08-29T11:40:00Z"),
        ]
        現在 = datetime(2026, 8, 29, 12, 31, 0, tzinfo=UTC)
        assert 該跳過嗎(歷史, "agy", 現在) is None

    def test_剛好屆滿冷卻期閉路(self) -> None:
        """剛好滿 30 分鐘時恢復閉路。"""
        最後失敗時間 = "2026-08-29T12:00:00Z"
