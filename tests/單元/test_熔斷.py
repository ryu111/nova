"""跨執行熔斷：同一個專案裡，某一家腦連續失敗太多次就暫停呼叫。

規格：
1. 連續失敗門檻 3 次。第 3 次才開路，第 2 次還不算。
2. 只看同一家。agy 連續失敗不影響 codex。
3. 中間出現一次成功就把連續次數歸零。
4. 惰性時間重置：最後一次失敗超過冷卻期（30 分鐘）就當作閉路，回 None。
5. 沒有歷史就回 None。

純函式，不碰網路與模型。
"""

from datetime import UTC, datetime

from nova.契約.帳本 import 一家的帳, 摘要
from nova.載體.熔斷 import 該跳過嗎


def _建立摘要(
    識別碼: str,
    迄: str,
    *各家帳: 一家的帳,
    起: str | None = None,
) -> 摘要:
    return 摘要(
        執行識別碼=識別碼,
        起=起 or 迄,
        迄=迄,
        各家=各家帳,
        階段們=("test",),
        沒收尾的呼叫=(),
        壞掉的行=0,
        總token=sum(家.輸入token + 家.輸出token for 家 in 各家帳),
    )


def _失敗(識別碼: str, 家: str, 迄時戳: str) -> 摘要:
    return _建立摘要(
        識別碼,
        迄時戳,
        一家的帳(
            供應商=家,
            次數=1,
            成功=0,
            失敗=1,
            未知=0,
            輸入token=100,
            輸出token=20,
        ),
    )


def _成功(識別碼: str, 家: str, 迄時戳: str) -> 摘要:
    return _建立摘要(
        識別碼,
        迄時戳,
        一家的帳(
            供應商=家,
            次數=1,
            成功=1,
            失敗=0,
            未知=0,
            輸入token=100,
            輸出token=20,
        ),
    )


class Test無歷史或次數不足:
    def test_沒有任何歷史紀錄不跳過(self) -> None:
        現在 = datetime(2026, 8, 29, 12, 0, tzinfo=UTC)
        assert 該跳過嗎([], "agy", 現在) is None

    def test_歷史中沒有該家的紀錄不跳過(self) -> None:
        現在 = datetime(2026, 8, 29, 12, 0, tzinfo=UTC)
        歷史 = [_失敗("r1", "codex", "2026-08-29T11:50:00Z")]
        assert 該跳過嗎(歷史, "agy", 現在) is None

    def test_連續失敗一次不跳過(self) -> None:
        現在 = datetime(2026, 8, 29, 12, 0, tzinfo=UTC)
        歷史 = [_失敗("r1", "agy", "2026-08-29T11:55:00Z")]
        assert 該跳過嗎(歷史, "agy", 現在) is None

    def test_連續失敗兩次仍不跳過(self) -> None:
        """門檻是 3 次，第 2 次還不算開路。"""
        現在 = datetime(2026, 8, 29, 12, 0, tzinfo=UTC)
        歷史 = [
            _失敗("r2", "agy", "2026-08-29T11:55:00Z"),
            _失敗("r1", "agy", "2026-08-29T11:50:00Z"),
        ]
        assert 該跳過嗎(歷史, "agy", 現在) is None


class Test連續失敗門檻與開路理由:
    def test_連續失敗三次開路並提供可行動理由(self) -> None:
        現在 = datetime(2026, 8, 29, 12, 0, tzinfo=UTC)
        歷史 = [
            _失敗("r3", "agy", "2026-08-29T11:55:00Z"),
            _失敗("r2", "agy", "2026-08-29T11:50:00Z"),
            _失敗("r1", "agy", "2026-08-29T11:45:00Z"),
        ]
        理由 = 該跳過嗎(歷史, "agy", 現在)
        assert 理由 is not None
        assert "agy" in 理由
        assert "3" in 理由
        assert "再試" in 理由 or "冷卻" in 理由 or "分" in 理由 or "2026" in 理由

    def test_連續失敗四次以上維持開路(self) -> None:
        現在 = datetime(2026, 8, 29, 12, 0, tzinfo=UTC)
        歷史 = [
            _失敗("r4", "agy", "2026-08-29T11:55:00Z"),
            _失敗("r3", "agy", "2026-08-29T11:50:00Z"),
            _失敗("r2", "agy", "2026-08-29T11:45:00Z"),
            _失敗("r1", "agy", "2026-08-29T11:40:00Z"),
        ]
        理由 = 該跳過嗎(歷史, "agy", 現在)
        assert 理由 is not None
        assert "agy" in 理由
        assert "4" in 理由


