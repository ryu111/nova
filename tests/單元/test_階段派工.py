"""命令列階段到派工表的對應。

不給腦旗標時，審查階段走派工表的推理列、測試階段走派工表的例行列。
"""

from nova.契約.工作流 import 階段代碼
from nova.契約.派工 import 工作種類
from nova.載體.命令列 import _階段的派法
from nova.載體.派工表 import 怎麼派


def test_不給腦旗標時審查走推理且測試走例行() -> None:
    """守住階段到派工表的接線：審查問到推理列、測試問到例行列。"""
    assert _階段的派法(階段代碼.審查).腦們 == 怎麼派(工作種類.推理).腦們
    assert _階段的派法(階段代碼.測試).腦們 == 怎麼派(工作種類.例行).腦們
