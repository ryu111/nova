"""接力：一串腦，前一顆失敗就換下一顆。

最關鍵的一條在 `Test結果未知`：**能不能換下一顆，要看權限**。
唯讀沒有副作用，重做是安全的；可編輯可能已經改了檔案，換一顆就是做第二次。
"""

import dataclasses
from pathlib import Path

import pytest

from nova.契約.模型回應 import 回應, 失敗代碼, 用量, 終局
from nova.契約.角色 import 呼叫選項, 權限, 語言模型, 預設選項
from nova.載體.模型.接力 import 可以換下一顆, 接力腦


def _答(終: 終局, 代碼: 失敗代碼 = 失敗代碼.無, 文字: str = "") -> 回應:
    return 回應(
        文字=文字,
        終局=終,
        失敗代碼=代碼,
        原始結束碼=0,
        對話識別碼=None,
        用量=用量(輸入token=1, 輸出token=1),
    )


def 做回應(
    終: 終局 = 終局.成功,
    代碼: 失敗代碼 = 失敗代碼.無,
    *,
    入: int = 1,
    出: int = 1,
    成本: float | None = None,
) -> 回應:
    """帶得動用量與成本的版本。`_答` 那個只管終局，用量固定 1/1。"""
    return 回應(
        文字="",
        終局=終,
        失敗代碼=代碼,
        原始結束碼=0,
        對話識別碼=None,
        用量=用量(輸入token=入, 輸出token=出, 成本美金=成本),
    )


class 假腦:
    def __init__(self, 名: str, 回: 回應) -> None:
        """記下被叫過幾次，好驗證「換下一顆」有沒有真的發生。"""
        self._名 = 名
        self._回 = 回
        self.叫過 = 0

    @property
    def 名稱(self) -> str:
        return self._名

    def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
        del 提示, 選項
        self.叫過 += 1
        return self._回


class Test可以換下一顆:
    """純函式，這是整個接力的判斷核心。"""

    @pytest.mark.parametrize("可以做什麼", list(權限))
    def test_確定失敗一律可以換(self, 可以做什麼: 權限) -> None:
        """請求根本沒出門，換一顆重做是安全的。"""
        assert 可以換下一顆(終局.確定失敗, 可以做什麼) is True

    def test_結果未知在唯讀時可以換(self) -> None:
        """唯讀沒有副作用可以重做——就算上一顆真的做了什麼，也沒改到東西。"""
        assert 可以換下一顆(終局.結果未知, 權限.唯讀) is True

    def test_結果未知在可編輯時不准換(self) -> None:
        """可能已經改了檔案。換一顆就是做第二次（at-most-once，寧漏不重）。"""
        assert 可以換下一顆(終局.結果未知, 權限.可編輯) is False

    @pytest.mark.parametrize("可以做什麼", list(權限))
    def test_成功不用換(self, 可以做什麼: 權限) -> None:
        assert 可以換下一顆(終局.成功, 可以做什麼) is False


class Test接力:
    def test_第一顆就成功就不叫第二顆(self) -> None:
        甲 = 假腦("甲", _答(終局.成功, 文字="好"))
        乙 = 假腦("乙", _答(終局.成功, 文字="也好"))
        答 = 接力腦(名稱="鏈", 腦們=(甲, 乙)).詢問("在嗎")
        assert 答.文字 == "好"
        assert (甲.叫過, 乙.叫過) == (1, 0)

    def test_確定失敗就換下一顆(self) -> None:
        甲 = 假腦("甲", _答(終局.確定失敗, 失敗代碼.認證))
        乙 = 假腦("乙", _答(終局.成功, 文字="我來"))
        答 = 接力腦(名稱="鏈", 腦們=(甲, 乙)).詢問("在嗎")
        assert 答.終局 is 終局.成功
        assert 答.文字 == "我來"
        assert (甲.叫過, 乙.叫過) == (1, 1)

    def test_可編輯時遇到結果未知當場停(self) -> None:
        """不知道做了沒，換一顆就可能把已經做過的事再做一次。"""
        甲 = 假腦("甲", _答(終局.結果未知, 失敗代碼.逾時))
        乙 = 假腦("乙", _答(終局.成功))
        答 = 接力腦(名稱="鏈", 腦們=(甲, 乙)).詢問("在嗎", 選項=呼叫選項(權限=權限.可編輯))
        assert 答.終局 is 終局.結果未知
        assert 乙.叫過 == 0, "可編輯下遇到結果未知竟然還換了下一顆"

    def test_唯讀時遇到結果未知可以換(self) -> None:
        甲 = 假腦("甲", _答(終局.結果未知, 失敗代碼.逾時))
        乙 = 假腦("乙", _答(終局.成功, 文字="我來"))
        答 = 接力腦(名稱="鏈", 腦們=(甲, 乙)).詢問("在嗎")  # 預設唯讀
        assert 答.文字 == "我來"
        assert 乙.叫過 == 1

    def test_全部失敗要留下試過誰的證據(self) -> None:
        """哪幾顆失敗、各自為什麼——只給最後一顆的錯誤，上游語意就丟了（§4.3）。"""
        甲 = 假腦("甲", _答(終局.確定失敗, 失敗代碼.認證))
        乙 = 假腦("乙", _答(終局.確定失敗, 失敗代碼.模型不存在, "找不到那個模型"))
        答 = 接力腦(名稱="鏈", 腦們=(甲, 乙)).詢問("在嗎")
        assert 答.終局 is 終局.確定失敗
        assert "甲" in 答.文字 and "auth" in 答.文字
        assert "乙" in 答.文字 and "model-not-found" in 答.文字
        assert "找不到那個模型" in 答.文字, "最後一顆的原話也要留著"

    def test_空的鏈要當場炸(self) -> None:
        """一顆腦都沒有還放行，會回一個假的成功。"""
        with pytest.raises(ValueError, match="至少要有一顆"):
            接力腦(名稱="鏈", 腦們=())

    def test_接力腦本身也是一顆腦(self) -> None:
        """所以它可以被 角色 持有，也可以被套進另一條鏈（組合）。"""
        鏈 = 接力腦(名稱="鏈", 腦們=(假腦("甲", _答(終局.成功)),))
        assert isinstance(鏈, 語言模型)

    def test_選項原樣傳給每一顆_型號除外(self, tmp_path: Path) -> None:
        """工作目錄、逾時、權限這些是鏈上共通的設定，換家時一個都不准掉。

        **型號是唯一的例外**，理由見 `Test型號只給第一家`：各家的模型命名空間
        不交集，帶著走只會讓備援用一個不存在的型號再炸一次。
        這支原本斷言整個物件相等，順帶把型號也綁了進去——那不是它要守的東西。
        """
        收到: list[呼叫選項] = []

        class 記錄腦:
            名稱 = "記錄"

            def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
                del 提示
                收到.append(選項)
                return _答(終局.確定失敗, 失敗代碼.認證)

        選 = 呼叫選項(模型="某型號", 工作目錄=tmp_path, 逾時秒=9.0)
        接力腦(名稱="鏈", 腦們=(記錄腦(), 記錄腦())).詢問("在嗎", 選項=選)
        assert 收到 == [選, dataclasses.replace(選, 模型=None)]


class Test用量要加總:
    """接力鏈燒掉的 token 是**每一顆的總和**，不是最後一顆的。

    這條是被 workflow 的審查抓到的，查證屬實：`接力.py` 原本完全沒碰 `用量`，
    `詢問` 回的是最後一顆的 `回應`——前面幾顆燒掉的 token 在預算裡憑空消失。

    **這不是統計失真，是停止條件失效。** `迴圈/工作流.py` 的 token 上限
    靠 `結果.花費.總token` 累計，低估就等於上限比宣稱的鬆。
    「沒有預算上限的迴圈是成本漏洞」——**算錯的上限也是**。
    """

    def test_換過腦就要把兩顆都算進去(self) -> None:
        鏈 = 接力腦(
            名稱="鏈",
            腦們=(
                假腦("codex", 做回應(終=終局.確定失敗, 代碼=失敗代碼.用法錯誤, 入=100, 出=10)),
                假腦("agy", 做回應(入=200, 出=20)),
            ),
        )
        答 = 鏈.詢問("在嗎")
        assert 答.終局 is 終局.成功
        assert (答.用量.輸入token, 答.用量.輸出token) == (300, 30)

    def test_全掛了也要把全部算進去(self) -> None:
        """全掛的那趟最容易被忽略，而它照樣花了錢。"""
        鏈 = 接力腦(
            名稱="鏈",
            腦們=(
                假腦("codex", 做回應(終=終局.確定失敗, 代碼=失敗代碼.用法錯誤, 入=100, 出=10)),
                假腦("agy", 做回應(終=終局.確定失敗, 代碼=失敗代碼.用法錯誤, 入=200, 出=20)),
            ),
        )
        assert 鏈.詢問("在嗎").用量.總token == 330

    def test_只有一顆不要動它(self) -> None:
        鏈 = 接力腦(名稱="鏈", 腦們=(假腦("agy", 做回應(入=200, 出=20)),))
        assert (鏈.詢問("在嗎").用量.輸入token, 鏈.詢問("在嗎").用量.輸出token) == (200, 20)

    def test_沒換腦就只算那一顆(self) -> None:
        """第一顆就成功時，第二顆根本沒跑，不能把它的用量算進去。"""
        鏈 = 接力腦(
            名稱="鏈",
            腦們=(假腦("codex", 做回應(入=100, 出=10)), 假腦("agy", 做回應(入=999, 出=999))),
        )
        assert 鏈.詢問("在嗎").用量.總token == 110

    def test_成本有一顆給不出來就整個不給(self) -> None:
        """CLAUDE.md：**不准為了讓三家對稱而自己估算。**

        只有 claude 給成本。把「claude 的成本」當成「整條鏈的成本」是低報，
        而低報的成本比沒有成本更危險——它看起來像個數字。
        """
        鏈 = 接力腦(
            名稱="鏈",
            腦們=(
                假腦("claude", 做回應(終=終局.確定失敗, 代碼=失敗代碼.用法錯誤, 成本=0.05)),
                假腦("agy", 做回應()),
            ),
        )
        assert 鏈.詢問("在嗎").用量.成本美金 is None

    def test_每一顆都給得出成本就相加(self) -> None:
        鏈 = 接力腦(
            名稱="鏈",
            腦們=(
                假腦("claude", 做回應(終=終局.確定失敗, 代碼=失敗代碼.用法錯誤, 成本=0.05)),
                假腦("claude2", 做回應(成本=0.25)),
            ),
        )
        成本 = 鏈.詢問("在嗎").用量.成本美金
        assert 成本 is not None
        assert abs(成本 - 0.30) < 1e-9


class Test權限被擋不要換腦:
    """換腦解得了「這顆腦壞了」，解不了「這堵牆擋著」。

    `可以換下一顆` 原本只看終局。但**同一個終局底下有兩種完全不同的處境**：

    | 失敗代碼 | 換下一顆會怎樣 |
    |---|---|
    | `model-not-found`／`not-installed` | 下一顆可能好好的——**該換** |
    | `permission-denied` | 下一顆撞同一堵牆（同一套沙箱、同一份旗標）——**不該換** |

    不分開的話，一條三顆腦的鏈遇到權限問題會白燒三次呼叫，
    而且最後回報的還是同一件事。
    """

    def test_權限被擋不准換下一顆(self) -> None:
        for 可以做什麼 in (權限.唯讀, 權限.可編輯, 權限.全開):
            assert not 可以換下一顆(終局.確定失敗, 可以做什麼, 失敗代碼.權限被擋), (
                f"{可以做什麼} 之下還在換腦——下一顆撞的是同一堵牆"
            )

    def test_其他確定失敗照樣換(self) -> None:
        """**這支防的是修過頭**：不要因為多了一條例外就把換腦整個關掉。"""
        for 代碼 in (失敗代碼.模型不存在, 失敗代碼.未安裝, 失敗代碼.上游):
            assert 可以換下一顆(終局.確定失敗, 權限.可編輯, 代碼), f"{代碼} 不該被擋下來"

    def test_結果未知的規則沒被動到(self) -> None:
        """at-most-once 那條是地基，加新規則不准把它挪走。"""
        assert 可以換下一顆(終局.結果未知, 權限.唯讀, 失敗代碼.未知)
        assert not 可以換下一顆(終局.結果未知, 權限.可編輯, 失敗代碼.未知)


class Test額度用完要換下一家:
    """**這是接力鏈存在的理由**，而在這條分類補上之前它不會觸發。

    補之前：codex 額度用完 → 分類成 `unknown` → 終局`結果未知`
    → 可編輯模式下不換腦 → 一條 `--用 codex,agy` 的鏈在最該換手的時候停住。
    """

    def test_額度用完可以換下一家(self) -> None:
        for 可以做什麼 in (權限.唯讀, 權限.可編輯, 權限.全開):
            assert 可以換下一顆(終局.確定失敗, 可以做什麼, 失敗代碼.額度耗盡), (
                f"{可以做什麼} 之下不換手——額度是綁在 provider 上的，換一家就好"
            )

    def test_跟權限被擋是相反的(self) -> None:
        """兩條新分類的處置**方向相反**，放在一起測才看得出來沒寫反。"""
        assert 可以換下一顆(終局.確定失敗, 權限.可編輯, 失敗代碼.額度耗盡)
        assert not 可以換下一顆(終局.確定失敗, 權限.可編輯, 失敗代碼.權限被擋)


class 記選項的假腦:
    """記下每次被叫到時收到的 `選項`。驗的是「傳了什麼下去」而不只是「叫了幾次」。"""

    def __init__(self, 名: str, 回: 回應) -> None:
        """`收到` 累積每一次的選項，順序就是鏈上的順序。"""
        self._名 = 名
        self._回 = 回
        self.收到: list[呼叫選項] = []

    @property
    def 名稱(self) -> str:
        return self._名

    def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
        del 提示
        self.收到.append(選項)
        return self._回


class Test型號只給第一家:
    """**型號名綁在指名它的那一家身上，不准跟著換腦走。**

    `轉接.py` 自己寫明「`選項.模型` 原樣傳下去不翻譯——各家的模型命名空間
    不交集」。所以指名了型號的鏈換到下一顆時，那個名字對新的一家一定不存在：
    `claude --model <codex 的型號>` 當場 `model-not-found`。

    後果不是「備援效果差一點」，是**備援根本不存在**——鏈上第一顆額度耗盡時，
    第二顆用一個不存在的型號再失敗一次，整條鏈照樣紅。而帳單看起來像是
    「兩家都掛了」，真正的原因（型號傳錯家）一個字都不會出現。

    這是派工表推理列 `模型=codex高階模型` 加 claude 備援的前提：
    沒有這條，那個備援是假的。
    """

    def test_第一家拿得到指名的型號(self) -> None:
        甲 = 記選項的假腦("甲", _答(終局.確定失敗))
        乙 = 記選項的假腦("乙", _答(終局.成功))
        接力腦(名稱="甲→乙", 腦們=(甲, 乙)).詢問(
            "題", 選項=呼叫選項(模型="甲家專屬型號", 權限=權限.唯讀)
        )
        assert 甲.收到[0].模型 == "甲家專屬型號"

    def test_換下一顆時把型號拿掉(self) -> None:
        甲 = 記選項的假腦("甲", _答(終局.確定失敗))
        乙 = 記選項的假腦("乙", _答(終局.成功))
        接力腦(名稱="甲→乙", 腦們=(甲, 乙)).詢問(
            "題", 選項=呼叫選項(模型="甲家專屬型號", 權限=權限.唯讀)
        )
        assert 乙.收到[0].模型 is None, "備援拿到別家的型號名，換過去只會再炸一次"

    def test_其餘旋鈕不准跟著被清掉(self) -> None:
        """只清型號。思考深度、權限、逾時是鏈上共通的設定，清掉等於偷偷改行為。"""
        甲 = 記選項的假腦("甲", _答(終局.確定失敗))
        乙 = 記選項的假腦("乙", _答(終局.成功))
        接力腦(名稱="甲→乙", 腦們=(甲, 乙)).詢問(
            "題", 選項=呼叫選項(模型="甲家專屬型號", 思考深度="max", 權限=權限.唯讀, 逾時秒=42)
        )
        收 = 乙.收到[0]
        assert (收.思考深度, 收.權限, 收.逾時秒) == ("max", 權限.唯讀, 42)
