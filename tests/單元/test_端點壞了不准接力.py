class 假腦:
    """照劇本回答的一顆腦。第 n 次被叫回第 n 個，用完之後一直回最後一個。"""

    def __init__(self, 名稱: str, 劇本: list[回應], *, 網址: str | None = None) -> None:
        """`劇本` 是這顆腦這一輪要依序回的答案。"""
        self.名稱 = 名稱
        self._劇本 = 劇本
        self.次數 = 0
        self._網址 = 網址

    @property
    def 網址(self) -> str:
        """有端點就回端點；沒有端點的假腦以名稱當健康鍵。"""
        return self._網址 or self.名稱

    def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
        del 提示, 選項
        self.次數 += 1
        return self._劇本[min(self.次數 - 1, len(self._劇本) - 1)]


def _壞端點(次數: int) -> 假腦:
    return 假腦("local", [_四〇九()] * 次數)


def _一條鏈(壞幾次: int) -> tuple[接力腦, 假腦, 假腦]:
    """本地一路 409、agy 一路成功的接力鏈。

    **回同一個實例讓測試重複問**：連續次數是跨呼叫的狀態，
    四條線共用一顆腦、一階問一次，出事那晚就是這個形狀。
    """
    本地 = _壞端點(壞幾次)
    備援 = 假腦("agy", [_成功()])
    return 接力腦(名稱="本地優先", 腦們=(本地, 備援)), 本地, 備援


def _正式TDD角色表(
    monkeypatch: pytest.MonkeyPatch,
    *,
    本地回應: Callable[[], 回應],
) -> tuple[Any, list[假腦], list[假腦]]:
    """走正式 `_建TDD角色表`，只把真正的供應商替成假端點。

    健康表由正式組裝點建立；假建構器只接收它，不在測試裡另開一份。
    每個角色仍拿到全新的鏈與腦，只有同一個端點網址能跨鏈共用狀態。
    """
    本地們: list[假腦] = []
    備援們: list[假腦] = []

    def 假建立(
        家: str,
        *,
        執行檔: Path | None,
        可以缺席: bool,
        記: Any,
    ) -> 語言模型:
        del 執行檔, 可以缺席, 記
        if 家 == "local":
            本地 = 假腦(
                f"local-{len(本地們) + 1}",
                [本地回應()],
                網址=_端點,
            )
            本地們.append(本地)
            return 本地
        備援 = 假腦(f"{家}-{len(備援們) + 1}", [_成功()])
        備援們.append(備援)
        return 備援

    monkeypatch.setattr(命令列模組, "建立或缺席", 假建立)
    藍圖們 = tuple(
        replace(藍圖, 派法=replace(藍圖.派法, 腦們=("local", "agy")))
        for 藍圖 in 建TDD角色藍圖(怎麼派)
    )
    角色表 = 命令列模組._建TDD角色表(
        藍圖們,
        執行檔=None,
        帳=不記帳本(),
        記全文=False,
    )
    return 角色表, 本地們, 備援們


class Test端點壞了就不准再接力:
    def test_上限有一個常數的家(self) -> None:
        """N 寫成一個常數，不准散在各處。值是 2 或 3 由實作決定——但不准是 1。"""
        上限 = getattr(接力模組, "連續失敗上限", None)
        assert isinstance(上限, int), "連續失敗上限沒有一個常數的家，判斷散在各處"
        assert 2 <= 上限 <= 3, f"連續失敗上限＝{上限}：1 等於廢掉接力，太大則攔不住那 23 分鐘"

    def test_只失敗一次照舊接力(self) -> None:
        """矯枉過正的反向護欄：單次失敗仍然要換下一家，這條不准被順手收緊。"""
        鏈, 本地, 備援 = _一條鏈(壞幾次=1)

        答 = 鏈.詢問("寫一支會紅的測試")

        assert 本地.次數 == 1
        assert 備援.次數 == 1, "只失敗一次就不接力了——收得太緊"
        assert 答.終局 is 終局.成功

    def test_額度耗盡連續三次仍走備援(self, monkeypatch: pytest.MonkeyPatch) -> None:
        """額度耗盡不是端點故障，連續三次也要照原策略換到備援。"""
        角色表, 本地們, 備援們 = _正式TDD角色表(monkeypatch, 本地回應=_額度耗盡)
        角色 = next(iter(角色表.values()))

        答們 = [角色.腦.詢問(f"第 {序} 次") for 序 in range(3)]

        assert [答.終局 for 答 in 答們] == [終局.成功] * 3
        assert 本地們[0].次數 == 3
        assert 備援們[0].次數 == 3, "額度耗盡被端點熔斷攔掉，沒有走備援"

    def test_連續三次409就不准再接力(self) -> None:
        """第三次撞上去時，備援不准再被叫，當場收成確定失敗。

        不綁死 N：N＝2 的話第二次就停了，第三次一樣停——備援次數只會更少。
        """
        鏈, 本地, 備援 = _一條鏈(壞幾次=3)

        答們 = [鏈.詢問(f"第 {序} 階") for 序 in range(3)]

        assert 本地.次數 <= 3, f"停下來之後還在打那個端點：問了 {本地.次數} 次"
        assert 備援.次數 <= 2, f"本地連三次同一種 409 了還在接力：agy 被叫了 {備援.次數} 次"
        assert 答們[-1].終局 is 終局.確定失敗, "端點壞了要收成確定失敗，不是拿備援的答案蓋過去"

    def test_停下來的訊息要指名端點與原文(self) -> None:
        """看訊息的人要能直接去修那台服務，所以網址與原句都得在。"""
        鏈, _, _ = _一條鏈(壞幾次=3)

        答 = [鏈.詢問(f"第 {序} 階") for 序 in range(3)][-1]

        assert _端點 in 答.文字, f"沒指名是哪個端點壞了：{答.文字}"
        assert _原文 in 答.文字, f"沒帶上游的原始錯誤字串：{答.文字}"

    def test_判死之後不准再打那個端點(self) -> None:
        """撞到上限就是判死，**判死之後的每一次詢問都不准再送出去**。

        現場那 23 分鐘打了至少 11 次 409。只停掉「接力」是停一半：
        剩下那幾次照樣一次一個來回地打在同一台壞掉的服務上，
        壞的是 unload 旗標，多打幾次不會把它打好，只會把時間燒完。
        所以短路要在打出去**之前**——被判死的端點不准再收到請求。

        這條同時逼出一件事：沒有新的一次呼叫，就沒有新的錯誤文字，
        「指名端點與原文」只能靠端點健康表記著上一次的原文長出來。
        訊息不准因為短路就退化成「呼叫失敗」，失敗代碼也要還是同一類。

        刻意不綁死 N：問 `連續失敗上限 + 2` 次，斷言「打出去的次數剛好等於上限」。
        """
        上限 = 接力模組.連續失敗上限
        鏈, 本地, 備援 = _一條鏈(壞幾次=上限 + 2)

        答們 = [鏈.詢問(f"第 {序} 次") for 序 in range(上限 + 2)]

        assert 本地.次數 == 上限, f"判死之後又去打了那個端點：一共打了 {本地.次數} 次"
        assert 備援.次數 <= 上限 - 1, f"判死之後還在接力：agy 被叫了 {備援.次數} 次"
        assert 答們[-1].終局 is 終局.確定失敗, "短路之後不准回成別的終局"
        assert 答們[-1].失敗代碼 is 失敗代碼.上游, f"短路把錯的種類弄丟了：{答們[-1].失敗代碼}"
        assert _端點 in 答們[-1].文字, f"短路之後就不指名端點了：{答們[-1].文字}"
        assert _原文 in 答們[-1].文字, f"短路之後就沒有上游原文了：{答們[-1].文字}"

    def test_中間成功一次就把連續次數歸零(self) -> None:
        """「連續」是連續，不是總數。中間好過一次，計數就得重新算。"""
        本地 = 假腦("local", [_四〇九(), _成功("恢復了"), _四〇九()])
        備援 = 假腦("agy", [_成功()])
        鏈 = 接力腦(名稱="本地優先", 腦們=(本地, 備援))

        答們 = [鏈.詢問(f"第 {序} 階") for 序 in range(3)]

        assert 本地.次數 == 3, "本地被提前判死了——中間成功那次沒有把連續次數歸零"
        assert 備援.次數 == 2, "歸零之後的第一次失敗不准直接停，那還在接力額度內"
        assert 答們[-1].終局 is 終局.成功

    def test_四階各建一顆新鏈仍然共用端點壞掉的狀態(self, monkeypatch: pytest.MonkeyPatch) -> None:
        """壞的是端點，不是某一條鏈的物件。

        `建角色表` 為四階各叫一次 `建腦`，四階拿到的是四條新鏈、四顆新本地腦。
        計數若綁在單一鏈實例上，現場「每階各一次 409」只會各自累計到 1，
        四條線照樣一路接力燒到底——修了等於沒修。
        """
        角色表, 本地們, 備援們 = _正式TDD角色表(monkeypatch, 本地回應=_四〇九)
        答們 = [角色.腦.詢問(f"第 {階} 階") for 階, 角色 in enumerate(角色表.values())]

        叫過備援 = sum(腦.次數 for 腦 in 備援們)
        assert 叫過備援 <= 2, f"換一條新鏈就把端點壞掉忘光了：agy 被叫了 {叫過備援} 次"
        assert 答們[-1].終局 is 終局.確定失敗, "第四階還在拿備援的答案蓋過去，沒有人喊本地腦壞了"
        assert _端點 in 答們[-1].文字, f"沒指名是哪個端點壞了：{答們[-1].文字}"
        assert _原文 in 答們[-1].文字, f"沒帶上游的原始錯誤字串：{答們[-1].文字}"


class Test整輪工作流:
    def test_端點壞了整輪就停在半路(self, monkeypatch: pytest.MonkeyPatch) -> None:
        """走**正式的角色建構路徑**：藍圖 → `建角色表` → 每階一顆新腦。

        不手動讓四階共用同一顆腦——那樣就是替實作把最難的一半先做掉了，
        而現場燒掉四條線的原因正是「每階都是新物件」。

        修好之前，這一輪會一路 409 → 接力 → 下一階，燒完四階的預算才收工，
        退出碼還是 0。修好之後：撞上限的那一階當場中止，審查根本走不到。
        """
        角色表, 本地們, _備援們 = _正式TDD角色表(monkeypatch, 本地回應=_四〇九)
        依識別碼 = {階段代碼(識別碼): 角 for 識別碼, 角 in 角色表.items()}
        剩 = [False, True, True]  # 驗證紅→紅、驗證綠→綠、驗證重構→綠

        def 跑判準(_: 任務) -> tuple[判準終局, str]:
            return (判準終局.綠 if (剩.pop(0) if 剩 else True) else 判準終局.紅), "假判準"

        執行 = 建TDD執行器(
            角色表={階段代碼(識別碼): 角 for 識別碼, 角 in 依識別碼.items()},
            跑判準=跑判準,
            篩選指定測試=可作指定pytest目標,
        )

        果 = 跑工作流(_一件事, 執行一步=執行)
        走過 = [步.階段 for 步 in 果.軌跡]

        assert 果.結束.代碼 is not 結束代碼.完成, f"端點壞了整輪卻收成完成：{果.結束.原因}"
        assert _工作流退出碼(果.結束, 果.軌跡) != 0, "退出碼 0——外圈看不出本地腦壞了"
        assert 階段代碼.審查 not in 走過, f"撞上限之後還往下走了：{走過}"
        assert sum(腦.次數 for 腦 in 本地們) <= 3, "停下來之後還在打那個端點"
        最後 = 果.軌跡[-1].證據
        assert _端點 in 最後 and _原文 in 最後, f"停下來了卻沒說是哪個端點、什麼錯：{最後}"


def _丟出(錯誤: BaseException) -> Callable[..., NoReturn]:
    """做一個永遠丟同一種錯的 `urlopen`，讓測試不需要真的連線。"""

    def 丟(*參數: object, **關鍵字: object) -> NoReturn:
        del 參數, 關鍵字
        raise 錯誤

    return 丟


def test_409的回應體要進到失敗訊息(monkeypatch: pytest.MonkeyPatch) -> None:
    """上游那句原話只存在於回應體裡。

    只說「回 HTTP 409」的話，連續三次之後就算停下來了，
    訊息裡也還是沒有那句可行動的原文——人看了還是不知道要去 unload 誰。
    """
    錯 = urllib.error.HTTPError(
        f"{_端點}/chat/completions",
        409,
        "Conflict",
        HTTPMessage(),
        io.BytesIO(f'{{"detail": "{_原文}"}}'.encode()),
    )
    monkeypatch.setattr(urllib.request, "urlopen", _丟出(錯))

    答 = 本地腦(網址=_端點).詢問("在嗎")

    assert 答.終局 is 終局.確定失敗
    assert _端點 in 答.文字
    assert "409" in 答.文字
    assert _原文 in 答.文字, f"409 的回應體被丟掉了，只剩狀態碼：{答.文字}"
