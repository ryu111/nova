"""端點壞了就不准再接力：連續 N 次同一個端點回同一類錯，當場停下並指名。

## 現場（2026-09-02 01:45 → 02:08）

記憶體壓力讓 oMLX 中止請求並卸載模型之後，本地端點的 unload 旗標卡住，
之後**每一個** `POST /v1/chat/completions` 都回：

    409 Model 'Qwen3.8-27B-8bit' is busy; cannot start work while unload is
    pending until active requests finish or are aborted

而同一時間 oMLX 自己的 `/admin/api/activity` 說 `active_requests: 0`
——一個進行中的請求都沒有，旗標卻卡在「等進行中的請求結束」。
23 分鐘、至少 11 次 409，四條線一路接力燒到底，**沒有任何一個地方
說過「本地腦壞了」**。

## 這支守什麼

「這一次呼叫失敗」與「這個端點壞了」是兩件事，正確反應相反：

| | 這一次失敗 | 端點壞了 |
|---|---|---|
| 該做 | 接力給下一家 | **當場停下，指名是哪個端點、什麼錯** |
| 出事那晚做的 | 接力 | 接力（錯） |

所以：**連續 `連續失敗上限` 次同一個端點回同一類錯，就不准再接力**，
收成確定失敗，訊息裡指名端點網址與原始錯誤字串。

N 由 `nova.載體.模型.接力.連續失敗上限` 一個常數說了算，不散在各處。
斷言刻意**不綁死 N 等於幾**：2 或 3 都跑得過（現場那晚 23 分鐘、至少 11 次
409，兩個值都攔得住），只有 1 不行——第一次失敗就停等於廢掉接力，
那條由 `test_只失敗一次照舊接力` 反向釘住。

## 計數住在哪：端點，不是某一條鏈

`迴圈/角色工廠.py` 的 `建角色表` 會**為四階各叫一次 `建腦`**，也就是四階
各拿到一條新的接力鏈、一顆新的 `本地腦` 物件。壞掉的是**那台服務**，
不是那顆 Python 物件——計數綁在單一鏈實例的話，現場「每階各一次 409」
只會各自累計到 1，四條線照樣一路接力燒到底，等於沒修。

所以整輪那支刻意走**正式的角色建構路徑**（`建TDD角色藍圖` ＋ `建角色表`），
`test_四階各建一顆新鏈仍然共用端點壞掉的狀態` 則把同一件事釘在單元層。

## 這支**不**守什麼

- 不去 administering oMLX。**nova 不准自己 unload／load 那台服務**，
  只要當場停下並說清楚，人看到訊息自己去修
  （`POST /admin/api/models/<id>/unload` 再 `load`，`active_requests` 為 0 時無損）。
- 不真的連 oMLX：端點是注入的假腦。不開子程序、不碰網路。

## 負控

把「連續 N 次就停」的判斷拿掉（或把 `連續失敗上限` 改成一個大數），
`test_連續三次409就不准再接力` 與 `test_端點壞了整輪就停在半路` 要紅。
把端點狀態改回綁在單一鏈實例（各鏈自己一份計數），
`test_四階各建一顆新鏈仍然共用端點壞掉的狀態` 與整輪那支要紅。
把「判死之後直接短路」那一段拿掉（改回每次都先打一次再看計數），
`test_判死之後不准再打那個端點` 要紅。
"""

