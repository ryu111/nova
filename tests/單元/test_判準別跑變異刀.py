"""判準不准跑那 121 把變異刀，**而且不准因此少驗任何一支別的測試**。

## 現在的洞

修正前，判準的全測試那一步是 `預設判準指令 = ("uv", "run", "pytest", "-q")`，
配上 `pyproject.toml` 的 `testpaths = ["tests"]`，於是 `tests/負控/` 底下
登記負控那個檔也被收進去——每一把變異刀都 fork 一次巢狀 pytest ＋
`coverage run`，序列跑。判準又進 `名稱="閘"` 的全域互斥鎖
（`判準.py` 的 `佔不到` 那段），所以這條序列工作把六條線串成一列
（量測見 `docs/設計/14-閘慢在哪.md`）。

一輪 TDD 有三個判準階段，六條線就是 18 次 × 121 把。

## 為什麼負控刀不該由判準跑

判準回答的是「這一輪的行為對不對」；變異刀驗的是「測試守不守得住」，
那是 CI 上 `registered-mutation` 那條規則的工作。每個判準階段各跑一次，
驗的是同一件早就驗過的事。

## 為什麼清單要從 `規則表.負控檔們` 推導

判準這邊手抄一份檔名的話，新增負控檔時判準不會跟上，這個洞會靜靜長回來。
所以斷言的右手邊一律是 `規則表` 現算出來的，**手抄檔名不算**。

## 判準不跑的是哪些刀

判準不跑的是**全量 220 把 × 18 次**；本線 diff 動過的那幾把（典型 1～3 把、約 6 秒）
由 `registered-mutation-diff` 在全綠之後跑一次，兩者不衝突。
"""

from pathlib import Path

from nova.載體.判準 import (
    _提交閘指令,
    判準步驟,
    子程序自己拿,
    預設判準指令,
    預設判準步驟們,
)
from nova.載體.規則表 import 負控檔們, 負控檔排除參數

#: 建表本身不碰硬碟，所以根目錄給一個不存在的路徑就夠了（同 `test_判準涵蓋提交閘.py`）。
_不碰硬碟的根 = Path("/不存在也沒關係/建表時不該碰硬碟")

#: 修正前的全測試指令。修正只准往後面接負控檔的 `--ignore`，**前面這幾段原樣不動**：
#: 動了就是換一條指令在跑，涵蓋是寬是窄無從得知。
_修正前的全跑指令 = ("uv", "run", "pytest", "-q")


def _全測試步驟() -> 判準步驟:
    """預設判準裡跑 pytest 的那一步。**現算，不假設它排第幾個。**"""
    候選 = [步 for 步 in 預設判準步驟們(_不碰硬碟的根) if "pytest" in 步.指令]
    assert len(候選) == 1, f"預設判準裡跑 pytest 的步驟不是剛好一步：{候選}"
    return 候選[0]


class Test判準別跑變異刀:
    def test_預設判準的全跑指令排除每一個負控檔(self) -> None:
        """`規則表.負控檔們` 裡的每一個檔，判準的全跑指令都要排掉。

        清單從規則表推導：這裡不寫任何一個檔名，右手邊是
        `負控檔排除參數`（`#196` 做好的單一來源）現算出來的。
        """
        # 先確認題目本身不是空的——空清單會讓下面那條斷言恆真（假綠）。
        assert 負控檔們, "規則表上一個負控檔都沒登記，這支測試在測空氣"
        assert 負控檔排除參數, "負控檔排除參數是空的，這支測試在測空氣"

        指令 = _全測試步驟().指令
        漏掉的 = [參數 for 參數 in 負控檔排除參數 if 參數 not in 指令]
        assert not 漏掉的, (
            f"判準的全跑指令還會收到這幾個負控檔（每一把變異刀都 fork 一次巢狀 "
            f"pytest，判準又在全域鎖裡）：{漏掉的}；現在的指令是 {list(指令)}"
        )

    def test_排除負控刀沒有讓判準的涵蓋變窄(self) -> None:
        """**這是最容易寫錯的一格。** 排除排太多會讓判準更快變綠，長得像改善。

        釘法是**整條指令逐段對齊**：修正前那條原樣留著，後面只准接規則表推導出來的
        `--ignore`。多一段就會紅——不論那一段是 `-m`／`--deselect` 這種少收集的旗標、
        是把範圍縮成某幾條路徑（範圍還是 `pyproject.toml` 的 `testpaths`，那個檔不准動），
        還是排掉負控檔以外的檔。**不必維護一份「哪些旗標算縮小」的黑名單。**

        這一格現在就是綠的——它的工作是在下一步實作之後**還是綠的**。
        """
        assert _全測試步驟().指令 == (*_修正前的全跑指令, *負控檔排除參數), (
            f"判準的全跑指令不是「修正前那條 ＋ 規則表推導的 --ignore」：{list(_全測試步驟().指令)}"
        )

    def test_登記的負控檔真的在硬碟上(self) -> None:
        """排除參數指到不存在的檔時，`--ignore` 會靜靜地什麼都沒排掉。

        那時第一支測試照樣綠，而 121 把刀還在跑——所以這裡順手釘住
        `負控檔們` 指的是真實路徑。
        """
        專案根 = Path(__file__).resolve().parents[2]
        不存在的 = [檔 for 檔 in 負控檔們 if not (專案根 / 檔).is_file()]
        assert not 不存在的, f"規則表登記的負控檔在硬碟上找不到：{不存在的}"

    def test_預設判準指令本身還是跑pytest(self) -> None:
        """判準的全跑不准被換成別的東西（例如只跑 `tests/單元`）。

        `_像pytest` 的退出碼翻譯（exit 4／5 是「沒驗到」而不是紅）綁在
        指令長得像 pytest 上，換掉就連帶把那個翻譯關掉。
        """
        assert "pytest" in 預設判準指令, f"預設判準指令不再是 pytest：{預設判準指令}"
        assert "-q" in 預設判準指令


class Test本線負控接在最後一步:
    """本線 diff 動過的那幾把刀，由判準的**最後一步**跑。"""

    def test_預設判準最後一步是nova閘本線(self) -> None:
        """本線負控排在全測試與提交閘**之後**，走 `nova 閘 本線`，欄位照抄提交閘那步。

        守四件事：
        1. 順序——排在全測試前面的話，`驗證紅` 那階會跑到它，
           而那階全測試本來就該紅，刀必然 `BASELINE_RED`（一條線停在假的紅上）。
        2. 走 `nova 閘 本線`，不是自己拼一條 pytest：拼 pytest 會讓「含 `pytest`
           的步驟剛好一步」當場破掉（見 `_全測試步驟`），輸出格式也不再跟其他閘一致。
        3. `涵蓋規則=()`——它跑的是本線動過的那幾把，不涵蓋 CI 那條全量的
           `registered-mutation`，宣告涵蓋就是說謊。
        4. `要幾個token` 與 `未知退出碼` 跟提交閘那步同一套：`nova 閘` 自己會去池子抽，
           父程序再佔一個就是自己鎖死自己（症狀是**掛住**，不是紅）；佔不到鎖時
           `nova 閘` 回 3 ＝ 沒跑到，不是紅。
        """
        步驟們 = 預設判準步驟們(_不碰硬碟的根)
        assert len(步驟們) == 3, f"預設判準不是三步：{[步.名稱 for 步 in 步驟們]}"
        assert 步驟們[0].指令 == 預設判準指令, "第一步不是全測試"
        assert 步驟們[1].指令 == _提交閘指令, "第二步不是提交閘"

        本線步 = 步驟們[-1]
        assert 本線步.指令 == ("uv", "run", "nova", "閘", "本線"), (
            f"最後一步不是 `nova 閘 本線`：{list(本線步.指令)}"
        )
        assert 本線步.涵蓋規則 == (), (
            f"本線那步不涵蓋 CI 的全量負控，涵蓋規則要是空的：{本線步.涵蓋規則}"
        )

        提交閘步 = 步驟們[1]
        assert 本線步.要幾個token is 子程序自己拿, (
            f"本線那步的 要幾個token 不是 子程序自己拿（會自己鎖死自己）：{本線步.要幾個token}"
        )
        assert 提交閘步.未知退出碼, "提交閘那步沒有未知退出碼，下面那條斷言會恆真"
        assert 本線步.未知退出碼 == 提交閘步.未知退出碼, (
            f"本線那步的未知退出碼沒跟提交閘那步一致：{本線步.未知退出碼}"
        )

        # 順手釘住最容易砸的既有斷言：多接一步不准把「跑 pytest 的剛好一步」弄破。
        assert _全測試步驟().指令 == 預設判準指令
