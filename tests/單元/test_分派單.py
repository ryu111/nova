from dataclasses import replace

from nova.契約.分派 import 分派問題代碼, 分派單, 分派單問題, 分派項目
from nova.契約.節點 import 停止政策, 分支識別碼, 節點識別碼, 結構識別碼
from nova.迴圈.計畫 import 執行限制, 驗證分派單

_已知節點 = 節點識別碼("已知節點")
_文字結構 = 結構識別碼("輸入-文字")
_正常停止 = 停止政策(最多呼叫=1, 最多token=100, 最多秒=1.0, 最多無進展=1)
_雙項停止 = 停止政策(最多呼叫=2, 最多token=200, 最多秒=2.0, 最多無進展=1)
_超額停止 = 停止政策(最多呼叫=2, 最多token=200, 最多秒=2.0, 最多無進展=1)
_正常項目 = 分派項目(
    識別碼="項目-001",
    節點=_已知節點,
    輸入結構=_文字結構,
    前置項目=(),
    分支=None,
    必要=True,
    停止=_正常停止,
    驗收出口=("驗收-完成",),
)
_正常限制 = 執行限制(
    停止=_正常停止,
    允許網路=True,
    允許編輯=True,
    可用節點=(_已知節點,),
    可用結構=(_文字結構,),
    最大分支數=1,
)
_雙項限制 = replace(_正常限制, 停止=_雙項停止)


def _建立分派單(
    *,
    項目: tuple[分派項目, ...] = (_正常項目,),
    最大分支數: int = 1,
    總停止: 停止政策 | None = _正常停止,
) -> 分派單:
    return 分派單(
        版本=1,
        項目=項目,
        最大分支數=最大分支數,
        總停止=總停止,
    )


def _驗證(分派: 分派單, *, 限制: 執行限制 = _正常限制) -> tuple[分派單問題, ...]:
    return 驗證分派單(分派, 限制=限制)


def _斷言只有指定代碼(
    分派: 分派單,
    代碼: 分派問題代碼,
    *,
    限制: 執行限制 = _正常限制,
) -> None:
    問題們 = _驗證(分派, 限制=限制)

    assert tuple(問題.代碼 for 問題 in 問題們) == (代碼,)


