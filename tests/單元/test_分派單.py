def test_同時犯多種錯時要收集每一種代碼() -> None:
    分派 = _建立分派單(
        項目=(
            replace(
                _正常項目,
                識別碼="重複項目",
                節點=節點識別碼("不存在的節點"),
                輸入結構=結構識別碼("不存在的結構"),
                前置項目=("不存在的依賴",),
            ),
            replace(_正常項目, 識別碼="重複項目"),
            replace(_正常項目, 識別碼="循環甲", 前置項目=("循環乙",)),
            replace(_正常項目, 識別碼="循環乙", 前置項目=("循環甲",)),
            replace(_正常項目, 識別碼="分支一", 分支=分支識別碼("分支-一")),
            replace(_正常項目, 識別碼="分支二", 分支=分支識別碼("分支-二")),
            replace(_正常項目, 識別碼="缺停止", 停止=None),
            replace(_正常項目, 識別碼="缺驗收", 驗收出口=()),
            replace(_正常項目, 識別碼="要網路", 需要網路=True),
        ),
        最大分支數=2,
        總停止=_超額停止,
    )

    問題代碼們 = {
        問題.代碼
        for 問題 in _驗證(
            分派,
            限制=replace(_正常限制, 允許網路=False, 最大分支數=1),
        )
    }

    assert 問題代碼們 == {
        分派問題代碼.未知節點,
        分派問題代碼.輸入結構錯誤,
        分派問題代碼.依賴不存在,
        分派問題代碼.重複項目,
        分派問題代碼.循環前置,
        分派問題代碼.超出扇出上限,
        分派問題代碼.超出預算,
        分派問題代碼.缺停止政策,
        分派問題代碼.缺驗收條件,
        分派問題代碼.權限不足,
    }
