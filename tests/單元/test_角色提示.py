"""四個角色提示都要講「怎麼找」，不能只講「做什麼」。

## 為什麼

量到的：agy 跑真任務單階 375,061／410,294 input token，claude 同一份工作約 8,600，
**46 倍**；codex 每輪重送 context，出現過 826 萬。

原因不是 CLI 把工作區打包進 context——三格實驗把這個假說量掉了：

| 條件 | input tokens |
|---|---|
| 空目錄 ＋「回一個字：好」 | 13,720 |
| **nova 目錄** ＋ 同一句 | **13,726**（只差 6 個） |
| nova 目錄 ＋ 真任務 | 375,061 / 410,294 |

第二格是關鍵：工作區從空的換成 2,007,790 字元的 repo，固定成本沒動。
**所以是模型自己在工具迴圈裡選擇讀滿**，而 `角色提示.py` 過去一個字都沒講讀取策略，
各家就各用各的預設。旗標也關不小：`codex exec --help` 沒有任何 token／budget／
max-turn 旗標，`agy --help` 只有 `--add-dir`（**加**目錄）。剩下的桿只有提示。

## 這支守得到什麼、守不到什麼

**守得到**：那幾段話不會被人順手刪掉或改成寫死路徑。這是防退化。

**守不到**：token 真的有沒有降下來。提示是懇求不是保證——模型可以讀了那句話還是
把 repo 吃滿。真驗收要**量**：重派後看帳本裡 agy 單階 input 對照基線 375k／410k
有沒有量級下降（`nova 帳本`）。兜底保證是 `契約/工作流.py` 的
`單次最多token`（預設 2,000,000），那條才是殼。

量法：`cd <目錄> && agy --model gemini-3.7-flash-high -p "回一個字：好" --output-format json`，
讀 `usage.input_tokens`。旗標是 `--model` 不是 `-m`。
"""

import pytest

from nova.迴圈.角色提示 import 實作員, 審查員, 測試員, 重構員

四個角色提示 = [
    ("測試員", 測試員),
    ("實作員", 實作員),
    ("重構員", 重構員),
    ("審查員", 審查員),
]
#: 不給 `ids` 的話 pytest 會拿**整段提示**當測試 id，紅的時候輸出爆炸到讀不了。
_角色名們 = [名 for 名, _ in 四個角色提示]


class Test角色提示讀取策略:
    """驗證四個角色的系統提示都明確規範了檔案讀取與探索策略。"""

    @pytest.mark.parametrize("角色名稱,提示內容", 四個角色提示, ids=_角色名們)
    def test_提示必須包含讀取策略段落(self, 角色名稱: str, 提示內容: str) -> None:
        """每個角色提示都必須有明確的讀取策略說明，不能只講做什麼。"""
        assert "讀取策略" in 提示內容 or "探索策略" in 提示內容, (
            f"{角色名稱} 的系統提示缺少「讀取策略」或「探索策略」段落說明"
        )

    @pytest.mark.parametrize("角色名稱,提示內容", 四個角色提示, ids=_角色名們)
    def test_讀取策略必須要求按需定位而非讀滿目錄(self, 角色名稱: str, 提示內容: str) -> None:
        """必須明講先定位／按需讀取，且不准把整個工作目錄讀進來。"""
        按需關鍵字 = ("按需", "定位", "只讀需要", "只讀真正需要", "只讀真需要")
        有按需或定位 = any(關鍵字 in 提示內容 for 關鍵字 in 按需關鍵字)
        assert 有按需或定位, f"{角色名稱} 的提示未指示先定位或按需讀取真正需要的檔案"

        禁止全讀關鍵字 = ("整個工作目錄", "全部檔案", "整個目錄", "整份repo", "整個專案")
        有禁止讀滿目錄 = any(關鍵字 in 提示內容 for 關鍵字 in 禁止全讀關鍵字)
        assert 有禁止讀滿目錄, f"{角色名稱} 的提示未明確禁止把整個工作目錄或全部檔案讀入"

    @pytest.mark.parametrize("角色名稱,提示內容", 四個角色提示, ids=_角色名們)
    def test_讀取策略不准寫死路徑(self, 角色名稱: str, 提示內容: str) -> None:
        """讀取策略不能把路徑寫死（如「只讀 src」），避免與特定專案結構綁死。"""
        assert "只讀 src" not in 提示內容, f"{角色名稱} 的讀取策略寫死了 src 路徑"
        assert "只讀 tests" not in 提示內容, f"{角色名稱} 的讀取策略寫死了 tests 路徑"


class Test不准自己跑全套測試:
    """**驗證是 verify-* 階段的事，模型階段跑全套等於同一份測試跑兩次。**

    帳本 `20260831T023011Z-49d782` 的 `text` 欄位逐字：
    seq 9「已啟動全套 pytest 測試並等待其執行完成／等待完整測試套件完成執行」、
    seq 31「正在等待測試驗收完成…繼續等待測試全套跑完…」。

    那套測試要跑約 140 秒，而 nova 在**下一階**（verify-*）會再跑一次同一套。
    模型每輪詢一次「跑完了沒」，就把整份 prefix 再送一次——而那一輪 90% 的
    token 正是同一次呼叫內部的 prefix 重送（單筆 cache_read 8,796,414，
    比單一請求的 context window 大將近一個數量級）。

    **省多少未知**（seq 15 是反例：等待文字最多、cache 卻最少），
    但它是目前唯一直接對準那 90%、而且成本近乎零的動作。
    真驗收要同題目跑 3 次以上比中位數——n=1 對 n=1 沒有意義。
    """

    @pytest.mark.parametrize("角色名稱,提示內容", 四個角色提示, ids=_角色名們)
    def test_提示明講不要自己跑全套測試(self, 角色名稱: str, 提示內容: str) -> None:
        關鍵 = ("全套", "整套", "全部測試", "所有測試")
        assert any(詞 in 提示內容 for 詞 in 關鍵), f"{角色名稱} 的提示沒提到全套測試這件事"

    @pytest.mark.parametrize("角色名稱,提示內容", 四個角色提示, ids=_角色名們)
    def test_提示要指出驗證是別的階段的事(self, 角色名稱: str, 提示內容: str) -> None:
        """只說「不要跑」不夠——要說明為什麼，否則模型會覺得自己在偷懶。"""
        assert "verify" in 提示內容 or "驗證階段" in 提示內容, (
            f"{角色名稱} 的提示沒說明驗證由誰負責"
        )
