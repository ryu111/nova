"""工具呼叫要留下證據。

2026-08-31 撞到：27B 走工作流跑滿 8 回合工具呼叫沒收尾，帳本記得到
`63667→5443 token · 9 分 6 秒`，但**完全看不到它叫了哪些工具**——
欄位裡沒有任何 tool 相關的東西。

「為什麼不收尾」這個問題因此無法從帳本回答，只能重跑一次在旁邊加 print。
而 CLAUDE.md 的診斷順序是「有動作但沒證據就停 → 查迴圈」——
迴圈層沒留下證據的話，那一步就卡在那裡。
"""

from nova.契約.帳本 import 事件, 事件種類, 欄位對應


def test_有工具呼叫這個事件種類() -> None:
    assert hasattr(事件種類, "工具呼叫")


def test_事件帶得動工具名稱與參數摘要() -> None:
    一筆 = 事件(種類=事件種類.工具呼叫, 工具名稱="read_file", 工具參數摘要="path=算術.py")
    assert 一筆.工具名稱 == "read_file"
    assert 一筆.工具參數摘要 == "path=算術.py"


def test_事件帶得動這是第幾回合() -> None:
    """**回合數是診斷的關鍵**：卡在第 2 回合跟跑滿 8 回合是兩種病。"""
    一筆 = 事件(種類=事件種類.工具呼叫, 工具回合=3)
    assert 一筆.工具回合 == 3


def test_事件帶得動工具成功與否() -> None:
    """工具失敗是正常的（模型會叫不存在的檔案），但**一直失敗**是病徵。"""
    一筆 = 事件(種類=事件種類.工具呼叫, 工具成功=False)
    assert 一筆.工具成功 is False


def test_欄位名是ASCII跨程序() -> None:
    """帳本是 JSONL，會被 grep 與 jq 讀——中文鍵在 shell 裡很難打。"""
    for 中, 英 in 欄位對應.items():
        if "工具" in 中:
            assert 英.isascii(), (中, 英)
