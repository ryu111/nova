"""單次上限比的是「這次呼叫燒掉多少新鮮 token」，不是「上下文有多大」。

單次上限是 runaway 護欄（`契約/工作流.py:212`：擋一次呼叫內部跑幾十輪的爆量）。
**快取讀取不是燒錢**：它是重讀已經快取好的上下文，兩家都按 0.1× 計價，
而且跟「這次呼叫做了多少工」無關——30 回合每回合重讀 70k 上下文就是
2.1M `cache_read`，真正的工只有 output 那兩萬。實測 21 筆被收 4 的
`single_token_exceeded` 全是 codex，快取佔 input 90%～98%，扣掉快取後
新鮮量 154k～685k，沒有一筆到 200 萬。

**快取建立相反**：它在 `input_tokens` 之外、按 1.25× 計價，是真的新鮮輸入，
一定要算。所以這一支釘的是同一條線的兩邊：
快取讀取三百萬不准收手，快取建立兩百一十萬非收不可。
"""

import dataclasses

import pytest

from nova.契約.模型回應 import 回應, 失敗代碼, 用量, 終局
from nova.契約.角色 import 呼叫選項, 預設選項
from nova.載體.命令列 import _單次上限腦, _單次超標

單次上限 = 2_000_000


@dataclasses.dataclass
class _假腦:
    """吃固定用量的假內層——這一支量的是護欄怎麼判，不是誰去問的。"""

    這次的用量: 用量
    名稱: str = "假腦"

    def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
        del 提示, 選項
        return 回應(
            文字="ok",
            終局=終局.成功,
            失敗代碼=失敗代碼.無,
            原始結束碼=0,
            對話識別碼=None,
            用量=self.這次的用量,
        )


def _問一次(這次的用量: 用量) -> 回應:
    腦 = _單次上限腦(內層=_假腦(這次的用量), 單次上限=單次上限)
    return 腦.詢問("隨便問")


def test_快取讀取三百萬不算燒錢_不准收手() -> None:
    """ac9295 那條線的形狀：上下文很大，這一次呼叫做的工很小。"""
    答 = _問一次(
        用量(輸入token=20_000, 輸出token=20_000, 快取建立token=10_000, 快取讀取token=3_000_000)
    )

    assert 答.文字 == "ok"


def test_快取建立兩百一十萬要算新鮮_必須收手() -> None:
    """快取建立不是快取讀取的子集，1.25× 計價，是真的付費的新鮮輸入。"""
    這次的用量 = 用量(輸入token=100, 輸出token=21_874, 快取建立token=2_100_000)

    with pytest.raises(_單次超標) as 收手:
        _問一次(這次的用量)

    assert 收手.value.單次上限 == 單次上限
    assert 收手.value.答.用量 == 這次的用量


def test_純輸出兩百一十萬照樣收手() -> None:
    """新鮮量的下界：一個快取欄都沒有時，行為不准因為這次改動走樣。"""
    with pytest.raises(_單次超標):
        _問一次(用量(輸入token=0, 輸出token=2_100_000))
