"""跨執行預算鎖：一段時間內花超過就不再打出去。

工作流那一層本來就有 stop rule（步數上限＋token 上限，一次執行之內累計）。
**缺的是跨執行那一段**：`nova 問` 一次只發一個請求，單看那一次永遠沒有超支，
但一天叫兩百次就是另一回事——而那正是排程開始自己跑之後會發生的事。

累計的對象是**這個專案的帳本**（成本落盤做完才有的東西）。

## 預設關閉，這是使用者明講的決定

「我主要是要看帳，但不要讓帳去把流程關閉。」熔斷是這樣，預算也是這樣。
機制存在、測得到、要用打開就有——但不准因為帳本裡的歷史而**預設**擋掉呼叫。

純函式，不碰硬碟，所以住單元層。
"""

import dataclasses
from datetime import UTC, datetime, timedelta

import pytest

from nova.契約.帳本 import 一家的帳, 摘要
from nova.載體.預算 import 上限, 花了多少, 超支了嗎

_現在 = datetime(2026, 8, 30, 12, 0, tzinfo=UTC)


def _一次(幾小時前: float, *, token: int = 1000, 成本: float | None = 0.5) -> 摘要:
    當時 = (_現在 - timedelta(hours=幾小時前)).isoformat()
    return 摘要(
        執行識別碼=f"r-{幾小時前}",
        起=當時,
        迄=當時,
        各家=(
            一家的帳(
                供應商="claude",
                次數=1,
                成功=1,
                失敗=0,
                未知=0,
                輸入token=token // 2,
                輸出token=token // 2,
                成本美金=成本,
            ),
        ),
        階段們=(),
        沒收尾的呼叫=(),
        壞掉的行=0,
        總token=token,
        總成本美金=成本,
    )


class Test花了多少:
    def test_窗口內的加起來(self) -> None:
        花 = 花了多少([_一次(1), _一次(2)], 現在=_現在, 幾小時=24)

        assert 花.token == 2000
        assert 花.美金 == 1.0

    def test_窗口外的不算(self) -> None:
        """**沒有窗口的預算不是預算，是一次性的封頂。**

        用了三個月之後永遠超支，然後使用者只能把上限調高——那就等於沒有。
        """
        花 = 花了多少([_一次(1), _一次(48)], 現在=_現在, 幾小時=24)

        assert 花.token == 1000

    def test_沒有歷史就是零(self) -> None:
        花 = 花了多少([], 現在=_現在, 幾小時=24)

        assert (花.token, 花.美金) == (0, 0.0)

    def test_有一次算不出成本整段就算不出(self) -> None:
        """**跟摘要同一條規則**：有一顆給不出來就整個不給。

        把算得出來的那幾次加起來是低報，而低報的預算會讓人以為還有額度。
        """
        花 = 花了多少([_一次(1), _一次(2, 成本=None)], 現在=_現在, 幾小時=24)

        assert 花.美金 is None
        assert 花.token == 2000, "token 每一家都給得出來，不該被成本拖下水"

    def test_讀不到時間的那次跳過但不擋住整段(self) -> None:
        """一筆壞掉就整個算不出來等於沒有預算鎖。"""
        壞的 = dataclasses.replace(_一次(1), 迄="這不是時間")

        花 = 花了多少([壞的, _一次(2)], 現在=_現在, 幾小時=24)

        assert 花.token == 1000


class Test超支了嗎:
    def test_沒設上限就一律放行(self) -> None:
        """**預設關閉是使用者明講的決定**：看帳跟關流程是兩件事。"""
        assert 超支了嗎(花了多少([_一次(1)], 現在=_現在, 幾小時=24), 上限()) is None

    def test_token超過就擋(self) -> None:
        花 = 花了多少([_一次(1, token=5000)], 現在=_現在, 幾小時=24)

        assert 超支了嗎(花, 上限(token=1000)) is not None

    def test_token剛好等於上限還沒超(self) -> None:
        """**邊界要講清楚**：等於不算超，不然「上限 1000」實際只能用到 999。"""
        花 = 花了多少([_一次(1, token=1000)], 現在=_現在, 幾小時=24)

        assert 超支了嗎(花, 上限(token=1000)) is None

    def test_成本超過就擋(self) -> None:
        花 = 花了多少([_一次(1, 成本=9.0)], 現在=_現在, 幾小時=24)

        assert 超支了嗎(花, 上限(美金=1.0)) is not None

    def test_算不出成本時成本上限一律放行(self) -> None:
        """**這一條是刻意的，而且方向跟「安全就擋」相反。**

        算不出成本就擋的話，只要鏈上有一家不回成本（codex、agy 都不回），
        整個預算鎖會變成「永遠擋住」——那不是保護，那是壞掉。
        擋不住的時候要說得出擋不住，而不是假裝擋得住。
        """
        花 = 花了多少([_一次(1, 成本=None)], 現在=_現在, 幾小時=24)

        assert 超支了嗎(花, 上限(美金=0.01)) is None

    def test_訊息裡要有數字(self) -> None:
        """「超支了」沒有下文的話，人不知道該調上限還是該等。"""
        花 = 花了多少([_一次(1, token=5000)], 現在=_現在, 幾小時=24)

        訊息 = 超支了嗎(花, 上限(token=1000))

        assert 訊息 is not None
        assert "5000" in 訊息
        assert "1000" in 訊息


@pytest.mark.parametrize("幾小時", [0, -1])
def test_窗口不准是零或負數(幾小時: int) -> None:
    """窗口是 0 的話什麼都不算，預算鎖看起來在跑但永遠不會擋——**假的保護**。"""
    with pytest.raises(ValueError, match="幾小時"):
        花了多少([], 現在=_現在, 幾小時=幾小時)
