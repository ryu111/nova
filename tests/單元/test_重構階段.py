"""重構階段的轉移：紅 → 綠 → **重構** → 再驗一次綠 → 審查。

SOP 來源（2026-08-29 查證）：Fowler 的微步循環是
「確認測試全綠 → 只做最小結構改動 → **立即重新驗證綠燈** → 提交」，
而做壞了的標準補救是「**嚴禁 fix-forward**，直接退回上一個綠燈」。

nova 的落地有兩個關鍵決定：

1. **`驗證重構` 是一個獨立的階段代碼，不是重用 `驗證綠`。**
   狀態機是純函式轉移表，只吃 `(階段定義, 步驟結果)`。重用的話
   `驗證綠` 就得記得「我是第幾次來的」——那需要狀態，純函式當場破功。
   兩個階段長得一樣但**去處不同**，這是轉移表的正確用法。

2. **`驗證重構` 紅了就中止，不退回重構。** SOP 明說不准 fix-forward；
   而且退回去是**無界回頭邊**，只靠步數上限收斂＝成本漏洞。
   nova 目前沒有回滾機制，中止至少留下一個乾淨的「這裡壞了」訊號。
"""

from nova.契約.工作流 import 審查判定, 步驟結果, 結束, 結束代碼, 階段代碼
from nova.契約.模型回應 import 終局
from nova.迴圈.狀態機 import 下一步, 查階段


def 做結果(階段: 階段代碼, *, 綠: bool | None = None, 終: 終局 = 終局.成功) -> 步驟結果:
    return 步驟結果(階段=階段, 終局=終, 判準綠=綠, 證據="")


class Test重構在哪:
    def test_驗證綠之後是重構不是審查(self) -> None:
        """全綠了才重構——這是 SOP 的第一步「確保測試綠燈」。"""
        下 = 下一步(查階段(階段代碼.驗證綠), 做結果(階段代碼.驗證綠, 綠=True))
        assert 下 is 階段代碼.重構

    def test_重構完要再驗一次綠(self) -> None:
        """**這是整個階段存在的理由**：行為沒變才叫重構。"""
        下 = 下一步(查階段(階段代碼.重構), 做結果(階段代碼.重構))
        assert 下 is 階段代碼.驗證重構

    def test_驗證重構綠了才進審查(self) -> None:
        下 = 下一步(查階段(階段代碼.驗證重構), 做結果(階段代碼.驗證重構, 綠=True))
        assert 下 is 階段代碼.審查


class Test弄壞了怎麼辦:
    def test_驗證重構紅了要停下來不准往前除錯(self) -> None:
        """SOP：嚴禁 fix-forward。而且退回重構是無界回頭邊。"""
        下 = 下一步(查階段(階段代碼.驗證重構), 做結果(階段代碼.驗證重構, 綠=False))
        assert isinstance(下, 結束)
        assert 下.代碼 is 結束代碼.護欄

    def test_重構做不出來也是中止(self) -> None:
        下 = 下一步(查階段(階段代碼.重構), 做結果(階段代碼.重構, 終=終局.確定失敗))
        assert isinstance(下, 結束)

    def test_重構的結果未知一律停(self) -> None:
        """它可能已經改了一半的檔案。這條蓋過所有階段的個別轉移。"""
        下 = 下一步(查階段(階段代碼.重構), 做結果(階段代碼.重構, 終=終局.結果未知))
        assert isinstance(下, 結束)


class Test沒有把原本的路走壞:
    def test_審查要求修改還是退回實作(self) -> None:
        """**不是退回重構**——要修改的是行為，那是實作的事。"""
        結果 = 步驟結果(
            階段=階段代碼.審查,
            終局=終局.成功,
            判準綠=None,
            證據="",
            審查結論=審查判定.要求修改,
        )
        assert 下一步(查階段(階段代碼.審查), 結果) is 階段代碼.實作

    def test_驗證綠沒綠還是退回實作(self) -> None:
        下 = 下一步(查階段(階段代碼.驗證綠), 做結果(階段代碼.驗證綠, 綠=False))
        assert 下 is 階段代碼.實作


def test_每個階段代碼都在表裡() -> None:
    """加了階段代碼卻忘了加轉移列＝那個階段永遠走不到，而且沒有人會發現。"""
    for 代碼 in 階段代碼:
        assert 查階段(代碼).代碼 is 代碼
