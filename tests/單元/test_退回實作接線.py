"""被退回的那一輪，**執行器實際送出去的那份提示**裡沒有禁令、而且帶著上一階的紅。

`test_退回實作的那一輪.py` 測的是提示函式的回傳值。函式對了不代表接上了——
真正送給實作員的是 `組提示(角色.系統提示, 工作流._提示(...))`，
所以斷言要打在腦收到的那一整串上，不是打在 helper 上。
"""

from pathlib import Path

from nova.契約.工作流 import 任務, 判準終局, 審查判定, 步驟結果, 階段代碼, 階段定義
from nova.契約.模型回應 import 回應, 失敗代碼, 用量, 終局
from nova.契約.角色 import 呼叫選項, 語言模型, 預設選項
from nova.載體.判準 import 可作指定pytest目標
from nova.載體.派工表 import 怎麼派
from nova.載體.角色 import 固定提示角色
from nova.迴圈.工作流 import 建TDD執行器
from nova.迴圈.狀態機 import 查階段
from nova.迴圈.角色工廠 import 建TDD角色藍圖, 建角色表, 這階算哪種工作

一件事 = 任務(描述="讓 X 變成 Y", 工作目錄=Path("/不存在但沒人會碰"))

#: 那條省 token 的禁令，原文照抄。
_禁令 = "**不要自己跑全套測試**"

#: 一條 `[test-design]`（路由去測試員）＋ 一條 `[impl]`（兩階之後才有人接得到）。
_混合審查 = (
    "ISSUE: [test-design] 邊界案例沒寫\nISSUE: [impl] 空輸入沒處理\nREVIEW: CHANGES-REQUESTED"
)

_紅 = (
    "FAILED tests/單元/test_判準涵蓋提交閘.py::Test判準涵蓋提交閘"
    "::test_測試涵蓋不准比全跑窄 - AssertionError: 判準步驟裡找不到全跑的指令"
)


class _假腦:
    """記下真正送出去的那一整串提示。這支測試不該真的呼叫模型。"""

    名稱 = "測試用假腦"

    def __init__(self, 收到: list[str]) -> None:
        self._收到 = 收到

    def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
        del 選項
        self._收到.append(提示)
        return 回應(
            文字="做好了",
            終局=終局.成功,
            失敗代碼=失敗代碼.無,
            原始結束碼=0,
            對話識別碼=None,
            用量=用量(輸入token=1, 輸出token=1),
        )


def _送給實作員的(軌跡: tuple[步驟結果, ...]) -> str:
    """用真的藍圖、真的角色、真的執行器跑實作那一步，回腦收到的整份提示。"""
    收到: list[str] = []

    def 建腦(_: object) -> 語言模型:
        return _假腦(收到)

    藍圖們 = 建TDD角色藍圖(怎麼派)
    依識別碼 = 建角色表(藍圖們, 建腦=建腦, 組角色=固定提示角色)
    執行一步 = 建TDD執行器(
        角色表={階段代碼(識別碼): 角 for 識別碼, 角 in 依識別碼.items()},
        跑判準=lambda _: (判準終局.綠, "假判準"),
        篩選指定測試=可作指定pytest目標,
    )
    定義: 階段定義 = 查階段(階段代碼.實作)
    執行一步(定義, 一件事, 軌跡)
    assert len(收到) == 1, "實作員該被叫剛好一次"
    return 收到[0]


def _做步驟(
    階段: 階段代碼,
    證據: str,
    *,
    綠: bool | None = None,
    審查結論: 審查判定 | None = None,
) -> 步驟結果:
    """照 `契約.工作流.步驟結果` 的欄位造替身：審查步的結論要**明講**。

    真的執行器在建步驟結果時就把 `審查結論` 填好了（`工作流.py` 的審查階）。
    替身不填就等於逼 production 回頭去解析 `證據` 的自由文字——
    那是第二個語意來源，測試不該養它。
    """
    return 步驟結果(階段=階段, 終局=終局.成功, 判準綠=綠, 證據=證據, 審查結論=審查結論)


class Test退回實作接線:
    def test_首輪送出去的提示仍帶禁令(self) -> None:
        """第一次進 impl 沒有紅可以看，省 token 的禁令是對的，不准順手拆掉。"""
        提示 = _送給實作員的((_做步驟(階段代碼.驗證紅, "1 failed", 綠=False),))
        assert _禁令 in 提示, "首輪的禁令在接線之後不見了"

    def test_被退回那一輪送出去的提示沒有禁令而且帶著紅(self) -> None:
        """`審查 → 實作` 是回頭邊：它要修的正是全測試的紅，得看得見也跑得動。"""
        提示 = _送給實作員的(
            (
                _做步驟(
                    階段代碼.審查,
                    f"REVIEW: CHANGES-REQUESTED\n{_紅}",
                    審查結論=審查判定.要求修改,
                ),
            )
        )
        assert _紅 in 提示, "被退回的那一輪拿不到上一階的紅，實作員只能用猜的"
        assert _禁令 not in 提示, "送出去的提示還寫著禁令——helper 對了但沒接上線"
        assert "全測試" in 提示, "沒有明講准它自己跑全測試"
        # 放寬的只有那條禁令，本業規矩一條都不准鬆。
        assert "不准改測試" in 提示

    def test_驗證綠退回來也算被退回(self) -> None:
        """回頭邊不只審查那一條；`驗證綠 → 實作` 一樣是拿著全測試的紅回來的。"""
        提示 = _送給實作員的((_做步驟(階段代碼.驗證綠, _紅, 綠=False),))
        assert _禁令 not in 提示
        assert _紅 in 提示

    def test_混合審查退回測試員之後送出去的提示帶著審查全文與退回策略(self) -> None:
        """混合意見整包退測試員，兩階之後的實作員上一步是 `驗證紅`——

        審查的 `[impl]` 條目沿著上一步流不過來。helper 對了不代表接上了，
        所以這支打在真正送出去的那一整串上。

        「全文」照字面驗：條目清單那一段也會重述證據，只斷言證據字串在不在，
        回顧那一整段被拆掉時這支照樣綠。
        """
        提示 = _送給實作員的(
            (
                _做步驟(階段代碼.審查, _混合審查, 審查結論=審查判定.要求修改),
                _做步驟(階段代碼.測試, "補了一支邊界測試"),
                _做步驟(階段代碼.驗證紅, f"1 failed\n{_紅}", 綠=False),
            )
        )
        assert "空輸入沒處理" in 提示, "退回循環裡的實作員拿不到審查的 [impl] 條目"
        assert "上一次審查：" in 提示.splitlines(), (
            "回顧那一整段沒接上——上一步是驗證紅，審查全文只能從這一段來"
        )
        assert "REVIEW: CHANGES-REQUESTED" in 提示, "審查全文（含判定行）沒跟著條目清單一起來"
        assert _紅 in 提示, "審查意見是多帶的，不是取代——這一輪的紅仍然要在"
        assert _禁令 not in 提示, "這一輪是被退回來的，禁令不該還在"

    def test_沒填審查結論的審查步不算要求修改(self) -> None:
        """「這一輪是不是被退回來的」只讀結構化的 `審查結論`，不去猜證據的自由文字。

        審查階建步驟結果時就把判定填好了，那是唯一的語意來源；
        缺欄位時回頭重新解析 `證據`，等於在退回循環裡養第二份「什麼叫要求修改」——
        兩份哪天不一致，實作員的讀取策略就會跟路由走反方向，而且沒有人看得出來。
        沒給就是沒給（`審查判定` 的 docstring），不准反推。
        """
        軌跡 = (
            # 同一份混合審查全文，但 `審查結論` 留空：只有自由文字說了 CHANGES-REQUESTED。
            _做步驟(階段代碼.審查, _混合審查),
            _做步驟(階段代碼.測試, "補了一支邊界測試"),
            _做步驟(階段代碼.驗證紅, f"1 failed\n{_紅}", 綠=False),
        )
        提示 = _送給實作員的(軌跡)
        assert _禁令 in 提示, "沒填 審查結論 卻被當成要求修改——證據的自由文字被當成第二個語意來源了"
        # 接不接審查回顧是另一條線（那一段不看判定），這支只釘讀取策略那一格。
        assert "空輸入沒處理" in 提示, "回顧那一段不該被這條判定牽動"

    def test_工作種類沒被這條接線改掉(self) -> None:
        """確認接線沒有改掉唯一的階段→工作種類對照。"""
        實作藍圖 = next(藍 for 藍 in 建TDD角色藍圖(怎麼派) if 藍.識別碼 == 階段代碼.實作.value)
        assert 實作藍圖.派法 == 怎麼派(這階算哪種工作(階段代碼.實作))
