"""`docs/設計/02` 必須有一張「三家用量欄位語意」表，而且每一列指得到出處。

解析器裡每一個減法（codex 的 `input − cached`、agy 要不要跟著扣）都是在宣告
「哪一欄含哪一欄」。這種宣告只要沒寫下來、沒有出處，就會退化成註解裡的猜測，
下一個人照著猜又改一次，帳本的數字沒人敢信。

這支測試盯的是：那張表在、三家各一列、每一列的欄位語意與計價倍率有交代，
而且**出處欄指得到東西**——官方文件網址，或本專案實測時打的那一行指令。
出處欄留白等於這一格是用推的，那正是這張表要擋掉的東西。

刻意不抄任何一格的內容進測試：表要寫什麼由實測結果決定，
測試只保證「有這張表、每格有來源」這個形狀，不預設答案。
"""

import re
from pathlib import Path

#: 表所在的章節標題。認關鍵字不認完整標題文字：標題怎麼寫是文件的自由。
_表標題 = re.compile(r"^#{2,4} .*用量欄位語意")
_任一標題 = re.compile(r"^#{1,6} ")
#: markdown 表格的分隔列（`|---|---|`）。
_分隔列 = re.compile(r"^\|[\s:|-]+\|$")

#: 每一列必須交代的欄。前六個是各家的欄位名，後三個是這張表存在的理由：
#: 誰含誰、按幾倍計價、憑什麼這樣說。
_必要欄 = ("非快取輸入", "快取讀取", "快取建立", "輸出", "思考", "total", "含不含", "倍率", "出處")

#: 三家的載體名，跟 `tests/conftest.py` 的實錄表同一組。
_三家 = ("claude", "codex", "agy")

#: 看起來有寫、其實沒寫的填充字。出處欄放這些跟留白同義。
_佔位字 = ("", "-", "—", "–", "?", "？", "n/a", "N/A", "TBD", "待補", "未填")


def _切格(一行: str) -> tuple[str, ...]:
    return tuple(格.strip() for 格 in 一行.strip().strip("|").split("|"))


def _表(專案根: Path) -> tuple[tuple[str, ...], list[tuple[str, ...]]]:
    """從 02 切出用量欄位語意表，回傳 (標頭, 資料列)。"""
    文件 = 專案根 / "docs" / "設計" / "02-統一LLM介面.md"
    assert 文件.is_file(), "docs/設計/02-統一LLM介面.md 不存在"
    行 = 文件.read_text(encoding="utf-8").splitlines()
    起 = next((i for i, 一行 in enumerate(行) if _表標題.match(一行)), None)
    assert 起 is not None, "02 裡找不到「…用量欄位語意」這一節——三家的含不含關係沒有落腳處"
    止 = next((i for i in range(起 + 1, len(行)) if _任一標題.match(行[i])), len(行))
    表格行 = [一行 for 一行 in 行[起:止] if 一行.startswith("|") and not _分隔列.match(一行)]
    assert len(表格行) >= 2, f"「用量欄位語意」那一節裡沒有 markdown 表格（只有 {len(表格行)} 行）"
    return _切格(表格行[0]), [_切格(一行) for 一行 in 表格行[1:]]


def _那一家(資料列: list[tuple[str, ...]], 家: str) -> tuple[str, ...]:
    """挑出某一家的那一列（認第一格）。"""
    命中 = [列 for 列 in 資料列 if 家 in 列[0].lower()]
    assert len(命中) == 1, f"用量欄位語意表裡 {家} 應該剛好一列，實際 {len(命中)} 列"
    return 命中[0]


def test_三家用量欄位語意各一列而且六欄語意齊全(專案根: Path) -> None:
    """三家的用量欄位語意寫成一張表：每家一列，六個欄位名加上含不含關係與計價倍率。"""
    標頭, 資料列 = _表(專案根)
    缺欄 = [欄 for 欄 in _必要欄 if not any(欄.lower() in 格.lower() for 格 in 標頭)]
    assert not 缺欄, f"用量欄位語意表缺欄：{缺欄}；實際標頭 {標頭}"

    for 家 in _三家:
        那列 = _那一家(資料列, 家)
        assert len(那列) == len(標頭), f"{家} 那一列有 {len(那列)} 格，標頭有 {len(標頭)} 格"
        空格 = [標頭[i] for i, 格 in enumerate(那列) if 格.strip() in _佔位字]
        assert not 空格, f"{家} 這幾格沒寫：{空格}——用量欄位語意留白等於沒有這張表"


def test_每一列的出處指得到官方句或實測指令(專案根: Path) -> None:
    """每家那一列的出處欄要指得到東西：官方文件網址，或本專案打過的那一行指令。"""
    標頭, 資料列 = _表(專案根)
    出處欄 = next((i for i, 格 in enumerate(標頭) if "出處" in 格), None)
    assert 出處欄 is not None, f"用量欄位語意表沒有出處欄，標頭是 {標頭}"

    for 家 in _三家:
        出處 = _那一家(資料列, 家)[出處欄]
        assert 出處.strip() not in _佔位字, f"{家} 的出處欄留白——這一格的語意是用推的"
        指得到 = "http" in 出處 or (f"`{家}" in 出處 or f"`{家.upper()}" in 出處)
        assert 指得到, f"{家} 的出處是「{出處}」：既不是官方網址，也不是可以重跑的實測指令"
