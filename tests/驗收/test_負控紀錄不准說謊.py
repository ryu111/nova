"""負控紀錄提到的測試，必須是 repo 裡真的存在的那一支。

**這支是被一次真事逼出來的。** 派 nova 做成本落盤那輪，`docs/負控紀錄.md`
一次進了七列，其中六列寫著「固定 smoke assertion」——負控是對著一段臨時寫、
驗完就刪的斷言做的。紀錄上看起來有七道防線，repo 裡只有一道。

**那比沒做更糟**：負控紀錄存在的理由就是「懷疑某條防護時，照著那一列做一次
就好，不必重推」。裡面的測試名如果搜不到，照著做的人會發現破壞之後什麼都沒紅，
然後不知道該相信哪一邊。**在防止假安全感的文件裡製造假安全感。**

所以規則寫在 `docs/負控紀錄.md` 第六次那一節，而這一支是它的執法點。
"""

import re
from pathlib import Path

專案根 = Path(__file__).resolve().parent.parent.parent
紀錄檔 = 專案根 / "docs" / "負控紀錄.md"
測試根 = 專案根 / "tests"

#: 反引號裡、以 test_ 開頭的東西就當成「這一列宣稱有這支測試」。
#: `[` 要斷開：參數化測試在紀錄裡是寫成 `test_某某[claude]` 的 ID 形式，
#: 而 repo 裡的 `def` 只有前半段。
_提到的測試 = re.compile(r"`(test_[^`\s([]+)")

#: 這些是拿來當反例講解的名字，不是宣稱存在的測試。
#: **加進來要附理由**——不然這份白名單會變成規避這支測試的後門。
_不是宣稱 = {
    "test_門面很小",  # §一 在講一支「被規避掉」的測試長什麼樣
}


def _repo裡所有的測試名() -> set[str]:
    名字: set[str] = set()
    for 檔 in 測試根.rglob("test_*.py"):
        名字.update(re.findall(r"^\s*def (test_\w+)", 檔.read_text(encoding="utf-8"), re.MULTILINE))
    return 名字


def _宣稱有的測試() -> set[str]:
    """抓出紀錄裡宣稱存在的測試名。檔名（含 `.`）不是測試名，跳過。"""
    全部 = _提到的測試.findall(紀錄檔.read_text(encoding="utf-8"))
    return {名 for 名 in 全部 if "." not in 名}


def test_紀錄裡提到的測試都真的存在() -> None:
    """搜不到的名字＝那一列在說謊，照著做的人會白忙一場。"""
    存在的 = _repo裡所有的測試名()
    宣稱的 = _宣稱有的測試() - _不是宣稱

    找不到 = sorted(名 for 名 in 宣稱的 if 名 not in 存在的)

    assert not 找不到, (
        f"負控紀錄提到這些測試，但 repo 裡搜不到：{找不到}。"
        "要嘛測試被刪了（那一列該一起改），要嘛負控當初驗的是臨時斷言（那不算負控）"
    )


def test_紀錄真的有在提測試() -> None:
    """**這支防的是上面那支被掏空。**

    把正規表達式改成永遠抓不到東西，`test_紀錄裡提到的測試都真的存在`
    會變成永遠綠——一支永遠綠的測試等於沒有測試。
    """
    宣稱的 = _宣稱有的測試()

    assert len(宣稱的) > 30, f"只抓到 {len(宣稱的)} 個測試名，抓法八成壞了"
