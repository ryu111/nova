"""`docs/負控紀錄/` 的收集規格：一主題一檔，收集要 fail-closed。

單一的 `docs/負控紀錄.md` 是並行度的第二個上限：硬規則 4 要求**每條線**做完
固定負控都往同一張表尾巴 append 一列，於是三列毫不相干的內容只因為在同一行
前後就互撞；而 `mergeStateStatus=DIRTY` 的 PR 連 CI 都不會跑
（實測 `gh run list --branch 兩份派法` 是空的），衝突會被誤診成「CI 壞了」。

解法照 `tests/負控/登記們/` 已經解過的形狀：**新線只加一個檔，零衝突**，
收集時 glob 起來。這裡釘住的是那個形狀最容易假綠的那一面——
**漏收不報錯就是假綠**：`登記.py` 的 `_收集` 就踩過（`__init__.py` 沒排除，
當場報「沒有 登記」），而拆檔這邊的漏收更安靜——檔案還在 git 裡，
只是 `test_文件提到的測試都真的存在` 從此不看它，保護悄悄消失。

硬規則 4 不准放寬：「補一列」還是要補，這裡只讓那個動作不再是跨線衝突點。

如果這一格的結論是**不拆**（例如判定它該由 nova 生成、或該離開 git），
那就連同理由把這個檔刪掉——但要有證據，不能只是覺得麻煩。
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from .test_文件即事實 import (
    _全部測試函式名,
    _宣稱的測試名,
    _要檢查的文件,
    負控紀錄目錄,
)

專案根目錄 = Path(__file__).resolve().parents[2]
#: 拆檔前的那一份大表格。它復活就代表衝突點回來了。
舊的單一檔 = 專案根目錄 / "docs" / "負控紀錄.md"

#: 探針檔名寫成「臨時」開頭，撿到殘留檔的人一眼看得出它不是真的主題檔。
探針檔名 = "臨時收集探針.md"
#: 這個名字不准真的存在於 tests/ 底下，否則探針證明不了任何事。
探針宣稱的不存在測試名 = "test_這支只存在於臨時收集探針裡"


def _目錄裡的紀錄檔們() -> list[Path]:
    """直接數 `docs/負控紀錄/` 底下的 `.md`——**不呼叫被檢查的那支收集器**。

    oracle 跟被驗的東西共用同一份 glob 的話，「漏收」永遠出不來：
    收集器改成寫死一份清單、或改成只收前三個，這裡照樣綠。所以自己數一次。

    連子目錄一起數（`rglob`）：收集器只掃一層，有人把紀錄塞進子目錄就是
    悄悄沒人守，那正是這幾支要抓的漏收。探針不算，它是測試自己丟的。
    """
    return sorted(檔 for 檔 in 負控紀錄目錄.rglob("*.md") if 檔.is_file() and 檔.name != 探針檔名)


def test_負控紀錄已經一主題一檔() -> None:
    """紀錄要拆到 `docs/負控紀錄/<主題>.md`，新線才不必碰同一個檔尾。

    只要求「目錄存在且不只一個檔」——不規定主題怎麼切、也不碰既有那份大表格的
    內容：改寫歷史紀錄跟解決衝突是兩件事，混在一起 diff 會大到沒人看得出
    哪裡是真的改動。
    """
    assert 負控紀錄目錄.is_dir(), (
        f"找不到 {負控紀錄目錄.relative_to(專案根目錄)}／；"
        "固定負控紀錄要拆成一主題一檔，新線加一個檔就好，不再 append 同一張表"
    )

    紀錄檔們 = _目錄裡的紀錄檔們()
    assert len(紀錄檔們) >= 2, (
        f"{負控紀錄目錄.relative_to(專案根目錄)}／ 只有 "
        f"{[檔.name for 檔 in 紀錄檔們]}；一個檔的拆法沒有消掉衝突點"
    )

    assert not 舊的單一檔.exists(), (
        f"{舊的單一檔.relative_to(專案根目錄)} 又出現了；"
        "拆檔的重點就是不要再有一個每條線都往尾巴 append 的檔"
    )


def test_每個主題檔都被文件檢查收走() -> None:
    """收集不准漏檔：漏掉的那個檔，等於它宣稱的測試從此沒人守。

    這支擋的是「寫死一份清單」的拆法——那種拆法今天綠、下一條線加檔就假綠。
    """
    紀錄檔們 = _目錄裡的紀錄檔們()
    assert 紀錄檔們, (
        f"{負控紀錄目錄.relative_to(專案根目錄)}／ 底下一個 .md 都沒有；"
        "沒有東西可以檢查的話這支只是永遠綠的假保護"
    )

    收集到的文件 = set(_要檢查的文件())
    漏收的 = sorted(
        檔.relative_to(專案根目錄).as_posix() for 檔 in 紀錄檔們 if 檔 not in 收集到的文件
    )

    assert not 漏收的, (
        "這些負控紀錄檔沒被 _要檢查的文件() 收走，裡面提到的測試名不再受檢：\n  "
        + "\n  ".join(漏收的)
    )


@pytest.mark.serial
def test_新增主題檔不改任何程式就受檢() -> None:
    """新線只丟一個檔進去，保護就要自動蓋上去——這才是零衝突的前提。

    斷言的不是「路徑有出現在清單裡」，是**整條檢查真的看到了它的內容**：
    探針裡宣稱一支不存在的測試，`test_文件提到的測試都真的存在` 用的那兩個
    函式必須把它算成缺的。只比路徑的話，收集改成只回傳路徑卻讀不到內容
    （例如收到目錄、收到 symlink）仍然會綠。

    會動到共用目錄，所以標 serial，不跟 xdist 的其他 worker 搶同一份檔案系統。
    """
    目錄原本不存在 = not 負控紀錄目錄.exists()
    負控紀錄目錄.mkdir(parents=True, exist_ok=True)
    探針 = 負控紀錄目錄 / 探針檔名
    探針.write_text(
        "# 臨時收集探針\n\n"
        "| 破壞什麼 | 哪支該紅 |\n"
        "| --- | --- |\n"
        f"| 這是測試寫的臨時檔 | `{探針宣稱的不存在測試名}` |\n",
        encoding="utf-8",
    )
    try:
        測試名們 = _全部測試函式名()
        assert 探針宣稱的不存在測試名 not in 測試名們, "探針用的假測試名居然真的存在，換一個"

        缺的 = [
            名
            for 檔 in _要檢查的文件()
            for 名 in _宣稱的測試名(檔.read_text(encoding="utf-8"))
            if 名 not in 測試名們
        ]
        assert 探針宣稱的不存在測試名 in 缺的, (
            f"新丟進 {負控紀錄目錄.name}／ 的 {探針檔名} 沒被檢查讀到；"
            "漏收不報錯就是假綠——下一條線的紀錄會靜靜地沒人守"
        )
    finally:
        探針.unlink()
        #: 目錄還不存在時（拆檔尚未做）不准留一個空目錄下來——
        #: 那會讓上面兩支的「目錄在不在」變成看跑序，紅綠不再可信。
        if 目錄原本不存在:
            負控紀錄目錄.rmdir()


#: 拆檔當下（2026-09-01，`origin/main` 的單檔版）數出來的負控列數。
#: **這是地板不是等號**：歷史只會長不會縮，新線補的列也算進來。
#: 要動這個數字只有一種正當理由——真的發現某一列是重複登記的，
#: 而那要在 commit 訊息裡說清楚是哪一列、為什麼重複。
拆檔當下的負控列數 = 518

_表頭或分隔 = re.compile(r"^\|[\s:\-|]+\|$")


def _一個檔裡的負控列數(文字: str) -> int:
    """數表格的資料列：以 `|` 開頭結尾，扣掉分隔線與 `| 破壞什麼` 那行表頭。"""
    數 = 0
    for 行 in 文字.splitlines():
        一行 = 行.strip()
        if not (一行.startswith("|") and 一行.endswith("|")):
            continue
        if _表頭或分隔.fullmatch(一行) or 一行.startswith("| 破壞什麼"):
            continue
        數 += 1
    return 數


def test_拆檔不准弄丟任何一列負控紀錄() -> None:
    """**歷史一列都不能少**——那是別人做過負控的證據。

    只數檔案數會恆真：把 2,500 行的歷史清空、留兩個空檔，檔案數照樣是 2。
    所以數的是「破壞什麼」那一欄真正的資料列。
    """
    總列數 = sum(_一個檔裡的負控列數(檔.read_text(encoding="utf-8")) for 檔 in _目錄裡的紀錄檔們())
    assert 總列數 >= 拆檔當下的負控列數, (
        f"負控紀錄的列數掉到 {總列數}，拆檔當下是 {拆檔當下的負控列數}——"
        "少掉的每一列都是一次沒人知道的保護消失"
    )
