"""路線圖是手維護的，所以它會爛。

爛掉的路線圖比沒有更糟——讀的人會以為某個東西已經做好了。
所以這裡把圖當成**被驗收的對象**：它宣稱存在的東西必須真的存在。

（這條判準來自宿主反轉那份文件：「文件若宣稱某件事會被自動擋下，
把關器必須存在且有測試背書」。圖也是文件。）
"""

import json
import re
from pathlib import Path
from typing import Any

import pytest

from nova.載體.模型.轉接 import _規格
from nova.載體.規則表 import 建規則表

專案根目錄 = Path(__file__).resolve().parents[2]
路線圖 = 專案根目錄 / "docs" / "路線圖.html"
合法狀態 = {"好", "半", "無"}


def 讀圖() -> dict[str, Any]:
    文字 = 路線圖.read_text(encoding="utf-8")
    樣式 = r'<script type="application/json" id="圖資料">\s*(.*?)\s*</script>'
    命中 = re.search(樣式, 文字, re.DOTALL)
    assert 命中, "路線圖裡找不到 id=圖資料 的 JSON 區塊——是不是被改成寫死在 JS 裡了？"
    結果: dict[str, Any] = json.loads(命中.group(1))
    return 結果


@pytest.fixture(scope="module")
def 圖() -> dict[str, Any]:
    return 讀圖()


def test_圖存在(圖: dict[str, Any]) -> None:
    assert 圖["節點"], "路線圖沒有任何節點"


def test_標成已完成的檔案必須真的存在(圖: dict[str, Any]) -> None:
    """這是最重要的一條：圖上綠燈的格子，指到的檔案要真的在。

    改了目錄結構卻忘了改圖，這支會紅。
    """
    for 節點 in 圖["節點"]:
        if 節點["態"] != "好":
            continue
        for 相對 in 節點.get("檔", []):
            assert (專案根目錄 / 相對).exists(), (
                f"路線圖說「{節點['標']}」已完成並指到 {相對}，但那個檔案不存在"
            )


def test_未做的格子不准宣稱檔案(圖: dict[str, Any]) -> None:
    """反方向：標成未做卻列了檔案，代表圖沒跟上實作。"""
    for 節點 in 圖["節點"]:
        if 節點["態"] == "無":
            assert not 節點.get("檔"), f"「{節點['標']}」標成未做，卻列了檔案 {節點.get('檔')}"


def test_閘的條數要跟規則表一致(圖: dict[str, Any]) -> None:
    """圖上寫「nova 閘（8 條）」，加規則卻忘了改圖，這支會紅。"""
    宣稱 = next(節點["閘數"] for 節點 in 圖["節點"] if "閘數" in 節點)
    實際 = len([條 for 條 in 建規則表(專案根目錄) if "ci" in 條.閘點])
    assert 宣稱 == 實際, f"路線圖說 {宣稱} 條閘，規則表實際有 {實際} 條"


def test_h_層要跟轉接器的規格表一致(圖: dict[str, Any]) -> None:
    """新增一家 CLI 卻沒畫上圖，或圖上畫了不存在的家，都要紅。"""
    圖上 = {節點["家"] for 節點 in 圖["節點"] if 節點.get("家")}
    assert 圖上 == set(_規格), f"圖上的 h：{sorted(圖上)}；轉接器實際支援：{sorted(_規格)}"


def test_連線兩端都要是存在的節點(圖: dict[str, Any]) -> None:
    識別碼 = {節點["id"] for 節點 in 圖["節點"]}
    for 線 in 圖["連線"]:
        assert 線["從"] in 識別碼, f"連線指向不存在的節點：{線['從']}"
        assert 線["到"] in 識別碼, f"連線指向不存在的節點：{線['到']}"


def test_狀態只能是三種之一(圖: dict[str, Any]) -> None:
    for 節點 in 圖["節點"]:
        assert 節點["態"] in 合法狀態, f"「{節點['標']}」的狀態 {節點['態']!r} 不合法"


合法排 = {"可做", "卡住", "押後", "決定"}
"""第二個軸：**現在能不能推**，跟「做到哪」互相獨立。

混成一個欄位就分不出「還沒輪到」與「推不動」，而那兩件事該做的處置完全不同：
可做的排進下一批，卡住的要先解前置，押後的不要每次都重新討論一遍，
決定的根本不是缺口——它是人選的，要動要先改主意。
"""


def test_還沒做完的格子都要說得出現在能不能推(圖: dict[str, Any]) -> None:
    """沒有這一格，看圖的人只知道「沒做完」，不知道該不該現在做。"""
    for 節點 in 圖["節點"]:
        if 節點["態"] == "好":
            continue
        assert 節點.get("排"), f"「{節點['標']}」是 {節點['態']} 卻沒說能不能推"


def test_排只能是四種之一(圖: dict[str, Any]) -> None:
    for 節點 in 圖["節點"]:
        排 = 節點.get("排")
        if 排 is not None:
            assert 排 in 合法排, f"「{節點['標']}」的排 {排!r} 不合法"


def test_做完的格子不准還掛著排(圖: dict[str, Any]) -> None:
    """**這支防的是忘了拿掉。** 做完了還標「可做」會讓可做清單一直有假貨。"""
    for 節點 in 圖["節點"]:
        if 節點["態"] == "好":
            assert "排" not in 節點, f"「{節點['標']}」已完成卻還標著排 {節點.get('排')!r}"


def test_說卡住就要說卡在誰(圖: dict[str, Any]) -> None:
    """「卡住」沒有下文等於「不想做」的體面說法——要能被人拿去解掉。"""
    for 節點 in 圖["節點"]:
        if 節點.get("排") == "卡住":
            assert 節點.get("卡在"), f"「{節點['標']}」說卡住卻沒說卡在誰"


#: 「某某不存在」的幾種說法。**直接跟模組名拼字串比，不用正規式抓**——
#: 第一版寫成 `([\u4e00-\u9fff]{2,6})(?:還)?不存在`，貪婪匹配在
#: 「而遮罩還不存在」上抓到的是「而遮罩」，永遠不會等於模組名。
#: 負控（把舊句子放回去）當場是綠的。
_不存在的說法 = ("{}不存在", "{}還不存在", "{}尚不存在", "{}都不存在")


def test_不准說一個已經有的模組不存在(圖: dict[str, Any]) -> None:
    """**註是散文，而散文遲早跟程式碼對不上。**

    真實案例：`③ journal.記` 那格的註寫著「repo public 而遮罩還不存在，
    所以不記模型全文」。遮罩做完之後全文早就在記了，但那句話留在圖上——
    讀的人會以為那一格還缺著，而它其實已經動了。

    這一條抓得住的只有最機械的那一種：**說某個模組不存在，
    而 `src/nova` 底下就有那個檔案**。抓不住所有漂移，但抓得住這一類，
    而且不需要任何人記得回來改。
    """
    模組們 = {路.stem for 路 in (專案根目錄 / "src" / "nova").rglob("*.py")}
    for 節點 in 圖["節點"]:
        註 = 節點.get("註", "")
        for 名 in 模組們:
            for 樣板 in _不存在的說法:
                assert 樣板.format(名) not in 註, (
                    f"「{節點['標']}」的註說「{樣板.format(名)}」，"
                    f"但 src/nova 底下就有 {名}.py——那句話是舊的"
                )
