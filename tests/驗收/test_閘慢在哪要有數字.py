"""`nova 閘 ci --全部跑完` 要六分鐘，而**沒有人量過那六分鐘花在哪**。

這支測的是 `docs/設計/14-閘慢在哪.md` 這份量測報告本身：
它必須是**實測**，不是估的。

## 為什麼要測文件

「哪條最慢」憑印象人人都答得出來（大家都會說 `registered-mutation`），
但憑印象改出來的東西沒辦法驗證省了多少。這份報告的價值全在數字上，
所以下面每一支測的都是**數字在不在、對不對得起來**：

- 表要涵蓋閘真的會跑的**每一條**規則。少一條就可能漏掉真兇。
- 每條要有中位數與佔比，佔比加起來要接近整份的時間，不然表是拼湊的。
- 要交代**量的時候機器上有沒有別的東西在跑**。六核滿載量到的數字，
  跟空機量到的不是同一件事；沒有 load average 的耗時數字不可複現。
- 至少三次取中位數。這台機器上常常有別的 nova 在跑，單次會被帶偏。
- 改進方向每條要有**預估省下多少秒**與**代價**。只寫「可以快取」不算——
  沒有代價的改進方向讀起來每條都值得做。

**這支不斷言誰最慢。** 誰最慢是量出來的結果，不是測試該規定的事。
"""

import re
from pathlib import Path

import pytest

from nova.載體.規則表 import 建規則表

專案根目錄 = Path(__file__).resolve().parents[2]
報告 = 專案根目錄 / "docs" / "設計" / "14-閘慢在哪.md"

#: 量測條件的欄位名。**寫死是故意的**：欄位名浮動的話，
#: 下一次重量就沒辦法跟這次比。
_量測次數 = re.compile(r"量測次數：\s*(\d+)")
_負載 = re.compile(r"load average：\s*([\d.]+)[,、\s]+([\d.]+)[,、\s]+([\d.]+)")
_總時間 = re.compile(r"總時間中位數：\s*([\d.]+)\s*(毫秒|秒)")
_百分比 = re.compile(r"([\d.]+)\s*%")
_數字 = re.compile(r"[\d.]+")

#: 至少三次。少於三次沒有中位數可言，只是「跑了兩次挑一個」。
_最少量測次數 = 3


def _原文() -> str:
    if not 報告.exists():
        pytest.fail(f"{報告} 不存在：這一格要交出的就是這份量測報告")
    return 報告.read_text(encoding="utf-8")


def _規則代碼們() -> list[str]:
    """閘實際會跑的規則代碼。**從規則表拿，不是抄一份。**

    抄一份的話，以後加規則不會有人記得回來補這張表。
    """
    return [一條.代碼 for 一條 in 建規則表(專案根目錄) if "ci" in 一條.閘點]


def _表格行(原文: str, 代碼: str) -> str | None:
    """找出那條規則在表裡的那一行。"""
    for 行 in 原文.splitlines():
        if 行.lstrip().startswith("|") and re.search(rf"(?<![\w-]){re.escape(代碼)}(?![\w-])", 行):
            return 行
    return None


def test_量測報告寫下來了() -> None:
    """先確認檔在。沒有檔的話下面每一支都在講同一件事，噪音太大。"""
    assert 報告.exists(), f"{報告} 不存在"


def test_講得出量的時候機器在忙什麼() -> None:
    """**六核滿載時量到的數字，跟空機量到的不是同一件事。**

    沒有 load average 的耗時就只是一個孤兒數字，下次沒辦法拿來比。
    """
    比對 = _負載.search(_原文())

    assert 比對 is not None, "沒有寫 `load average：` 的三個數字，這份數字不可複現"


def test_至少量了三次() -> None:
    """**單次會被機器當下的負載帶偏。** 這台機器上常常有別的 nova 在跑。"""
    比對 = _量測次數.search(_原文())

    assert 比對 is not None, "沒有寫 `量測次數：`，看不出中位數是從幾次裡取的"
    assert int(比對.group(1)) >= _最少量測次數, (
        f"只量了 {比對.group(1)} 次，少於 {_最少量測次數} 次談不上中位數"
    )


def test_有整份閘的總時間() -> None:
    """佔比要有分母。沒有總時間，「佔四成」是浮的。"""
    assert _總時間.search(_原文()) is not None, "沒有寫 `總時間中位數：`，佔比就沒有分母"


@pytest.mark.parametrize("代碼", _規則代碼們())
def test_每條規則都量到了(代碼: str) -> None:
    """**少一條就可能漏掉真兇。**

    每一行要有兩個數字：中位數耗時、佔總時間幾成。
    """
    行 = _表格行(_原文(), 代碼)

    assert 行 is not None, f"表裡沒有 {代碼} 這條，它在 `nova 閘 ci --全部跑完` 裡會跑"
    assert _百分比.search(行) is not None, f"{代碼} 那行沒有佔比"
    assert len(_數字.findall(行)) >= 2, f"{代碼} 那行只有一個數字，中位數與佔比要都在"


def test_佔比加起來要對得上整份() -> None:
    """每條的佔比湊不出整份，表就是拼湊的——多半是不同次量測混在一起。"""
    原文 = _原文()
    佔比們 = [
        float(比對.group(1))
        for 代碼 in _規則代碼們()
        if (行 := _表格行(原文, 代碼)) and (比對 := _百分比.search(行))
    ]
    合計 = sum(佔比們)

    assert 80 <= 合計 <= 101, f"各規則佔比加起來是 {合計:.1f}%，湊不出整份閘的時間"


def test_表按耗時由多到少排() -> None:
    """**這張表是拿來回答「哪條最慢」的。** 亂序的表要讀的人自己排。"""
    原文 = _原文()
    耗時們 = [
        float(_數字.findall(行)[0])
        for 代碼 in _規則代碼們()
        if (行 := _表格行(原文, 代碼)) and _數字.findall(行)
    ]

    assert 耗時們 == sorted(耗時們, reverse=True), f"表沒有由慢到快排：{耗時們}"


def test_改進方向每條都寫了省多少與代價() -> None:
    """**沒有代價的改進方向，讀起來每條都值得做。**

    這一格不實作，所以「值不值得」是下一個人看數字決定的——
    他要看得到省下的秒數，也要看得到要付什麼。
    """
    原文 = _原文()

    assert "改進方向" in 原文, "沒有改進方向那一段"
    assert 原文.count("預估省下") >= 1, "改進方向沒有寫預估省下多少秒"
    assert 原文.count("代價") >= 1, "改進方向沒有寫代價"
    assert 原文.count("預估省下") == 原文.count("代價"), (
        f"「預估省下」出現 {原文.count('預估省下')} 次、"
        f"「代價」{原文.count('代價')} 次：每條改進方向兩樣都要有"
    )
