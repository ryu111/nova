"""審查意見按問題種類分流，測試設計問題退回測試員整合測試。

規格保證：
1. 當審查員指出測試設計問題（問題種類：測試設計）時，工作流退回測試員而非實作員。
2. 測試員取得審查指出的測試設計問題，並可重新修訂測試。
3. 當審查員指出實作問題（問題種類：實作）時，工作流維持退回實作員。
4. 當審查員連續兩輪提出相同未解問題且無進展時，觸發停止護欄。
"""

from pathlib import Path

from nova.契約.工作流 import (
    任務,
    停止條件,
    判準終局,
    執行器,
    結束代碼,
    階段代碼,
)
from nova.契約.模型回應 import 回應, 失敗代碼, 用量, 終局
from nova.迴圈.工作流 import 建TDD執行器, 跑工作流

一件事 = 任務(描述="修訂具有嚴謹邊界條件的功能", 工作目錄=Path("/不存在但沒人會碰"))
過關的審查回覆 = "看起來沒問題。\nREVIEW: PASS"


def _假回應(文字: str = "做好了", *, 終: 終局 = 終局.成功) -> 回應:
    return 回應(
        文字=文字,
        終局=終,
        失敗代碼=失敗代碼.無 if 終 is 終局.成功 else 失敗代碼.逾時,
        原始結束碼=0,
        對話識別碼=None,
        用量=用量(輸入token=1, 輸出token=1),
    )


class 假角色:
    def __init__(self, 名稱: str, 回: 回應 | list[回應] | None = None) -> None:
        """名稱只是給錯誤訊息看的；`回` 讓測試決定這個角色會回什麼。"""
        self.名稱 = 名稱
        序列 = 回 if isinstance(回, list) else [回 or _假回應()]
        if not 序列:
            訊息 = "假角色至少要有一個回應"
            raise ValueError(訊息)
        self._序列 = 序列
        self.收到: list[str] = []

    def 做(self, 提示: str, *, 工作目錄: Path | None = None) -> 回應:
        del 工作目錄
        self.收到.append(提示)
        return self._序列[min(len(self.收到) - 1, len(self._序列) - 1)]


def _執行器(
    判準序列: list[bool], 角色們: dict[str, 假角色] | None = None
) -> tuple[執行器, dict[str, 假角色]]:
    人 = {
        "測試": 假角色("測試"),
        "實作": 假角色("實作"),
        "重構": 假角色("重構"),
        "審查": 假角色("審查", _假回應(文字=過關的審查回覆)),
        **(角色們 or {}),
    }
    剩 = list(判準序列)

    def 跑判準(_: 任務) -> tuple[判準終局, str]:
        綠 = 剩.pop(0) if 剩 else True
        return (判準終局.綠 if 綠 else 判準終局.紅), "假判準"

    執行 = 建TDD執行器(
        角色表={
            階段代碼.測試: 人["測試"],
            階段代碼.實作: 人["實作"],
            階段代碼.重構: 人["重構"],
            階段代碼.審查: 人["審查"],
        },
        跑判準=跑判準,
    )
    return 執行, 人


class Test審查問題導向角色分流:
    def test_審查指出測試設計問題退回測試員而不是實作員(self) -> None:
        """當審查員指出測試設計問題時，退回測試員重新修改測試。

        軌跡順序：測試 -> 驗證紅 -> 實作 -> 驗證綠 -> 重構 -> 驗證重構 -> 審查
                -> 測試（第二輪，測試設計問題）-> 驗證紅 -> 實作 -> 驗證綠
                -> 重構 -> 驗證重構 -> 審查
        """
        人 = {
            "測試": 假角色(
                "測試",
                [
                    _假回應(文字="已撰寫初始測試"),
                    _假回應(文字="已補上空輸入邊界測試"),
                ],
            ),
            "實作": 假角色(
                "實作",
                [
                    _假回應(文字="初版實作"),
                    _假回應(文字="配合新測試修正實作"),
                ],
            ),
            "重構": 假角色("重構"),
            "審查": 假角色(
                "審查",
                [
                    _假回應(
                        文字=(
                            "測試設計不夠嚴謹，未涵蓋空輸入邊界。\n"
                            "ISSUE: [test-design] 缺少空輸入邊界測試\n"
                            "REVIEW: CHANGES-REQUESTED"
                        )
                    ),
                    _假回應(文字=過關的審查回覆),
                ],
            ),
        }
        # 兩輪 TDD 迴圈的判準序列：
        # 第 1 輪：驗證紅 (False, 期望紅), 驗證綠 (True), 驗證重構 (True)
        # 第 2 輪：驗證紅 (False, 期望紅), 驗證綠 (True), 驗證重構 (True)
        執行, 人 = _執行器([False, True, True, False, True, True], 人)

        果 = 跑工作流(一件事, 執行一步=執行)

        assert 果.結束.代碼 is 結束代碼.完成, 果.結束.原因
        assert len(人["測試"].收到) == 2, "審查指出測試設計問題，測試員應被呼叫第二次"
        assert "缺少空輸入邊界測試" in 人["測試"].收到[1], "測試員提示應包含審查指出的測試設計問題"
        assert [步.階段 for 步 in 果.軌跡] == [
            階段代碼.測試,
            階段代碼.驗證紅,
            階段代碼.實作,
            階段代碼.驗證綠,
            階段代碼.重構,
            階段代碼.驗證重構,
            階段代碼.審查,
            階段代碼.測試,
            階段代碼.驗證紅,
            階段代碼.實作,
            階段代碼.驗證綠,
            階段代碼.重構,
            階段代碼.驗證重構,
            階段代碼.審查,
        ]

    def test_審查指出實作問題維持退回實作員(self) -> None:
        """當審查員指出實作問題時，維持退回實作員。"""
        人 = {
            "測試": 假角色("測試"),
            "實作": 假角色(
                "實作",
                [
                    _假回應(文字="初版實作"),
                    _假回應(文字="修復除以零邊界"),
                ],
            ),
            "重構": 假角色("重構"),
            "審查": 假角色(
                "審查",
                [
                    _假回應(
                        文字=(
                            "實作邏輯未處理除以零邊界。\n"
                            "ISSUE: [impl] 運算邏輯未處理除以零異常\n"
                            "REVIEW: CHANGES-REQUESTED"
                        )
                    ),
                    _假回應(文字=過關的審查回覆),
                ],
            ),
        }
        # 第 1 輪：驗證紅 (False), 驗證綠 (True), 驗證重構 (True)
        # 退回實作後：驗證綠 (True), 驗證重構 (True)
        執行, 人 = _執行器([False, True, True, True, True], 人)

        果 = 跑工作流(一件事, 執行一步=執行)

        assert 果.結束.代碼 is 結束代碼.完成, 果.結束.原因
        assert len(人["測試"].收到) == 1, "實作問題不應退回測試員"
        assert len(人["實作"].收到) == 2, "實作問題應退回實作員"
        assert "運算邏輯未處理除以零異常" in 人["實作"].收到[1]

    def test_退回測試員也一樣會撞連續退回護欄(self) -> None:
        """**新的分流不准讓迴圈變成不死的。**

        測試設計問題會退回測試員，那條路比退回實作員多繞一段。
        `連續審查要求修改` 數的是連續幾次 `要求修改`，跟退回誰無關——
        這支就是在釘死這件事：走測試員那條路，一樣在門檻上收護欄。
        """
        人 = {
            "測試": 假角色("測試"),
            "實作": 假角色("實作"),
            "重構": 假角色("重構"),
            "審查": 假角色(
                "審查",
                [
                    _假回應(
                        文字=(
                            "測試未涵蓋負數。\n"
                            "ISSUE: [test-design] 缺少負數測試案例\n"
                            "REVIEW: CHANGES-REQUESTED"
                        )
                    ),
                    _假回應(
                        文字=(
                            "測試仍未涵蓋負數。\n"
                            "ISSUE: [test-design] 缺少負數測試案例\n"
                            "REVIEW: CHANGES-REQUESTED"
                        )
                    ),
                ],
            ),
        }
        執行, 人 = _執行器([False, True, True, False, True, True, False, True, True], 人)

        果 = 跑工作流(
            一件事,
            執行一步=執行,
            停止=停止條件(最多步數=20, 最多token=10**9),
        )

        assert 果.結束.代碼 is 結束代碼.護欄
        # **不准寫成「或」。** 三個關鍵詞任一命中就算過的話，這支對「訊息是哪一種」
        # 完全沒有分辨力——兩條分支都含「審查」，改壞了照樣綠。
        assert "審查意見連續要求修改" in 果.結束.原因, 果.結束.原因
