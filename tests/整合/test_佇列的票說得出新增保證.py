"""佇列上的票要**說得出**「這張是新增保證」，而且那句話要一路走到 `任務`。

## 為什麼還要這一支

`tests/單元/test_測試員要補負控登記.py` 已經釘住兩件事：迴圈那層看到
`任務.新增保證` 就把負控那段接給測試員；`nova.派工`（Python 門面）填得進這一欄。

**但真線不是走門面。** 排程、`nova 跑`、`nova 派工` 最後都收斂成
「往收件匣丟一個檔」，再由 `nova 工作流 --從收件匣` 撈起來
（`src/nova/載體/收件.py` 的模組說明：檔案就是事件，那是唯一的橋）。
而那條路上：

- `收件單` 沒有「這張票新增保證」這一欄——票寫了也沒有地方放；
- `src/nova/載體/命令列.py` 造 `任務` 的那一行只帶 `描述／工作目錄／前情`。

於是佇列來的票**永遠**拿到預設的 `False`，測試員永遠看不到負控那段。
CLAUDE.md 判準第 3 條：有實作、沒有可達的呼叫端，等於沒有。

## 為什麼標記長這樣

`<!--nova:新增保證-->` 抄 `<!--nova:驗收 <指令>-->` 的形狀：票是 markdown，
註解在算繪時看不見，而**開票的人**是唯一有資格判斷「這張票要不要多付一次負控」的人。
判準從資料來，不從模型的自覺來。

只從**題目**讀、不從前情讀，也跟驗收同一條理由：前情是模型自己的輸出。
差別在方向——驗收怕模型替自己種一條穩過的閘，負控怕的是相反的那一半：
模型在自己的前情裡把票升級成「新增保證」，替下一輪多開一次寫測試檔的許可。
兩邊的答案一樣：**只有票說了算。**

## 這支**不**守什麼

- 不真的呼叫模型（`跑工作流` 被攔下來，接下來那一整輪不會發生）。
- 不碰護欄：實作員那一階不准動測試檔這件事，由既有那支守。
- 不驗提示的字面內容，那是 `test_測試員要補負控登記.py` 的事。

## 負控

把 `命令列` 造 `任務` 那一行的 `新增保證=` 拿掉（收了就丟），
`test_從收件匣撈起來的票把新增保證帶進任務` 要紅。

把 `收件._搶下來` 讀標記那一步拿掉，
`test_票上宣告的新增保證會被收件單帶下來` 要紅。
"""

from collections.abc import Callable
from pathlib import Path

import pytest

from nova.契約.工作流 import 任務, 結束, 結束代碼
from nova.載體 import 命令列
from nova.載體.收件 import 丟一件, 你敲, 收下一件, 收件目錄
from nova.迴圈.工作流 import 工作流結果

#: 開票的人宣告「這張票新增保證」的那一句。註解形式：算繪出來看不見，
#: 而且跟 `<!--nova:驗收 ...-->` 同一個命名空間。
_新增保證標記 = "<!--nova:新增保證-->"

_一張新增保證的票 = f"""新增：截斷的回應要當場收成失敗，不准當成綠

{_新增保證標記}
"""

_一張純重構的票 = "重構：把三處重複的階段判斷收成一個查詢，行為不變\n"


class Test票上說得出新增保證:
    """`收件單` 要有地方放「這張票新增保證」。沒有這一欄，票寫了也等於沒寫。"""

    def test_票上宣告的新增保證會被收件單帶下來(self, tmp_path: Path) -> None:
        匣 = tmp_path / "收件"
        丟一件(_一張新增保證的票, 來源=你敲, 目錄=匣)

        單 = 收下一件(匣)

        assert 單 is not None, "剛丟進去的那一件該收得下來"
        assert 單.新增保證 is True, (
            "票上宣告了新增保證，收件單卻沒帶下來——佇列這條路上這個意思會當場蒸發"
        )

    def test_沒宣告的票預設不新增保證(self, tmp_path: Path) -> None:
        """不新增保證的票（純重構、純文件）不准被要求補負控，否則每張票都多付一次成本。"""
        匣 = tmp_path / "收件"
        丟一件(_一張純重構的票, 來源=你敲, 目錄=匣)

        單 = 收下一件(匣)

        assert 單 is not None
        assert 單.新增保證 is False, "沒宣告就被當成新增保證，等於每張票都多繞一次負控"

    def test_前情裡的新增保證不算數(self, tmp_path: Path) -> None:
        """接續票的前情是**模型自己的輸出**，不准拿它替下一輪升級票種。"""
        匣 = tmp_path / "收件"
        丟一件(
            f"{_一張純重構的票}\n"
            f"<!--nova:接續 輪次=2-->\n"
            f"上一輪我覺得這其實是新增保證 {_新增保證標記}\n",
            來源=你敲,
            目錄=匣,
        )

        單 = 收下一件(匣)

        assert 單 is not None
        assert 單.新增保證 is False, (
            "前情裡的標記算數的話，模型可以在自己的輸出裡替下一輪多開一次許可"
        )


def _攔下工作流收到的任務(monkeypatch: pytest.MonkeyPatch) -> list[任務]:
    """讓 `nova 工作流 --從收件匣` 跑到「造好任務、交給工作流」為止，把那個任務接下來。

    攔在 `跑工作流` 是因為要驗的正是**命令列造出來的那個 `任務` 物件**：
    再往裡走就要真的呼叫模型，而那跟這一格要守的東西無關。
    """
    收到: list[任務] = []

    def 假跑工作流(任: 任務, **其餘: object) -> 工作流結果:
        del 其餘
        收到.append(任)
        return 工作流結果(結束=結束(代碼=結束代碼.完成, 原因="這支測試沒有真的跑"), 軌跡=())

    monkeypatch.setattr(命令列, "跑工作流", 假跑工作流)
    return 收到


def _跑一輪收件匣(專案: Path, 執行檔: Path) -> int:
    """真的走 `主程式`，不自己拼 `任務`——這一支守的就是那條路上的接線。"""
    return 命令列.主程式(
        [
            "工作流",
            "--從收件匣",
            "--工作目錄",
            str(專案),
            "--用",
            "claude",
            "--審查用",
            "codex",
            "--執行檔",
            str(執行檔),
            "--判準",
            "true",
            "--不記帳",
        ]
    )


class Test從佇列撈起來的票帶得動新增保證:
    """`nova 工作流 --從收件匣` 是排程與派工最後都會走的那條路。

    門面（`nova.派工`）填得進這一欄不代表佇列填得進——今天佇列這條路上
    造 `任務` 的那一行根本沒有這個欄位，所以真線永遠拿到 `False`。
    """

    def test_從收件匣撈起來的票把新增保證帶進任務(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
        做假CLI: Callable[..., tuple[Path, Path]],
    ) -> None:
        """**這是這一格存在的全部理由。**"""
        monkeypatch.setenv("XDG_STATE_HOME", str(tmp_path / "state"))
        專案 = tmp_path / "某個專案"
        專案.mkdir()
        執行檔, _ = 做假CLI("claude")
        丟一件(_一張新增保證的票, 來源=你敲, 目錄=收件目錄(專案))
        收到 = _攔下工作流收到的任務(monkeypatch)

        碼 = _跑一輪收件匣(專案, 執行檔)

        assert 收到, f"命令列該把任務交給工作流剛好一次（退出碼 {碼}）"
        assert 收到[0].新增保證 is True, (
            "佇列上的票宣告了新增保證，命令列造任務時卻沒帶進去——測試員在真線上永遠看不到負控那段"
        )

    def test_從收件匣撈起來的普通票不新增保證(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
        做假CLI: Callable[..., tuple[Path, Path]],
    ) -> None:
        """接上這條線不准讓每一張票都變貴。"""
        monkeypatch.setenv("XDG_STATE_HOME", str(tmp_path / "state"))
        專案 = tmp_path / "某個專案"
        專案.mkdir()
        執行檔, _ = 做假CLI("claude")
        丟一件(_一張純重構的票, 來源=你敲, 目錄=收件目錄(專案))
        收到 = _攔下工作流收到的任務(monkeypatch)

        碼 = _跑一輪收件匣(專案, 執行檔)

        assert 收到, f"命令列該把任務交給工作流剛好一次（退出碼 {碼}）"
        assert 收到[0].新增保證 is False, "純重構的票被當成新增保證，等於每張票都多付一次成本"
