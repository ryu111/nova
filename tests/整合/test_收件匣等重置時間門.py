"""收件匣自己的時間門：票躺在匣裡不等於安全。

2026-09-02 撞到上游 session limit 那天，票被排回收件匣，下一次醒來馬上又把它
搶走、又撞同一個額度、又燒一次錢。所以 `不早於` 光寫在票上沒有用——**要有人讀
它，而且要在 `rename` 之前讀**：搬進 `處理中/` 之後才發現「時候還沒到」，這一輪
已經算開跑了，票也不在使用者看得到的地方。

這支檔守的是收件匣邊界那一段：標記讀得出三個選填欄位、時間門擋不擋得住、
以及等額度那個計數器的界限。誰把 `不早於` 寫上去、誰去讀等重置的清單，不在這裡。

時刻一律注入（`收下一件(現在=…)`），不摸機器時鐘——測真時鐘的話這幾支會在
重置時刻前後那一分鐘自己翻面。
"""

from datetime import UTC, datetime, timedelta
from pathlib import Path

import pytest

from nova.載體.收件 import (
    接著排,
    收下一件,
    收件單,
    時候到了嗎,
    最多輪次,
    等重置的,
    等重置的一件,
    額度等待最多,
)

#: 那天假 claude 回的重置時刻，帶時區的 UTC ISO。
重置的ISO = "2026-09-02T08:40:00+00:00"
重置時刻 = datetime.fromisoformat(重置的ISO)


def _等了幾次的那件(匣: Path, 已經等過: int, *, 輪次: int = 1) -> 收件單:
    """造一張「已經為了額度等過 N 次、跑到第幾輪」的票。

    `接著排(額度等待=…)` 收的是**候選票**上要寫的那個數字（呼叫端傳
    `收件.額度等待 + 1`），不是手上這張的——兩者差一，界限就差一個 5 小時視窗。

    `輪次` 收成參數，是為了測得動「兩個計數器各數各的」：輪次已經用完的票，
    等額度那條路照樣要排得出去。
    """
    return 收件單(
        名稱="某件事",
        任務="把某件事做完",
        處理中路徑=匣 / "處理中" / "某件事.md",
        前情="",
        輪次=輪次,
        額度等待=已經等過,
    )


def test_不早於還沒到收下一件就不放行到了才放行(tmp_path: Path) -> None:
    """等重置的票在重置時刻之前不准被搶走，**而且要留在原地**；之後才放行。

    兩件事一起守，因為漏掉任何一件那 72 分鐘就回來：

    1. 時間沒到就回 `None`：搶走的話下一步立刻再撞一次同一個額度、再燒一次錢，
       `不早於` 就只是一個看起來很負責的欄位。
    2. 回 `None` 的那一次**票還在收件匣**：時間門擺在 `rename` 之後的話，票已經
       進了 `處理中/`，「沒到就不放行」實際上變成「沒到也先搶走再說」，而且
       使用者從外面看它就像做過了。
    3. 那一次 `等重置的` **要指得出是哪一張、等到什麼時候**：`收下一件` 回 `None`
       有兩種意思——匣子真的空著（該去生票），跟票在、時鐘還沒到（什麼都不要
       做）。分不出來的話每次醒來都會再長一張票去撞同一個額度。永遠回空清單
       的實作在這裡就要紅。

    時間到了之後收回來的那張，三個新欄位要原封不動帶著，`輪次` 不准加一
    ——等額度一步都沒推進，把它算成一輪等於用「沒進展」的名義吃掉 `最多輪次`。
    """
    匣 = tmp_path / "收件"
    匣.mkdir()

    票 = 接著排(
        _等了幾次的那件(匣, 已經等過=0),
        前情="撞到上游額度了",
        目錄=匣,
        起點="test",
        不早於=重置的ISO,
        額度等待=1,
    )
    assert 票 is not None, "前提：第一次等額度要排得出票"

    assert 時候到了嗎(重置的ISO, 現在=重置時刻 - timedelta(seconds=1)) is False
    assert 收下一件(匣, 現在=重置時刻 - timedelta(seconds=1)) is None, (
        "重置前就被搶走＝下一次醒來馬上再撞一次額度、再燒一次錢"
    )
    assert 票.exists(), "沒到時間的票要**留在原地**（不 rename）：搬走了人就以為做過了"
    assert 等重置的(匣, 現在=重置時刻 - timedelta(seconds=1)) == [
        等重置的一件(路徑=票, 不早於=重置的ISO)
    ], (
        "「匣子空了」跟「有票但時鐘沒到」要分得出來：回空清單的話，下一次醒來會"
        "當成沒事做、再生一張新票去撞同一個額度"
    )
    assert 等重置的(匣, 現在=重置時刻 + timedelta(seconds=1)) == [], (
        "時間到了就不算在等——還留在清單裡的話，那張票會被當成「還在等」而沒人去撿"
    )

    收到 = 收下一件(匣, 現在=重置時刻 + timedelta(seconds=1))
    assert 收到 is not None, "重置之後還不放行的話，那條線就永遠等下去了"
    assert 收到.起點 == "test", "接續要從停下來的那一階接（這輪停在 test），不從頭挑一階"
    assert 收到.不早於 == 重置的ISO
    assert 收到.額度等待 == 1
    assert 收到.輪次 == 1, (
        "額度不吃輪次：`最多輪次` 數的是「撞 nova 自己的上限＝題目可能卡住」，"
        "額度撞三次只證明額度小"
    )
    assert not 票.exists(), "時間到了就要真的搶下來（rename 是 at-most-once 的所有權宣告）"


@pytest.mark.parametrize(
    ("標記", "期望起點", "期望不早於", "期望額度等待"),
    [
        ("<!--nova:接續 輪次=2 上一輪=abc-->", "", "", 0),
        ("", "", "", 0),
    ],
)
def test_沒有新欄位的舊票照樣收得下來(
    tmp_path: Path, 標記: str, 期望起點: str, 期望不早於: str, 期望額度等待: int
) -> None:
    """手丟的票與**三個新欄位落地之前**排出來的接續票都讀得回來——它們是選填的。

    不放這一格的話，最省事的實作是「讀不到就炸」，而炸掉的是使用者昨天丟進
    收件匣的那張票；沒有 `不早於` 的票也不准被時間門順手擋住。
    """
    匣 = tmp_path / "收件"
    匣.mkdir()
    (匣 / "20260901T000000Z-file-舊票-aabbcc.md").write_text(
        f"把某件事做完\n\n{標記}\n", encoding="utf-8"
    )

    收到 = 收下一件(匣, 現在=datetime(2026, 9, 2, 8, 41, tzinfo=UTC))

    assert 收到 is not None, "沒有 `不早於` 的票不准被時間門擋住"
    assert 收到.起點 == 期望起點
    assert 收到.不早於 == 期望不早於
    assert 收到.額度等待 == 期望額度等待


def test_第六個等待窗還在額度上限內就要排得出去(tmp_path: Path) -> None:
    """`額度等待最多 == 6` 是「六個窗都准等」，不是「等到第六次就交人」。

    界限差一格不是美觀問題：一個窗 5 小時。把第六次砍掉＝一天的最後一個窗白白
    丟給人，而且**不會有任何徵兆**——票沒排、狀態看起來就像做完了。停下來交給
    人要有理由（等了一整天還在等），「第六次」沒有這個理由，它跟第五次一樣只是
    在等時鐘。

    這一格由**候選票上的數字**定義：`接著排(額度等待=6)` 是「這張要排出去的票是
    第 6 次等」，所以它必須排得出去，而且排出來的票自己記得是第 6 次——記錯的話
    下一輪的呼叫端 +1 會算出第 8 次，界限就再漂一格。

    手上這張的 `輪次` 故意就是 `最多輪次`：**兩個計數器各數各的**。等額度那條路
    要是照樣先套 `輪次 >= 最多輪次`，票在第一個視窗就停在這裡等人，界限寫得再對
    也沒有用——而且外面看不出差別，一樣是「沒排票」。
    """
    匣 = tmp_path / "收件"
    匣.mkdir()

    assert 額度等待最多 == 6, "一天六個 5h 視窗——這個數字改了就要改這支測試的理由"
    排了 = 接著排(
        _等了幾次的那件(匣, 已經等過=額度等待最多 - 1, 輪次=最多輪次),
        前情="又撞到了",
        目錄=匣,
        起點="impl",
        不早於=重置的ISO,
        額度等待=額度等待最多,
    )
    assert 排了 is not None, (
        f"第 {額度等待最多} 次等待還在 `額度等待最多 = {額度等待最多}` 之內，"
        "卻已經不排票了——上限被實作成「排到 5 就停」（界限漂一格），或是等額度"
        f"那條路還在吃 `最多輪次 = {最多輪次}`；兩種都讓那個 5 小時視窗沒人等"
    )
    assert 排了.exists(), "回了路徑就要真的有那個檔，不然下一次醒來撿不到"

    收到 = 收下一件(匣, 現在=重置時刻 + timedelta(seconds=1))
    assert 收到 is not None, "重置時間過了，第六張等待票就該撿得起來"
    assert 收到.額度等待 == 額度等待最多, (
        f"票上要寫「這是第 {額度等待最多} 次等」，實際 {收到.額度等待}——"
        "呼叫端下一輪拿它 +1，這裡漂一格界限就跟著漂一個 5 小時視窗"
    )
    assert 收到.起點 == "impl", "等重置不會讓進度倒退，接的還是停下來那一階"
    assert 收到.輪次 == 最多輪次, (
        "等額度一步都沒推進，輪次不准加一，也不准被 `最多輪次` 擋下來——兩個計數器各數各的"
    )


def test_額度等待用完就不再排接續票(tmp_path: Path) -> None:
    """一天最多六個 5 小時視窗；**第七次**就不是「等一下」，是有人要看一眼了。

    **它是自己的計數器，不吃 `最多輪次`**：吃掉輪次的話，四條線並行的日子每條線
    傍晚都會停下來等人——那正是這條規則要消滅的東西。
    """
    匣 = tmp_path / "收件"
    匣.mkdir()

    assert 額度等待最多 == 6, "一天六個 5h 視窗——這個數字改了就要改這支測試的理由"
    排了嗎 = 接著排(
        _等了幾次的那件(匣, 已經等過=額度等待最多),
        前情="又撞到了",
        目錄=匣,
        起點="impl",
        不早於=重置的ISO,
        # 第七次：六個窗都等過了，這一張要再等就超出上限。
        額度等待=額度等待最多 + 1,
    )
    assert 排了嗎 is None, "等了一整天還在等，就該停下來讓人看見，不要無限接下去"
    assert not list(匣.glob("*.md")), "回 None 就不准偷偷落檔"


@pytest.mark.parametrize(
    "無時區時戳",
    [
        # 解得出來、但沒帶時區：沒辦法跟帶時區的現在比。
        "2026-09-02T08:40:00",
        # 根本解不出來：模型把「五小時後」原封不動寫進標記的那一種。
        "五小時後",
    ],
)
def test_無時區的不早於視為無效時戳而放行(tmp_path: Path, 無時區時戳: str) -> None:
    """讀不懂的 `不早於` 一律放行——擋下去等於一張壞標記能把票永遠關起來。

    兩種讀不懂都要放行：**沒帶時區**的（比不了）與**根本解不出來**的（`fromisoformat`
    直接炸）。只守前者的話，後者會從時間門裡拋出去，一張壞標記就把整個收件匣
    卡死——連排在它後面、跟額度無關的票都撿不起來。時間門的職責是擋等重置的
    那幾張，不是替壞掉的欄位把使用者的票鎖在收件匣裡。
    """
    匣 = tmp_path / "收件"
    匣.mkdir()
    票 = 匣 / "20260902T000000Z-file-無時區-aabbcc.md"
    票.write_text(
        "把某件事做完\n\n"
        f"<!--nova:接續 輪次=1 上一輪=abc 起點=impl 不早於={無時區時戳} 額度等待=1-->\n",
        encoding="utf-8",
    )

    此刻 = datetime(2026, 9, 2, 8, 41, tzinfo=UTC)
    assert 時候到了嗎(無時區時戳, 現在=此刻) is True, "讀不動的時戳要放行，不准拋例外也不准擋"

    收到 = 收下一件(匣, 現在=此刻)

    assert 收到 is not None, "無時區的壞時戳應放行，不得讓這張票卡死收件匣"
    assert 收到.起點 == "impl"
    assert 收到.不早於 == 無時區時戳
    assert 收到.額度等待 == 1
    assert 收到.處理中路徑.exists(), "放行後票應已移入處理中"
    assert not 票.exists(), "放行後不應把原票留在收件匣根目錄"
