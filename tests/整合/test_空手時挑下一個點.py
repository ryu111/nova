"""nova 空手的時候要自己找得到下一個點，不是安靜退出等人丟票。

現在的迴圈只閉在「維護」那半邊：撈到票就跑七階、撞上限就排接續票、
main 閘紅就落一張修理票。**推進票一張都不是 nova 生的**——
每一個新的點都是人讀 `docs/設計/13-規格做到哪了.md` 挑出來、手寫四欄丟進來的。

所以這一格只回答一件事：**收件匣空的時候，nova 找不找得到下一個點。**

## 為什麼挑法要綁在那份文件上

`13-規格做到哪了.md` 自己就寫明了挑法與理由（「是別條缺口的前提」、
「成本最低而風險最實」、「唯一不需要新模型呼叫」）。這裡不另立第二套優先序，
也**不叫模型去想一個新的點**：硬規則二不准同一個對話自寫自評，
而 nova 生票、nova 做、nova 驗的那條鏈，源頭必須追得到一份**外部文件**，
不能追到一次模型呼叫上。文件裡沒寫的缺口就不挑，安靜退出。

測試從 CLI 進去而不是直接呼叫新模組：要釘的是「空收件匣那條路徑真的接上了」，
新模組怎麼切是實作者的事，測試不該替他決定函式簽名。
"""

from pathlib import Path

import pytest

from nova.契約.退出碼 import 放行
from nova.載體 import 缺口成票
from nova.載體.健康度 import 健康度指標
from nova.載體.命令列 import 主程式
from nova.載體.收件 import (
    丟一件,
    你敲,
    待處理,
    收件目錄,
    缺哪幾欄,
    要驗收嗎,
    誰造的,
    讀出驗收,
)

_專案根 = Path(__file__).resolve().parents[2]

#: 真的那份規格對照。**抄真的，不是自己捏一份像的**——
#: 捏的那份只證明得了「我的實作看得懂我自己的格式」。
_真的規格對照 = _專案根 / "docs" / "設計" / "13-規格做到哪了.md"

#: 那份文件在「所以下一批該做什麼」裡自己挑出來的三條。
#: 挑哪一條由實作照文件的理由決定，但**一定是這三條之一**，
#: 不准是文件裡沒有的第四條。
_文件自己挑的三條 = ("隔離工作區", "診斷表", "存檔")

#: 一份「沒有缺口」的規格對照：每一列都是「有」，下一批那段明說沒東西可挑。
#: 格式照真的那份，只換內容——**不能靠格式壞掉來讓它挑不到**，
#: 那樣測到的是剖析失敗，不是「沒有缺口」。
_沒有缺口的規格對照 = """# 規格做到哪了：逐節對照 nova 的現況

## 對照表

| 規格哪一節 | 它要求什麼 | nova 現在 | 證據 |
|---|---|---|---|
| §1.1 | 模型以外的一切都算載體 | 有 | `src/nova/載體/閘.py`；`test_禁令hook存在` |
| §1.5 | 以證據循環：測試通過才算成功 | 有 | `src/nova/載體/判準.py`；`test_驗證是機械的不是模型` |

## 所以下一批該做什麼

沒有缺口。表上每一列都是「有」，這一輪沒有東西可挑。
"""


@pytest.fixture
def 假專案(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """一個乾淨的專案：狀態根目錄搬到 tmp，收件匣因此是空的。"""
    monkeypatch.setenv("XDG_STATE_HOME", str(tmp_path / "狀態"))
    專案 = tmp_path / "專案"
    (專案 / "docs" / "設計").mkdir(parents=True)
    return 專案


def _放規格對照(專案: Path, 內文: str) -> None:
    (專案 / "docs" / "設計" / "13-規格做到哪了.md").write_text(內文, encoding="utf-8")


def _抄真的規格對照(專案: Path) -> None:
    _放規格對照(專案, _真的規格對照.read_text(encoding="utf-8"))


def _跑收件(專案: Path) -> int:
    return 主程式(["--根目錄", str(專案), "收件"])


@pytest.fixture(autouse=True)
def _健康度當成全綠(monkeypatch: pytest.MonkeyPatch) -> None:
    """這一份驗的是**挑點**，不是背壓。

    背壓（健康度紅就不生推進票）由 `tests/整合/test_健康度紅不生推進票.py` 守。
    這裡不把它餵成綠的話，每一支都會被背壓擋掉——而紅的原因會變成
    「gh 在測試環境查不到」，跟這份要驗的東西無關。
    """
    monkeypatch.setattr(
        缺口成票,
        "查健康度指標",
        lambda _: 健康度指標(main綠嗎=True, 卡住的線數=0, 沒收尾的件數=0, 壞掉的PR數=0),
    )


class Test空手時從規格對照挑下一個點:
    """空收件匣是這一格唯一的觸發條件。"""

    def test_空收件匣時落出一張票(self, 假專案: Path) -> None:
        """**空手不再等於沒事做。** 落一張進收件匣，下一輪排程就撈得到它。

        票要指得回那份文件：來源追不到外部文件的話，
        這條鏈就變成 nova 自己想一個題目、自己做、自己驗。
        """
        _抄真的規格對照(假專案)

        碼 = _跑收件(假專案)

        assert 碼 == 放行
        票們 = 待處理(收件目錄(假專案))
        assert len(票們) == 1, "空手時應該正好落一張票"
        內容 = 票們[0].read_text(encoding="utf-8")
        assert any(標題 in 內容 for 標題 in _文件自己挑的三條), (
            f"挑的點要是文件自己挑出來的那三條之一，實際落出來的是：\n{內容}"
        )
        assert "13-規格做到哪了" in 內容, "票上要指得回它的出處，不然來源追不到外部文件"

    def test_落出來的票四欄齊全(self, 假專案: Path) -> None:
        """**生得出一張自己會擋下來的票是最難看的那種假綠。**

        `丟一件` 對自主來源要求四欄齊全（`tests/單元/test_四欄才准派.py`），
        自己剛做的檢查要吃得下自己生的票。
        """
        _抄真的規格對照(假專案)

        _跑收件(假專案)

        票 = 待處理(收件目錄(假專案))[0]
        內容 = 票.read_text(encoding="utf-8")
        assert 缺哪幾欄(內容) == (), f"票缺了欄：{缺哪幾欄(內容)}"
        assert 讀出驗收(內容), "自主來源的票沒帶機械驗收就等於沒有停止條件"
        assert 要驗收嗎(誰造的(票.name)), "這張票是 nova 自己生的，來源要記成自主來源"

    def test_規格對照裡沒有缺口就安靜退出不生票(self, 假專案: Path) -> None:
        """反向保證：少了這條，nova 會在沒事做的時候憑空生票，然後永遠有事做。"""
        _放規格對照(假專案, _沒有缺口的規格對照)

        碼 = _跑收件(假專案)

        assert 碼 == 放行
        assert 待處理(收件目錄(假專案)) == [], "文件裡沒有缺口就不准挑，維持安靜退出"

    def test_規格對照不在就安靜退出不生票(self, 假專案: Path) -> None:
        """讀不到那份文件時也不准自己想一個題目出來。"""
        碼 = _跑收件(假專案)

        assert 碼 == 放行
        assert 待處理(收件目錄(假專案)) == []

    def test_收件匣還有票就不再生一張(self, 假專案: Path) -> None:
        """**觸發條件是空手，不是每次醒來。**

        不擋的話，排程每十五分鐘就往一個已經有事做的佇列裡再塞一張，
        而佇列是先進先出——人剛丟進去的那張會被自己生的票越推越後面。
        """
        _抄真的規格對照(假專案)
        本來那張 = 丟一件("人手丟的題目", 來源=你敲, 目錄=收件目錄(假專案))

        碼 = _跑收件(假專案)

        assert 碼 == 放行
        assert 待處理(收件目錄(假專案)) == [本來那張]
