"""本線負控**綠的時候**也要看得見它跑到哪幾把刀。

## 守什麼

`registered-mutation-diff` 這條的證據是給人核對用的：這條線動過的登記檔選到了哪幾把、
還是一把都沒動（`0 把`）。**選錯集合的症狀是綠**——把數與刀名印不出來的話，
「選到 0 把卻一路綠到 CI」跟「真的沒動過登記檔」在終端機上長得一模一樣。

同時守反面：綠的別條規則（pytest 那幾條的整段輸出）**不准**跟著印。
每次閘綠都洗掉半個畫面的話，這一行也會跟著被學會忽略。
"""

import pytest

from nova.契約.檢查結果 import 檢查結果
from nova.契約.退出碼 import 放行
from nova.載體.命令列 import _印結果
from nova.載體.本線負控 import 判定選到的刀
from tests.負控.登記們.本線負控 import 登記 as _本檔登記的刀們

_這個登記檔 = "tests/負控/登記們/本線負控.py"

#: **兩句摘要都是問產生端要來的，不寫死。** 寫死的話「印得出來」跟「印的是對的東西」
#: 就分了家：產生端漏掉刀名、或把選到幾把的那句誤報成 `0 把`，這支照樣綠。
_沒動過通過, _沒動過登記檔 = 判定選到的刀((), 選到=())
_選到通過, _選到幾把 = 判定選到的刀((_這個登記檔,), 選到=_本檔登記的刀們)
#: 印出來要核對的刀名：一樣現算，不手抄。
_某一把的刀名 = min(一筆.識別 for 一筆 in _本檔登記的刀們)
#: 綠的 pytest 規則長這樣：一大段進度點。它不該被印出來。
_一大段pytest輸出 = "bringing up nodes...\n" + "\n".join(
    f"{'.' * 72} [{i:3}%]" for i in range(1, 61)
)


def _綠的(代碼: str, 證據: str) -> 檢查結果:
    return 檢查結果(代碼=代碼, 名稱=代碼, 通過=True, 負責層="測試", 證據=證據)


def _印一次(結果表: list[檢查結果], capsys: pytest.CaptureFixture[str]) -> tuple[int, str]:
    """直接呼叫 `_印結果`，不走 subprocess——走子程序的話覆蓋率追不到那幾行。"""
    退出碼 = _印結果(結果表)
    抓到 = capsys.readouterr()
    return 退出碼, 抓到.out + 抓到.err


def test_全綠時本線負控的把數與刀名照樣印得出來(capsys: pytest.CaptureFixture[str]) -> None:
    """全綠那一次的輸出裡，本線負控的摘要在；別條綠規則的整段輸出不在。

    摘要本身也在這裡驗：產生端要真的把「幾把」與「哪幾把」寫進那句話，
    綠的那一句才有人核對得動。
    """
    assert _選到通過 is True, f"選到刀了卻不是綠：{_選到幾把!r}"
    assert _沒動過通過 is True, f"本線沒動登記檔是綠的，不是紅：{_沒動過登記檔!r}"
    assert f"{len(_本檔登記的刀們)} 把" in _選到幾把, f"摘要沒說選到幾把：{_選到幾把!r}"
    assert _某一把的刀名 in _選到幾把, f"摘要沒列出選到的刀名：{_選到幾把!r}"
    assert "0 把" in _沒動過登記檔, f"沒動過登記檔那句要誠實說 0 把：{_沒動過登記檔!r}"

    退出碼, 印出來 = _印一次(
        [
            _綠的("pytest-parallel", _一大段pytest輸出),
            _綠的("registered-mutation-diff", _選到幾把),
        ],
        capsys,
    )

    assert 退出碼 == 放行, "全綠就是放行，印證據不准改退出碼"
    assert _選到幾把 in 印出來, f"本線負控綠的時候摘要沒印出來：\n{印出來}"
    assert _某一把的刀名 in 印出來, "選到的刀名要印得出來，只印把數看不出選錯"
    assert "bringing up nodes" not in 印出來, (
        f"綠的 pytest 規則整段輸出被印出來了，會把摘要洗掉：\n{印出來}"
    )

    退出碼, 印出來 = _印一次([_綠的("registered-mutation-diff", _沒動過登記檔)], capsys)

    assert 退出碼 == 放行
    assert _沒動過登記檔 in 印出來, f"沒動過登記檔那一句也要印出來：\n{印出來}"
