def _跑一輪被驗收擋下來的CLI(
    專案: Path,
    monkeypatch: pytest.MonkeyPatch,
    做假CLI: Callable[..., tuple[Path, Path]],
) -> int:
    """工作流自己收在「完成」，票宣告的驗收紅——回真正的最終退出碼。

    走的是真的 `主程式`：`_驗收說了算` 改碼、`_歸檔成果` 落帳這兩段接線都要真的走過，
    因為這一格要守的正是原因從產生它的那一行流不流得到帳上。
    """
    _丟一張帶驗收的票(專案)
    執行檔, _ = 做假CLI("claude")

    def 假跑工作流(_任: 任務, **其餘: object) -> 工作流結果:
        """工作流自己跑完了、收在完成——**驗收才是那個說不的人**。"""
        del _任, 其餘
        return 工作流結果(結束=結束(代碼=結束代碼.完成, 原因="模型說做完了"), 軌跡=())

    monkeypatch.setattr(命令列, "跑工作流", 假跑工作流)
    return 命令列.主程式(
        [
            "工作流",
            "--從收件匣",
            "--工作目錄",
            str(專案),
            "--用",
            "claude",
            "--執行檔",
            str(執行檔),
            "--判準",
            "true",
            "--不記帳",
        ]
    )


def test_驗收紅換來的那個4帳上也答得出是驗收擋的(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    做假CLI: Callable[..., tuple[Path, Path]],
) -> None:
    """**這條 4 不是工作流發的，是收尾發的。**

    `_驗收說了算` 在工作流回 0 之後才把碼改成 4，而這時工作流那個 `結束`
    收在「完成」、身上沒有護欄原因——所以落帳那一步只讀 `果.結束` 是不夠的，
    這一筆會變成帳上最常見的一種沒有原因的 4：模型說做完了，
    但票宣告的驗收不同意。分不出它跟「撞上限」的差別，
    事後查「這件為什麼一直做不完」就查不出來，**而那兩件事的修法完全相反**。
    這一格要求的是：碼是 4，帳上就要答得出這個 4 是驗收擋的。
    """
    monkeypatch.setenv("XDG_STATE_HOME", str(tmp_path / "狀態"))
    專案 = tmp_path / "某個專案"

    碼 = _跑一輪被驗收擋下來的CLI(專案, monkeypatch, 做假CLI)

    assert 碼 == _護欄退出碼, "前提壞了：驗收紅該把這一輪的退出碼改成 4"
    筆們 = 列出成果(已處理目錄(專案))
    assert 筆們, "驗收紅的那一輪根本沒落帳"
    一筆 = 筆們[0]
    assert 一筆.退出碼 == _護欄退出碼
    assert 一筆.收場 == 結束代碼.完成.value, (
        f"前提壞了：工作流自己是收在完成的，`outcome` 不該被改掉（{一筆.收場}）"
    )
    assert 一筆.護欄原因 == 護欄原因.驗收紅.value, (
        f"驗收擋下來的 4 在帳上寫的是 `{一筆.護欄原因}`——"
        "歸成別種護欄的話，修法會指到調上限或退回上一個綠燈去"
    )


def test_驗收紅與重構改壞行為在帳上不准塌成同一種護欄(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    做假CLI: Callable[..., tuple[Path, Path]],
) -> None:
    """兩條 4，兩種修法，帳上要是兩個字。

    要擋的是這種湊法：落帳只讀驗收之前那個 `果.結束`，驗收紅時它是「完成」、
    身上沒有護欄原因，於是帳上那個字只能靠「碼是 4、收場卻不是護欄」事後反推，
    而反推挑得到的既有格子，正好就是重構改壞行為那一格——兩條 4 塌成同一個字。

    塌在一起的代價很具體：重構改壞行為要**退回上一個綠燈**，驗收紅是模型
    說做完了、票宣告的驗收不同意，要**回去重做**。帳上同一個字，
    讀帳的人就得回去翻日誌猜是哪一種，等於沒有這一欄。
    """
    monkeypatch.setenv("XDG_STATE_HOME", str(tmp_path / "狀態"))
    專案 = tmp_path / "某個專案"

    碼 = _跑一輪被驗收擋下來的CLI(專案, monkeypatch, 做假CLI)
    assert 碼 == _護欄退出碼, "前提壞了：驗收紅該把這一輪的退出碼改成 4"
    驗收紅那筆們 = 列出成果(已處理目錄(專案))
    assert 驗收紅那筆們, "驗收紅的那一輪根本沒落帳"
    驗收紅那筆 = 驗收紅那筆們[0]

    重構那筆 = _落一筆(
        tmp_path / "帳本",
        _跑到重構改壞行為(tmp_path / "重構工作區"),
        識別="20260902T104500Z-refac",
    )

    assert 驗收紅那筆.護欄原因 == 護欄原因.驗收紅.value, (
        f"驗收擋下來的 4 在帳上寫的是 `{驗收紅那筆.護欄原因}`：這一輪是模型說做完了、"
        "票宣告的驗收不同意，要回去重做"
    )
    assert 重構那筆.護欄原因 == 護欄原因.重構改壞行為.value, (
        f"重構改壞行為的 4 在帳上寫的是 `{重構那筆.護欄原因}`：這一輪是重構把行為改掉了，"
        "要退回上一個綠燈"
    )
    assert 驗收紅那筆.驗收, "驗收紅那一筆連跑了哪條驗收都沒留下，那個字更無從對帳"


def _做一個乾淨的工作樹(專案: Path) -> None:
    專案.mkdir()
    subprocess.run(["git", "init", "-q"], cwd=專案, check=True)
    (專案 / "README.md").write_text("測試用工作樹\n", encoding="utf-8")
    subprocess.run(["git", "add", "README.md"], cwd=專案, check=True)
    subprocess.run(
        [
            "git",
            "-c",
            "user.name=測試",
            "-c",
            "user.email=test@example.com",
            "commit",
            "-qm",
            "初始化",
        ],
        cwd=專案,
        check=True,
    )


def _取出線段落(輸出文字: str, 線名關鍵字: str) -> list[str]:
    for 段 in (段.strip().splitlines() for 段 in 輸出文字.strip().split("\n\n")):
        if 段 and any(線名關鍵字 in 行 for 行 in 段 if 行.startswith("線：")):
            return 段
    pytest.fail(f"輸出裡找不到 {線名關鍵字} 那一段：\n{輸出文字}")


def test_狀態檔被下一次醒來蓋掉之後同一筆還是答得出護欄原因(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """排程每 15 分鐘醒一次，`寫下現況` 整檔覆寫——原因不准只住在那裡。

    **從頭到尾是同一筆**：真的跑一輪撞到「無進展」的工作流、真的落帳，
    然後把 狀態.json 換成**下一次醒來**的內容（另一個執行識別碼、理由是空的），
    也就是舊的 `_護欄原因` 唯一的取數來源被蓋掉之後的樣子。
    看板那一格要從成果帳讀，照樣說得出是「原地打轉」。
    """
    主專案 = tmp_path / "主專案"
    _做一個乾淨的工作樹(主專案)
    線名 = "護欄線"
    工作樹 = tmp_path / f"nova-wt-{線名}"
    subprocess.run(["git", "worktree", "add", "-q", str(工作樹), "HEAD"], cwd=主專案, check=True)
    monkeypatch.setenv("XDG_STATE_HOME", str(tmp_path / "狀態"))

    果 = _跑到卡住(tmp_path / "工作區")
    撞護欄那次 = "20260902T100000Z-abcdef"
    _落一筆(已處理目錄(工作樹).parent / "帳本", 果, 識別=撞護欄那次)

    # 15 分鐘後排程醒來一次：整檔覆寫，上一次的理由當場消失。
    寫下現況(
        現況(
            上次醒來="2026-09-02T10:15:00Z",
            上次結果="idle",
            上次退出碼=0,
            上次理由="",
            上次執行識別碼="20260902T101500Z-nextup",
        ),
        路徑=狀態檔(工作樹),
    )
    monkeypatch.chdir(主專案)

    碼 = 命令列.主程式(["--根目錄", str(主專案), "線"])

    輸出 = capsys.readouterr()
    assert 碼 == 0, 輸出.out + 輸出.err
    收場欄 = next(行 for 行 in _取出線段落(輸出.out, f"nova-wt-{線名}") if "上一次怎麼收的" in 行)
    assert f"退出碼 {_護欄退出碼}" in 收場欄, 收場欄
    assert "查不到" not in 收場欄, f"不准把「查不到」當成答案：{收場欄}"
    assert 護欄原因.無進展.value in 收場欄, f"狀態檔被蓋掉之後就答不出是哪一種護欄了：{收場欄}"
