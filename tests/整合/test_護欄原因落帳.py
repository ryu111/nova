def test_收在護欄的那一輪帳上答得出是哪一種護欄(tmp_path: Path) -> None:
    """成果帳那一筆要指名是「卡住」，不是只留一個 `guardrail`。

    **原因要落在自己的 ASCII 欄位上**（帳要跨程序讀，讀的人可能不是 python）。
    塞進 `task` 或 `outcome` 字串裡湊不算：那樣讀帳的人要靠字串比對，
    等於沒有這個欄位。
    """
    果 = _跑到卡住(tmp_path / "工作區")
    識別 = "20260902T101500Z-guard1"

    一筆 = _落一筆(tmp_path / "帳本", 果, 識別=識別)

    assert 一筆.退出碼 == _護欄退出碼
    assert 一筆.護欄原因 == 護欄原因.無進展.value, f"帳上答不出是哪一種護欄：{一筆}"
    落盤 = json.loads((tmp_path / "已處理" / f"{識別}.json").read_text(encoding="utf-8"))
    assert 落盤["guardrail_reason"] == 護欄原因.無進展.value
    assert 落盤["outcome"] == 結束代碼.護欄.value, "原因不准把 outcome 那一格改掉"
    assert 護欄原因.無進展.value not in 落盤["task"], "原因不准塞進 task 湊"


def test_每一種走得到退出碼4的護欄在帳上都分得開(tmp_path: Path) -> None:
    """預算／步數／卡住／重構改壞行為／動了測試——五條路，五個答案。

    退出碼 4 有好幾個發出點：迴圈自己算的那幾種（預算、步數、無進展）、
    狀態機發的（重構把行為改掉了）、階段邊界發的（不准動測試的那一階動了測試）。
    **只補迴圈那幾種等於沒補**：剩下的照樣在帳上留一個沒有原因的 4，
    而看板會對那些說「查不到」。

    每一條路釘死它**該對到哪一個**列舉值。只驗「彼此不同」是不夠的：
    「動了測試」與「重構改壞行為」互換，兩個答案照樣不同、照樣合法，
    而看板會叫人去退回上一個綠燈，現場其實是實作員把紅測試改成恆綠。
    """
    跑法們: dict[護欄原因, Callable[[Path], 工作流結果]] = {
        護欄原因.預算: _跑到預算用完,
        護欄原因.步數: _跑到步數用完,
        護欄原因.無進展: _跑到卡住,
        護欄原因.重構改壞行為: _跑到重構改壞行為,
        護欄原因.動了測試: _跑到動了測試,
    }
    帳本目錄 = tmp_path / "帳本"

    答案們: dict[護欄原因, str | None] = {}
    for 序, (該是, 跑) in enumerate(跑法們.items()):
        果 = 跑(tmp_path / f"工作區{序}")
        一筆 = _落一筆(帳本目錄, 果, 識別=f"20260902T10{序}000Z-kind{序}")
        assert 一筆.退出碼 == _護欄退出碼
        答案們[該是] = 一筆.護欄原因

    對錯了的 = {該是.name: 答案們[該是] for 該是 in 跑法們 if 答案們[該是] != 該是.value}
    assert not 對錯了的, (
        f"這幾條路在帳上答錯了種類（左邊是走的路，右邊是帳上的字）：{對錯了的}——"
        "照著錯的字去修就是修錯地方"
    )


