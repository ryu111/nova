"""退出碼 4 是**哪一種**護欄，要留在成果帳上，而且要活得比 狀態.json 久。

護欄有好幾種來源（預算、步數、卡住、重構改壞行為、動了測試、驗收紅），
`outcome` 那一格分不出它們：工作流自己收在護欄的那幾種，`outcome` 一律是
`guardrail`；驗收紅那條連 `guardrail` 都不是——工作流收在**完成**
（`outcome` 是 `done`），是收尾的 `_驗收說了算` 把**最終退出碼**改成 4。
所以這一檔認的是**退出碼 4**，不是 `outcome`。
「模型每次都撞上限」與「模型每次都在原地打轉」的修法完全相反，
分不出來的話，那個 4 事後不可歸因。

原因**不准只**記在 狀態.json 的 `last_wake_reason`：`寫下現況` 是**整檔覆寫**，
排程每 15 分鐘醒一次就把它蓋掉，隔天早上看板就只剩「查不到」。
所以這一檔測的是同一件事的幾面：

1. 一輪真的收在退出碼 4 的工作流，落帳之後那一筆自己答得出是哪一種；
2. **每一條走得到 4 的路都要答得出**——不只迴圈自己算出來的那幾種
   （累計預算、單次爆量、步數、無進展），還有狀態機（重構改壞行為）、
   階段邊界（動了測試）與收尾（驗收紅）；
3. 同一筆成果在 狀態.json 被下一次醒來整檔蓋掉之後，`nova 線` 照樣答得出。

**原因都是真的跑出來的，不是手捏一個 `結束` 或手造一筆 `成果`。** 手造等於把
中間那段接線跳過去：這一格要守的正是「原因從產生它的那一行流得到帳上」。

會碰硬碟、會開 git、會走命令列，所以住整合層。
"""

