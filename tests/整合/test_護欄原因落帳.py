def _平凡的一步(定義: 階段定義) -> 步驟結果:
    """判準階段照 `期望綠` 交差，模型階段說「做好了」。這一輪從判準看是完美的。"""
    if 定義.種類 is 種類.判準:
        return 步驟結果(階段=定義.代碼, 終局=終局.成功, 判準綠=bool(定義.期望綠), 證據="假判準")
    return 步驟結果(階段=定義.代碼, 終局=終局.成功, 判準綠=None, 證據="做好了")


def _跑到卡住(工作區: Path) -> 工作流結果:
    """讓一輪工作流真的撞上「無進展」那道護欄，回它的結果。

    同一批測試連著紅、工作區雜湊一動也沒動——這是「模型在原地打轉」那一種。
    """
    工作區.mkdir(parents=True, exist_ok=True)
    (工作區 / "實作.py").write_text("固定內容\n", encoding="utf-8")
    判準紅次數 = 0

    def 執行一步(定義: 階段定義, _任務: 任務, _軌跡: tuple[步驟結果, ...]) -> 步驟結果:
        nonlocal 判準紅次數
        del _任務, _軌跡
        if 定義.代碼 is 階段代碼.驗證紅:
            return 步驟結果(階段=定義.代碼, 終局=終局.成功, 判準綠=False, 證據="初始測試確實是紅的")
        if 定義.代碼 is 階段代碼.驗證綠:
            判準紅次數 += 1
            順序 = _失敗的測試們 if 判準紅次數 % 2 else tuple(reversed(_失敗的測試們))
            return 步驟結果(
                階段=定義.代碼,
                終局=終局.成功,
                判準綠=False,
                證據=f"FAILED {順序[0]}\nFAILED {順序[1]}\n耗時 {判準紅次數 * 7} ms",
            )
        return 步驟結果(
            階段=定義.代碼,
            終局=終局.成功,
            判準綠=None if 定義.種類 is 種類.模型 else 定義.期望綠,
            證據="本輪沒有改動工作區",
        )

    前 = sha256((工作區 / "實作.py").read_bytes()).hexdigest()
    果 = 跑工作流(
        任務(描述="修好一個卡住的功能", 工作目錄=工作區),
        執行一步=執行一步,
        停止=停止條件(最多步數=35, 最多token=10**9),
    )
    assert 果.結束.代碼 is 結束代碼.護欄, f"前提壞了，這一輪沒收在護欄：{果.結束}"
    assert sha256((工作區 / "實作.py").read_bytes()).hexdigest() == 前
    return 果


