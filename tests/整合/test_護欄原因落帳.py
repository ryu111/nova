def test_動了測試與重構改壞行為要有自己那一格不准借別人的(tmp_path: Path) -> None:
    """這兩條 4 是**新的種類**，列舉原本那六格涵蓋不了它們。

    要擋的是「借格子」這種寫法：動了測試借 `fanout-limit`（那一格的意思是
    「扇出開太多」）、重構改壞行為借 `invalid-output`（那一格的意思是
    「交出來的東西不符格式約定」）。借了就分不出來也讀不對——看板印出
    `fanout-limit`，人會去查扇出設定，而現場其實是實作員把紅測試改成恆綠；
    印出 `invalid-output`，人會去看模型回應的格式，而現場是重構把行為改掉了、
    該退回上一個綠燈。

    所以這兩種各自要在列舉裡有自己的一格：**仍然是列舉的值**（讀帳的人要拿
    固定的值分類）、**不准是舊有那六格裡的任何一個**，而且**不准互換**——
    互換的話兩個答案照樣是新的一格，看板卻會把兩種相反的修法指反。
    """
    跑法們: dict[護欄原因, Callable[[Path], 工作流結果]] = {
        護欄原因.動了測試: _跑到動了測試,
        護欄原因.重構改壞行為: _跑到重構改壞行為,
    }

    for 序, (該是, 跑) in enumerate(跑法們.items()):
        果 = 跑(tmp_path / f"工作區{序}")
        一筆 = _落一筆(tmp_path / "帳本", 果, 識別=f"20260902T11{序}000Z-own{序}")
        assert 一筆.退出碼 == _護欄退出碼
        assert 一筆.護欄原因 not in _舊有的六格, (
            f"「{該是.name}」在帳上借了 `{一筆.護欄原因}` 這一格——"
            "那一格講的是別件事，照著它去修會修錯地方"
        )
        assert 一筆.護欄原因 == 該是.value, (
            f"「{該是.name}」在帳上寫的是 `{一筆.護欄原因}`："
            "「回去寫實作」跟「退回上一個綠燈」被指反了"
        )


