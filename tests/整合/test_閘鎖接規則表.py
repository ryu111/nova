"""要幾個 token **由規則表逐條宣告**，而且只包住那一條規則的檢查。

## 這一支守什麼

`test_閘鎖token池.py` 驗的是鎖原語本身（給 4 就拿 4、給 N 就抽乾）。
可是原語對了不代表接線對了：只要有人在 `載體/命令列.py` 用「這個閘點裡
最大的那條」算一個數字、再把整次 `跑閘` 包起來，CI 就會**從第一條 ruff
一路抽乾池子到最後一條**——池子有 12 個 token，實際還是一次一條閘，
而所有原語測試依然全綠。

所以這一支盯兩件事：

1. **宣告在規則表上**：`registered-mutation` 抽乾整池（它的 `最多秒` 是牆鐘，
   多一個鄰居就可能把好測試殺成假紅）、`pytest-parallel` 取 `平行度()`
   （它自己就開那麼多 worker）、序列的那幾條（ruff／mypy／`pytest tests/單元`）
   各取 1。**這是固定負控的著力點**：把刀改回取 1，第一支就得紅。
2. **只包住那一條**：跑序列規則的時候池子只少 1 個，別條閘還進得來；
   跑刀的時候才一個不剩；整個 `跑閘` 結束就全還回去。

## 為什麼不真的跑閘

驗的是額度怎麼被拿走，不是規則跑不跑得完。所以第二支用假規則表：
每條規則的「檢查」只做一件事——**當場數池子裡還剩幾個 token**。
一支測試零個 pytest 子程序，鎖目錄與核心數都是注入的。

住整合層是因為它動的是檔案系統上的鎖，不是純函式。
"""

from contextlib import ExitStack
from pathlib import Path

from nova.載體.規則表 import 平行度, 建規則表
from nova.載體.閘 import 抽乾整池, 規則, 跑閘
from nova.載體.閘鎖 import 佔不到, 佔住, 池大小

#: 假裝的核心數。4 × `平行成數`(0.75) = 3 個 token——**故意用小池子**：
#: 3 個位子就數得清「少了 1 個」跟「一個不剩」的差別。
_假核心數 = 4


def _剩幾個token(鎖目錄: Path) -> int:
    """池子裡現在還有幾個 token 拿得到。一次拿一個，拿到拿不動為止。

    `最多等幾秒=0` ＝ 不排隊，當場問當場答；這一支要的是**快照**，不是等待行為。
    """
    with ExitStack() as 堆疊:
        剩 = 0
        while True:
            try:
                堆疊.enter_context(
                    佔住(
                        "閘",
                        要幾個token=1,
                        最多等幾秒=0,
                        鎖目錄=鎖目錄,
                        核心數=_假核心數,
                    )
                )
            except 佔不到:
                return 剩
            剩 += 1


def test_每條規則自己宣告要幾個token(tmp_path: Path) -> None:
    """額度是**逐條**宣告的，不是整個閘點取一個最大值。

    刀抽乾整池、平行測試取 `平行度()`、序列的那幾條各取 1。
    十二條序列的閘同時跑得動，靠的就是最後那一行。
    """
    宣告 = {條.代碼: 條.要幾個token for 條 in 建規則表(tmp_path)}

    assert 宣告["registered-mutation"] is 抽乾整池
    #: 本線那幾把刀跑得少，要的機器一樣多：`最多秒` 是牆鐘，鄰居線同時跑測試
    #: 就會把好刀殺成假紅，而假紅會退掉一整輪。留預設值 1 的症狀正是那個。
    assert 宣告["registered-mutation-diff"] is 抽乾整池
    assert 宣告["pytest-parallel"] == 平行度()
    assert 宣告["ruff-check"] == 1
    assert 宣告["ruff-format"] == 1
    assert 宣告["mypy"] == 1
    assert 宣告["pytest-unit"] == 1
    assert 宣告["pytest-serial"] == 1


def test_額度只包住正在跑的那一條規則(tmp_path: Path) -> None:
    """一條規則跑完就把 token 還掉，下一條再自己拿。

    序列那條在跑的時候池子只少 1 個（3 個位子還剩 2），別條閘進得來；
    抽乾的那條在跑的時候才一個不剩。整次 `跑閘` 收工，3 個全部回到池子裡。
    """
    當時剩幾個: dict[str, int] = {}

    def 數池子(代碼: str) -> tuple[bool, str]:
        當時剩幾個[代碼] = _剩幾個token(tmp_path)
        return True, f"{代碼} 跑的時候池子剩 {當時剩幾個[代碼]} 個"

    規則表 = [
        規則(
            代碼="序列的",
            名稱="只吃一個核心的檢查",
            閘點=frozenset({"提交"}),
            負責層="載體",
            檢查=lambda: 數池子("序列的"),
            要幾個token=1,
        ),
        規則(
            代碼="刀",
            名稱="登記負控（要整台機器）",
            閘點=frozenset({"提交"}),
            負責層="測試",
            檢查=lambda: 數池子("刀"),
            要幾個token=抽乾整池,
        ),
    ]

    結果表 = 跑閘("提交", 規則表, 鎖目錄=tmp_path, 核心數=_假核心數)

    assert [結果.通過 for 結果 in 結果表] == [True, True], "兩條規則都要真的跑到"
    assert 池大小(核心數=_假核心數) == 3
    assert 當時剩幾個 == {"序列的": 2, "刀": 0}
    assert _剩幾個token(tmp_path) == 3, "跑完了 token 要全部還回池子"
