"""接續票：撞到上限停下來的那件，怎麼變回下一輪的收件檔。

## 為什麼是「排回收件匣」不是「別搬走」

收件匣的三個目錄各有意思：`收件/` 是還沒動的、`處理中/` 是收下沒收尾的、
`已處理/` 是做完的。撞到上限那一輪**真的做完了一輪**——帳記了、成果落了、
原始請求歸檔了。把它留在 `處理中/` 會讓「被殺掉」跟「按設計停下」長得一樣，
而那兩件正是使用者要求分開處理的兩件。

所以：**那一輪照常收尾，另外排一張新的票**。每一輪都是獨立的執行識別碼，
跟事件帳本、成果帳的形狀一致。

## 輪次上限是停止規則，不是設定

沒有它，一件永遠撞上限的工作會每 15 分鐘重排一次，**永遠**。
使用者選了不設預算上限，所以這裡是唯一擋得住無限重排的東西。
`迴圈` 那層七欄位缺 stop rule 的不是迴圈，是成本漏洞——這裡同一條。
"""

from pathlib import Path

import pytest

from nova.載體.收件 import 丟一件, 你敲, 接著排, 收下一件, 收件單, 最多輪次


def _收下(匣: Path) -> 收件單:
    單 = 收下一件(匣)
    assert 單 is not None
    return 單


class Test接續票長什麼樣:
    def test_描述不變前情帶著輪次加一(self, tmp_path: Path) -> None:
        """**下一輪要接著做，不是從頭來**——所以題目要原封不動，進度要帶著。"""
        匣 = tmp_path / "收件"
        丟一件("把某件事做完", 來源=你敲, 目錄=匣)
        第一輪 = _收下(匣)

        票 = 接著排(第一輪, 前情="## 測1\n寫了一支測試", 目錄=匣)

        assert 票 is not None
        第二輪 = _收下(匣)
        assert 第二輪.任務 == "把某件事做完"
        assert "寫了一支測試" in 第二輪.前情
        assert 第二輪.輪次 == 2

    def test_來源沿用原本的(self, tmp_path: Path) -> None:
        """**來源是誰造了這件事的血緣**，不是誰把它撿起來的。

        接續票不另立第五個 semantic id——你敲的那件接續之後還是你敲的。
        """
        匣 = tmp_path / "收件"
        丟一件("把某件事做完", 來源=你敲, 目錄=匣)
        接著排(_收下(匣), 前情="走到一半", 目錄=匣)

        assert _收下(匣).來源 == 你敲

    def test_沒有標記的普通收件檔是第一輪(self, tmp_path: Path) -> None:
        """手丟進來的檔案不帶標記，**不能因此炸掉或算成第 0 輪**。"""
        匣 = tmp_path / "收件"
        丟一件("手丟的一件", 來源=你敲, 目錄=匣)

        單 = _收下(匣)

        assert 單.輪次 == 1
        assert 單.前情 == ""


class Test輪次用完就停:
    def test_最後一輪不再排(self, tmp_path: Path) -> None:
        """**回 None ＝ 不排了。** 由 `nova 狀態` 讓人看到，不是靜靜消失。"""
        匣 = tmp_path / "收件"
        丟一件("永遠做不完的事", 來源=你敲, 目錄=匣)
        單 = _收下(匣)
        for _ in range(最多輪次 - 1):
            assert 接著排(單, 前情="又撞上限", 目錄=匣) is not None
            單 = _收下(匣)

        assert 單.輪次 == 最多輪次
        assert 接著排(單, 前情="又撞上限", 目錄=匣) is None
        assert 收下一件(匣) is None


class Test前情要過遮罩:
    def test_祕密一個字都不進接續票(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        """**收件匣是狀態目錄的磁碟，跟已處理同一級。**

        進度檔可以不遮，因為路徑是使用者自己挑的（他知道那份內容能不能公開）；
        接續票的路徑是 **nova 自己挑的**，所以要遮。實測過模型會把祕密原封不動
        講回來，而前情正是模型講的話。
        """
        祕密 = "sk-" + "x" * 40
        monkeypatch.setenv("MY_SECRET_TOKEN", 祕密)
        匣 = tmp_path / "收件"
        丟一件("把某件事做完", 來源=你敲, 目錄=匣)

        票 = 接著排(_收下(匣), 前情=f"模型說：金鑰是 {祕密}", 目錄=匣)

        assert 票 is not None
        assert 祕密 not in 票.read_text(encoding="utf-8")
