"""扇出派工時，每個分支要在**自己那棵 git worktree** 裡動手。

住整合層不住單元層，理由就是這一格存在的全部理由：墊片測得出「參數有沒有傳對」，
測不出「兩個真目錄是不是真的隔離」。所以這裡真的開兩棵樹、各寫一次同一個檔名，
再比對兩邊讀回來的內容。

**兩個分支都不宣告 `寫入範圍`**——這是刻意的。宣告出來的相交由
`契約/分派.py` 那條擋掉了；工作樹擋的是**沒宣告**的那一種：兩個分支的輸入互不相干、
屏障也收得齊，卻都寫同一個地方，先寫的被後寫的蓋掉，而蓋掉的樣子跟兩個都成功
一模一樣。那種失敗看起來像模型變笨，會被誤診成別的層的問題。
"""

import subprocess
import threading
from pathlib import Path

from nova.契約.工作流 import 任務
from nova.契約.扇出 import 分支工作, 扇出政策, 扇出模式
from nova.契約.節點 import (
    停止政策,
    分支識別碼,
    執行識別碼,
    工作流識別碼,
    節點上下文,
    節點成功,
    節點識別碼,
    結果代碼,
    結構識別碼,
    證據來源,
    邊包,
    邊識別碼,
)
from nova.載體.扇出工作樹 import 帶著工作樹扇出

共用檔名 = "共用.txt"


def _跑(根: Path, *參數: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["git", *參數], cwd=根, capture_output=True, text=True, check=False)


def _造一個commit的repo(根: Path) -> str:
    """造一個只有一個 commit 的 repo，回傳那個 commit 的完整 sha。"""
    for 指令 in (
        ("init", "-q", "-b", "main"),
        ("config", "user.email", "測試@例子"),
        ("config", "user.name", "測試"),
    ):
        assert _跑(根, *指令).returncode == 0

    (根 / 共用檔名).write_text("主工作區原本的內容\n", encoding="utf-8")
    assert _跑(根, "add", "-A").returncode == 0
    assert _跑(根, "commit", "-q", "-m", "第一版").returncode == 0
    return _跑(根, "rev-parse", "HEAD").stdout.strip()


def _工作(分支: str) -> 分支工作[str, None]:
    分支代碼 = 分支識別碼(分支)
    return 分支工作(
        分支=分支代碼,
        輸入=邊包(
            結構=結構識別碼("題目"),
            版本=1,
            內容=f"{分支}要寫的東西",
            來源=證據來源(
                執行=執行識別碼("執行-001"),
                工作流=工作流識別碼("扇出-001"),
                分支=分支代碼,
                節點=節點識別碼("扇出分支"),
                嘗試=1,
                父邊=(邊識別碼("根輸入"),),
            ),
        ),
        依賴=None,
        必要=True,
        寫入範圍=(),  # 刻意不宣告：工作樹要擋的就是沒宣告的那一種
    )


def _上下文(工作目錄: Path) -> 節點上下文:
    return 節點上下文(
        任務=任務(描述="兩個分支各寫一次同一個檔名", 工作目錄=工作目錄),
        執行=執行識別碼("執行-001"),
        工作流=工作流識別碼("扇出-001"),
        節點=節點識別碼("扇出"),
        分支=分支識別碼("根"),
        父邊=(邊識別碼("根輸入"),),
        嘗試=1,
        停止=停止政策(最多呼叫=2, 最多token=200, 最多秒=30.0, 最多無進展=1),
    )


def _政策(必要分支: frozenset[分支識別碼]) -> 扇出政策:
    return 扇出政策(
        最大分支數=2,
        最大並行數=2,
        最少成功數=2,
        必要分支=必要分支,
        每分支最多token=100,
        階段最多token=200,
        最多秒=30.0,
        最多呼叫=2,
        模式=扇出模式.屏障,
    )


def _換掉內容(原本: 邊包[str], 內容: str) -> 邊包[str]:
    """複製一份只換內容的邊包；分支用它把「讀回來的東西」當產出交出去。"""
    return 邊包(結構=原本.結構, 版本=原本.版本, 內容=內容, 來源=原本.來源)


def test_兩個分支寫同一個檔名不會互相蓋掉(tmp_path: Path) -> None:
    """兩顆分支同時寫 `共用.txt`，各自讀回來的必須還是自己寫的那一份。

    關鍵在那道柵欄：**兩邊都寫完了才准讀**。沒有它，甲寫完馬上讀就讀到自己的，
    就算兩顆其實在同一個目錄裡也一樣綠——這支測試就白寫了。有柵欄的話，
    共用同一個目錄時後寫的會蓋掉先寫的，兩邊讀回來會是同一句話，當場紅。
    """
    專案 = tmp_path / "專案"
    專案.mkdir()
    起點commit = _造一個commit的repo(專案)
    樹根 = tmp_path / "樹"

    工作 = (_工作("甲"), _工作("乙"))
    都寫完了 = threading.Barrier(2)
    各自的工作目錄: dict[分支識別碼, Path] = {}
    鎖 = threading.Lock()

    def 執行一顆(工作項: 分支工作[str, None], 這顆上下文: 節點上下文) -> 節點成功[str]:
        工作目錄 = 這顆上下文.任務.工作目錄
        with 鎖:
            各自的工作目錄[工作項.分支] = 工作目錄
        (工作目錄 / 共用檔名).write_text(工作項.輸入.內容, encoding="utf-8")
        都寫完了.wait(timeout=10.0)  # 兩邊都寫完才准讀：沒有這道柵欄就測不到蓋掉
        讀回來 = (工作目錄 / 共用檔名).read_text(encoding="utf-8")
        return 節點成功(產出=_換掉內容(工作項.輸入, 讀回來), 證據=(), 用量=None)

    結果 = 帶著工作樹扇出(
        工作,
        執行一顆=執行一顆,
        上下文=_上下文(專案),
        政策=_政策(frozenset({工作[0].分支, 工作[1].分支})),
        專案=專案,
        樹根=樹根,
        起點commit=起點commit,
    )

    assert 結果.終局 is 結果代碼.成功, f"兩顆分支都該跑成，缺口：{結果.缺口}"

    讀回來的: dict[分支識別碼, str] = {}
    for 項 in 結果.分支結果:
        assert isinstance(項.結果, 節點成功), f"{項.分支} 沒跑成：{項.結果}"
        讀回來的[項.分支] = 項.結果.產出.內容
    assert 讀回來的 == {
        分支識別碼("甲"): "甲要寫的東西",
        分支識別碼("乙"): "乙要寫的東西",
    }, f"分支互相蓋掉了——它們寫在同一個目錄裡，不是各自的工作樹：{讀回來的}"

    甲目錄 = 各自的工作目錄[分支識別碼("甲")]
    乙目錄 = 各自的工作目錄[分支識別碼("乙")]
    assert 甲目錄 != 乙目錄, f"兩顆分支拿到同一個工作目錄：{甲目錄}"
    assert 甲目錄 != 專案 and 乙目錄 != 專案, "分支被派回共用的主工作區，等於沒有隔離"
    assert (專案 / 共用檔名).read_text(encoding="utf-8") == "主工作區原本的內容\n", (
        "分支的產出漏回主工作區了"
    )

    # 兩棵樹都寫過檔，扇出刻意留現場收不掉；測試自己收乾淨，不能讓 worktree 越跑越多。
    for 一棵 in (甲目錄, 乙目錄):
        assert _跑(專案, "worktree", "remove", "--force", str(一棵)).returncode == 0
