"""階段邊界要擋「動測試」——實作階段與重構階段跑完，`tests/` 不准被動過。

## 這支釘的是哪個洞

`載體/重構護欄.py` 的判準（跑之前 vs 跑之後拍兩張快照）**只有一個呼叫端**：
`載體/命令列.py` 的 `nova 重構` 這個獨立子命令。自主 TDD 七階
（收件匣那條、**沒有人在場的那條**）一格都沒接上。

於是最經典的作弊全程無感：實作員把紅測試改成恆綠 → `驗證綠` 當然綠 → 過。
提示裡「不准改測試」那兩句（`迴圈/角色提示.py:30`、`:46`）是**懇求**，
模型可以忽略，而且忽略了沒有人會發現。CLAUDE.md 的判準是：規則寫在 prompt 裡
是虛線，寫在包住執行者的程式碼裡才是實線的包圍環。

**收場不是紅也不是綠。** 紅／綠是「測試怎麼樣」，而這裡的事實是
「這一步不算數」——把它算成紅會讓實作員回去再改一次測試，那是拿更多錢
餵同一個作弊。

**但「這一步不算數」不等於「這一輪報廢」**：同一輪第一次伸手退回**測試員**
（那幾個檔要不要留那些改動、要怎麼改，本來就是測試員的職權，不是實作員的），
線不死；**同一輪第二次**伸手才收護欄——再犯才是慣犯。所以這一檔的每一支
都要說清楚自己釘的是第幾次。

## 這支怎麼接線

`跑工作流` 住迴圈，而**迴圈不准 import 載體**（架構閘）。所以護欄的兩個動作
都是參數：`拍快照`（拍一張、之後比得出有沒有動過）與 `動到測試了嗎`
（兩張快照差在哪幾個測試檔）。這裡由測試當組裝點，把載體的真實作注入進去
——`nova 重構` 已經是這個形狀。

**判準是角色不是階段名**：測試員那一階的工作就是寫測試，動 `tests/` 要放行，
所以最後一支負控釘的是「別把護欄做成階段盲的」。
"""

from pathlib import Path

import pytest

from nova.契約.工作流 import (
    任務,
    執行器,
    審查判定,
    步驟結果,
    種類,
    結束代碼,
    階段代碼,
    階段定義,
)
from nova.契約.模型回應 import 終局
from nova.載體.重構護欄 import 動到測試了嗎, 拍測試快照
from nova.迴圈.工作流 import 工作流結果, 跑工作流

#: 這一輪「該紅的那支測試」。護欄要指名它，不能只說「有測試被動了」——
#: 沒有檔名的護欄訊息，人得自己去 diff 才知道發生什麼事。
既有測試檔 = "tests/test_既有.py"
會紅的內容 = "def test_既有() -> None:\n    assert 1 + 1 == 3\n"


def 被改成恆綠(第幾次: int) -> str:
    """實作員第 `第幾次` 次伸手寫進去的內容。

    **每次的內容一定要不一樣**：護欄比的是快照，同樣的字串寫第二次在快照上
    等於沒動過，第二次伸手就抓不到了。
    """
    return f"def test_既有() -> None:\n    assert True  # 第 {第幾次} 次\n"


@pytest.fixture
def 假工作區(tmp_path: Path) -> Path:
    """一個只有一支紅測試的工作區。護欄比的就是這棵 `tests/` 樹。"""
    (tmp_path / "tests").mkdir()
    (tmp_path / 既有測試檔).write_text(會紅的內容, encoding="utf-8")
    return tmp_path


def _執行器(動手的階段: 階段代碼, 伸手幾次: int = 2) -> 執行器:
    """假執行器：零 LLM、零子程序。走到 `動手的階段` 的前 `伸手幾次` 次偷改既有測試檔。

    判準階段一律「照 `期望綠` 交差」——`驗證紅` 的 `期望綠` 是 False，
    所以它回紅（真的紅了，往下走）；兩個綠判準回綠。也就是說**這一輪從判準
    的角度看是完美的一輪**，作弊只看得出來於快照比對。

    `伸手幾次=1` 是「伸手一次就收手」：釘第一次那條退回測試員的邊；
    預設 2 是「再犯」：釘第二次收護欄。
    """
    已伸手 = 0

    def 執行一步(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> 步驟結果:
        nonlocal 已伸手
        del 軌跡
        if 定義.種類 is 種類.判準:
            return 步驟結果(階段=定義.代碼, 終局=終局.成功, 判準綠=bool(定義.期望綠), 證據="假判準")
        if 定義.代碼 is 動手的階段 and 已伸手 < 伸手幾次:
            已伸手 += 1
            (任.工作目錄 / 既有測試檔).write_text(被改成恆綠(已伸手), encoding="utf-8")
        return 步驟結果(
            階段=定義.代碼,
            終局=終局.成功,
            判準綠=None,
            證據="做好了",
            審查結論=審查判定.通過 if 定義.種類 is 種類.審查 else None,
        )

    return 執行一步


def _跑(工作區: Path, 執行: 執行器) -> 工作流結果:
    """把載體的護欄能力注入迴圈——依賴反轉，迴圈不必知道那是碰硬碟做到的。"""
    return 跑工作流(
        任務(描述="讓 X 變成 Y", 工作目錄=工作區),
        執行一步=執行,
        拍快照=拍測試快照,
        動到測試了嗎=動到測試了嗎,
    )


class Test實作階段動測試第一次退回測試員:
    def test_實作員第一次動測試檔不算數但線不死要退回測試階(self, 假工作區: Path) -> None:
        """三條作弊路徑裡最經典的那條：不寫實作，改測試。

        判準全程配合（驗證紅紅了、後面該綠的都綠），所以**只有快照比對抓得到**。
        抓到之後那一步不算數——但收線是另一回事：那個檔要不要留、怎麼改是
        **測試員**的職權，所以回頭邊接的是測試階，不是實作階、也不是結束。
        """
        果 = _跑(假工作區, _執行器(階段代碼.實作, 伸手幾次=1))
        assert [步.階段 for 步 in 果.軌跡][:4] == [
            階段代碼.測試,
            階段代碼.驗證紅,
            階段代碼.實作,  # 伸手了 → 這一步不算數
            階段代碼.測試,  # 決定權回到測試員手上，不是當場殺線
        ], f"第一次伸手要退回測試員：{[步.階段 for 步 in 果.軌跡]}"
        assert 果.結束.代碼 is not 結束代碼.護欄, (
            f"第一次伸手不准收 4——整棵工作樹的改動會變孤兒：{果.結束.原因}"
        )

    def test_不准往下走到驗綠就把作弊換來的綠寫進軌跡(self, 假工作區: Path) -> None:
        """護欄是「這一步不算數」，不是「先驗完綠再說」——

        往下走到 `驗證綠` 的話，那個綠是作弊換來的，而它會被寫進軌跡當證據。
        """
        果 = _跑(假工作區, _執行器(階段代碼.實作, 伸手幾次=1))
        伸手那步 = [步.階段 for 步 in 果.軌跡].index(階段代碼.實作)
        assert 果.軌跡[伸手那步 + 1].階段 is not 階段代碼.驗證綠, (
            "伸手那一步之後不准接驗證綠：那個綠是改測試換來的"
        )


class Test同一輪第二次動測試才收護欄:
    def test_實作員再犯就收在護欄而不是成功(self, 假工作區: Path) -> None:
        """再犯才是慣犯：退回測試員之後又伸手，這一輪就報廢。"""
        果 = _跑(假工作區, _執行器(階段代碼.實作))
        assert 果.結束.代碼 is 結束代碼.護欄, f"收場應該是護欄，實際 {果.結束.原因}"

    def test_護欄原因要指名被動的那個檔(self, 假工作區: Path) -> None:
        """「有測試被動了」不可行動，「`tests/test_既有.py` 被動了」才可行動。"""
        果 = _跑(假工作區, _執行器(階段代碼.實作))
        assert 既有測試檔 in 果.結束.原因, f"原因沒指名哪個檔：{果.結束.原因}"

    def test_擋在第二次那一步之後就停不准再往下驗綠(self, 假工作區: Path) -> None:
        果 = _跑(假工作區, _執行器(階段代碼.實作))
        assert [步.階段 for 步 in 果.軌跡] == [
            階段代碼.測試,
            階段代碼.驗證紅,
            階段代碼.實作,  # 伸手①：退回測試員
            階段代碼.測試,
            階段代碼.驗證紅,
            階段代碼.實作,  # 伸手②：收在這裡
        ]


class Test重構階段動測試也照同一條規矩:
    def test_重構員第一次動測試檔退回測試員(self, 假工作區: Path) -> None:
        """**不准把「不准動測試的階段」縮成只有重構或只有實作**：兩個角色同一條規矩。"""
        果 = _跑(假工作區, _執行器(階段代碼.重構, 伸手幾次=1))
        階段們 = [步.階段 for 步 in 果.軌跡]
        assert 階段們[:6] == [
            階段代碼.測試,
            階段代碼.驗證紅,
            階段代碼.實作,
            階段代碼.驗證綠,
            階段代碼.重構,  # 伸手了 → 不算數
            階段代碼.測試,  # 退回測試員
        ], f"重構員第一次伸手也是退回測試員：{階段們}"
        assert 果.結束.代碼 is not 結束代碼.護欄, f"第一次伸手不准收 4：{果.結束.原因}"

    def test_重構員再犯會收在護欄而不是成功(self, 假工作區: Path) -> None:
        """`nova 重構` 這個子命令擋得到，七階裡的同一個角色擋不到——同一條判準兩種待遇。"""
        果 = _跑(假工作區, _執行器(階段代碼.重構))
        assert 果.結束.代碼 is 結束代碼.護欄, f"收場應該是護欄，實際 {果.結束.原因}"
        assert 既有測試檔 in 果.結束.原因, f"原因沒指名哪個檔：{果.結束.原因}"

    def test_擋在重構第二次那一步之後就停(self, 假工作區: Path) -> None:
        果 = _跑(假工作區, _執行器(階段代碼.重構))
        assert [步.階段 for 步 in 果.軌跡] == [
            階段代碼.測試,
            階段代碼.驗證紅,
            階段代碼.實作,
            階段代碼.驗證綠,
            階段代碼.重構,
            階段代碼.測試,
            階段代碼.驗證紅,
            階段代碼.實作,
            階段代碼.驗證綠,
            階段代碼.重構,
        ]


class Test測試員那一階要放行:
    def test_測試員動測試不算違規(self, 假工作區: Path) -> None:
        """負控：判準是**角色**不是「有沒有動 tests/」。

        做成階段盲的話，第一階就會把自己擋死——寫測試的人動測試是它的工作。
        """
        果 = _跑(假工作區, _執行器(階段代碼.測試))
        assert 果.結束.代碼 is 結束代碼.完成, f"測試員不該被擋：{果.結束.原因}"
