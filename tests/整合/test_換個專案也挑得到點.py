"""換一個工作目錄，「空手時挑下一個點」對別的專案也要成立。

`docs/設計/10-目標長什麼樣.md` 開頭那條約束：**底下每一條都不准依賴
「這是 nova 自己」這個事實**。而 `缺口成票` 現在只認
`docs/設計/13-規格做到哪了.md` 這個 **nova 專屬的檔名**與它專屬的段落格式，
所以換一個專案跑起來，空手時什麼都挑不到——那不是「這個專案沒缺口」那種
正確的空手，是**這個機制對它根本不存在**。

## 這支測試釘的是什麼

一個 `tmp_path` 造出來的假專案（一支記帳小工具，跟 nova 沒有任何關係，
目錄底下連 `docs/設計/` 都沒有）：它照 nova 約定的方式寫了一份
「我的目標是什麼、現在做到哪」，nova 就該從**那份文件**挑出下一個點。

**不准拿 nova 自己的 repo 當輸入**——那正是這個 bug 活到現在的原因：
所有既有情境都餵真的那份 `13-規格做到哪了.md`，於是寫死的檔名一路綠。

## 這支測試不替實作決定的事

那份目標對照**放哪個檔名**是實作的選擇（票上列了甲、乙、丙三個方向）。
所以假專案把同一份內容放在兩個約定位置（`.nova/目標.md` 與 `docs/目標.md`），
認得其中任何一個都算綠；**兩個都不認**才是「還沒通用」。
格式則沿用 nova 那份現有的段落格式——這一格要修的是寫死的**路徑**，
不是順手改格式。

（走 `空手時落一張票` 而不從 CLI 進去：`命令列.py` 有另外兩條線正在改，
而空收件匣接到這個模組那一段已經被 `test_空手時挑下一個點.py` 釘住了。）
"""

from pathlib import Path

import pytest

from nova.載體.收件 import 待處理, 收件目錄, 缺哪幾欄, 要驗收嗎, 誰造的, 讀出驗收
from nova.載體.缺口成票 import 空手時落一張票

#: 假專案會把自己的目標對照放在這幾個位置（同一份內容）。
#: 實作認得任何一個都算通用；這支測試不替它決定是哪一個。
_目標對照候選位置 = (Path(".nova") / "目標.md", Path("docs") / "目標.md")

#: nova 專屬、不准出現在別人專案的票上的字串。
#: 出現就代表挑點這件事還綁在「這是 nova 自己」上面。
_nova專屬的字串 = ("13-規格做到哪了", "AGENT_ARCHITECTURE")

#: 假專案自己那份目標對照：一支記帳小工具，格式照 nova 現有的段落格式，
#: 內容跟 nova 一個字都不重疊——挑出來的點只可能來自這份文件。
_記帳小抄的目標對照 = """# 記帳小抄：規格做到哪了

對照的對象是 `需求/使用者故事.md`——外部規格原文，一個字都不准改。

## 對照表

| 規格哪一節 | 它要求什麼 | 記帳小抄現在 | 證據 |
|---|---|---|---|
| §1 | 匯入銀行 CSV，算得出每月總支出 | 有 | `記帳/彙總.py`；`test_每月總支出` |
| §2 | 多幣別的帳要先換算成台幣再加總 | 沒有 | — |
| §3 | 匯出報表成 PDF | 沒有 | — |

## 所以下一批該做什麼

挑一條：多幣別那條是報表那條的前提——加總本身是錯的時候，報表印得再漂亮也是錯的。

**一、§2 多幣別的帳換算成台幣再加總。**
`記帳/彙總.py` 現在把不同幣別的金額直接相加，總支出那個數字是錯的。
匯率表已經在 `資料/匯率.csv`，缺的是換算那一步與它的測試。

**二、§3 匯出報表成 PDF。**
排在第一條後面：加總正確之前印出來的報表沒有意義。
"""


@pytest.fixture
def 記帳小抄(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """一個不是 nova 的專案：幾個檔而已，沒有 `docs/設計/`，收件匣是空的。"""
    monkeypatch.setenv("XDG_STATE_HOME", str(tmp_path / "狀態"))
    專案 = tmp_path / "記帳小抄"
    (專案 / "記帳").mkdir(parents=True)
    (專案 / "README.md").write_text(
        "# 記帳小抄\n\n一支把銀行 CSV 算成月報的小工具。\n", encoding="utf-8"
    )
    (專案 / "記帳" / "彙總.py").write_text(
        "def 每月總支出(帳):\n    return sum(筆.金額 for 筆 in 帳)\n", encoding="utf-8"
    )
    for 位置 in _目標對照候選位置:
        (專案 / 位置).parent.mkdir(parents=True, exist_ok=True)
        (專案 / 位置).write_text(_記帳小抄的目標對照, encoding="utf-8")
    assert not (專案 / "docs" / "設計").exists(), "這個假專案必須不長得像 nova，不然測不到通用性"
    return 專案


def test_不是nova的專案也挑得到自己的下一個點(記帳小抄: Path) -> None:
    """換個工作目錄，挑點這個機制要照樣成立，而且挑的是**那個專案自己的**缺口。"""
    票 = 空手時落一張票(記帳小抄)

    assert 票 is not None, (
        "換一個專案就挑不到任何東西——挑點還綁在 nova 專屬的檔名上。"
        f"這個專案把目標對照放在 {[str(位置) for 位置 in _目標對照候選位置]}，兩個都沒被認"
    )
    assert 待處理(收件目錄(記帳小抄)) == [票], "票要落進這個專案自己的收件匣"

    內容 = 票.read_text(encoding="utf-8")
    assert "多幣別" in 內容, f"挑的要是這個專案文件自己挑出來的第一條，實際落出來的是：\n{內容}"
    for 字串 in _nova專屬的字串:
        assert 字串 not in 內容, f"別人專案的票上不准出現 nova 專屬的 `{字串}`：\n{內容}"

    出處們 = [位置 for 位置 in _目標對照候選位置 if "/".join(位置.parts) in 內容]
    assert 出處們, f"票上要指得回這個專案裡那份目標對照，來源才追得到外部文件：\n{內容}"
    assert (記帳小抄 / 出處們[0]).is_file(), "票上寫的出處要是這個專案裡真的存在的檔"

    assert 缺哪幾欄(內容) == (), f"別人專案的票一樣要四欄齊全，缺了：{缺哪幾欄(內容)}"
    assert 讀出驗收(內容), "自主來源的票沒帶機械驗收就等於沒有停止條件"
    assert 要驗收嗎(誰造的(票.name)), "這張票是 nova 自己生的，來源要記成自主來源"
