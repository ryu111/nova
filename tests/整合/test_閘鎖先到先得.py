"""排隊要有順序：**等最久的先拿到**。

## 這一支守什麼

`閘鎖._等到拿得到` 是非阻塞加固定間隔輪詢。鎖一放開，正在 `sleep` 的那幾條
誰先醒誰先拿——**醒的時機由各自的 sleep 相位決定，跟等了多久完全無關**。
於是等了 1:32:01 的可以一輪又一輪輸給等了 38:29 的，而沒有任何機制阻止它。

這裡守的是行為：三條依序進入排隊，持有者放手之後，**取得順序等於進場順序**。

## 為什麼進場順序是用事件排的、不是用 sleep 排的

這裡排順序的事件是**「已經抽到號碼牌」**，不是「子程序開始跑」。
序號在 `閘鎖._圈住發號` 裡面加一並寫回（`閘鎖._抽號碼牌`），所以序號檔的數字
往前跳一格，就等於「有一條真的入隊了」；父程序等到那一跳才放下一條進場。

到場檔只剩安全網的身分：它證明的是「這條子程序活著、正要去排隊」，
中間還隔著一次 import 與 `佔住` 的前置，**它出現的時候號碼牌還沒抽**。
拿它當順序閘門，量到的就不是抽號順序——那正是這一支在 CI 上偶爾亂序紅、
本地卻常綠的成因。多睡幾秒只會把機率壓小，握手點錯了就是錯了。

## 為什麼要跑三輪

現行實作正是**相位決定勝負**，單輪有三分之一的機率碰巧照順序出來，
那種綠證明不了任何事。三輪都要全對，碰巧的機率是 (1/6)^3。
等到排隊真的有順序之後，這三輪一律綠，不多不少。

住整合層是因為它真的 fork 子程序才測得出「跨程序排隊」。
"""

import fcntl
import subprocess
import sys
import textwrap
import time
from pathlib import Path

import pytest

from nova.載體.閘鎖 import _同一層的, _圈住發號, _排隊目錄, 佔住, 鎖檔路徑

#: 三個等待者的名字，**同時也是期望的取得順序**。
_等待者們 = ("甲", "乙", "丙")

#: 每個等待者進場前先睡多久。**刻意錯開輪詢相位**：三條的 `sleep` 節拍不一致，
#: 而這裡要證明的是**相位改不了勝負**——先抽到號碼牌的先拿到，跟它醒在哪個
#: 節拍上無關。這幾個數字都小於一個輪詢間隔，只用來打散節拍，不是勝負的桿。
_進場前先睡幾秒 = {"甲": 0.0, "乙": 0.07, "丙": 0.13}

#: 等一個事件（號碼發出去、檔案出現、子程序結束）最多等多久才判定測試自己壞了。
#: **這不是被測行為的一部分**，只是不讓測試整台掛住的安全網。
_事件上限秒 = 60.0


def _現在有哪幾張牌(落點: Path) -> list[str]:
    """排隊目錄裡現在躺著哪幾張牌。**只給錯誤訊息用**，不是握手的依據。"""
    try:
        return sorted(牌.name for 牌 in _排隊目錄(落點).iterdir())
    except OSError:
        return []


def _有人鎖著(牌檔: Path) -> bool:
    """這張號碼牌現在被別人 `flock` 住嗎。

    **只准在 `_圈住發號` 裡面呼叫**：拿不到鎖才代表牌有主人，而在發號鎖外面探，
    探的人會贏在等待者 `open` 與 `flock` 的空隙裡，把活著的等待者打死。
    """
    with 牌檔.open("a+") as handle:
        try:
            fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            return True
        fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
    return False


def _現在發到幾號(落點: Path) -> int | None:
    """序號檔現在寫著幾號；還沒建、空的、或讀到寫到一半就回 `None`。

    **`None` 不等於 0**：序號檔是被 `_圈住發號` 圈著寫回去的，讀到殘缺內容
    只代表「此刻正在發號」，把它當成 0 會讓握手秒過。
    """
    try:
        內容 = _同一層的(落點, "序號").read_text(encoding="utf-8").strip()
    except OSError:
        return None
    try:
        return int(內容)
    except ValueError:
        return None


def _等到號碼發到(落點: Path, *, 至少: int) -> int:
    """等到 `落點` 的序號檔至少發到 `至少` 號，回傳當下的號碼。

    這是這一組測試的握手點：序號在 `閘鎖._圈住發號` 裡面加一並寫回
    （`閘鎖._抽號碼牌`），所以「那個數字往前跳了」就等於「有人抽到號碼牌了」。
    `至少=0` 是純讀一次，用來取基準號。

    契約（寫的時候這幾條不准偷懶）：

    * 序號檔的路徑要跟實作算同一份：`閘鎖._同一層的(落點, "序號")`，
      不准在測試裡拼 `鎖目錄 / "閘.序號"`——那是抄第二份路徑規則，
      實作改了尾巴這裡會綠著壞掉。
    * 檔還沒建、內容是空字串、或讀到寫到一半的非整數，都要**重試**，不准當成 0。
    * 等超過 `_事件上限秒` 就 `pytest.fail`，訊息要印**現在發到幾號、在等幾號、
      排隊目錄裡現在有哪幾張牌**（`_現在有哪幾張牌`）——只印「timeout」的話，
      下次紅了還得回來加 print。
    """
    截止 = time.monotonic() + _事件上限秒
    while True:
        現在 = _現在發到幾號(落點)
        if 現在 is not None and 現在 >= 至少:
            return 現在
        if time.monotonic() > 截止:
            pytest.fail(
                f"等不到號碼發到 {至少} 號：現在發到 {現在}，排隊目錄裡是 {_現在有哪幾張牌(落點)}"
            )
        time.sleep(0.005)


def _等待者腳本(鎖目錄: Path, 到場檔: Path, 順序檔: Path, 名字: str) -> str:
    """一個等待者：報到 → 排隊 → 拿到鎖就把自己的名字寫進順序檔。

    順序檔的寫入本身被鎖圈住，所以它記的就是**取得鎖的先後**。
    """
    return textwrap.dedent(f"""
        import time
        from pathlib import Path
        from nova.載體.閘鎖 import 佔住

        time.sleep({_進場前先睡幾秒[名字]})
        Path({str(到場檔)!r}).write_text({名字!r}, encoding="utf-8")
        with 佔住("閘", 最多等幾秒=45, 鎖目錄=Path({str(鎖目錄)!r})):
            with Path({str(順序檔)!r}).open("a", encoding="utf-8") as 檔:
                檔.write({名字!r} + "\\n")
    """)


def _等到出現(檔: Path) -> None:
    """等到某個檔出現。**只是「子程序活著」的安全網，不是排序的依據**。

    到場檔是在 `佔住` 之前落的，它出現的時候號碼牌還沒抽；排順序一律用
    `_等到號碼發到`。留著它是因為等待者根本沒生出來時，這裡的訊息比
    「號碼沒往前跳」清楚得多。
    """
    截止 = time.monotonic() + _事件上限秒
    while not 檔.exists():
        if time.monotonic() > 截止:
            pytest.fail(f"等不到 {檔.name} 出現——等待者沒生出來，測試自己壞了")
        time.sleep(0.01)


def _跑一輪(工作目錄: Path) -> list[str]:
    """持有者佔著鎖，三條依序進場，放手之後回傳實際的取得順序。"""
    鎖目錄 = 工作目錄 / "鎖"
    落點 = 鎖檔路徑("閘", 鎖目錄)
    順序檔 = 工作目錄 / "取得順序.txt"
    程序們: list[subprocess.Popen[str]] = []
    with 佔住("閘", 鎖目錄=鎖目錄):
        # 父程序自己也抽了一張牌（沒給 `最多等幾秒`），接力要從它的號往後算。
        基準 = _等到號碼發到(落點, 至少=0)
        for 第幾個, 名字 in enumerate(_等待者們, start=1):
            到場檔 = 工作目錄 / f"到場-{名字}"
            程序們.append(
                subprocess.Popen(  # noqa: S603
                    [sys.executable, "-c", _等待者腳本(鎖目錄, 到場檔, 順序檔, 名字)],
                    text=True,
                )
            )
            _等到出現(到場檔)  # 安全網：這條真的生出來了
            # **順序閘門**：號碼往前跳了才算入隊，到場檔出現的時候還沒抽號。
            _等到號碼發到(落點, 至少=基準 + 第幾個)
    for 程序 in 程序們:
        assert 程序.wait(timeout=_事件上限秒) == 0, "等待者沒拿到鎖就死了"
    return 順序檔.read_text(encoding="utf-8").split()


@pytest.mark.serial
def test_等到入隊才放下一條進場(tmp_path: Path) -> None:
    """握手回來的時候，那一條已經**抽到號碼牌、而且把牌鎖住**了，不只是「活著」。

    握手點落在抽號之前的話，量到的順序就不是抽號順序，
    而這一組斷言的正是抽號順序決定的取得順序。
    """
    鎖目錄 = tmp_path / "鎖"
    落點 = 鎖檔路徑("閘", 鎖目錄)
    順序檔 = tmp_path / "取得順序.txt"
    到場檔 = tmp_path / "到場-甲"
    with 佔住("閘", 鎖目錄=鎖目錄):
        # 父程序自己也抽了一張牌（沒給 `最多等幾秒`），基準要從它之後算起。
        我的號 = _等到號碼發到(落點, 至少=0)
        程序 = subprocess.Popen(  # noqa: S603
            [sys.executable, "-c", _等待者腳本(鎖目錄, 到場檔, 順序檔, "甲")],
            text=True,
        )
        try:
            _等到出現(到場檔)  # 安全網：這條真的生出來了
            _等到號碼發到(落點, 至少=我的號 + 1)  # 順序閘門：它已經抽到號了
            # 探牌一律在發號鎖裡面，不然探的人會搶在等待者的 flock 前面把它打死。
            with _圈住發號(落點):
                牌們 = sorted(牌 for 牌 in _排隊目錄(落點).iterdir() if 牌.name.isdigit())
                新的 = [牌 for 牌 in 牌們 if int(牌.name) > 我的號]
                assert [牌.name for 牌 in 新的] == [f"{我的號 + 1:020d}"], (
                    f"握手回來卻沒有多一張牌：我的號是 {我的號}，"
                    f"排隊目錄裡是 {_現在有哪幾張牌(落點)}"
                )
                assert _有人鎖著(新的[0]), (
                    f"牌 {新的[0].name} 建了卻沒人鎖著——那條還沒真的入隊，"
                    "或者建牌之後那道 flock 根本沒下，它會被當成死人牌回收掉"
                )
        finally:
            程序.kill()
            程序.wait(timeout=_事件上限秒)


@pytest.mark.serial
@pytest.mark.parametrize("輪", [1, 2, 3])
def test_先進排隊的先拿到鎖(tmp_path: Path, 輪: int) -> None:
    """**先到先得**：先抽到號碼牌的先拿到鎖，跟各自的輪詢相位無關。"""
    實際 = _跑一輪(tmp_path / f"第{輪}輪")
    assert 實際 == list(_等待者們), f"排隊亂序：進場是 {list(_等待者們)}，拿到是 {實際}"
