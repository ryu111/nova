def _跑(*參數: str, 狀態: Path, 在: Path) -> subprocess.CompletedProcess[str]:
    """走真的 `nova`。

    **不能 `主程式([...])` 行程內叫**：那條路上有好幾格直接讀 `sys.argv`
    （`_派工該擋的理由`、`_背景起一條線`），pytest 的 argv 會讓它在第一道門
    就回 2，測到的是別的東西。
    """
    return subprocess.run(
        [str(nova執行檔), *參數],
        cwd=在,
        env={**os.environ, "XDG_STATE_HOME": str(狀態)},
        capture_output=True,
        text=True,
        check=False,
    )


def _唯一的(狀態: Path, 相對: str) -> Path:
    """這個專案的那一份（收件匣／狀態檔／成果帳）。專案目錄名帶雜湊，所以用 glob。"""
    return next((狀態 / "nova" / "專案").glob(f"*/{相對}"))


def _等著的(狀態: Path) -> list[Path]:
    """收件匣**根目錄**躺著的票：等重置的那張就在這裡，不在 `處理中/`。"""
    return sorted(路 for 路 in _唯一的(狀態, "收件").iterdir() if 路.is_file())


def _角色表(執行檔: Path) -> Mapping[階段代碼, object]:
    """四階共用同一顆假 claude。**第一步就撞牆**，所以其餘三階只是把表填滿。"""

    def 建腦(_: object) -> object:
        """哪一階、派法是什麼都不影響：這顆假 claude 一律吐那個 429 信封。"""
        return 建立("claude", 執行檔=執行檔)

    return {
        階段代碼(藍圖.識別碼): 建角色(
            藍圖,
            建腦=建腦,  # type: ignore[arg-type]
            組角色=固定提示角色,
        )
        for 藍圖 in 建TDD角色藍圖(怎麼派)
    }


def _執行器(執行檔: Path) -> object:
    def 跑判準(_: 任務) -> tuple[判準終局, str]:
        return 判準終局.綠, "這一支不會走到判準"

    return 建TDD執行器(
        角色表=_角色表(執行檔),  # type: ignore[arg-type]
        跑判準=跑判準,
        篩選指定測試=可作指定pytest目標,
    )


def _換掉那句話(原檔: Path, 落點: Path, 新的一句: str) -> Path:
    """拿同一個信封、只換 `result` 那句話——形狀一模一樣，只有時間讀不出來。"""
    信封 = json.loads(原檔.read_text(encoding="utf-8"))
    信封["result"] = 新的一句
    落點.write_text(json.dumps(信封, ensure_ascii=False), encoding="utf-8")
    return 落點


def test_假claude回429時工作流收成額度而不是中止且重置時戳正確(
    tmp_path: Path, 做假CLI: 做假CLI型
) -> None:
    """一句話：**那 218 秒不是「請求沒出門」**，所以收場不准是「東西壞了」。

    四個斷言各釘一格，缺一格這條路就漏：

    - `結束.代碼 is 結束代碼.額度`：今天是 `中止`（→ 退出碼 1 → 沒人接）。
    - `軌跡[-1].角色失敗代碼 is 失敗代碼.額度耗盡`：迴圈要拿**欄位**判，
      不准去比對證據字串裡那個 `[quota-exhausted]` 前綴（那是給人看的）。
    - `軌跡[-1].終局 is 終局.確定失敗`：終局表**沒有動**。改成「結果未知」
      會讓退出碼變 3、接續永遠不排，而且 `test_接力腦.py:270` 會紅。
    - `結束.不早於 == 重置的ISO`：時刻要**準**。差一小時的重置時戳比沒有更糟——
      早了就再撞一次、晚了就白等。
    """
    執行檔, _紀錄 = 做假CLI("claude", "claude_quota.txt")
    工地 = tmp_path / "工地"
    工地.mkdir()

    果 = 跑工作流(
        任務(描述="把某件事做完", 工作目錄=工地),
        執行一步=_執行器(執行檔),  # type: ignore[arg-type]
        起點=階段代碼.實作,
        現在=lambda: 撞到的時刻,
    )

    assert 果.結束.代碼 is 結束代碼.額度, (
        f"撞到上游額度被收成 {果.結束.代碼}——那條路的退出碼是 1，"
        f"外圈會當成「東西壞了、人來修」，然後沒有人來：{果.結束.原因}"
    )
    最後 = 果.軌跡[-1]
    assert 最後.角色失敗代碼 is 失敗代碼.額度耗盡, (
        "迴圈那一層看不到失敗代碼，所有確定失敗都被壓成同一種"
    )
    assert 最後.終局 is 終局.確定失敗, "終局表不准動：額度耗盡仍然是『確定沒做完』"
    assert 果.結束.不早於 == 重置的ISO, f"重置時戳不對：{果.結束.不早於}"


