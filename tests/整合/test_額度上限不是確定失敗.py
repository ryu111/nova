def test_額度那次在成果帳與線上不准冒充護欄(tmp_path: Path, 做假CLI: 做假CLI型) -> None:
    """額度沿用退出碼 4，但**不准因此被說成護欄**：分流看的是收場，不是那個碼。

    護欄是「nova 自己設的上限擋下來了，放寬與否是人的決定」——預算、步數、
    無進展、動了測試、重構改壞行為、驗收紅都是這一類，所以成果帳上才有
    `guardrail_reason` 那一格，`nova 線` 也把它印在「上一次怎麼收的」那一行。
    上游額度不屬於這一類：沒有上限可放寬，人沒有任何決定要下，
    要做的只有一件事——等到重置時間再從原階段接。

    所以這一輪的帳上，`guardrail_reason` 要是空的：那一格答的是
    「是哪一種護欄」，而這一輪根本沒有護欄，硬填一個字就是拿收場當原因用，
    下游任何一支「有 guardrail_reason 就是護欄」的判斷都會跟著說錯話。
    `outcome=quota` 已經把「是哪一種收場」說完了。

    人話那一行同理：15:29 打開 `nova 線`，要讀到「額度用完，等重置」——
    看得出這條線既不是壞了、也不必去看判準與測試；印成「護欄生效」
    會把人推去翻 nova 自己的上限設定，那裡沒有東西可調。
    分流因此得從成果的收場走，光看退出碼 4 分不出這兩件事。
    """
    狀態, 專案 = tmp_path / "state", tmp_path / "某個專案"
    專案.mkdir()
    執行檔, _紀錄 = 做假CLI("claude", "claude_quota.txt")

    跑完 = _跑(
        "跑",
        "把某件事做完",
        "--用",
        "claude",
        "--審查用",
        "codex",
        "--執行檔",
        str(執行檔),
        "--最多步數",
        "1",
        "--判準",
        "true",
        狀態=狀態,
        在=專案,
    )

    assert 跑完.returncode == 護欄碼, f"這一支要的是額度那條路：{跑完.stderr[-400:]}"
    帳 = json.loads(_唯一的(狀態, "已處理/*.json").read_text(encoding="utf-8"))
    assert 帳["outcome"] == 結束代碼.額度.value, f"前提：這一輪要收成額度：{帳}"
    assert 帳.get("guardrail_reason") != 護欄原因.驗收紅.value, (
        "撞到上游額度被歸檔成「驗收沒過」——這一輪一條驗收都沒跑過，"
        f"帳上卻叫人回去看判準與測試：{帳}"
    )
    assert 帳.get("guardrail_reason") is None, (
        "額度那一輪沒有護欄擋過任何東西，「是哪一種護欄」那一格就得留空——"
        "成果帳只落有值的鍵，所以「留空」就是這一格根本不出現；"
        f"填了字，下游「有 guardrail_reason 就是護欄」的判斷全都會跟著說錯：{帳}"
    )

    線 = _跑("線", 狀態=狀態, 在=專案)
    那一行 = next((行 for 行 in 線.stdout.splitlines() if "上一次怎麼收的" in 行), "")
    assert 那一行, f"`nova 線` 沒印出這條線上一次怎麼收的：\n{線.stdout}\n{線.stderr[-300:]}"
    assert "額度用完，等重置" in 那一行, (
        f"那一行要看得出「這條線是等重置，不是壞了、也不用改判準」：{那一行}"
    )
    assert "護欄" not in 那一行, (
        "印成護欄會把人推去翻 nova 自己的上限設定，而那裡沒有東西可調——"
        f"上游的窗時間到自己開：{那一行}"
    )


