def _角色表(執行檔: Path) -> Mapping[階段代碼, object]:
    """四階共用同一顆假 claude。**第一步就撞牆**，所以其餘三階只是把表填滿。"""

    def 建腦(_: object) -> object:
        """哪一階、派法是什麼都不影響：這顆假 claude 一律吐那個 429 信封。"""
        return 建立("claude", 執行檔=執行檔)

    return {
        階段代碼(藍圖.識別碼): 建角色(
            藍圖,
            建腦=建腦,  # type: ignore[arg-type]
            組角色=固定提示角色,
        )
        for 藍圖 in 建TDD角色藍圖(怎麼派)
    }


def _執行器(執行檔: Path) -> object:
    def 跑判準(_: 任務) -> tuple[判準終局, str]:
        return 判準終局.綠, "這一支不會走到判準"

    return 建TDD執行器(
        角色表=_角色表(執行檔),  # type: ignore[arg-type]
        跑判準=跑判準,
        篩選指定測試=可作指定pytest目標,
    )


def _換掉那句話(原檔: Path, 落點: Path, 新的一句: str) -> Path:
    """拿同一個信封、只換 `result` 那句話——形狀一模一樣，只有時間讀不出來。"""
    信封 = json.loads(原檔.read_text(encoding="utf-8"))
    信封["result"] = 新的一句
    落點.write_text(json.dumps(信封, ensure_ascii=False), encoding="utf-8")
    return 落點


def test_假claude回429時工作流收成額度而不是中止且重置時戳正確(
    tmp_path: Path, 做假CLI: 做假CLI型
) -> None:
    """一句話：**那 218 秒不是「請求沒出門」**，所以收場不准是「東西壞了」。

    四個斷言各釘一格，缺一格這條路就漏：

    - `結束.代碼 is 結束代碼.額度`：`中止` 那條路的退出碼是 1，外圈會當成
      「東西壞了、人來修」，然後沒有人來。
    - `軌跡[-1].角色失敗代碼 is 失敗代碼.額度耗盡`：迴圈要拿**欄位**判，
      不准去比對證據字串裡那個 `[quota-exhausted]` 前綴（那是給人看的顯示文字，
      拿它當介面等於把顯示格式凍住）。
    - `軌跡[-1].終局 is 終局.確定失敗`：終局表**沒有動**。改成「結果未知」
      會讓退出碼變 3、接續永遠不排，接力那條路的語意也跟著壞掉。
    - `結束.不早於 == 重置的ISO`：時刻要**準**。差一小時的重置時戳比沒有更糟——
      早了就再撞一次、晚了就白等。
    - `_工作流退出碼(...) == 護欄碼`：新的收場代碼要在退出碼表上**有一格**。
      `_收場的退出碼[收場.代碼]` 是裸的 dict 取值，缺這一格的話真撞到 429
      就是 KeyError 加 traceback——沒有成果帳，外圈什麼都看不到。
    """
    執行檔, _紀錄 = 做假CLI("claude", "claude_quota.txt")
    工地 = tmp_path / "工地"
    工地.mkdir()

    果 = 跑工作流(
        任務(描述="把某件事做完", 工作目錄=工地),
        執行一步=_執行器(執行檔),  # type: ignore[arg-type]
        起點=階段代碼.實作,
        現在=lambda: 撞到的時刻,
    )

    assert 果.結束.代碼 is 結束代碼.額度, (
        f"撞到上游額度被收成 {果.結束.代碼}——那條路的退出碼是 1，"
        f"外圈會當成「東西壞了、人來修」，然後沒有人來：{果.結束.原因}"
    )
    最後 = 果.軌跡[-1]
    assert 最後.角色失敗代碼 is 失敗代碼.額度耗盡, (
        "迴圈那一層看不到失敗代碼，所有確定失敗都被壓成同一種"
    )
    assert 最後.終局 is 終局.確定失敗, "終局表不准動：額度耗盡仍然是『確定沒做完』"
    assert 果.結束.不早於 == 重置的ISO, f"重置時戳不對：{果.結束.不早於}"
    碼 = _工作流退出碼(果.結束, 果.軌跡)
    assert 碼 == 護欄碼 == 4, (
        f"額度收場的退出碼是 {碼}——退出碼表少了這一格就會在裸 dict 取值那裡 KeyError"
    )


def test_讀不出重置時間仍然收成額度但不早於是空的(tmp_path: Path, 做假CLI: 做假CLI型) -> None:
    """`resets soon` 讀不出時刻——**那就不准猜**。

    猜一個（例如「加 5 小時」）的代價是不對稱的：猜早了就再撞一次、再燒一次錢，
    而且看起來像是自己好了；猜晚了那條線整晚躺著。讀不出來的正確行為是
    「照樣收成額度（不是壞了），但 `不早於` 是 None，留給人看一眼」。
    """
    實錄 = Path(__file__).resolve().parent / "實錄" / "claude_quota.txt"
    改過的 = _換掉那句話(
        實錄, tmp_path / "說不清楚幾點.txt", "You've hit your session limit · resets soon"
    )
    執行檔, _紀錄 = 做假CLI("claude", str(改過的))
    工地 = tmp_path / "工地"
    工地.mkdir()

    果 = 跑工作流(
        任務(描述="把某件事做完", 工作目錄=工地),
        執行一步=_執行器(執行檔),  # type: ignore[arg-type]
        起點=階段代碼.實作,
        現在=lambda: 撞到的時刻,
    )

    assert 果.結束.代碼 is 結束代碼.額度, "讀不出時間不代表它變成另一種失敗"
    assert 果.結束.不早於 is None, f"讀不出來就不准填：{果.結束.不早於}"


def _一步就回這個(答: 步驟結果) -> object:
    """一顆只會回同一個 `步驟結果` 的執行器：這一支要控的是**欄位**，不是模型。"""

    def 執行一步(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> 步驟結果:
        del 任, 軌跡
        return 步驟結果(
            階段=定義.代碼,
            終局=答.終局,
            判準綠=答.判準綠,
            證據=答.證據,
            角色失敗代碼=答.角色失敗代碼,
        )

    return 執行一步


def test_額度只認欄位不認證據字串裡的顯示前綴(tmp_path: Path) -> None:
    """判額度的介面是 `角色失敗代碼` 這一欄，`[quota-exhausted]` 只是給人看的字。

    真實錄那條路上兩者永遠同時出現，所以那一支背書不了「拿哪一個判」——
    改成比對字串照樣全綠。這一支把兩者拆開，兩個方向各鎖一邊：

    - **有欄位、證據裡沒有前綴**（人話換一種寫法、或前綴哪天改掉）：照樣是額度，
      而且時刻照樣從證據那句話讀得出來。比字串的話這裡會掉回中止。
    - **沒欄位、證據裡有前綴**（角色把上游的錯誤訊息原文抄進證據）：這是別種
      確定失敗，收場必須是中止（退出碼 1，人來修），不准因為字面像就當額度等重置
      ——真的等下去，那條線會躺到一個永遠不會好的東西上。
    """
    工地 = tmp_path / "工地"
    工地.mkdir()

    有欄位沒前綴 = 步驟結果(
        階段=階段代碼.實作,
        終局=終局.確定失敗,
        判準綠=None,
        證據="模型在第 218 秒停下：You've hit your session limit · resets 4:40pm (Asia/Taipei)",
        角色失敗代碼=失敗代碼.額度耗盡,
    )
    果 = 跑工作流(
        任務(描述="把某件事做完", 工作目錄=工地),
        執行一步=_一步就回這個(有欄位沒前綴),  # type: ignore[arg-type]
        起點=階段代碼.實作,
        現在=lambda: 撞到的時刻,
    )
    assert 果.結束.代碼 is 結束代碼.額度, (
        f"少了顯示前綴就分不出額度——判準吊在給人看的字串上：{果.結束.原因}"
    )
    assert 果.結束.不早於 == 重置的ISO, f"重置時戳不對：{果.結束.不早於}"

    有前綴沒欄位 = 步驟結果(
        階段=階段代碼.實作,
        終局=終局.確定失敗,
        判準綠=None,
        證據=(
            "[quota-exhausted] 這句是角色抄進證據的上游原文："
            "You've hit your session limit · resets 4:40pm (Asia/Taipei)"
        ),
        角色失敗代碼=失敗代碼.權限被擋,
    )
    別種失敗 = 跑工作流(
        任務(描述="把某件事做完", 工作目錄=工地),
        執行一步=_一步就回這個(有前綴沒欄位),  # type: ignore[arg-type]
        起點=階段代碼.實作,
        現在=lambda: 撞到的時刻,
    )
    assert 別種失敗.結束.代碼 is 結束代碼.中止, (
        f"證據裡有前綴就被當成額度——沙箱擋下來的東西會被排去等一個不會到的重置："
        f"{別種失敗.結束.原因}"
    )
    assert 別種失敗.結束.不早於 is None, f"不是額度就不准填時刻：{別種失敗.結束.不早於}"
    assert _工作流退出碼(別種失敗.結束, 別種失敗.軌跡) == 閘紅, "別種確定失敗仍該是「人來修」"
