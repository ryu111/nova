"""撞到上游額度上限**不是**「東西壞了」，所以不准收成中止（退出碼 1）。

2026-09-02 15:29 台北，四條線在同一分鐘內全部收在 `outcome=failed`、退出碼 1，
四本帳的 `text` 一字不差：`You've hit your session limit · resets 4:40pm (Asia/Taipei)`。
合計 $3.75、41 分鐘的模型時間，然後 **72 分鐘沒有任何機制會動**——主 agent 等到
16:40 之後才手敲四次接續。這一支守的就是那 72 分鐘那一格：

1. 額度是它自己那一類：**知道沒做完**（所以不是「結果未知」）、**沒有東西要修**
   （所以不是「確定失敗＝人來修」）、**沒有上限可放寬**（所以不是預算那種護欄）。
   它要的只有一件事：等到重置時間，同一階接著做。
2. 迴圈那一層要看得到兩樣機器讀得到的東西：`結束代碼.額度`，以及一個釘死的
   重置時戳（`結束.不早於`）。

**為什麼走真實錄不走假回應**：這條路的第一格是 claude CLI 那個信封
（`is_error: true` ＋ 那句話），從信封一路到 `結束代碼.額度` 中間有五層轉手
（解析 → 回應 → 步驟結果 → 迴圈 → 結束）。任何一層把失敗代碼降成顯示文字，
迴圈就再也分不出額度與其他確定失敗，所以不能從中間開始測。

**時刻靠注入不靠機器時鐘**：`跑工作流(現在=…)`。讀真時鐘的話這支測試
在每天 16:40 前後那一分鐘會自己翻面。

接續票怎麼排、收件匣的時間門、命令列怎麼呈現，都不在這一支的守備範圍。
"""

