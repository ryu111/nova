"""**排隊等了多久，外面要看得見。**

## 這一支守什麼

`docs/設計/14-閘慢在哪.md:78-100` 量過一輪：433.9 秒裡約 180 秒在排隊、
248 秒在做事。那個 180 秒是靠 `lsof` 一個鎖檔加 `ps` 手動推斷出來的——
**下一次沒有人會想到去 lsof 一個鎖檔**，於是「閘很慢」永遠分不出是
「檢查本身重」還是「機器上排了十二條」，而兩者的下一步完全相反
（前者要拆規則，後者要調額度）。

token 池把粒度改對之後更需要這個數字：改完排隊該消失，
而「消失了沒」只有量得到才證明得了。

## 三個出口，缺一個就等於沒有

| 出口 | 誰在看 | 這裡怎麼驗 |
|---|---|---|
| 判準證據 | 工作流的下一階（模型讀得到） | 證據開頭 `等鎖 N.N 秒` |
| 帳本 | 事後對帳、算比例 | `規則開始` 事件的 `lock_wait_ms` |
| 線的輸出 | 正在等的人 | `nova 閘` 的 stderr（**不在這一支**，見下） |

第三個出口住 `tests/整合/test_命令列.py` 那一側：它要的是真的 CLI，
而這一支刻意零個閘子程序。

## 沒等就不准出聲

每一格都配一個「沒等」的反例。少了它，實作可以無條件印 `等鎖 0.0 秒`
把三支都變綠——那樣的欄位只是雜訊，而雜訊會讓人學會忽略它，
連真的排了三分鐘那次也一起忽略。

住整合層是因為它動的是檔案系統上的真鎖、真的 fork 判準子程序。
"""

import json
import re
import sys
import threading
import time
from io import StringIO
from pathlib import Path

import pytest

from nova.契約.工作流 import 任務, 判準終局, 判準逾時證據標記
from nova.契約.檢查結果 import 檢查結果
from nova.載體.判準 import 建判準
from nova.載體.帳本 import 建帳本
from nova.載體.閘 import 規則, 跑閘
from nova.載體.閘鎖 import 佔住, 池大小

#: 把池子佔住多久才放。**這一段就是被測的量**：放手之後等待方拿到 token，
#: 它回報的毫秒數必須看得出這一段。輪詢間隔 0.2 秒，擋 0.6 秒＝三輪。
_擋住幾秒 = 0.6

#: 判定「真的有量到」的下限。比 `_擋住幾秒` 鬆一大截：量的是牆鐘，
#: 忙的機器只會讓它更久，不會更短。**寫死 0 或漏掉計時就到不了這裡。**
_至少等到幾秒 = 0.4

#: 等待方最多跑多久。**不是被測行為**，只是不讓測試在哪裡卡死都沒人知道。
_最多等幾秒 = 30.0

#: 逾時那一格用的子程序時限。要比 `_擋住幾秒` 短，才證明得了
#: 「排隊的時間沒有被算進判準自己的逾時」。
_逾時秒 = 0.5

#: 假裝的核心數。4 × `平行成數`(0.75) = 3 個 token——小池子好抽乾。
_假核心數 = 4

_等鎖開頭 = re.compile(r"^等鎖 (\d+(?:\.\d+)?) 秒")


@pytest.fixture
def 專屬狀態目錄(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """把鎖檔挪到這次測試的暫存目錄，別去碰真的機器鎖。"""
    monkeypatch.setenv("XDG_STATE_HOME", str(tmp_path / "狀態"))
    return tmp_path


def _等鎖幾秒(證據: str) -> float:
    """從證據開頭讀出「等了幾秒」。開頭沒這一段就當場說清楚缺了什麼。"""
    對到 = _等鎖開頭.match(證據)
    assert 對到 is not None, f"證據開頭沒有『等鎖 N.N 秒』，只有：{證據[:120]!r}"
    return float(對到.group(1))


def _擋住整池再放手(佔住整池: threading.Event) -> None:
    """把池子抽乾 `_擋住幾秒`，然後放手。**等待方就是在等這一段。**"""
    with 佔住("閘"):  # 不給 `要幾個token` ＝ 抽乾整池
        佔住整池.set()
        time.sleep(_擋住幾秒)


def test_判準等過鎖就要在證據裡說等了多久(專屬狀態目錄: Path) -> None:
    """**判準的證據是模型讀得到的那一份。**

    判準回綠只講「測試過了」的話，一輪跑了五分鐘裡有四分鐘在排隊這件事
    就沒有任何地方講得出來，而下一顆腦會拿「判準很慢」去改它跑的那條指令。
    """
    判準 = 建判準((sys.executable, "-c", "print('測試跑完了')"))
    佔住整池 = threading.Event()
    收場們: list[tuple[判準終局, str]] = []

    擋著的 = threading.Thread(target=_擋住整池再放手, args=(佔住整池,))
    擋著的.start()
    try:
        assert 佔住整池.wait(_最多等幾秒), "抽乾池子的那條線根本沒拿到 token"
        收場們.append(判準(任務(描述="量等鎖", 工作目錄=專屬狀態目錄)))
    finally:
        擋著的.join(timeout=_最多等幾秒)

    收場, 證據 = 收場們[0]
    assert 收場 is 判準終局.綠, f"判準該綠，收場是 {收場}：{證據}"
    assert _等鎖幾秒(證據) >= _至少等到幾秒, f"等了那麼久卻報成 {證據[:60]!r}"
    assert "測試跑完了" in 證據, f"冠上等鎖之後把判準原本的證據弄丟了：{證據!r}"


def test_判準沒等過就不准在證據裡出聲(專屬狀態目錄: Path) -> None:
    """**沒等就不要講。**

    無條件印 `等鎖 0.0 秒` 的話，欄位就變成雜訊，
    而雜訊會讓人學會忽略它——連真的排了三分鐘那一次也一起忽略。
    """
    判準 = 建判準((sys.executable, "-c", "print('測試跑完了')"))

    收場, 證據 = 判準(任務(描述="沒人跟我搶", 工作目錄=專屬狀態目錄))

    assert 收場 is 判準終局.綠, 證據
    assert "等鎖" not in 證據, f"沒有排隊卻報了等鎖：{證據!r}"


def test_排了隊又被逾時殺掉也要留得下等了多久(專屬狀態目錄: Path) -> None:
    """**「排了很久然後被殺」是最需要那個數字的一次。**

    只在成功那條路上冠等鎖的話，最貴的那種紅（排隊排到判準逾時）
    反而什麼都看不到，而它長得跟「測試自己卡死在死迴圈」一模一樣。

    順便釘住另一件事：**排隊不算進判準自己的逾時**——
    擋了 0.6 秒、逾時只有 0.5 秒，子程序仍要真的跑起來才被殺。
    """
    判準 = 建判準((sys.executable, "-c", "import time; time.sleep(30)"), 逾時秒=_逾時秒)
    佔住整池 = threading.Event()
    收場們: list[tuple[判準終局, str]] = []

    擋著的 = threading.Thread(target=_擋住整池再放手, args=(佔住整池,))
    擋著的.start()
    try:
        assert 佔住整池.wait(_最多等幾秒), "抽乾池子的那條線根本沒拿到 token"
        收場們.append(判準(任務(描述="排隊排到逾時", 工作目錄=專屬狀態目錄)))
    finally:
        擋著的.join(timeout=_最多等幾秒)

    收場, 證據 = 收場們[0]
    assert 收場 is 判準終局.紅, f"逾時要當紅處理，收場是 {收場}：{證據}"
    assert _等鎖幾秒(證據) >= _至少等到幾秒, f"排了隊才被殺，證據卻是 {證據[:60]!r}"
    assert 判準逾時證據標記 in 證據, f"冠上等鎖之後把逾時標記弄丟了：{證據!r}"


def _跑兩條規則(鎖目錄: Path, 串流: StringIO) -> list[檢查結果]:
    """一次 `跑閘`：第一條開跑時池子是空的（要排隊），第二條不必等。"""
    規則表 = [
        規則(
            代碼="先跑的",
            名稱="開跑時池子被抽乾了",
            閘點=frozenset({"提交"}),
            負責層="載體",
            檢查=lambda: (True, "先跑的跑完了"),
            要幾個token=1,
        ),
        規則(
            代碼="後跑的",
            名稱="輪到它的時候沒人跟它搶",
            閘點=frozenset({"提交"}),
            負責層="載體",
            檢查=lambda: (True, "後跑的跑完了"),
            要幾個token=1,
        ),
    ]
    return 跑閘(
        "提交",
        規則表,
        帳=建帳本(串流, 執行識別碼="測等鎖"),
        鎖目錄=鎖目錄,
        核心數=_假核心數,
    )


def _規則開始的事件們(串流: StringIO) -> dict[str, dict[str, object]]:
    """帳本落下來的 `規則開始` 事件，按規則代碼收。"""
    事件們 = [json.loads(行) for 行 in 串流.getvalue().splitlines() if 行.strip()]
    return {事件["rule"]: 事件 for 事件 in 事件們 if 事件.get("event") == "rule_started"}


def test_等鎖的毫秒數要落進帳本(tmp_path: Path) -> None:
    """**帳本是事後唯一算得出比例的地方。**

    「433.9 秒裡 180 秒在排隊」這種話要能從落盤的檔案算出來，
    不能每次都靠一個人在現場 `lsof`。鍵用 ASCII（`lock_wait_ms`）：
    這個檔會被 jq 讀，跟 `duration_ms` 同一條規矩。
    """
    佔住整池 = threading.Event()
    串流 = StringIO()

    def 抽乾再放手() -> None:
        with 佔住("閘", 要幾個token=池大小(核心數=_假核心數), 鎖目錄=tmp_path, 核心數=_假核心數):
            佔住整池.set()
            time.sleep(_擋住幾秒)

    擋著的 = threading.Thread(target=抽乾再放手)
    擋著的.start()
    try:
        assert 佔住整池.wait(_最多等幾秒), "抽乾池子的那條線根本沒拿到 token"
        _跑兩條規則(tmp_path, 串流)
    finally:
        擋著的.join(timeout=_最多等幾秒)

    開始們 = _規則開始的事件們(串流)
    assert set(開始們) == {"先跑的", "後跑的"}, f"兩條規則都要有開始事件：{開始們}"

    等了 = 開始們["先跑的"].get("lock_wait_ms")
    assert isinstance(等了, int), f"排了隊的那一條沒把等待落進帳本：{開始們['先跑的']}"
    assert 等了 >= _至少等到幾秒 * 1000, f"等了 {_擋住幾秒} 秒卻只記了 {等了} 毫秒"

    assert "lock_wait_ms" not in 開始們["後跑的"], (
        f"沒等的那一條不該落盤這個鍵（落 0 就分不出「沒等」跟「沒量」）：{開始們['後跑的']}"
    )


def test_等鎖的毫秒數要住在檢查結果上而且帳本讀的是同一個值(tmp_path: Path) -> None:
    """**等了多久是這條規則的判定的一部分，不是帳本的私房話。**

    現在 `跑閘` 量到毫秒之後只餵給帳本就丟掉，`檢查結果` 上沒有這一格。
    於是下游（CLI 要印給正在等的人看、收件票要寫進紅在哪）只剩兩條爛路：
    回頭去 parse 帳本檔，或去 parse 證據字串——兩條都是在重建上游已經算好的東西，
    而重建出來的第二個來源遲早會跟第一個對不上（規格 §4.3：邊承載結構化證據）。

    **等號不是 ≥**：帳本那格與結果物件那格必須是同一個 int，
    差一毫秒就代表有人在第二個地方又量了一次。
    """
    佔住整池 = threading.Event()
    串流 = StringIO()

    def 抽乾再放手() -> None:
        with 佔住("閘", 要幾個token=池大小(核心數=_假核心數), 鎖目錄=tmp_path, 核心數=_假核心數):
            佔住整池.set()
            time.sleep(_擋住幾秒)

    擋著的 = threading.Thread(target=抽乾再放手)
    擋著的.start()
    try:
        assert 佔住整池.wait(_最多等幾秒), "抽乾池子的那條線根本沒拿到 token"
        結果表 = _跑兩條規則(tmp_path, 串流)
    finally:
        擋著的.join(timeout=_最多等幾秒)

    assert [結果.代碼 for 結果 in 結果表] == ["先跑的", "後跑的"], f"跑出來的是 {結果表}"

    排過隊的 = 結果表[0]
    assert 排過隊的.等待毫秒 >= _至少等到幾秒 * 1000, (
        f"開跑前排了 {_擋住幾秒} 秒，結果物件上卻是 {排過隊的.等待毫秒} 毫秒"
    )
    assert 結果表[1].等待毫秒 == 0, (
        f"沒排隊的那一條要誠實回 0（結果型別裡 0 就是沒等）：{結果表[1].等待毫秒}"
    )

    落盤的 = _規則開始的事件們(串流)["先跑的"]["lock_wait_ms"]
    assert 落盤的 == 排過隊的.等待毫秒, (
        f"帳本記 {落盤的}、結果物件記 {排過隊的.等待毫秒}——"
        "兩個數字要從同一個變數出去，不然遲早對不上"
    )
