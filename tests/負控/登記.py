#: **錨點從模組切出來，不寫死。**
#:
#: 寫死的話每改一次提示就要回來補三個字串，而且 `替換一次` 要求錨點恰好出現一次
#: ——四個角色共用同一段讀取策略，寫死的短錨點會撞到 4 次。
#: 切片保證跟著實作走：測試員專屬的尾巴（含「測試放在 tests/ 底下」）天然唯一。
