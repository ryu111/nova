"""守「本線 diff 動過的那幾把刀，線內就跑得到」的三把固定負控刀。

三把各守一格，對應本票的三支指名測試：
新增而還沒 `git add` 的登記檔算不算本線動過、選不到刀是不是 fail-closed 的紅、
以及那一步有沒有真的掛在判準的最後。
"""

from pathlib import Path

from tests.負控.登記 import 刪除一次, 替換一次, 變異

_專案根 = Path(__file__).resolve().parents[3]

#: **錨點從原始碼切出來，不整段寫死。** 那一步有兩行註解，寫死的話註解改一個字
#: 就會「錨點出現 0 次」當場炸，而那不是行為壞掉。切片跟著實作走。
_判準原始碼 = (_專案根 / "src/nova/載體/判準.py").read_text(encoding="utf-8")
_本線那步起 = _判準原始碼[_判準原始碼.index('        判準步驟(\n            名稱="本線負控",') :]
_本線那步 = _本線那步起[: _本線那步起.index("        ),\n") + len("        ),\n")]

#: 問「新增但還沒 `git add` 的檔」的那一段。**同樣切片，不寫死參數怎麼排。**
#: 寫死的話，那個呼叫換一種寫法（例如參數從一行排成兩行）就「錨點出現 0 次」當場
#: `RUN_ERROR`——而那不是行為壞掉，是刀自己過期了。
_規則表原始碼 = (_專案根 / "src/nova/載體/規則表.py").read_text(encoding="utf-8")
_未追蹤那段起 = _規則表原始碼[_規則表原始碼.index("    新增還沒add的 = ") :]
_未追蹤那一段 = _未追蹤那段起[: _未追蹤那段起.index("\n    )\n") + len("\n    )\n")]

#: 換成空清單，不是整段刪掉：刪掉的話那個名字沒定義，紅在 `NameError` 而不是
#: 「新檔沒被算進來」。要驗的是後者。
_不問未追蹤的檔 = "    新增還沒add的 = ()\n"

_新增檔也算 = "tests/整合/test_本線負控吃得到新增檔.py::test_還沒add的新登記檔也算本線動過"
_選不到不是綠 = "tests/單元/test_本線負控篩選.py::test_只選這幾個登記檔的刀_選不到就不是綠"
_接在最後一步 = (
    "tests/單元/test_判準別跑變異刀.py::Test本線負控接在最後一步::test_預設判準最後一步是nova閘本線"
)

登記 = (
    #: 只問 `git diff` 的話，**新增一把刀**（最常見的情形）選到 0 把、一路綠到 CI。
    變異(
        識別="本線動過的檔漏掉還沒add的新登記檔",
        目標檔=Path("src/nova/載體/規則表.py"),
        操作=替換一次(_未追蹤那一段, _不問未追蹤的檔),
        該紅=(_新增檔也算,),
        最多秒=60.0,
    ),
    #: 動過的檔非空卻一把都選不到＝打錯字或 deselect 壞掉，那是假綠不是綠。
    變異(
        識別="選不到刀還當綠",
        目標檔=Path("src/nova/載體/本線負控.py"),
        操作=替換一次(
            'return False, f"[本線負控] 這幾個登記檔一把刀都選不到（是假綠不是綠）：{檔名單}"',
            'return True, f"[本線負控] 這幾個登記檔一把刀都選不到（是假綠不是綠）：{檔名單}"',
        ),
        該紅=(_選不到不是綠,),
        最多秒=20.0,
    ),
    #: 步驟掉了就回到「刀只有 CI 跑得到」，而症狀是判準變快變綠。
    變異(
        識別="判準拿掉本線負控那一步",
        目標檔=Path("src/nova/載體/判準.py"),
        操作=刪除一次(_本線那步),
        該紅=(_接在最後一步,),
        最多秒=20.0,
    ),
)
