"""守「派工儀表板的每個數字只有一個來源」的那五把刀。

儀表板最危險的失效不是壞掉，是**看起來對**：一個算不出來的成本被畫成 0、
或一格從契約上消失而模板照樣渲染出空白，人會照著那個數字做決定。
所以這幾把刀都對準「安靜地變成 0／不見／憑空長出來」這條路徑，
而且**契約、資料、模板三層都有**——只砍前兩層的話，
模板自己補一個數字上去那條路徑完全沒人守。

模板那三把裡有兩把砍的是**版面**而不是數字：重複列少一欄（表還在、
列數還對，只有那一欄不見了）、body 自己發明一批 CSS 沒定義過的 class
（樣式逐字抄自設計稿，畫面卻是另一份）。兩種都不會有人在畫面上發現。

**這幾把刀的錨點是給實作的約定**（登記先寫，實作後到）：

* `契約/儀表板.py` 的 `儀表板` 上要有一格 `算不出成本的執行數: int`
  ——跳過的執行數要數得出來，不是註解裡的一句話。
* `載體/儀表板/資料.py` 判斷「這本帳算不算得出成本」要寫成
  `<摘要>.總成本美金 is None`（全檔恰好一次）——那是唯一該分岔的地方，
  兩處分岔就會有一處先腐爛。
* `載體/儀表板/模板.html` 裡「今日合併」這四個字**恰好出現一次**，
  就在那個未接線的格子上。出現兩次的話這把刀連套都套不上去。
* 同一個檔裡各家用量那一列有一欄是 `${供應商}`，而 `<style>` 那段
  以 `</style>` 收尾——兩個都是 `tests/單元/test_儀表板模板.py` 已經釘住的形狀。
"""

