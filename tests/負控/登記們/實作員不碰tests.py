"""守實作員規矩裡「`tests/` 底下任何檔」那個路徑判準不被刪回「不准改斷言」。"""

import re
from pathlib import Path

from tests.負控.登記 import 替換一次, 變異

_角色提示檔 = Path("src/nova/迴圈/角色提示.py")

#: **錨點從模組切出來，不寫死**（同 `登記.py` 的作法）：提示每潤一次措辭就要回來補
#: 字串的話，這把刀很快就會因為錨點找不到而爛掉。切 `_實作員規矩` 那整段字面量，
#: 它在檔裡天然唯一，而 `tests/` 這個子字串在別的段落（例如首輪讀取策略的
#: `tests/單元`）也有，直接拿短錨點會撞到多次。
_原始碼 = (Path(__file__).resolve().parents[3] / _角色提示檔).read_text(encoding="utf-8")
_實作員規矩段 = _原始碼[_原始碼.index("_實作員規矩 = ") : _原始碼.index("_實作員收尾 = ")]

#: 破壞什麼：**只**把「`tests/` 底下任何檔」這個帶量詞的機械定義換成含糊的「測試檔」，
#: 一句話都不多動——禁令、四種被踩過的資產、交棒格式全部留著。
#:
#: 為什麼不整段把 `tests/` 換掉：那樣連交棒格式的 `<tests/ 底下的路徑>` 也一起沒了，
#: 於是「全文有沒有 `tests/`」這種漏勺哨兵也會紅，這把刀就證明不了哨兵真的守著定義。
#: 這裡刻意把其餘的 `tests/` 留在原地，紅只能來自量詞那句不見了。
_定義 = re.compile(r"`?tests/`?\s*底下[^\n]{0,4}(?:任何|每一個|每個|所有)[^\n]{0,4}檔")
_拔掉路徑判準後 = _定義.sub("測試檔", _實作員規矩段)

assert _拔掉路徑判準後 != _實作員規矩段, "機械定義在 `_實作員規矩` 裡找不到，這把刀已經爛掉"
assert "tests/" in _拔掉路徑判準後, (
    "變異後 `_實作員規矩` 裡一個 `tests/` 都不剩，這把刀會連漏勺哨兵一起弄紅、失去鑑別力"
)

_拔掉路徑判準 = 替換一次(_實作員規矩段, _拔掉路徑判準後)

_該紅 = (
    (
        "tests/單元/test_角色提示.py::Test實作員知道tests底下都不准碰"
        "::test_規矩用tests底下的路徑當判準而不是斷言"
    ),
)


登記 = (
    變異(
        識別="角色提示刪掉實作員規矩裡的tests底下路徑判準",
        目標檔=_角色提示檔,
        操作=_拔掉路徑判準,
        該紅=_該紅,
        最多秒=5.0,
    ),
)
