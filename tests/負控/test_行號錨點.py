"""行號錨點推導的回歸測試。"""

from pathlib import Path

import pytest

from . import 執行器
from .登記 import 替換一次, 變異

專案根目錄 = Path(__file__).resolve().parents[2]


def test_跨行錨點的每個可執行行都被推導() -> None:
    操作 = 替換一次(
        "@property\n"
        "    def 結果(self) -> 結果代碼:\n"
        '        """回傳結果未知終局。"""\n'
        "        return 結果代碼.結果未知\n",
        "",
    )
    一筆 = 變異(
        識別="跨行推導",
        目標檔=Path("src/nova/契約/節點.py"),
        操作=操作,
        該紅=(),
        最多秒=1.0,
    )

    推導的行 = 執行器._推導破壞行(專案根目錄 / 一筆.目標檔, 一筆)

    assert len(推導的行) == 3


def test_字串常數內容推導不到執行行時回空集合() -> None:
    """**多行字串的內容不是 executable 行，coverage 追不到。**

    角色提示、說明文字這類保證住在模組層的字串常數裡，破壞它的錨點必然落在
    字串內容中間。原本一律 `RUN_ERROR：操作沒有可推導的 executable 行`，
    等於整類保證都不准登記——而 nova 治本靠的正是角色提示那幾段話。

    回空集合是「這一刀沒有可追的覆蓋行，固定測試直接驗值」的標記，
    跟 `必須覆蓋=frozenset()` 同一個語意。**只在模組層單一名稱的賦值時成立**，
    否則打歪的錨點會被靜默放行。
    """
    # **錨點從原始碼切出來，不寫死**——寫死的話每改一次提示這支就會紅，
    # 而它要測的是「字串常數推導不到執行行」這個機制，不是提示的內容。
    原始碼 = (專案根目錄 / "src/nova/迴圈/角色提示.py").read_text(encoding="utf-8")
    測試員段 = 原始碼[原始碼.index("測試員 = ") : 原始碼.index("實作員 = ")]
    起 = 測試員段.index("讀取策略：")
    迄 = 測試員段.rindex("底下。") + len("底下。")
    操作 = 替換一次(
        測試員段[起:迄], "專案規矩：繁體中文命名與註解，不准簡體字。測試放在 tests/ 底下。"
    )
    一筆 = 變異(
        識別="字串常數內容",
        目標檔=Path("src/nova/迴圈/角色提示.py"),
        操作=操作,
        該紅=(),
        最多秒=1.0,
    )

    assert 執行器._推導破壞行(專案根目錄 / 一筆.目標檔, 一筆) == frozenset()


def test_推導不到執行行又不是模組層常數就要炸() -> None:
    """空集合是**標記**不是後備。函式內部推導不到行代表錨點打歪了，要當場紅。

    少了這一格，打歪的錨點會拿到「不要求覆蓋」的待遇——刀看起來 KILLED，
    其實根本沒破壞到被測的東西。
    """
    操作 = 替換一次("這串字在檔案裡根本不存在所以會先炸在別的地方", "")
    一筆 = 變異(
        識別="打歪的錨點",
        目標檔=Path("src/nova/迴圈/角色提示.py"),
        操作=操作,
        該紅=(),
        最多秒=1.0,
    )

    with pytest.raises(執行器.負控錯誤, match="錨點應恰好一次"):
        執行器._推導破壞行(專案根目錄 / 一筆.目標檔, 一筆)
