"""`tests/負控/登記們/` 的動態收集規格。

新增一把負控刀只該加一個檔，不必回頭改 `登記.py`——否則並行的線全被那一個
檔尾的 append 序列化掉。這裡釘住收集的四件事：收得到、識別不重複、順序穩定、
沒有 `登記們/` 也不炸。
"""

from __future__ import annotations

import importlib
from pathlib import Path

import pytest

from . import 登記 as 登記模組

負控目錄 = Path(__file__).resolve().parent
登記們目錄 = 負控目錄 / "登記們"

#: **這裡刻意沒有「凍住的筆數」那種寫死的數字。**
#:
#: 第一版有，而且它在並行環境下本質上測不穩：這條線開跑時 `登記.py` 是 105 筆，
#: 跑的期間 #180、#181、#182 陸續合併，各自往檔尾 append 自己的刀，
#: 於是每 rebase 一次就要回來改一次基準（實測改了兩次：105 → 114 → 116）。
#:
#: 那個數字測的是「這個 worktree 開跑時的快照」，而快照不是需求。
#: 需求只有兩條，兩條都跟絕對筆數無關：
#: **搬過去的不要留兩份**（重複識別檢查已經在收集當下擋著），
#: **收集有生效**（本檔的 + `登記們/` 的 = 全部）。

#: 「收尾跑驗收」那一批，被搬去 `登記們/驗收.py` 當樣本。
驗收那四把 = (
    "驗收指令走shell",
    "驗收第一條紅了還繼續跑",
    "驗收只看最後一條",
    "驗收從整份內容讀含模型寫的前情",
)


def _寫臨時登記模組(目錄: Path, 檔名: str, *識別們: str) -> Path:
    """在 `目錄` 底下產一個合法的登記模組，內含指定識別的變異。"""
    行: list[str] = [
        '"""測試用的臨時登記模組。"""',
        "",
        "from pathlib import Path",
        "",
        "from tests.負控.登記 import 替換一次, 變異",
        "",
        "登記 = (",
    ]
    for 識別 in 識別們:
        行 += [
            "    變異(",
            f'        識別="{識別}",',
            '        目標檔=Path("src/nova/契約/派工.py"),',
            '        操作=替換一次("思考深度: str", \'思考深度: str = "high"\'),',
            '        該紅=("tests/單元/test_派工表.py::test_派法必須明確指定思考深度",),',
            "        最多秒=2.0,",
            "    ),",
        ]
    行 += [")", ""]
    檔 = 目錄 / 檔名
    檔.write_text("\n".join(行), encoding="utf-8")
    return 檔


@pytest.mark.serial
def test_登記們底下的新模組會出現在登記裡() -> None:
    """收集要 fail-closed：放進去的模組沒被收到，這支就要紅。

    只有這一支非動真的 `登記們/` 不可——要證明 `登記` 本身接上了收集，
    不是只有 `_收集` 這個函式會動。因為會增刪共用目錄又重載模組，標 serial，
    不跟 xdist 的其他 worker 搶同一份檔案系統。
    """
    登記們目錄.mkdir(exist_ok=True)
    臨時檔 = _寫臨時登記模組(登記們目錄, "零_臨時收集探針.py", "臨時收集探針")
    try:
        重載後 = importlib.reload(登記模組)
        識別們 = [一筆.識別 for 一筆 in 重載後.登記]
        assert "臨時收集探針" in 識別們, (
            f"登記們/{臨時檔.name} 有登記卻沒被收進 登記；漏收不報錯就是假綠"
        )
    finally:
        臨時檔.unlink()
        importlib.reload(登記模組)


def test_模組沒有登記屬性要當場報錯(tmp_path: Path) -> None:
    """`登記們/` 裡放了 `.py` 卻沒有 `登記`，要當場炸，不准安靜跳過。"""
    (tmp_path / "零_臨時空模組.py").write_text('"""沒有登記的模組。"""\n', encoding="utf-8")

    with pytest.raises(ValueError, match="零_臨時空模組"):
        登記模組._收集(tmp_path)


def test_識別重複要在收集當下就報錯(tmp_path: Path) -> None:
    """兩個檔登記同名的刀，執行器分不出來，所以要在收集時就擋。"""
    _寫臨時登記模組(tmp_path, "甲.py", "重複的刀")
    _寫臨時登記模組(tmp_path, "乙.py", "只有這裡有的刀", "重複的刀")

    with pytest.raises(ValueError, match="重複的刀"):
        登記模組._收集(tmp_path)


def test_收集順序按檔名再按檔內順序(tmp_path: Path) -> None:
    """順序不穩定的話，兩次執行印出來不一樣，沒辦法比對。"""
    _寫臨時登記模組(tmp_path, "甲.py", "甲一")
    _寫臨時登記模組(tmp_path, "乙.py", "乙一", "乙二")
    _寫臨時登記模組(tmp_path, "丙.py", "丙一")

    識別們 = [一筆.識別 for 一筆 in 登記模組._收集(tmp_path)]

    #: 檔名按碼位排序：丙 U+4E19 < 乙 U+4E59 < 甲 U+7532。
    assert 識別們 == ["丙一", "乙一", "乙二", "甲一"]
    assert [一筆.識別 for 一筆 in 登記模組._收集(tmp_path)] == 識別們


def test_登記們為空或不存在時只剩本檔的登記(tmp_path: Path) -> None:
    """沒有 `登記們/` 也要能跑，登記就等於 `登記.py` 自己那一批。"""
    assert 登記模組._收集(tmp_path) == ()
    assert 登記模組._收集(tmp_path / "根本沒這個目錄") == ()

    本檔的 = 登記模組._這個檔裡的
    assert 登記模組.登記[: len(本檔的)] == 本檔的


def test_驗收那四把已經搬到登記們而且沒留兩份() -> None:
    """搬一筆過去當樣本：兩邊都跑得動，而且舊的那份要真的搬走。

    **不比對絕對筆數**（理由見檔頭）。比的是關係：
    搬過去那四把不准還留在 `登記.py`，而全部 = 本檔的 + `登記們/` 的。
    """
    樣本檔 = 登記們目錄 / "驗收.py"
    assert 樣本檔.exists(), "應把收尾跑驗收那四把搬到 tests/負控/登記們/驗收.py"

    樣本的 = 登記模組._載入登記模組(樣本檔)
    assert {一筆.識別 for 一筆 in 樣本的} == set(驗收那四把), (
        "登記們/驗收.py 應恰好是搬過去的那四把"
    )

    本檔的識別 = {一筆.識別 for 一筆 in 登記模組._這個檔裡的}
    留了兩份的 = 本檔的識別 & set(驗收那四把)
    assert not 留了兩份的, f"這幾把同時留在 登記.py 與 登記們/：{sorted(留了兩份的)}"

    收集到的 = 登記模組._收集(登記們目錄)
    assert len(登記模組.登記) == len(登記模組._這個檔裡的) + len(收集到的), (
        "全部應等於「本檔的 + 登記們/ 的」——對不上代表收集漏了或重了"
    )


def test_package標記不算登記模組(tmp_path: Path) -> None:
    """`__init__.py` 是 python 的 package 標記，不是登記模組。

    **不排除的話收集會當場炸**：它沒有 `登記` 屬性，而「沒有 `登記` 就報錯」
    是這個機制刻意要有的 fail-closed——那條規則沒錯，錯的是把標記也當模組。

    實測 2026-08-31：別條線為了自己匯流建了 `登記們/__init__.py`，
    收集當場報 `登記們/__init__.py 沒有 登記；漏收不報錯就是假綠`。
    """
    (tmp_path / "__init__.py").write_text("", encoding="utf-8")
    (tmp_path / "甲.py").write_text(
        "from tests.負控.登記 import 變異, 替換一次\n"
        "from pathlib import Path\n"
        "登記 = (變異(識別='甲', 目標檔=Path('x'), "
        "操作=替換一次('a', 'b'), 該紅=('t',), 最多秒=1.0),)\n",
        encoding="utf-8",
    )
    收到 = 登記模組._收集(tmp_path)
    assert [一筆.識別 for 一筆 in 收到] == ["甲"]
