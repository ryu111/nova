_實作員規矩 = """你是 nova 工作流裡的實作員。上一步已經有一支紅的測試了。

規矩：
1. 用**最少**的程式碼讓那支測試變綠。這一步允許寫得醜。
2. **不准改測試。** 測試紅了先假設是實作的問題。
3. 不做沒被要求的抽象：一個實作不寫 interface，不會變的值不寫 config。
4. 既有測試斷言舊行為時不要改它，回報「需要測試員改寫：<檔:函式>」清單。
5. 只改票的範圍；順路看到的問題寫進回報，不要修。
6. 改了行為就同步改掉講舊語意的名字、註解、docstring。
7. 回覆時說明你改了哪些檔案。"""

_實作員收尾 = "專案規矩：繁體中文命名與註解，不准簡體字。"


#: 實作員的**身分**：本業規矩，不含這一輪的讀取策略。
#:
#: 系統提示一次建好、每輪不變（`角色藍圖.系統提示`），而讀取策略是 per-round 的：
#: 首輪禁跑全測試，被退回的那一輪反過來要它跑。所以那一段不住在這裡，
#: 由 `工作流._提示` 每輪接在使用者提示上（`這一輪的讀取策略`）。
def _組合實作員提示(*中間段落: str) -> str:
    """把實作員固定規矩、每輪段落與收尾組成完整提示。"""
    return "\n\n".join((_實作員規矩, *中間段落, _實作員收尾))


實作員身分 = _組合實作員提示()


#: 首輪實作員看到的全文（身分 ＋ 首輪讀取策略）。**production 的系統提示是
#: `實作員身分`**：那一段每輪不變，讀取策略才是每輪重接的。這個常數是兩段合起來
#: 的樣子，留給提示測試比對。
實作員 = _組合實作員提示(_首輪讀取策略)


def 這一輪的讀取策略(*, 被退回: bool) -> str:
    """這一輪的讀取策略。

    `被退回` 由呼叫端從軌跡算出來（`工作流._看階段才帶的段落`）：上一步是回頭邊
    （`狀態機.是回頭邊`），或這一輪落在審查退回循環裡（`工作流._在審查退回循環裡`）。
    兩者都是結構算出來的，不是提示自己猜的。
    """
    return _退回輪讀取策略 if 被退回 else _首輪讀取策略


def 實作員提示(*, 被退回: bool, 上一階證據: str) -> str:
    """實作員這一輪看到的全文（身分 ＋ 上一階的紅 ＋ 這一輪的讀取策略）。

    真正送出去的那份由 `工作流._提示` ＋ `組提示` 組成，**段落不保證逐字相等**：
    退回循環裡那一輪還會多帶最近一次審查全文（`工作流._上次審查與其後回報`），
    那段要看整條軌跡，這裡看不到。這支只保證身分與讀取策略這兩段一致。
    """
    中間段落: list[str] = []
    if 被退回:
        中間段落.append(f"上一階的紅（你要修的就是這個）：\n{上一階證據}")
    中間段落.append(這一輪的讀取策略(被退回=被退回))
    return _組合實作員提示(*中間段落)


