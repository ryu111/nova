"""用 immutable blueprint 組出固定提示角色。

**兩個相依都是參數，不是 import**（依賴反轉）：這裡只需要「這種工作該怎麼派」
與「怎麼組一個固定提示角色」兩個動作，不需要知道派工表住哪個檔、
角色是哪個 dataclass。由呼叫端（組裝點）把它們傳進來。
"""

from collections.abc import Callable, Mapping
from dataclasses import dataclass
from types import MappingProxyType
from typing import Protocol

from nova.契約.工作流 import 階段代碼
from nova.契約.派工 import 工作種類, 派法
from nova.契約.角色 import 權限, 角色, 語言模型, 預設逾時秒
from nova.迴圈 import 角色提示

#: TDD 一階可能跑完整套測試再收尾；一小時是有限且比單次問話長的上限。
TDD階段預設逾時秒 = 3600.0


@dataclass(frozen=True, slots=True)
class 角色藍圖:
    """一個工作流角色的不可變組合資料。"""

    識別碼: str
    名稱: str
    什麼時候派我: str
    系統提示: str
    派法: 派法
    權限: 權限
    逾時秒: float
    模型: str | None = None
    #: `None` ＝ 用那一家的預設。走派工表時由 `派法.思考深度` 填；
    #: `--用` 指名一家時刻意留 `None`——指名的人沒說深度，就不要替他決定。
    思考深度: str | None = None


type 建腦 = Callable[[派法], 語言模型]
#: 這種工作該怎麼派。形狀由這裡宣告，派工表（載體）去符合。
type 派法查詢 = Callable[[工作種類], 派法]


class 組角色器(Protocol):
    """怎麼組一個固定提示角色。同上：組出來的是不是 dataclass，這裡不需要知道。

    形狀寫全（每個關鍵字參數都列出來），不用 `Callable[..., 角色]`：
    `...` 等於不檢查，傳錯參數要等到執行期才知道。
    """

    def __call__(  # noqa: PLR0913 —— 形狀就是角色的欄位，列全比 `...` 誠實
        self,
        *,
        名稱: str,
        系統提示: str,
        腦: 語言模型,
        模型: str | None,
        思考深度: str | None,
        逾時秒: float,
        權限: 權限,
        什麼時候派我: str,
    ) -> 角色:
        """組出一個角色。"""
        ...


def 建角色(藍圖: 角色藍圖, *, 建腦: 建腦, 組角色: 組角色器) -> 角色:
    """依藍圖建立一個固定提示角色。"""
    return 組角色(
        名稱=藍圖.名稱,
        系統提示=藍圖.系統提示,
        腦=建腦(藍圖.派法),
        模型=藍圖.模型,
        思考深度=藍圖.思考深度,
        逾時秒=藍圖.逾時秒,
        權限=藍圖.權限,
        什麼時候派我=藍圖.什麼時候派我,
    )


def 建角色表(
    藍圖們: tuple[角色藍圖, ...],
    *,
    建腦: 建腦,
    組角色: 組角色器,
) -> Mapping[str, 角色]:
    """把一組角色藍圖組成不可變的識別碼對角色表。"""
    角色表 = {藍圖.識別碼: 建角色(藍圖, 建腦=建腦, 組角色=組角色) for 藍圖 in 藍圖們}
    return MappingProxyType(角色表)


def 建TDD角色藍圖(怎麼派: 派法查詢) -> tuple[角色藍圖, ...]:
    """TDD 四階的藍圖。派工策略是參數，這裡只說每一階算哪一種工作。"""
    return (
        角色藍圖(
            識別碼=階段代碼.測試.value,
            名稱="測試員",
            什麼時候派我="需求要先被寫成一支會紅的測試時",
            系統提示=角色提示.測試員,
            派法=怎麼派(工作種類.例行),
            權限=權限.可編輯,
            逾時秒=TDD階段預設逾時秒,
        ),
        角色藍圖(
            識別碼=階段代碼.實作.value,
            名稱="實作員",
            什麼時候派我="已經看見紅測試、可以補最少實作時",
            系統提示=角色提示.實作員,
            派法=怎麼派(工作種類.例行),
            權限=權限.可編輯,
            逾時秒=TDD階段預設逾時秒,
        ),
        角色藍圖(
            識別碼=階段代碼.重構.value,
            名稱="重構員",
            什麼時候派我="測試全綠、可以整理但不能改行為時",
            系統提示=角色提示.重構員,
            派法=怎麼派(工作種類.例行),
            權限=權限.可編輯,
            逾時秒=TDD階段預設逾時秒,
        ),
        角色藍圖(
            識別碼=階段代碼.審查.value,
            名稱="審查員",
            什麼時候派我="重構再次驗證通過、需要另一顆腦挑毛病時",
            系統提示=角色提示.審查員,
            派法=怎麼派(工作種類.推理),
            權限=權限.唯讀,
            逾時秒=TDD階段預設逾時秒,
        ),
    )


