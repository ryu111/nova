"""用 immutable blueprint 組出固定提示角色。"""

from collections.abc import Callable, Mapping
from dataclasses import dataclass
from types import MappingProxyType

from nova.契約.工作流 import 階段代碼
from nova.契約.派工 import 工作種類, 派法
from nova.契約.角色 import 權限, 角色, 語言模型, 預設逾時秒
from nova.載體.派工表 import 怎麼派
from nova.載體.角色 import 固定提示角色
from nova.迴圈 import 角色提示

#: TDD 一階可能跑完整套測試再收尾；一小時是有限且比單次問話長的上限。
TDD階段預設逾時秒 = 3600.0


@dataclass(frozen=True, slots=True)
class 角色藍圖:
    """一個工作流角色的不可變組合資料。"""

    識別碼: str
    名稱: str
    什麼時候派我: str
    系統提示: str
    派法: 派法
    權限: 權限
    逾時秒: float
    模型: str | None = None
    #: `None` ＝ 用那一家的預設。走派工表時由 `派法.思考深度` 填；
    #: `--用` 指名一家時刻意留 `None`——指名的人沒說深度，就不要替他決定。
    思考深度: str | None = None


type 建腦 = Callable[[派法], 語言模型]


def 建角色(藍圖: 角色藍圖, *, 建腦: 建腦) -> 角色:
    """依藍圖建立一個固定提示角色。"""
    return 固定提示角色(
        名稱=藍圖.名稱,
        系統提示=藍圖.系統提示,
        腦=建腦(藍圖.派法),
        模型=藍圖.模型,
        思考深度=藍圖.思考深度,
        逾時秒=藍圖.逾時秒,
        權限=藍圖.權限,
        什麼時候派我=藍圖.什麼時候派我,
    )


def 建角色表(
    藍圖們: tuple[角色藍圖, ...],
    *,
    建腦: 建腦,
) -> Mapping[str, 角色]:
    """把一組角色藍圖組成不可變的識別碼對角色表。"""
    角色表 = {藍圖.識別碼: 建角色(藍圖, 建腦=建腦) for 藍圖 in 藍圖們}
    return MappingProxyType(角色表)


