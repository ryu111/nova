"""用 immutable blueprint 組出固定提示角色。

**兩個相依都是參數，不是 import**（依賴反轉）：這裡只需要「這種工作該怎麼派」
與「怎麼組一個固定提示角色」兩個動作，不需要知道派工表住哪個檔、
角色是哪個 dataclass。由呼叫端（組裝點）把它們傳進來。
"""

from collections.abc import Callable, Mapping
from dataclasses import dataclass
from types import MappingProxyType
from typing import Protocol

from nova.契約.工作流 import 階段代碼
from nova.契約.派工 import 工作種類, 派法
from nova.契約.角色 import 權限, 角色, 語言模型, 預設逾時秒
from nova.迴圈 import 角色提示

#: TDD 一階可能跑完整套測試再收尾；一小時是有限且比單次問話長的上限。
TDD階段預設逾時秒 = 3600.0


@dataclass(frozen=True, slots=True)
class 角色藍圖:
    """一個工作流角色的不可變組合資料。"""

    識別碼: str
    名稱: str
    什麼時候派我: str
    系統提示: str
    派法: 派法
    權限: 權限
    逾時秒: float
    模型: str | None = None
    #: `None` ＝ 用那一家的預設。走派工表時由 `派法.思考深度` 填；
    #: `--用` 指名一家時刻意留 `None`——指名的人沒說深度，就不要替他決定。
    思考深度: str | None = None


type 建腦 = Callable[[派法], 語言模型]
#: 這種工作該怎麼派。形狀由這裡宣告，派工表（載體）去符合。
type 派法查詢 = Callable[[工作種類], 派法]
#: 這一階算哪一種工作。同上是個查詢，讓呼叫端可以換掉。
type 工作種類查詢 = Callable[[階段代碼], 工作種類]

#: 哪一階算動腦。**全 repo 只准有這一份**——原本載體的資格檢查
#: （`_階段的工作`）跟這裡的藍圖各存一份，兩份可以走散成「甲說推理、
#: 乙派例行」，護欄就會去驗一家沒人叫的腦（靜默放行）或誤擋。
#:
#: 住迴圈不住載體：載體讀得動迴圈，反過來被架構閘擋（迴圈不准 import 載體），
#: 所以合併的落點只能是這裡（或契約）。
#:
#: 分法照 `工作種類` 自己的定義，不是憑感覺：測試是例行；實作／重構是
#: 建構；審查是「設計取捨、找漏洞、答案對不對要靠推理」。
TDD階段的工作 = {
    階段代碼.測試: 工作種類.例行,
    階段代碼.實作: 工作種類.建構,
    階段代碼.重構: 工作種類.建構,
    階段代碼.審查: 工作種類.推理,
}


def 這階算哪種工作(階段: 階段代碼) -> 工作種類:
    """這一階算例行、建構還是推理。**沒配到就當場炸，不猜**——

    猜一個預設的代價是每一次都派錯家，而且沒有人會發現：
    輸出看起來一樣，只是慢、貴、或笨。
    """
    種 = TDD階段的工作.get(階段)
    if 種 is None:
        訊息 = f"派工表不知道 {階段.value} 算例行、建構還是推理"
        raise ValueError(訊息)
    return 種


class 組角色器(Protocol):
    """怎麼組一個固定提示角色。同上：組出來的是不是 dataclass，這裡不需要知道。

    形狀寫全（每個關鍵字參數都列出來），不用 `Callable[..., 角色]`：
    `...` 等於不檢查，傳錯參數要等到執行期才知道。
    """

    def __call__(  # noqa: PLR0913 —— 形狀就是角色的欄位，列全比 `...` 誠實
        self,
        *,
        名稱: str,
        系統提示: str,
        腦: 語言模型,
        模型: str | None,
        思考深度: str | None,
        逾時秒: float,
        權限: 權限,
        什麼時候派我: str,
    ) -> 角色:
        """組出一個角色。"""
        ...


def 建角色(藍圖: 角色藍圖, *, 建腦: 建腦, 組角色: 組角色器) -> 角色:
    """依藍圖建立一個固定提示角色。"""
    return 組角色(
        名稱=藍圖.名稱,
        系統提示=藍圖.系統提示,
        腦=建腦(藍圖.派法),
        模型=藍圖.模型,
        思考深度=藍圖.思考深度,
        逾時秒=藍圖.逾時秒,
        權限=藍圖.權限,
        什麼時候派我=藍圖.什麼時候派我,
    )


def 建角色表(
    藍圖們: tuple[角色藍圖, ...],
    *,
    建腦: 建腦,
    組角色: 組角色器,
) -> Mapping[str, 角色]:
    """把一組角色藍圖組成不可變的識別碼對角色表。"""
    角色表 = {藍圖.識別碼: 建角色(藍圖, 建腦=建腦, 組角色=組角色) for 藍圖 in 藍圖們}
    return MappingProxyType(角色表)


def 建TDD角色藍圖(
    怎麼派: 派法查詢,
    算哪種工作: 工作種類查詢 = 這階算哪種工作,
) -> tuple[角色藍圖, ...]:
    """TDD 四階的藍圖。

    **哪一階算哪種工作不再寫死在這裡**：問 `算哪種工作`。它預設就是上面那份
    唯一的表，呼叫端要換（測試、或以後改成從別處讀）也換得掉。
    """

    def 這一階(
        階段: 階段代碼,
        *,
        名稱: str,
        什麼時候派我: str,
        系統提示: str,
        權限: 權限,
    ) -> 角色藍圖:
        """一階的藍圖。**階段只寫一次**：識別碼與派法都從它推出來——

        兩處各寫一次的話，就有人可以把識別碼寫成審查、派法卻去問重構，
        而且看起來完全正常。
        """
        return 角色藍圖(
            識別碼=階段.value,
            名稱=名稱,
            什麼時候派我=什麼時候派我,
            系統提示=系統提示,
            派法=怎麼派(算哪種工作(階段)),
            權限=權限,
            逾時秒=TDD階段預設逾時秒,
        )

    return (
        這一階(
            階段代碼.測試,
            名稱="測試員",
            什麼時候派我="需求要先被寫成一支會紅的測試時",
            系統提示=角色提示.測試員,
            權限=權限.可編輯,
        ),
        這一階(
            階段代碼.實作,
            名稱="實作員",
            什麼時候派我="已經看見紅測試、可以補最少實作時",
            # **不是 `角色提示.實作員`**：那份含首輪的讀取策略，而讀取策略是 per-round 的
            # （被退回的那一輪要准它跑全測試）。系統提示只放身分，那一段由 `工作流._提示` 每輪接。
            系統提示=角色提示.實作員身分,
            權限=權限.可編輯,
        ),
        這一階(
            階段代碼.重構,
            名稱="重構員",
            什麼時候派我="測試全綠、可以整理但不能改行為時",
            系統提示=角色提示.重構員,
            權限=權限.可編輯,
        ),
        這一階(
            階段代碼.審查,
            名稱="審查員",
            什麼時候派我="重構再次驗證通過、需要另一顆腦挑毛病時",
            系統提示=角色提示.審查員,
            權限=權限.唯讀,
        ),
    )


def 建研究角色藍圖(怎麼派: 派法查詢) -> tuple[角色藍圖, ...]:
    """研究工作流的三個角色。這幾階是唯讀單次問話，維持單次問話的預設逾時。"""
    return (
        角色藍圖(
            識別碼="搜尋",
            名稱="搜尋員",
            什麼時候派我="需要找資料並留下可追溯出處時",
            系統提示="你是研究工作流裡的搜尋員。",
            派法=怎麼派(工作種類.例行),
            權限=權限.唯讀,
            逾時秒=預設逾時秒,
        ),
        角色藍圖(
            識別碼="對抗",
            名稱="對抗員",
            什麼時候派我="需要主動找反例、漏洞與相反證據時",
            系統提示="你是研究工作流裡的對抗員。",
            派法=怎麼派(工作種類.推理),
            權限=權限.唯讀,
            逾時秒=預設逾時秒,
        ),
        角色藍圖(
            識別碼="整合",
            名稱="整合員",
            什麼時候派我="各分支都有結果、需要整理成有來源的結論時",
            系統提示="你是研究工作流裡的整合員。",
            派法=怎麼派(工作種類.推理),
            權限=權限.唯讀,
            逾時秒=預設逾時秒,
        ),
    )


def 建系統架構師角色藍圖(怎麼派: 派法查詢) -> tuple[角色藍圖, ...]:
    """系統架構師那一階的藍圖。"""
    return (
        角色藍圖(
            識別碼="系統架構師",
            名稱="系統架構師",
            什麼時候派我=(
                "研究證據要由系統架構師決定工作流形狀、節點契約、出口或停止政策時；"
                "只決定這次先做哪幾步就派計畫員（PlanWorker）"
            ),
            系統提示=角色提示.系統架構師,
            派法=怎麼派(工作種類.推理),
            權限=權限.唯讀,
            逾時秒=預設逾時秒,
        ),
    )
