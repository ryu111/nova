def 建索引(階段表: tuple[階段定義, ...]) -> Mapping[階段代碼, 階段定義]:
    """代碼 → 定義。**同一個代碼出現兩次就當場炸。**

    dict 推導式會靜默留下最後一列，被蓋掉那列的邊就這樣消失了——
    而那正是「表上讀不到的邊」的另一種長相。
    """
    索引: dict[階段代碼, 階段定義] = {}
    for 定義 in 階段表:
        if 定義.代碼 in 索引:
            訊息 = f"階段表有重複的代碼：{定義.代碼.value}"
            raise ValueError(訊息)
        索引[定義.代碼] = 定義
    return MappingProxyType(索引)


_索引 = 建索引(TDD階段表)


#: 階段在 `TDD階段表` 上的先後。import 時建一次，跟 `_索引` 同一個作法。
_次序 = MappingProxyType({定義.代碼: 序 for 序, 定義 in enumerate(TDD階段表)})


def 是回頭邊(來源: 階段代碼, 去處: 階段代碼) -> bool:
    """這一步是往回退嗎？**定義住在階段表：去處排在來源前面就是回頭邊。**

    退回實作的那一輪要修的是「上一階那份紅」，實作員得看得見它。
    這個訊號從這裡流過去，不是讓提示自己猜，也不是在別處寫死一份
    「哪些階段會退回實作」的清單——那份清單會跟階段表分岔。
    """
    if 來源 not in _次序 or 去處 not in _次序:
        return False
    return _次序[去處] < _次序[來源]


def 查階段(代碼: 階段代碼) -> 階段定義:
    """依代碼取**TDD 階段表**裡的定義。查不到當場炸——靜默回 None 會讓工作流走進黑洞。

    自訂階段表要用 `建索引`：這支只認那張正典的表。
    """
    if 代碼 not in _索引:
        訊息 = f"不存在的階段：{代碼}（可用：{'、'.join(_索引)}）"
        raise KeyError(訊息)
    return _索引[代碼]


def 達到期望(定義: 階段定義, 結果: 步驟結果) -> bool:
    """這一步達到它該達到的了嗎？

    模型階段：跑完就算。判準階段：還要紅綠符合期望——
    `驗證紅` 期望紅，所以綠了反而是沒達到。
    """
    if 定義.種類 is 種類.模型:
        return True
    return 結果.判準綠 is 定義.期望綠


def _審查的出口(結果: 步驟結果) -> 出口標籤:
    """審查員給的判定 → 出口標籤。**沒給就是沒給，不准當成通過。**

    | 判定 | 出口 | 為什麼 |
    |---|---|---|
    | 通過 | 綠（完成） | |
    | 要求修改 | 紅（退回實作） | 審出問題就回去改，這是回頭邊 |
    | 沒給結論 | **自己一格**（中止） | 讀不出判定跟「它說可以」是兩件事 |

    第三列是 fail-closed：讀不出來就停下來讓人看，不猜。
    **它不共用「紅」**——紅的意思是「回去再改一次」，而讀不出判定的時候，
    根本不知道要改什麼。
    """
    if 結果.審查結論 is 審查判定.通過:
        return 出口標籤.綠
    if 結果.審查結論 is 審查判定.要求修改:
        return 出口標籤.紅
    return 出口標籤.沒給結論


def 判出口(定義: 階段定義, 結果: 步驟結果) -> 出口標籤:
    """(這個階段, 它的結果) → **這是哪一種收場**。純函式，而且**不決定去哪**。

    判「是哪一種」與判「去哪」分開，是為了讓去處**完全住在表上**：
    這支只認收場的種類，去處一律由 `定義.出口` 回答。

    **結果未知一律停**，蓋過所有階段的個別轉移：不知道做了沒的時候，
    往下走或退回重做都可能把已經做過的事再做一次（at-most-once，寧漏不重）。
    """
    if 結果.終局 is 終局.結果未知:
        return 出口標籤.結果未知
    if 結果.終局 is 終局.確定失敗:
        # 確定失敗（如角色未出門就掛了）直接走確定失敗出口，不准走紅邊重做。
        return 出口標籤.確定失敗
    if 定義.種類 is 種類.審查:
        return _審查的出口(結果)
    return 出口標籤.綠 if 達到期望(定義, 結果) else 出口標籤.紅


#: 這幾階的角色**不准動測試**：實作員（`角色提示.py` 第 2 條）與重構員（第 1 條）。
#: 判準是角色不是階段名——測試員那一階的工作就是寫測試，所以它不在這裡；
#: 做成階段盲的話第一階就會把自己擋死。轉移要看它，所以它住在狀態機這一側。
不准動測試的階段 = frozenset({階段代碼.實作, 階段代碼.重構})


def 伸手動了測試(階段: 階段代碼, 動過的測試檔: tuple[str, ...]) -> bool:
    """這一步是「不准動測試的階段動了測試檔」嗎？

    **全樹只准有這一份**：轉移（要不要接回測試階）與 runner 的再犯計數、
    提示遮蔽問的都得是同一個純函式，兩份同名不同簽章的拷貝會靜靜走散。
    原料取到最小的 `(階段代碼, 動過的測試檔)`，兩側手上的東西才都餵得進來。
    """
    return 階段 in 不准動測試的階段 and bool(動過的測試檔)


def _重構行為紅(定義: 階段定義, 結果: 步驟結果) -> bool:
    """辨認重構後的行為測試紅；lint／格式判準會帶 `[ruff]` 證據前綴。"""
    return (
        定義.代碼 is 階段代碼.驗證重構
        and 結果.判準綠 is False
        and bool(結果.證據)
        and not 結果.證據.startswith("[ruff]")
    )


def 紅在哪些既有測試(結果: 步驟結果) -> tuple[str, ...]:
    """這份判準證據裡，紅的哪幾支**不是**這一輪測試員動過的（＝既有測試）。

    只認證據的 `FAILED …::…` 行與 `動過的測試檔`，不拿模型的自由文字判斷。
    抽不出 `FAILED` 行就回空——寧可照原路退回實作，也不猜。
    """
    這輪動過的檔們 = set(結果.動過的測試檔)
    紅節點們 = _取失敗測試(結果.證據)
    return tuple(sorted(節點 for 節點 in 紅節點們 if _節點所在的檔(節點) not in 這輪動過的檔們))


def _節點所在的檔(測試節點: str) -> str:
    """`FAILED` 行的 `檔路徑::類別::函式`，取檔路徑那一段。"""
    return 測試節點.split("::", maxsplit=1)[0]


#: `載體/命令列.py` 把提交閘紅的規則代碼印成 `閘紅：<代碼>、<代碼>`（stderr 最後一行，
#: 證據取尾端 4000 字所以砍不到它）。`nova 閘 提交` 提前停止，所以那行通常只有一個代碼，
#: **不當成完整集合**——只拿它問「紅的這幾條都在合格集合裡嗎」。
_閘紅行樣式 = re.compile(r"(?m)^閘紅：(.+)$")

#: 三種工具吐路徑的長相：`path:line:col: CODE msg`（ruff check）、
#: `Would reformat: path`（ruff format --check）、`path:line: error:`（mypy）。
_證據裡的檔樣式 = re.compile(r"(?:^|[\s:])([^\s:]+\.py)(?::(\d+))?")

#: `載體/命令列.py:_證據挑幾行` 砍過中段時留下的字樣。看不到全貌就不准斷言「路徑全在 tests/」。
_證據被截過的字樣 = "（中間省略"

#: `載體/判準.py:建預設判準` 給每一步的證據冠 `[步名] ` 前綴。提交閘是最後一步、
#: 而且第一個非綠就停，所以這一行之後的東西全都屬於提交閘。
_提交閘的步名前綴 = "[提交閘] "


def _從這行起的整段(行們: list[str], 是起點嗎: Callable[[str], bool]) -> str:
    """從第一個符合條件的行起、到結尾的那一段；沒有那一行就回空字串。

    「找不到起點就回空」是這兩個呼叫點共用的 fail-closed 姿勢：讀不到那一段，
    就不准對它的內容下任何斷言。
    """
    起點 = next((索引 for 索引, 行 in enumerate(行們) if 是起點嗎(行)), None)
    return "" if 起點 is None else "\n".join(行們[起點:])


def _提交閘那一段(證據: str) -> str:
    """證據裡屬於**提交閘那一步**的那一段；根本沒跑到提交閘就回空字串。

    分流要兩個獨立訊號：哪一步紅、紅在哪條規則。少問前者的話，一支斷言
    `閘紅：` 訊息的既有測試自己紅掉（那行字印在 `[全測試] ` 那段裡），
    就會被當成排版紅送給測試員，繞過既有測試那條「連紅第二次才退」的保守判準。
    """
    return _從這行起的整段(證據.splitlines(), lambda 行: 行.startswith(_提交閘的步名前綴))


def _閘紅的規則代碼(證據: str) -> frozenset[str]:
    """**提交閘那一段**裡 `閘紅：` 那行點名的規則代碼。不是紅在提交閘就回空集合。"""
    那一段 = _提交閘那一段(證據)
    代碼們 = (
        代碼.strip() for 命中 in _閘紅行樣式.finditer(那一段) for 代碼 in 命中.group(1).split("、")
    )
    return frozenset(代碼 for 代碼 in 代碼們 if 代碼)


def _閘紅那一段(證據: str) -> str:
    """提交閘那一段裡屬於**紅掉那條規則**的部分：從第一行 `[紅]` 起，不含 `閘紅：` 那行。

    判準第一個非綠就停，所以 `[紅]` 只會有一個；**找不到就回空字串**（fail-closed：
    看不到是哪條規則紅在哪裡，就不准斷言「只紅在 `tests/`」）。
    """
    沒有閘紅那行的 = [行 for 行 in _提交閘那一段(證據).splitlines() if not 行.startswith("閘紅：")]
    return _從這行起的整段(沒有閘紅那行的, lambda 行: "[紅]" in 行)


def _閘紅點名的位置(證據: str) -> tuple[str, ...]:
    """提交閘紅掉那條規則的證據點名了哪幾個 `檔` 或 `檔:行`，照出現順序去重；抽不出來就回空。"""
    位置們 = [
        f"{命中.group(1)}:{命中.group(2)}" if 命中.group(2) else 命中.group(1)
        for 命中 in _證據裡的檔樣式.finditer(_閘紅那一段(證據))
    ]
    return tuple(dict.fromkeys(位置們))


def 閘只紅在測試檔的哪幾處(結果: 步驟結果) -> tuple[str, ...]:
    """這一步是「提交閘只紅在 `tests/` 底下的 lint／型別」嗎？是就回 `檔:行 規則` 清單。

    只認 `閘紅：` 那行的規則代碼與證據裡抽得出的路徑，**不拿模型的自由文字判斷**。
    實作員被明令禁止碰 `tests/`，這種紅它不可能修得掉，所以第一次紅就送測試員，
    不套「連紅第二次」那條保守判準（那條是為了「可能是實作員改壞的」而留的）。

    fail-closed，三種情形一律回空（照舊退回實作員）：
    (i) 證據被 `_證據挑幾行` 截過——看不到全貌，不能斷言路徑全在 `tests/`；
    (ii) 抽得出的路徑有任何一個不在 `tests/` 底下；
    (iii) 一個路徑都抽不出來。
    """
    if not 是紅掉的驗證綠(結果):
        return ()
    代碼們 = _閘紅的規則代碼(結果.證據)
    if not 代碼們 or not 代碼們 <= 測試員修得掉的規則代碼:
        return ()
    if _證據被截過的字樣 in 結果.證據:
        return ()
    位置們 = _閘紅點名的位置(結果.證據)
    if not 位置們 or any(not 位置.startswith("tests/") for 位置 in 位置們):
        return ()
    規則 = "、".join(sorted(代碼們))
    return tuple(f"{位置} {規則}" for 位置 in 位置們)


def _驗證綠紅了(階段: 階段代碼, 判準綠: bool | None) -> bool:
    """「是 `驗證綠` 這一階、而且它紅了」——「紅在既有測試」那條路的入口條件，定義在這一處。

    拆成兩個欄位收，是因為兩個呼叫點手上的東西不同：走軌跡的看某一步自己記的階段，
    `下一步` 看的是它正在轉移的那個階段定義。
    """
    return 階段 is 階段代碼.驗證綠 and 判準綠 is False


def 是紅掉的驗證綠(步: 步驟結果) -> bool:
    """這一步是紅掉的 `驗證綠` 嗎？"""
    return _驗證綠紅了(步.階段, 步.判準綠)


def _最近一輪驗證綠(軌跡: tuple[步驟結果, ...], 略過: 步驟結果 | None = None) -> 步驟結果 | None:
    """軌跡裡**最近一輪** `驗證綠`；沒跑過就回 `None`。

    `略過` 用 `is` 認同一個物件、不比值：**真的連紅兩輪時，那兩步是兩個相等但不同的
    物件**，照樣數得到。呼叫端有兩種軌跡：`工作流` 傳的快照拍在這一步跑完之前（不含它），
    單元測試常把這一步自己也放進去。
    """
    return next(
        (步 for 步 in reversed(軌跡) if 步.階段 is 階段代碼.驗證綠 and 步 is not 略過), None
    )


def _上一次驗證綠紅在哪些既有測試(
    軌跡: tuple[步驟結果, ...],
    這一步: 步驟結果 | None = None,
) -> tuple[str, ...] | None:
    """**上一輪** `驗證綠` 紅在哪幾支既有測試；那輪不是紅的（或沒跑過）就回 `None`。

    看的是上一輪，不是「上一次紅的」：`紅 A → 綠 → 紅 A` 中間那盞綠燈把連紅
    打斷了，跳過它會把兩段各自的第一次紅接成一段假的連紅。
    """
    上一次 = _最近一輪驗證綠(軌跡, 略過=這一步)
    if 上一次 is None or not 是紅掉的驗證綠(上一次):
        return None
    return 紅在哪些既有測試(上一次)


def _既有測試連紅該退回測試員(
    定義: 階段定義,
    結果: 步驟結果,
    軌跡: tuple[步驟結果, ...],
) -> bool:
    """`驗證綠` 紅在既有測試、而且同一批連紅第二次了嗎？

    判準粗細取選項 (i)：第一次紅仍退實作（可能只是實作員把行為改壞了），
    **同一批連紅第二次**才確定是慣例要改，退回測試員。
    """
    if not _驗證綠紅了(定義.代碼, 結果.判準綠):
        return False
    既有紅 = 紅在哪些既有測試(結果)
    return bool(既有紅) and 既有紅 == _上一次驗證綠紅在哪些既有測試(軌跡, 結果)


def _測試檔閘紅該退回測試員(定義: 階段定義, 結果: 步驟結果) -> bool:
    """`驗證綠` 紅在提交閘、而且那條紅**只落在 `tests/` 底下**了嗎？

    不看軌跡：實作員被明令禁止碰 `tests/`，它不可能修得掉，**第一次紅就退**，
    不套上面那條「連紅第二次」的保守判準。細節與 fail-closed 見 `閘只紅在測試檔的哪幾處`。
    """
    return _驗證綠紅了(定義.代碼, 結果.判準綠) and bool(閘只紅在測試檔的哪幾處(結果))


def _補完測試檔閘紅該回去驗證綠(定義: 階段定義, 結果: 步驟結果, 軌跡: tuple[步驟結果, ...]) -> bool:
    """這一步是「被測試檔閘紅退回來的測試員做完了」嗎？是的話下一步回「全綠了嗎」。

    表上 `測試 → 驗證紅` 的前提是「測試員新寫了一支會紅的測試」。被 lint／型別紅
    退回來的那一輪不是那件事：它只補排版，行為測試從頭到尾都是綠的，
    照表走會撞上「竟然是綠的 → 退回重寫」，變成 `測試 → 驗證紅 → 測試 → …` 的無限迴圈，
    而那條迴圈裡一行 `FAILED` 都沒有、連紅計數也數不到。回「全綠了嗎」才是問對問題：
    修好了就往下，沒修好就是同一批 lint 紅又來一輪，`卡住了` 數得到它。
    """
    if 定義.代碼 is not 階段代碼.測試 or 判出口(定義, 結果) is not 出口標籤.綠:
        return False
    上一次驗證綠 = _最近一輪驗證綠(軌跡)
    return 上一次驗證綠 is not None and bool(閘只紅在測試檔的哪幾處(上一次驗證綠))


def 下一步(定義: 階段定義, 結果: 步驟結果, 軌跡: tuple[步驟結果, ...] = ()) -> "階段代碼 | 結束":
    """純函式轉移：(這個階段, 它的結果) → 下一步。

    一般結果照表查；重構後的行為測試紅是既有護欄，不能誤當成可由重構員
    繼續修的 lint／格式紅。
    審查要求修改時，若包含測試設計問題則退回測試員，否則退回實作員。
    `驗證綠` 紅在**既有測試**（不在這一輪 `動過的測試檔` 裡）且同一批連紅第二次時，
    退回測試員：實作員唯一能讓它綠的動作是改測試檔，而那是它被禁止做的事。
    提交閘**只紅在 `tests/` 底下的 lint／型別**時同樣退回測試員，而且第一次紅就送
    （見 `閘只紅在測試檔的哪幾處`）：那種紅一行 `FAILED` 都沒有，上面那條問不到。
    那一輪的測試員做完之後回的是「全綠了嗎」而不是「親眼看到它紅」
    （見 `_補完測試檔閘紅該回去驗證綠`）：它補的是排版，不是一支新的紅測試。
    `不准動測試的階段` 自己伸手動了測試檔時也退回測試員：這一步不算數，
    那幾個檔該不該改、怎麼改是測試員的職權。（同一輪第二次伸手是**收場**，由 runner 收 4。）
    """
    if _重構行為紅(定義, 結果):
        return 結束(
            結束代碼.護欄,
            "重構把行為改掉了（測試紅了）——不准往前除錯，請自己退回上一個綠燈",
            護欄原因=護欄種類.重構改壞行為,
        )
    改道 = _改道去哪(定義, 結果, 軌跡)
    if 改道 is not None:
        return 改道
    return 定義.出口[判出口(定義, 結果)]


def _改道去哪(
    定義: 階段定義,
    結果: 步驟結果,
    軌跡: tuple[步驟結果, ...],
) -> 階段代碼 | None:
    """表以外的那幾條邊：不改道就回 `None`，由 `下一步` 照表查。

    列在一處是為了讓「表上讀不到的邊」全部看得見；理由各自寫在被呼叫的述詞上。
    """
    if 伸手動了測試(定義.代碼, 結果.動過的測試檔):
        return 階段代碼.測試
    if _既有測試連紅該退回測試員(定義, 結果, 軌跡):
        return 階段代碼.測試
    if _測試檔閘紅該退回測試員(定義, 結果):
        return 階段代碼.測試
    if _補完測試檔閘紅該回去驗證綠(定義, 結果, 軌跡):
        return 階段代碼.驗證綠
    if 定義.代碼 is 階段代碼.審查 and 結果.審查結論 is 審查判定.要求修改:
        問題列 = 讀審查問題列(結果.證據)
        if any(問.種類 is 問題種類.測試設計 for 問 in 問題列):
            return 階段代碼.測試
    return None


連續審查要求修改門檻 = 2


def 連續審查要求修改(軌跡: tuple[步驟結果, ...]) -> str | None:
    """審查連續要求修改達門檻就停，不看判準階段的紅綠。

    **只數帶 `ISSUE:` 的那幾輪。** `FOLLOW-UP:` 是範圍外的後續發現，
    它會落成新票、不退回這一張——把它數進來的話，一條每輪都有進展的線
    會被收成「無進展」，而那正是今天的病。
    """
    連續要求修改次數 = 0
    for 步驟 in reversed(軌跡):
        if 步驟.階段 is not 階段代碼.審查:
            continue
        if 步驟.審查結論 is not 審查判定.要求修改:
            break
        if not 讀審查問題列(步驟.證據):
            continue
        連續要求修改次數 += 1
        if 連續要求修改次數 >= 連續審查要求修改門檻:
            return f"審查意見連續要求修改 {連續要求修改次數} 次，停止讓人檢視"
    return None


#: 「同一批測試連續紅三輪，且工作區雜湊未變，才算無進展。」
#:
#: 3 不是抄來的：OpenHands 的 stuck detector 用 4（相同 action＋observation 連續 4 次）
#: 而且它掃最後 20 個事件。nova 的整輪上限就是 20 步，回頭邊一來一回算 2 步，
#: 所以等到第 4 次的時候已經燒掉 8 步；3 小於曾經燒掉的 12 輪，
#: **門檻要配迴圈的長度，不是抄別人的數字**。
卡住門檻 = 3

#: 判準逾時的**專屬**門檻。比一般紅低，因為逾時不是回饋：
#: 機器過載時模型改再多 code 也不會讓它跑得完，多繞一輪只是多燒一個模型階段。
逾時卡住門檻 = 2

#: `驗證紅` 連續判成綠幾次，就算「這張票本來就沒有紅可看」。
#:
#: 2 照 `卡住門檻` 的算法推、不是抄的：`測試 → 驗證紅（竟然是綠的）→ 測試` 這條回頭邊
#: 一來一回是 2 步，第 2 次綠的時候已經燒掉 4 步。不取 1 是因為第一次綠可能只是測試
#: 寫歪了，退回重寫一次是對的；不取 3 是因為那要燒到第 6 步，而實測燒滿 24 步的那條線
#: 正是這條邊繞了 12 圈。
沒有紅可看門檻 = 2

#: `驗證紅` 連綠達門檻時的理由。做成常數是為了讓工作流認得出「是這一種護欄」，
#: 不必去比對自由文字。
沒有紅可看的理由 = (
    f"「{階段代碼.驗證紅.value}」連續 {沒有紅可看門檻} 次是綠的："
    "這張票沒有紅可看（補紀錄／補登記／重構型工作），不是測試員寫錯"
)


def _沒有紅可看(軌跡: tuple[步驟結果, ...]) -> bool:
    """`驗證紅` 連續 `沒有紅可看門檻` 次判成綠了嗎？

    **不看工作區雜湊**（同判準逾時那條的理由）：測試員每一輪都真的重寫測試檔，
    雜湊必變，把「雜湊未變」放進條件等於這條護欄永遠不會生效。
    也不看證據的自由文字：只認 `驗證紅` 這一階的 `判準綠`。
    """
    連綠次數 = 0
    for 步 in 軌跡:
        if 步.階段 is not 階段代碼.驗證紅:
            continue
        連綠次數 = 連綠次數 + 1 if 步.判準綠 is True else 0
        if 連綠次數 >= 沒有紅可看門檻:
            return True
    return False


def 卡住了(
    軌跡: tuple[步驟結果, ...],
    階段表: tuple[階段定義, ...] = TDD階段表,
    *,
    工作區雜湊們: tuple[str | None, ...] | None = None,
) -> str | None:
    """沒進展就停。回傳可行動的理由，沒卡住回 `None`。**純函式。**

    守的是：「同一批測試連續紅三輪，且工作區雜湊未變，才算無進展。」有工作區快照時，
    只有**判準階段同一批紅連續三輪，且每輪之間的工作區雜湊相同**才會停。
    模型階段是回頭邊的一部分，不拿它的自由文字判定。

    **判準逾時是例外**：它有自己的計數（`逾時卡住門檻`），而且不看工作區雜湊——
    逾時不是回饋，兩次逾時之間工作區必然改過，拿雜湊當條件這條就永遠不會生效。

    **`驗證紅` 連綠也是例外**：它有自己的計數（`沒有紅可看門檻`），一路上一個紅都沒有，
    只數紅的無進展偵測對它完全隱形；它也不看工作區雜湊（理由同判準逾時那條）。

    沒有快照時保留純函式原本的證據比對，供沒有工作區的狀態機單元測試使用；真正的
    工作流一律從工作目錄取得快照。

    這條擋的洞：兩條回頭邊（驗證紅沒紅退回測試、驗證綠沒綠退回實作）本來就可能
    來回不停，若只剩步數上限擋它，那是「燒完一整條線才停」，不是「發現沒進展就停」，
    中間那些步全是白花的錢。現在兩條邊各有各的計數擋著：驗證綠那條數同一批連紅
    （`卡住門檻`），驗證紅那條數連續判成綠（`沒有紅可看門檻`）。
    """
    if _沒有紅可看(軌跡):
        return 沒有紅可看的理由
    # 名字只是給人看的：跟著傳進來的那張表走，不然自訂表會印出 TDD 表的階段名。
    名字 = {定義.代碼: 定義.名稱 for 定義 in 階段表}
    if 工作區雜湊們 is not None:
        return _工作區無進展(軌跡, 階段表, 工作區雜湊們, 名字)
    次數: dict[tuple[階段代碼, str], int] = {}
    for 步 in 軌跡:
        if 步.判準綠 is not False:
            continue
        鍵 = (步.階段, 步.證據)
        次數[鍵] = 次數.get(鍵, 0) + 1
        if 次數[鍵] >= 卡住門檻:
            return (
                f"「{名字.get(步.階段, 步.階段.value)}」（{步.階段.value}）"
                f"第 {卡住門檻} 次吐出一模一樣的紅，"
                f"沒有進展——換策略或縮小題目，不要再燒步數"
            )
    return None


def _工作區無進展(
    軌跡: tuple[步驟結果, ...],
    階段表: tuple[階段定義, ...],
    工作區雜湊們: tuple[str | None, ...],
    名字: dict[階段代碼, str],
) -> str | None:
    """判定判準階段有沒有停在原地：同一批紅在未改動的工作區連續重現，或連續逾時。

    「一批」是失敗測試的 nodeid，或 lint／型別紅的 `代碼:檔:行`（見 `_這一批紅是誰`）。

    逾時走**自己的計數**，而且**條件裡不准出現工作區雜湊**。
    逾時不是回饋，兩次逾時之間實作員一定改過檔、雜湊必變，
    把雜湊當條件這條護欄就永遠不會生效（等於沒做）。
    """
    階段們 = {定義.代碼: 定義 for 定義 in 階段表}
    上一批紅: frozenset[str] | None = None
    上一工作區雜湊: str | None = None
    連紅次數 = 0
    連續逾時次數 = 0
    for 索引, 步 in enumerate(軌跡):
        這一階 = 階段們.get(步.階段)
        if 這一階 is None or 這一階.種類 is not 種類.判準:
            continue
        if _如期的紅(這一階, 步):
            continue
        是紅 = 步.判準綠 is False
        是逾時紅 = 是紅 and _是逾時證據(步.證據)

        連續逾時次數 = 連續逾時次數 + 1 if 是逾時紅 else 0
        if 連續逾時次數 >= 逾時卡住門檻:
            return _連續逾時的理由(步, 連續逾時次數, 名字)

        # 綠、或逾時（證據裡本來就沒有 FAILED 行）都讓連紅那條的狀態歸零。
        這一批紅 = _這一批紅是誰(步.證據) if 是紅 and not 是逾時紅 else frozenset()
        目前工作區雜湊 = 工作區雜湊們[索引] if 索引 < len(工作區雜湊們) else None
        if not 這一批紅 or 目前工作區雜湊 is None:
            上一批紅 = None
            上一工作區雜湊 = None
            連紅次數 = 0
            continue
        連紅次數 = 連紅次數 + 1 if 這一批紅 == 上一批紅 and 目前工作區雜湊 == 上一工作區雜湊 else 1
        上一批紅 = 這一批紅
        上一工作區雜湊 = 目前工作區雜湊
        if 連紅次數 >= 卡住門檻:
            return _同一批連紅的理由(步, 連紅次數, 這一批紅, 名字)
    return None


def _如期的紅(定義: 階段定義, 步: 步驟結果) -> bool:
    """這一步是「親眼看到它紅」那種**如期**的紅嗎？如期紅了算通過，不進連紅計數。

    它既不是回饋也不是倒退：中立。不中立的話，「全綠了嗎」紅在既有測試
    而退回測試員的那條回頭邊，中間會夾一次驗證紅把連紅計數洗掉——
    同一批既有測試就永遠數不到三輪。
    """
    return 定義.期望綠 is False and 步.判準綠 is False


def _連續逾時的理由(步: 步驟結果, 連續逾時次數: int, 名字: dict[階段代碼, str]) -> str:
    return (
        f"無進展（沒有進展）：「{名字.get(步.階段, 步.階段.value)}」"
        f"（{步.階段.value}）判準連續逾時 {連續逾時次數} 次："
        "逾時不是測試給的回饋，再退回實作也改變不了——"
        "先查機器負載或縮小判準範圍，不要再燒步數"
    )


def _這一批紅是誰(證據: str) -> frozenset[str]:
    """這一輪紅的「這一批是誰」：有 `FAILED` nodeid 就用它，lint／型別紅則用 `代碼:檔:行`。

    lint 紅**一行 `FAILED` 都沒有**。只認 nodeid 的話，連紅計數每一輪都被當成
    「這批是空的」而歸零，於是「測試 → 全綠了嗎 lint 紅 → 測試 → …」這條回頭邊
    永遠不會被護欄停下。兩種鍵都只由確定性的輸出組成，跨輪比得起來。
    """
    失敗測試 = _取失敗測試(證據)
    if 失敗測試:
        return 失敗測試
    return _閘紅的批次鍵(證據)


def _閘紅的批次鍵(證據: str) -> frozenset[str]:
    """lint／型別紅的「這一批是誰」：`代碼:檔:行`；抽不出位置就退成只有代碼。

    這裡不做 `tests/` 的分流判斷——護欄要數的是「同一批紅又來了」，
    紅在哪一層都算。沒有 `閘紅：` 那行（例如純 pytest 輸出）就回空，維持原本的歸零。
    """
    代碼們 = _閘紅的規則代碼(證據)
    if not 代碼們:
        return frozenset()
    位置們 = _閘紅點名的位置(證據)
    if not 位置們:
        return 代碼們
    return frozenset(f"{代碼}:{位置}" for 代碼 in 代碼們 for 位置 in 位置們)


def _同一批連紅的理由(
    步: 步驟結果,
    連紅次數: int,
    這一批紅: frozenset[str],
    名字: dict[階段代碼, str],
) -> str:
    這批清單 = "、".join(sorted(這一批紅))
    return (
        f"無進展（沒有進展）：「{名字.get(步.階段, 步.階段.value)}」"
        f"（{步.階段.value}）同一批紅連續 {連紅次數} 輪：{這批清單}；"
        "工作區雜湊未變，請換策略或縮小題目，不要再燒步數"
    )


def _是逾時證據(證據: str) -> bool:
    """這份證據是判準逾時嗎？

    真實路徑上證據會被 `建預設判準` 加上 `[全測試] ` 這種步名前綴，
    所以認的是**行首**（前綴可有可無），不是整份字串的開頭。
    """
    return bool(re.search(rf"(?m)^(?:\[[^\n]+\]\s*)?{re.escape(判準逾時證據標記)}", 證據))


#: `FAILED` 行認 nodeid 的**唯一**規則：行首可有 `[步名] ` 前綴、nodeid 要在同一行、要帶 `::`。
_失敗行樣式 = re.compile(r"^(?:\[[^\n]+\][^\S\n]*)?FAILED[^\S\n]+(\S+::\S+)")


def 失敗行的測試節點(行: str) -> str | None:
    """這一行是 `FAILED …::…` 就回那個 nodeid，否則回 `None`。

    **解析 `FAILED` 的唯一入口**：是 `FAILED` 行（含步名前綴）但抽不出 `::` nodeid
    → 不算任何測試紅。光禿禿的一行 `FAILED` 與收集失敗那種 `FAILED 檔路徑 - …`
    都走這條，不會被當成某支測試紅了，也不會炸。
    """
    命中 = _失敗行樣式.match(行)
    return 命中.group(1) if 命中 is not None else None


def _取失敗測試(證據: str) -> frozenset[str]:
    """從判準證據取出失敗測試的 nodeid，忽略每次執行會變的其他輸出。

    逐行走 `失敗行的測試節點`，兩處解析共用同一套失敗關閉的規則。
    """
    節點們 = (失敗行的測試節點(行) for 行 in 證據.splitlines())
    return frozenset(節點 for 節點 in 節點們 if 節點 is not None)
