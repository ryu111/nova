"""工作流的控制流程。

**這不是圖層。** 規格的圖層管的是「多條路徑之間該走哪一條」；這裡是單一路徑
加兩條回頭邊，屬於迴圈七欄位裡的 action policy 與 stop rule（§3.2）。
等真的出現多路徑分歧、線性寫不動了，才把它升成圖層——CLAUDE.md 明文規定
在那之前新增 `src/nova/圖/` 算違規。

寫成表不是 `if` 鏈的三個理由：印得出來（可以直接進 journal）、
測得動（純函式，零 LLM）、加階段只要加一列（開放封閉）。
"""

from nova.契約.工作流 import 審查判定, 步驟結果, 種類, 結束, 結束代碼, 階段代碼, 階段定義
from nova.契約.模型回應 import 終局

# 順序不是我挑的，是規則的明文：
# 先寫會紅的測試 → **跑它，親眼看到它紅** → 最少的碼讓它綠 → 全綠下重構。
#
# 兩個驗證是**機械判準**不是模型：驗收權不在執行者手上（硬規則 4）。
# 審查是模型，但呼叫端應該給它**另一顆腦**——自己審自己等於沒審。
TDD階段表: tuple[階段定義, ...] = (
    階段定義(
        代碼=階段代碼.測試,
        名稱="寫一支會紅的測試",
        種類=種類.模型,
        期望綠=None,
        綠=階段代碼.驗證紅,
        紅=結束(結束代碼.中止, "測試角色寫不出測試"),
    ),
    階段定義(
        代碼=階段代碼.驗證紅,
        名稱="親眼看到它紅",
        種類=種類.判準,
        期望綠=False,  # 期望的是紅
        綠=階段代碼.實作,  # 真的紅了 → 往下
        紅=階段代碼.測試,  # 竟然是綠的 → 這支測試沒在測東西，退回重寫
    ),
    階段定義(
        代碼=階段代碼.實作,
        名稱="最少的程式碼讓它綠",
        種類=種類.模型,
        期望綠=None,
        綠=階段代碼.驗證綠,
        紅=結束(結束代碼.中止, "實作角色做不出來"),
    ),
    階段定義(
        代碼=階段代碼.驗證綠,
        名稱="全綠了嗎",
        種類=種類.判準,
        期望綠=True,
        綠=階段代碼.重構,  # 全綠了才重構——SOP 的第一步就是「確保測試綠燈」
        紅=階段代碼.實作,  # fallback：沒綠就退回實作
    ),
    階段定義(
        代碼=階段代碼.重構,
        名稱="只清乾淨，不改行為",
        種類=種類.模型,
        期望綠=None,
        綠=階段代碼.驗證重構,  # **一定要再驗一次**，這是這個階段存在的理由
        紅=結束(結束代碼.中止, "重構角色做不出來"),
    ),
    階段定義(
        代碼=階段代碼.驗證重構,
        名稱="行為真的沒變嗎",
        種類=種類.判準,
        期望綠=True,
        綠=階段代碼.審查,
        # **紅了就中止，不退回重構。** SOP 明說做壞了嚴禁 fix-forward；
        # 而且退回去是無界回頭邊，只靠步數上限收斂＝成本漏洞。
        # nova 還沒有回滾機制，中止至少留下一個乾淨的「這裡壞了」訊號。
        紅=結束(結束代碼.中止, "重構把行為改掉了（測試紅了）——不准往前除錯，請自己退回上一個綠燈"),
    ),
    階段定義(
        代碼=階段代碼.審查,
        名稱="設計審查（換一顆腦）",
        種類=種類.審查,  # **不是 種類.模型**——模型階段「跑完就算」，那會宣布假的完成
        期望綠=None,
        綠=結束(結束代碼.完成, "全綠且通過審查"),
        紅=階段代碼.實作,  # 要求修改 → 退回實作，這是第三條回頭邊
    ),
)

_索引 = {階段.代碼: 階段 for 階段 in TDD階段表}


def 查階段(代碼: 階段代碼) -> 階段定義:
    """依代碼取階段定義。查不到當場炸——靜默回 None 會讓工作流走進黑洞。"""
    if 代碼 not in _索引:
        訊息 = f"不存在的階段：{代碼}（可用：{'、'.join(_索引)}）"
        raise KeyError(訊息)
    return _索引[代碼]


def 達到期望(定義: 階段定義, 結果: 步驟結果) -> bool:
    """這一步達到它該達到的了嗎？

    模型階段：跑完就算。判準階段：還要紅綠符合期望——
    `驗證紅` 期望紅，所以綠了反而是沒達到。
    """
    if 定義.種類 is 種類.模型:
        return True
    return 結果.判準綠 is 定義.期望綠


def _審查的下一步(定義: 階段定義, 結果: 步驟結果) -> "階段代碼 | 結束":
    """審查階段有三條出口，`階段定義` 只放得下兩條，所以第三條寫在這裡。

    | 判定 | 去哪 | 為什麼 |
    |---|---|---|
    | 通過 | `定義.綠`（完成） | |
    | 要求修改 | `定義.紅`（退回實作） | 審出問題就回去改，這是回頭邊 |
    | 沒給結論 | 中止 | **不准當成通過**。讀不出判定跟「它說可以」是兩件事 |

    第三列是 fail-closed：讀不出來就停下來讓人看，不猜。
    """
    if 結果.審查結論 is 審查判定.通過:
        return 定義.綠
    if 結果.審查結論 is 審查判定.要求修改:
        return 定義.紅
    return 結束(
        結束代碼.中止,
        f"{定義.名稱}沒給判定（要 REVIEW: PASS 或 REVIEW: CHANGES-REQUESTED）——不准當成通過",
    )


def 下一步(定義: 階段定義, 結果: 步驟結果) -> "階段代碼 | 結束":
    """純函式轉移：(這個階段, 它的結果) → 下一步。

    **結果未知一律停**，蓋過所有階段的個別轉移：不知道做了沒的時候，
    往下走或退回重做都可能把已經做過的事再做一次（at-most-once，寧漏不重）。
    """
    if 結果.終局 is 終局.結果未知:
        return 結束(結束代碼.中止, f"{定義.名稱}的結果未知，不准自動重試（可能已經做了一半）")
    if 結果.終局 is 終局.確定失敗:
        if 定義.種類 is 種類.判準:
            return 定義.紅
        return 結束(結束代碼.中止, f"{定義.名稱}確定失敗")
    if 定義.種類 is 種類.審查:
        return _審查的下一步(定義, 結果)
    return 定義.綠 if 達到期望(定義, 結果) else 定義.紅
