def _結果未知就停(名稱: str) -> 結束:
    """不知道做了沒的時候一律停。**這條每個階段都一樣，但每個階段都要自己列。**

    往下走或退回重做，都可能把已經做過的事再做一次（at-most-once，寧漏不重），
    或在環境有問題時盲目重試。原本它寫在 `下一步()` 裡蓋過所有階段——那是表上讀不到的邊。
    """
    return 結束(結束代碼.護欄, f"{名稱}的結果未知，不准自動重試")


def _確定失敗就中止(名稱: str) -> 結束:
    """角色沒出門就掛了（認證、額度、接線等確定不可恢復的異常）。**中止不是護欄**：東西壞了，去查環境。"""
    return 結束(結束代碼.中止, f"{名稱}確定失敗")


def _沒給結論就中止(名稱: str) -> 結束:
    """讀不出約定的判定標記。**fail-closed：讀不出來跟「它說可以」是兩件事。**"""
    return 結束(
        結束代碼.中止,
        f"{名稱}沒給判定（要 REVIEW: PASS 或 REVIEW: CHANGES-REQUESTED）——不准當成通過",
    )


