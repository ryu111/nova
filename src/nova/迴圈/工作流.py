"""工作流的執行器：照狀態機走，走到結束為止。

七欄位契約（§3.2）在這裡的落點：

| 欄位 | 這裡是什麼 |
|---|---|
| Trigger | 呼叫 `跑工作流` |
| Goal | 走到 `結束(完成)` |
| Memory | `軌跡`——每一步的結果，下一步看得到 |
| Action policy | 狀態機的轉移表，只准走表上有的路 |
| Evidence | 每步的 `步驟結果`（終局＋判準紅綠＋證據） |
| Feedback | 紅掉時退回哪個階段，由表決定 |
| **Stop rule** | `停止條件`（步數上限＋token 上限）——**缺它的不是迴圈，是成本漏洞** |

`執行一步` 是參數不是內建：高層決定需要什麼形狀，低層去符合（依賴反轉）。
所以這支 runner 的測試不必碰任何 LLM 或子程序。
"""

