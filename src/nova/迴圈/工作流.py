"""工作流的執行器：照狀態機走，走到結束為止。

七欄位契約（§3.2）在這裡的落點：

| 欄位 | 這裡是什麼 |
|---|---|
| Trigger | 呼叫 `跑工作流` |
| Goal | 走到 `結束(完成)` |
| Memory | `軌跡`——每一步的結果，下一步看得到 |
| Action policy | 狀態機的轉移表，只准走表上有的路 |
| Evidence | 每步的 `步驟結果`（終局＋判準紅綠＋證據） |
| Feedback | 紅掉時退回哪個階段，由表決定 |
| **Stop rule** | `最多步數`——**缺它的不是迴圈，是成本漏洞** |

`執行一步` 是參數不是內建：高層決定需要什麼形狀，低層去符合（依賴反轉）。
所以這支 runner 的測試不必碰任何 LLM 或子程序。
"""

from dataclasses import dataclass

from nova.契約.工作流 import (
    任務,
    判準,
    執行器,
    步驟結果,
    種類,
    結束,
    結束代碼,
    階段代碼,
    階段定義,
)
from nova.契約.模型回應 import 終局
from nova.契約.角色 import 角色
from nova.迴圈.狀態機 import TDD階段表, 下一步, 查階段

預設最多步數 = 12


@dataclass(frozen=True, slots=True)
class 工作流結果:
    """走完之後的全部證據。"""

    結束: 結束
    軌跡: tuple[步驟結果, ...]


def 跑工作流(
    任務: 任務,
    *,
    執行一步: 執行器,
    階段表: tuple[階段定義, ...] = TDD階段表,
    起點: 階段代碼 = 階段代碼.測試,
    最多步數: int = 預設最多步數,
) -> 工作流結果:
    """從起點開始走，走到結束或撞到步數上限。

    上限不是保險，是 stop rule 本身：`驗證紅` 沒紅會退回 `測試`、
    `驗證綠` 沒綠會退回 `實作`，兩條回頭邊都可能來回不停。
    """
    del 階段表  # 目前只有一張表；留參數是為了之後換表，不是為了現在用
    軌跡: list[步驟結果] = []
    目前: 階段代碼 | 結束 = 起點
    for _ in range(最多步數):
        if isinstance(目前, 結束):
            return 工作流結果(結束=目前, 軌跡=tuple(軌跡))
        定義 = 查階段(目前)
        結果 = 執行一步(定義, 任務, tuple(軌跡))
        軌跡.append(結果)
        目前 = 下一步(定義, 結果)
    if isinstance(目前, 結束):
        return 工作流結果(結束=目前, 軌跡=tuple(軌跡))
    收尾 = 結束(結束代碼.中止, f"超過最多步數 {最多步數}，停止（沒有停止條件的迴圈是成本漏洞）")
    return 工作流結果(結束=收尾, 軌跡=tuple(軌跡))


def 建TDD執行器(*, 測試: 角色, 實作: 角色, 審查: 角色, 跑判準: 判準) -> 執行器:
    """把四個零件接成一個執行器。

    這就是 `BaseWorkflow(task, 測試, 實作, 驗證, review)` 的形狀——但**驗證不是角色**，
    是機械判準（硬規則 4：不得讓同一個模型自寫自評）。而且它出現兩次：
    實作之前確認測試真的紅了，實作之後確認全綠了。

    `審查` 應該給**另一顆腦**——自己審自己等於沒審。這條目前是呼叫端的責任。
    """
    角色表: dict[階段代碼, 角色] = {
        階段代碼.測試: 測試,
        階段代碼.實作: 實作,
        階段代碼.審查: 審查,
    }

    def 執行一步(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> 步驟結果:
        if 定義.種類 is 種類.判準:
            綠, 證據 = 跑判準(任)
            return 步驟結果(階段=定義.代碼, 終局=終局.成功, 判準綠=綠, 證據=證據)
        答 = 角色表[定義.代碼].做(_提示(定義, 任, 軌跡), 工作目錄=任.工作目錄)
        return 步驟結果(階段=定義.代碼, 終局=答.終局, 判準綠=None, 證據=答.文字)

    return 執行一步


def _提示(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> str:
    """給角色的提示：這次的任務 ＋ 上一步的證據（Memory）。

    只帶**上一步**，不重播全部——重播整段歷史會讓 context 隨輪數線性膨脹。
    """
    段落 = [f"任務：{任.描述}", f"你現在的階段：{定義.名稱}"]
    if 軌跡:
        上一步 = 軌跡[-1]
        段落.append(f"上一步（{上一步.階段}）的結果：\n{上一步.證據}")
    return "\n\n".join(段落)
