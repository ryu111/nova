@dataclass(frozen=True, slots=True)
class 工作流結果:
    """走完之後的全部證據。"""

    結束: 結束
    軌跡: tuple[步驟結果, ...]


type 結果未知判定器 = Callable[[任務, 階段代碼], 工作區判定 | str]
#: 拍下工作區現況。**這支不知道那是碰硬碟做到的**，它只要「拍一張、之後比得出有沒有動過」。
type 拍快照器 = Callable[[Path], Mapping[str, str]]
#: 兩張快照差在哪幾個測試檔。**這支不知道「什麼算測試」是怎麼判的**，那是載體的知識。
type 動測試偵測器 = Callable[[Mapping[str, str], Mapping[str, str]], tuple[str, ...]]
#: 給幾個測試檔，做一個「只驗這幾支」的判準。**這支不知道判準是跑 pytest 做到的**。
type 指定測試判準工廠 = Callable[[tuple[str, ...]], 判準]
#: 篩出能作為指定測試目標的檔案。**這支不知道排除規則是 pytest 或負控登記的知識**，由載體注入。
type 測試檔篩選器 = Callable[[str], bool]

#: 這幾階的角色**不准動測試**：實作員（`角色提示.py` 第 2 條）與重構員（第 1 條）。
#: 判準是角色不是階段名——測試員那一階的工作就是寫測試，所以它不在這裡；
#: 做成階段盲的話第一階就會把自己擋死。
不准動測試的階段 = frozenset({階段代碼.實作, 階段代碼.重構})

#: 這幾階跑完要比對 `tests/`。比對的**用途兩種**：不准動測試的那幾階拿它收護欄，
#: 測試階段拿它回答「這一輪新寫的是哪幾支」——`驗證紅` 只准驗那幾支。
要比對測試的階段 = 不准動測試的階段 | {階段代碼.測試}


@dataclass(frozen=True, slots=True)
class _測試護欄:
    """比對測試檔要用的兩個能力。**它們是成對的**：少一個就沒有護欄可言。

    綁成一顆帶著走，「這一輪到底有沒有接上護欄」就只判一次（`_建測試護欄`），
    而不是拍快照前判一次、比對時再判一次。
    """

    拍快照: 拍快照器
    動到測試了嗎: 動測試偵測器


class 工作區判定器(Protocol):
    """唯讀查一次工作區，交出結構化判定。同上：怎麼查是低層的事，高層只宣告形狀。

    形狀寫全（前兩個位置參數、兩個關鍵字參數都列出來），不用 `Callable[..., 工作區判定]`：
    `...` 等於不檢查，傳錯參數要等到執行期才知道。
    """

    def __call__(
        self,
        任: 任務,
        階段: 階段代碼,
        /,
        *,
        前快照: Mapping[str, str] | None = None,
        階段表: tuple[階段定義, ...] | None = None,
    ) -> 工作區判定:
        """查一次工作區，回結構化判定。"""
        ...


def 跑工作流(  # noqa: PLR0913, PLR0911 —— 唯讀收場注入點；每種護欄各自一個收場
    任務: 任務,
    *,
    執行一步: 執行器,
    階段表: tuple[階段定義, ...] = TDD階段表,
    起點: 階段代碼 = 階段代碼.測試,
    停止: 停止條件 = 預設停止,
    結果未知判定: 結果未知判定器 | None = None,
    拍快照: 拍快照器 | None = None,
    動到測試了嗎: 動測試偵測器 | None = None,
    判定工作區: 工作區判定器 | None = None,
) -> 工作流結果:
    """從起點開始走，走到結束、撞到步數上限、或花完預算為止。

    上限不是保險，是 stop rule 本身：`驗證紅` 沒紅會退回 `測試`、
    `驗證綠` 沒綠會退回 `實作`，兩條回頭邊都可能來回不停。

    **步數與 token 是兩個不同的洞。** 步數擋「來回幾次」，token 擋「花多少」——
    一步可以很貴，十二步的上限對成本沒有任何保證。

    **三個不同的洞，所以是三個閘**：步數擋「來回幾次」、token 擋「花多少」、
    `卡住了` 擋「來回但沒在動」。前兩個是硬上限，第三個是**沒進展就提早停**——
    光有步數上限的話，同一個判準吐一模一樣的紅可以合法燒到第 20 步。

    預算是累計式的：每次回來加總，**下一次呼叫之前**擋下。擋不到「這一次會花多少」
    （那要等它回來才知道），所以最後一步一定會超出一點。誠實的上限，不是精準的上限。

    `階段表` 真的是走的那張表：這支不認全域的 `TDD階段表`，只認參數。
    收下卻不用等於**靜默忽略**——呼叫端拿到一次照舊的跑法，而且沒有任何訊號。

    `結果未知判定` 只在結果未知時呼叫一次；不傳時改用 `判定工作區`（連同 `拍快照`
    拍下的前後對照）交出工作區證據。

    **`拍快照` 與 `判定工作區` 是參數不是 import**：這支只需要「拍一張快照」與
    「唯讀判一次工作區」兩個動作，不需要知道那是碰硬碟、跑 git、跑閘做到的
    （依賴反轉：高層宣告形狀，低層去符合）。兩個都不傳＝這一輪沒有查證能力，
    結果未知時就只說得出「未知」——**誠實的退化，不是靜默的退化**：
    收尾訊息會直說沒有接上判定，而不是假裝查過了。
    """
    索引 = 建索引(階段表)
    _檢查階段表(索引, 起點)
    測試護欄 = _建測試護欄(拍快照, 動到測試了嗎)
    軌跡: list[步驟結果] = []
    工作區雜湊們: list[str | None] = []
    已花token = 0
    目前: 階段代碼 | 結束 = 起點
    # 這張前快照是給「結果未知走到注入的 `判定工作區`」用的；其餘情況拍了沒人看。
    # **測試護欄的那張是另一回事**：它每一個要比對的階段都要拍，只是拍到這張就借來用
    # （`_跑之前拍測試快照` 的 `已拍的`），不重讀一次整棵樹。
    這輪的拍快照器 = 拍快照 if 結果未知判定 is None and 判定工作區 is not None else None
    for _ in range(停止.最多步數):
        if isinstance(目前, 結束):
            return 工作流結果(結束=目前, 軌跡=tuple(軌跡))
        軌跡快照 = tuple(軌跡)
        # **判準階段不叫模型、花費是 0**，不該被預估擋下——擋了它就等於
        # 「因為下一個模型階段太貴，所以連免費的驗證都不准跑」，那是擋錯東西。
        估 = 0 if 索引[目前].種類 is 種類.判準 else _估下一階(軌跡快照)
        剩餘階數 = _算剩餘階數(階段表, 目前)
        預算不足原因 = _預算不夠(已花token, 停止.最多token, 估, 剩餘階數)
        if 預算不足原因 is not None:
            收尾 = 結束(
                結束代碼.護欄,
                f"{預算不足原因}——停在「{索引[目前].名稱}」之前（沒有預算上限的迴圈是成本漏洞）",
            )
            return 工作流結果(結束=收尾, 軌跡=tuple(軌跡))
        護欄原因 = 連續審查要求修改(軌跡快照) or 卡住了(
            軌跡快照,
            階段表,
            工作區雜湊們=tuple(工作區雜湊們) if 任務.工作目錄.is_dir() else None,
        )
        if 護欄原因 is not None:
            return 工作流結果(結束=結束(結束代碼.護欄, 護欄原因), 軌跡=軌跡快照)
        定義 = 索引[目前]
        # 必須在執行一步之前拍快照，事後拍就分不出沒被動過。
        前快照 = 這輪的拍快照器(任務.工作目錄) if 這輪的拍快照器 is not None else None
        前測試快照 = _跑之前拍測試快照(測試護欄, 定義, 任務.工作目錄, 前快照)
        結果 = 執行一步(定義, 任務, 軌跡快照)
        動過的測試檔 = _跑之後動過哪些測試(測試護欄, 任務.工作目錄, 前測試快照)
        軌跡.append(_記下這輪新寫的測試(結果, 定義, 動過的測試檔))
        工作區雜湊們.append(_工作區雜湊(任務.工作目錄) if 定義.種類 is 種類.判準 else None)
        已花token += _這步燒了多少token(結果)
        if 結果.終局 is 終局.結果未知:
            return 工作流結果(
                結束=_結果未知收場(任務, 定義, 結果未知判定, 前快照, 階段表, 判定工作區=判定工作區),
                軌跡=tuple(軌跡),
            )
        # 「這一步跑完就得停」的兩種收場：動了測試、單次爆量。判準各自在自己的函式裡。
        跑完就停 = _動了測試就收護欄(定義, 動過的測試檔) or _單次超支(定義, 結果, 停止)
        if 跑完就停 is not None:
            return 工作流結果(結束=跑完就停, 軌跡=tuple(軌跡))
        目前 = 下一步(定義, 結果)
    if isinstance(目前, 結束):
        return 工作流結果(結束=目前, 軌跡=tuple(軌跡))
    收尾 = 結束(
        結束代碼.護欄, f"超過最多步數 {停止.最多步數}，停止（沒有停止條件的迴圈是成本漏洞）"
    )
    return 工作流結果(結束=收尾, 軌跡=tuple(軌跡))


def _建測試護欄(拍快照: 拍快照器 | None, 動到測試了嗎: 動測試偵測器 | None) -> _測試護欄 | None:
    """兩個能力任缺一個就等於這一輪沒有測試護欄——**誠實的退化**：照舊跑，不假裝擋過。"""
    if 拍快照 is None or 動到測試了嗎 is None:
        return None
    return _測試護欄(拍快照=拍快照, 動到測試了嗎=動到測試了嗎)


def _跑之前拍測試快照(
    護欄: _測試護欄 | None,
    定義: 階段定義,
    工作目錄: Path,
    已拍的: Mapping[str, str] | None,
) -> Mapping[str, str] | None:
    """要比對測試的階段，在跑之前拍一張；不比的階段回 `None`（跑之後也就跳過）。

    事後才拍就分不出有沒有被動過，所以這張一定要在 `執行一步` 之前拍。
    `已拍的`：這一步為了「結果未知」已經拍過一張就借來用，不要再讀一次整棵樹。
    """
    if 護欄 is None or 定義.代碼 not in 要比對測試的階段:
        return None
    return 已拍的 if 已拍的 is not None else 護欄.拍快照(工作目錄)


def _跑之後動過哪些測試(
    護欄: _測試護欄 | None,
    工作目錄: Path,
    前測試快照: Mapping[str, str] | None,
) -> tuple[str, ...]:
    """跑完之後再拍一張比對，回傳這一步動過哪幾個測試檔。沒接護欄就回空。"""
    if 護欄 is None or 前測試快照 is None:
        return ()
    return 護欄.動到測試了嗎(前測試快照, 護欄.拍快照(工作目錄))


def _記下這輪新寫的測試(結果: 步驟結果, 定義: 階段定義, 動過的測試檔: tuple[str, ...]) -> 步驟結果:
    """測試階段動過哪幾支要寫進軌跡——`驗證紅` 就是靠這份清單知道要驗哪幾支。

    其餘階段原樣回傳：它們動測試是違規（`_動了測試就收護欄`），不是這一輪的題目。
    """
    if 定義.代碼 is not 階段代碼.測試:
        return 結果
    return replace(結果, 動過的測試檔=動過的測試檔)


def _動了測試就收護欄(定義: 階段定義, 動了: tuple[str, ...]) -> 結束 | None:
    """不准動測試的那幾階動了測試就交出護欄收場，其餘（含測試員）回 `None`。

    **收護欄不是收紅**：紅會讓它回去再改一次測試，那是拿更多錢餵同一個作弊。
    原因要指名哪幾個檔——「有測試被動了」不可行動，人還得自己去 diff。
    """
    if 定義.代碼 not in 不准動測試的階段 or not 動了:
        return None
    return 結束(
        結束代碼.護欄,
        f"「{定義.名稱}」這一步動了測試檔：{'、'.join(動了)}"
        "——測試是驗收機制，動它等於自己給自己發及格證，這一步不算數",
    )


def _這步燒了多少token(結果: 步驟結果) -> int:
    """一步的新鮮 token；沒有花費（判準階段不叫模型）當 0。"""
    return 結果.花費.新鮮token if 結果.花費 is not None else 0


def _單次超支(定義: 階段定義, 結果: 步驟結果, 停止: 停止條件) -> 結束 | None:
    """這一次呼叫是不是自己就爆了單次上限。沒爆回 `None`。"""
    單次token = _這步燒了多少token(結果)
    if 單次token <= 停止.單次最多token:
        return None
    return 結束(
        結束代碼.護欄,
        f"單次呼叫花費 {單次token} token，達到單次上限 {停止.單次最多token}"
        f"——停在「{定義.名稱}」之後（沒有單次上限的呼叫是成本漏洞）",
    )


def _算剩餘階數(階段表: tuple[階段定義, ...], 目前: 階段代碼) -> int:
    """算出從目前階段起，階段表還有幾個階段。"""
    目前位置 = next(位置 for 位置, 定義 in enumerate(階段表) if 定義.代碼 is 目前)
    return len(階段表) - 目前位置


def _工作區雜湊(工作目錄: Path) -> str | None:
    """以檔案路徑與內容雜湊組出工作區快照，忽略執行時快取。"""
    if not 工作目錄.is_dir():
        return None
    總雜湊 = sha256()
    for 檔案 in sorted(工作目錄.rglob("*")):
        相對路徑 = 檔案.relative_to(工作目錄)
        if not 檔案.is_file() or any(
            片段 in {".git", ".venv", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache"}
            for 片段 in 相對路徑.parts
        ):
            continue
        if 檔案.name == ".coverage":
            continue
        總雜湊.update(str(相對路徑).encode("utf-8"))
        總雜湊.update(sha256(檔案.read_bytes()).digest())
    return 總雜湊.hexdigest()


def _結果未知收場(  # noqa: PLR0913 —— 唯讀判定的相依都是參數，收成物件只是換個地方列
    任務: 任務,
    定義: 階段定義,
    唯讀判定: 結果未知判定器 | None,
    前快照: Mapping[str, str] | None,
    階段表: tuple[階段定義, ...],
    *,
    判定工作區: 工作區判定器 | None,
) -> 結束:
    """結果未知時只做一次唯讀判定；判定失敗仍維持未知。

    掛住（hang）不在這裡處理：跑閘目前無逾時參數，需由外部程序監控。
    """
    收尾 = 結束(結束代碼.護欄, f"{定義.名稱}的結果未知，不准自動重試")
    try:
        證據: 工作區判定 | str
        if 唯讀判定 is not None:
            證據 = 唯讀判定(任務, 定義.代碼)
        elif 判定工作區 is not None:
            證據 = 判定工作區(任務, 定義.代碼, 前快照=前快照, 階段表=階段表)
        else:
            return 結束(收尾.代碼, f"{收尾.原因}；沒有接上唯讀判定，查不了工作區")
    except Exception as 錯:  # noqa: BLE001 —— 唯讀查詢失敗（包含簽章或檢查拋錯）仍要 fail-closed 交出未知證據
        理由 = str(錯) or type(錯).__name__
        return 結束(收尾.代碼, f"{收尾.原因}；唯讀判定失敗，仍為未知：{理由}")
    證據文字 = _工作區判定文字(證據) if isinstance(證據, 工作區判定) else 證據
    return 結束(收尾.代碼, f"{收尾.原因}；唯讀判定：{證據文字}")


def _工作區判定文字(判定: 工作區判定) -> str:
    """把結構化工作區判定格式化成收尾訊息。"""
    if 判定.狀態 is 工作區狀態.綠:
        文字 = f"工作區綠：{'、'.join(判定.綠的)}"
    elif 判定.狀態 is 工作區狀態.紅:
        文字 = f"工作區紅：{'、'.join(判定.紅的)}"
    else:
        文字 = "工作區沒被動過"
    if 判定.未跑的階段:
        尚未 = "、".join(階段.name for 階段 in 判定.未跑的階段)
        文字 += f"；尚未執行：{尚未}"
    return 文字


def _預算不夠(已花: int, 上限: int, 估: int, 剩餘階數: int) -> str | None:
    """下一階跑不跑得起。跑不起就回一句**說得出理由**的話，跑得起回 `None`。

    **兩個條件都要，各擋各的**：

    - `已花 >= 上限`：已經花到上限。`上限=0`（一步都不准跑）也靠這條——
      事前那條在第一階沒有歷史可估，`0 + 0 > 0` 是 False，攔不住。
    - `已花 + 估 > 上限`：**事前擋**，不要跑完才發現超支。

    少了第一條，「預算 0」這個明確的指令會被忽略；
    少了第二條，就退回「跑完才發現」——實測那次多燒了 253,486 token。
    """
    if 已花 >= 上限:
        return f"已花 {已花} token，達到上限 {上限}"
    if 已花 + 估 > 上限:
        剩餘token = 剩餘階數 * 估
        建議上限 = _向上取整到百萬(已花 + 剩餘token)
        return (
            f"已花 {已花} token，上一個模型階段花了 {估}，再跑一階預估會超過上限 {上限}"
            f"——剩下 {剩餘階數} 階、照這一階的花費估要再 {剩餘token} token，"
            f"整輪抓 `--最多token {建議上限}` 重跑"
        )
    return None


def _向上取整到百萬(token: int) -> int:
    """把 token 預算向上取整到百萬。"""
    return (token + 999_999) // 1_000_000 * 1_000_000


def _估下一階(軌跡: tuple[步驟結果, ...]) -> int:
    """下一階大概要花多少。**用觀測到的成本，不是猜的。**

    取**最近一次非零**的花費，不是「上一階」：判準階段不叫模型、花費是 `None`，
    拿它當估計等於沒估——事前擋就退化回「事後才發現超支」。

    為什麼需要估：實測一輪重構工作流，`refactor` 花 498,053、`review` 花 555,433，
    累計 1,053,486 撞上 800,000 的上限。**護欄是在 review 跑完之後才發現的**，
    多燒了 253,486。而進 review 之前已經花掉 498,053、只剩 301,947——
    上一階的成本就在眼前，事前擋得下來。

    **這不是把上限調高**（那是拆執法點），是把同一個上限提早生效。
    第一階沒有歷史可用，回 0 ＝ 照舊只擋「已經超了」，這是誠實的退化不是漏洞。
    """
    for 步 in reversed(軌跡):
        這步 = _這步燒了多少token(步)
        if 這步 > 0:
            return 這步
    return 0


def _檢查階段表(索引: Mapping[階段代碼, 階段定義], 起點: 階段代碼) -> None:
    """接不起來的表在開跑前就炸，不要走到那一步才 `KeyError`——那時 token 已經花掉了。

    **理由跟 `_檢查角色表` 同一套**，只是這次少的是一條邊不是一個角色。
    `階段表` 是參數，所以它可能是呼叫端現組的：指到表外的階段、
    起點根本不在表上，都是接線錯誤，而且都要在花錢之前講清楚是哪一格。

    出口窮不窮舉不歸這裡管——那是 `階段定義` 建構當場就擋掉的事。
    """
    壞: list[str] = []
    if 起點 not in 索引:
        壞.append(f"起點 {起點.value} 不在表上")
    for 定義 in 索引.values():
        for 標籤, 去處 in 定義.出口.items():
            if not isinstance(去處, 結束) and 去處 not in 索引:
                壞.append(f"{定義.代碼.value} 的「{標籤.value}」指向表外的 {去處.value}")
    if 壞:
        訊息 = f"階段表接不起來：{'、'.join(壞)}"
        raise ValueError(訊息)


def _檢查角色表(角色表: Mapping[階段代碼, 角色]) -> None:
    """少接一格就當場炸，不要等跑到那一階才 `KeyError`——那時 token 已經花掉了。

    **要哪些階段是從 `TDD階段表` 推導的**，不是寫死四個：寫死的話，
    下次加階段忘了回來改守衛，又回到「跑到一半才發現沒接線」。
    """
    缺 = [
        定義.代碼.value
        for 定義 in TDD階段表
        if 定義.種類 is not 種類.判準 and 定義.代碼 not in 角色表
    ]
    if 缺:
        訊息 = f"角色表少了這些階段：{'、'.join(缺)}"
        raise ValueError(訊息)


def _兩條都要綠(
    *, pytest結果: tuple[判準終局, str], ruff結果: tuple[判準終局, str]
) -> tuple[判準終局, str]:
    """`驗證重構` 兩條都要綠。**紅的那條擺證據前面**——人先看到的該是壞掉的那個。

    「跑不起來」蓋過「紅」：那不是重構弄壞了什麼，是這一步根本沒跑到。
    """
    pytest收場, pytest證據 = pytest結果
    ruff收場, ruff證據 = ruff結果
    if pytest收場 is 判準終局.紅:
        證據 = f"[pytest] {pytest證據}\n[ruff] {ruff證據}"
    else:
        證據 = f"[ruff] {ruff證據}\n[pytest] {pytest證據}"
    收場們 = (pytest收場, ruff收場)
    if any(項 is 判準終局.跑不起來 for 項 in 收場們):
        return 判準終局.跑不起來, 證據
    if all(項 is 判準終局.綠 for 項 in 收場們):
        return 判準終局.綠, 證據
    return 判準終局.紅, 證據


def _只驗這輪新寫的測試(
    工廠: 指定測試判準工廠 | None,
    軌跡: tuple[步驟結果, ...],
    *,
    篩選: 測試檔篩選器,
) -> tuple[判準, tuple[str, ...]] | None:
    """`驗證紅` 該用的判準：只驗測試階段動過的那幾支。做不到就回 `None`。

    **整套 suite 的非零退出不算「這一輪的測試紅了」**：repo 本來就有一支紅
    （flaky／遺留）的時候，那個非零是別人的紅，而新測試從未被證明會紅。

    兩種做不到的情況都退回全套（**誠實的退化**：照舊跑，不假裝驗過那幾支）——
    沒接工廠、或這一輪動過的檔案過濾掉非測試檔後為空。
    """
    if 工廠 is None:
        return None
    全部檔們 = next(
        (步.動過的測試檔 for 步 in reversed(軌跡) if 步.階段 is 階段代碼.測試 and 步.動過的測試檔),
        (),
    )
    檔們 = tuple(檔 for 檔 in 全部檔們 if 篩選(檔))
    if not 檔們:
        return None
    return 工廠(檔們), 檔們


def 建TDD執行器(
    *,
    角色表: Mapping[階段代碼, 角色],
    跑判準: 判準,
    篩選指定測試: 測試檔篩選器,
    跑重構判準: 判準 | None = None,
    建指定測試判準: 指定測試判準工廠 | None = None,
) -> 執行器:
    """把角色表與機械判準接成一個執行器。

    這就是 `BaseWorkflow(task, 測試, 實作, 驗證, review)` 的形狀——但**驗證不是角色**，
    是機械判準（硬規則 4：不得讓同一個模型自寫自評）。而且它出現兩次：
    實作之前確認測試真的紅了，實作之後確認全綠了。

    `審查` 應該給**另一顆腦**——自己審自己等於沒審。這條目前是呼叫端的責任。
    """
    _檢查角色表(角色表)

    def 跑這階的判準(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> tuple[判準終局, str]:
        """判準階段跑哪一條：`驗證重構` 要 pytest ＋ ruff、`驗證紅` 只驗這輪新寫的、其餘全套。"""
        if 定義.代碼 is 階段代碼.驗證重構 and 跑重構判準 is not None:
            return _兩條都要綠(pytest結果=跑判準(任), ruff結果=跑重構判準(任))
        只驗這輪的 = (
            _只驗這輪新寫的測試(建指定測試判準, 軌跡, 篩選=篩選指定測試)
            if 定義.代碼 is 階段代碼.驗證紅
            else None
        )
        if 只驗這輪的 is not None:
            判, 檔們 = 只驗這輪的
            收場, 原證據 = 判(任)
            # 證據要指名驗了哪幾支：退回測試員時，「哪支該紅而沒紅」才可行動。
            return 收場, f"只驗這一輪動過的測試（{'、'.join(檔們)}）：\n{原證據}"
        return 跑判準(任)

    def 執行一步(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> 步驟結果:
        if 定義.種類 is 種類.判準:
            收場, 證據 = 跑這階的判準(定義, 任, 軌跡)
            if 收場 is 判準終局.跑不起來:
                # **不是紅，是這一步根本沒跑到。** 終局標成結果未知，
                # 狀態機就會收在「結果未知」讓人去查環境，而不是回去再實作一次。
                return 步驟結果(階段=定義.代碼, 終局=終局.結果未知, 判準綠=None, 證據=證據)
            return 步驟結果(
                階段=定義.代碼,
                終局=終局.成功,
                判準綠=收場 is 判準終局.綠,
                證據=證據,
            )
        答 = 角色表[定義.代碼].做(_提示(定義, 任, 軌跡), 工作目錄=任.工作目錄)
        # 失敗時把代碼寫進證據——只給一段自由文字，下游要重建「為什麼失敗」（§4.3）。
        證據 = 答.文字 if 答.終局 is 終局.成功 else f"[{答.失敗代碼.value}] {答.文字}"
        # 審查階段的驗收權在判定上，不在「子程序有沒有跑完」上。
        結論 = 讀審查判定(答.文字) if 定義.種類 is 種類.審查 else None
        return 步驟結果(
            階段=定義.代碼,
            終局=答.終局,
            判準綠=None,
            證據=證據,
            審查結論=結論,
            花費=答.用量,
        )

    return 執行一步


def _提示(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> str:
    """給角色的提示：這次的任務 ＋ 上一步的證據（Memory）；前情與證據都用不可信圍欄包住。

    每一階都帶的只有這裡列的幾段：任務、階段、前情、**上一步**的證據。
    不重播全部——重播整段歷史會讓 context 隨輪數線性膨脹。
    看階段（或看票的種類）才多帶的那幾段收在 `_看階段才帶的段落`。
    """
    提示段落 = [f"任務：{任.描述}", f"你現在的階段：{定義.名稱}"]
    if 任.前情:
        提示段落.append(f"前情（上一輪的進度，這一輪要接著做，不要從頭來）：\n{_包不可信(任.前情)}")
    if 軌跡:
        上一步結果 = 軌跡[-1]
        提示段落.append(f"上一步（{上一步結果.階段}）的結果：\n{_包不可信(上一步結果.證據)}")
    提示段落.extend(_看階段才帶的段落(定義, 任, 軌跡))
    return "\n\n".join(提示段落)


def _看階段才帶的段落(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> list[str]:
    """只有某一階、或只有某一種票才接上的段落，依送出去的先後排好。

    **這幾段都不能住在系統提示裡**：系統提示一次建好、每輪不變，
    而這裡每一段都是 per-round 或 per-ticket 的。

    - 再次審查：另外帶上次審查與其後的實作回報。
    - 測試員遇上「新增保證」的票：多一段固定負控登記。負控只接給測試員——
      它本來就能寫測試檔；接給實作員等於教它去撞「不准動測試檔」的護欄。
    - 實作員：這一輪的讀取策略。首輪禁跑全測試（省 token），
      被退回的那一輪反過來要它跑——它要修的正是全測試的紅。
    """
    段落: list[str] = []
    if 定義.代碼 is 階段代碼.審查:
        上次審查回顧 = _上次審查與實作回報(軌跡)
        if 上次審查回顧 is not None:
            段落.append(上次審查回顧)
    if 定義.代碼 is 階段代碼.測試 and 任.新增保證:
        段落.append(角色提示.測試員負控段落)
    if 定義.代碼 is 階段代碼.實作:
        被退回 = bool(軌跡) and 是回頭邊(軌跡[-1].階段, 定義.代碼)
        段落.append(角色提示.這一輪的讀取策略(被退回=被退回))
    return 段落


def _上次審查與實作回報(軌跡: tuple[步驟結果, ...]) -> str | None:
    """整理再次審查需要的上一輪審查與其後實作回報。"""
    上次審查索引 = next(
        (索引 for 索引 in range(len(軌跡) - 1, -1, -1) if 軌跡[索引].階段 is 階段代碼.審查),
        None,
    )
    if 上次審查索引 is None:
        return None

    上次審查 = 軌跡[上次審查索引]
    上次審查後的實作 = next(
        (步驟 for 步驟 in reversed(軌跡[上次審查索引 + 1 :]) if 步驟.階段 is 階段代碼.實作),
        None,
    )
    審查回顧段落 = [
        "上一次審查與其後實作回報：",
        f"上一次審查：\n{_包不可信(上次審查.證據)}",
    ]
    if 上次審查後的實作 is not None:
        審查回顧段落.append(f"其後實作回報：\n{_包不可信(上次審查後的實作.證據)}")
    return "\n".join(審查回顧段落)


def _包不可信(資料: str) -> str:
    """把上游文字限制在固定的不可信資料圍欄內。

    這是資料邊界衛生，不是完整的提示注入防護牆；模型仍可能服從圍欄內的句子。
    """
    開始標記 = "<<<UNTRUSTED"
    結束標記 = "UNTRUSTED>>>"
    # 清除後可能接合出新標記，因此反覆清除直到沒有 marker。
    while 開始標記 in 資料 or 結束標記 in 資料:
        資料 = 資料.replace(開始標記, "").replace(結束標記, "")
    return f"{開始標記} {資料} {結束標記}"
