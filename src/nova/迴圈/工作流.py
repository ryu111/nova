def _第一次伸手的還原收場(  # noqa: PLR0913, PLR0917 —— 還原所需的階段、工作樹與前後快照
    定義: 階段定義,
    工作目錄: Path,
    動過的測試檔: tuple[str, ...],
    前測試快照: Mapping[str, str] | None,
    軌跡: tuple[步驟結果, ...],
    護欄: _測試護欄 | None,
) -> 結束 | None:
    """第一次伸手就先還原；還原失敗才交出護欄收場。"""
    if not 伸手動了測試(定義.代碼, 動過的測試檔) or _這輪之前伸手過(軌跡):
        return None
    還原失敗 = _還原動過的測試檔(
        護欄,
        工作目錄,
        動過的測試檔,
        前測試快照,
    )
    if 還原失敗 is None:
        return None
    return 結束(
        結束代碼.護欄,
        f"「{定義.名稱}」這一步動了測試檔：{'、'.join(動過的測試檔)}；"
        f"還原失敗：{還原失敗}——不准帶著未還原的改動往下走",
        護欄原因=護欄種類.動了測試,
    )


def _填上這輪動過的測試檔(
    結果: 步驟結果,
    定義: 階段定義,
    動過的測試檔: tuple[str, ...],
    軌跡: tuple[步驟結果, ...],
) -> 步驟結果:
    """測試階段動過哪幾支要寫進軌跡——`驗證紅` 就是靠這份清單知道要驗哪幾支。

    `驗證綠` 帶的是**累計**那一份（`_這輪測試員動過的`）：它的紅要分得出
    「紅的是這一輪新寫的」還是「紅的是既有測試」，而分類器只有拿得到清單
    才比得到東西——沒有它就永遠在跟空集合比，本輪新測試連紅兩次也會被
    誤判成既有測試。**`驗證紅` 那份不跟著累計**（`_只驗這輪新寫的測試` 仍取
    最近一次）：第一輪那幾支這時可能已經綠了，累計會讓驗證紅永遠綠。

    不准動測試的那幾階也記：它們動測試是違規，而「同一輪第幾次違規」只有記在
    軌跡上才數得出來（第一次退回測試員、第二次收護欄）。兩種用途不同、要記的
    東西同一份——**自己這一步動過的那幾支**，也就是 `要比對測試的階段` 全體。
    """
    if 定義.代碼 is 階段代碼.驗證綠:
        return replace(結果, 動過的測試檔=_這輪測試員動過的(軌跡))
    if 定義.代碼 in 要比對測試的階段:
        return replace(結果, 動過的測試檔=動過的測試檔)
    return 結果


def _這輪測試員動過的(軌跡: tuple[步驟結果, ...]) -> tuple[str, ...]:
    """這次跑工作流**所有**測試階動過的檔的聯集（排序去重）；沒有就回空。

    「本輪」是整趟工作流，不是最近一次測試階：測試員被退回一次、第二輪去改
    打架的既有測試之後，第一輪寫的那幾支**仍然是這一輪的產物**，紅在它們
    永遠是實作員的事。只取最近一次的話它們會掉出本輪、被誤算成既有測試，
    等於請測試員去改自己剛寫的那支。
    """
    return tuple(sorted({檔 for 步 in 軌跡 if 步.階段 is 階段代碼.測試 for 檔 in 步.動過的測試檔}))


def _最近一次測試階動過的(軌跡: tuple[步驟結果, ...]) -> tuple[str, ...]:
    """最近一次測試階動過的那幾支；沒有就回空。`驗證紅` 的目標用這份。"""
    return next(
        (步.動過的測試檔 for 步 in reversed(軌跡) if 步.階段 is 階段代碼.測試 and 步.動過的測試檔),
        (),
    )


def _上一步伸手動了測試(軌跡: tuple[步驟結果, ...]) -> bool:
    """剛剛那一步就是「不准動測試的階段動了測試檔」嗎？軌跡空就不是。"""
    return bool(軌跡) and 伸手動了測試(軌跡[-1].階段, 軌跡[-1].動過的測試檔)


def _這輪之前伸手過(軌跡: tuple[步驟結果, ...]) -> bool:
    """同一輪工作流裡，之前已經有哪一步伸手動過測試檔了嗎？（不跨接續票）"""
    return any(伸手動了測試(步.階段, 步.動過的測試檔) for 步 in 軌跡)


def _動了測試就收護欄(
    定義: 階段定義,
    動過的測試檔: tuple[str, ...],
    軌跡: tuple[步驟結果, ...],
) -> 結束 | None:
    """不准動測試的那幾階**同一輪第二次**動測試就交出護欄收場，其餘回 `None`。

    **收護欄不是收紅**：紅會讓它回去再改一次測試，那是拿更多錢餵同一個作弊。
    第一次不收線而是退回測試員：那幾個檔該不該改、怎麼改本來就是測試員的職權，
    這跟「退回實作員再改一次」不是同一件事。再犯才是慣犯。
    原因要指名哪幾個檔——「有測試被動了」不可行動，人還得自己去 diff。
    """
    # 條件的字面是負控登記（`tests/負控/登記們/動測試護欄.py`）的變異錨點，
    # 改寫法（例如抽成 `再犯 = …`）會讓那一刀對不上原始碼，變 RUN_ERROR 而不是 KILLED。
    if not 伸手動了測試(定義.代碼, 動過的測試檔) or not _這輪之前伸手過(軌跡):
        return None
    return 結束(
        結束代碼.護欄,
        f"「{定義.名稱}」這一步動了測試檔：{'、'.join(動過的測試檔)}"
        "——測試是驗收機制，動它等於自己給自己發及格證，這一步不算數",
        護欄原因=護欄種類.動了測試,
    )


def _這步燒了多少token(結果: 步驟結果) -> int:
    """一步的新鮮 token；沒有花費（判準階段不叫模型）當 0。"""
    return 結果.花費.新鮮token if 結果.花費 is not None else 0


def _單次超支(定義: 階段定義, 結果: 步驟結果, 停止: 停止條件) -> 結束 | None:
    """這一次呼叫是不是自己就爆了單次上限。沒爆回 `None`。"""
    單次token = _這步燒了多少token(結果)
    if 單次token <= 停止.單次最多token:
        return None
    return 結束(
        結束代碼.護欄,
        f"單次呼叫花費 {單次token} token，達到單次上限 {停止.單次最多token}"
        f"——停在「{定義.名稱}」之後（沒有單次上限的呼叫是成本漏洞）",
        護欄原因=護欄種類.預算,
    )


def _算剩餘階數(階段表: tuple[階段定義, ...], 目前: 階段代碼) -> int:
    """算出從目前階段起，階段表還有幾個階段。"""
    目前位置 = next(位置 for 位置, 定義 in enumerate(階段表) if 定義.代碼 is 目前)
    return len(階段表) - 目前位置


def _工作區雜湊(工作目錄: Path) -> str | None:
    """以檔案路徑與內容雜湊組出工作區快照，忽略執行時快取。"""
    if not 工作目錄.is_dir():
        return None
    總雜湊 = sha256()
    for 檔案 in sorted(工作目錄.rglob("*")):
        相對路徑 = 檔案.relative_to(工作目錄)
        if not 檔案.is_file() or any(
            片段 in {".git", ".venv", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache"}
            for 片段 in 相對路徑.parts
        ):
            continue
        if 檔案.name == ".coverage":
            continue
        總雜湊.update(str(相對路徑).encode("utf-8"))
        with 檔案.open("rb") as 內容:
            總雜湊.update(sha256(內容.read()).digest())
    return 總雜湊.hexdigest()


def _結果未知收場(  # noqa: PLR0913 —— 唯讀判定的相依都是參數，收成物件只是換個地方列
    任務: 任務,
    定義: 階段定義,
    唯讀判定: 結果未知判定器 | None,
    前快照: Mapping[str, str] | None,
    階段表: tuple[階段定義, ...],
    *,
    判定工作區: 工作區判定器 | None,
) -> 結束:
    """結果未知時只做一次唯讀判定；判定失敗仍維持未知。

    掛住（hang）不在這裡處理：跑閘目前無逾時參數，需由外部程序監控。
    """
    收尾 = 結束(結束代碼.護欄, f"{定義.名稱}的結果未知，不准自動重試")
    try:
        證據: 工作區判定 | str
        if 唯讀判定 is not None:
            證據 = 唯讀判定(任務, 定義.代碼)
        elif 判定工作區 is not None:
            證據 = 判定工作區(任務, 定義.代碼, 前快照=前快照, 階段表=階段表)
        else:
            return 結束(收尾.代碼, f"{收尾.原因}；沒有接上唯讀判定，查不了工作區")
    except Exception as 錯:  # noqa: BLE001 —— 唯讀查詢失敗（包含簽章或檢查拋錯）仍要 fail-closed 交出未知證據
        理由 = str(錯) or type(錯).__name__
        return 結束(收尾.代碼, f"{收尾.原因}；唯讀判定失敗，仍為未知：{理由}")
    證據文字 = _工作區判定文字(證據) if isinstance(證據, 工作區判定) else 證據
    return 結束(收尾.代碼, f"{收尾.原因}；唯讀判定：{證據文字}")


def _工作區判定文字(判定: 工作區判定) -> str:
    """把結構化工作區判定格式化成收尾訊息。"""
    if 判定.狀態 is 工作區狀態.綠:
        文字 = f"工作區綠：{'、'.join(判定.綠的)}"
    elif 判定.狀態 is 工作區狀態.紅:
        文字 = f"工作區紅：{'、'.join(判定.紅的)}"
    else:
        文字 = "工作區沒被動過"
    if 判定.未跑的階段:
        尚未 = "、".join(階段.name for 階段 in 判定.未跑的階段)
        文字 += f"；尚未執行：{尚未}"
    return 文字


def _預算不夠(已花: int, 上限: int, 估: int, 剩餘階數: int) -> str | None:
    """下一階跑不跑得起。跑不起就回一句**說得出理由**的話，跑得起回 `None`。

    **兩個條件都要，各擋各的**：

    - `已花 >= 上限`：已經花到上限。`上限=0`（一步都不准跑）也靠這條——
      事前那條在第一階沒有歷史可估，`0 + 0 > 0` 是 False，攔不住。
    - `已花 + 估 > 上限`：**事前擋**，不要跑完才發現超支。

    少了第一條，「預算 0」這個明確的指令會被忽略；
    少了第二條，就退回「跑完才發現」——實測那次多燒了 253,486 token。
    """
    if 已花 >= 上限:
        return f"已花 {已花} token，達到上限 {上限}"
    if 已花 + 估 > 上限:
        剩餘token = 剩餘階數 * 估
        建議上限 = _向上取整到百萬(已花 + 剩餘token)
        return (
            f"已花 {已花} token，上一個模型階段花了 {估}，再跑一階預估會超過上限 {上限}"
            f"——剩下 {剩餘階數} 階、照這一階的花費估要再 {剩餘token} token，"
            f"整輪抓 `--最多token {建議上限}` 重跑"
        )
    return None


def _向上取整到百萬(token: int) -> int:
    """把 token 預算向上取整到百萬。"""
    return (token + 999_999) // 1_000_000 * 1_000_000


def _估下一階(軌跡: tuple[步驟結果, ...]) -> int:
    """下一階大概要花多少。**用觀測到的成本，不是猜的。**

    取**最近一次非零**的花費，不是「上一階」：判準階段不叫模型、花費是 `None`，
    拿它當估計等於沒估——事前擋就退化回「事後才發現超支」。

    為什麼需要估：實測一輪重構工作流，`refactor` 花 498,053、`review` 花 555,433，
    累計 1,053,486 撞上 800,000 的上限。**護欄是在 review 跑完之後才發現的**，
    多燒了 253,486。而進 review 之前已經花掉 498,053、只剩 301,947——
    上一階的成本就在眼前，事前擋得下來。

    **這不是把上限調高**（那是拆執法點），是把同一個上限提早生效。
    第一階沒有歷史可用，回 0 ＝ 照舊只擋「已經超了」，這是誠實的退化不是漏洞。
    """
    for 步 in reversed(軌跡):
        這步 = _這步燒了多少token(步)
        if 這步 > 0:
            return 這步
    return 0


def _檢查階段表(索引: Mapping[階段代碼, 階段定義], 起點: 階段代碼) -> None:
    """接不起來的表在開跑前就炸，不要走到那一步才 `KeyError`——那時 token 已經花掉了。

    **理由跟 `_檢查角色表` 同一套**，只是這次少的是一條邊不是一個角色。
    `階段表` 是參數，所以它可能是呼叫端現組的：指到表外的階段、
    起點根本不在表上，都是接線錯誤，而且都要在花錢之前講清楚是哪一格。

    出口窮不窮舉不歸這裡管——那是 `階段定義` 建構當場就擋掉的事。
    """
    壞: list[str] = []
    if 起點 not in 索引:
        壞.append(f"起點 {起點.value} 不在表上")
    for 定義 in 索引.values():
        for 標籤, 去處 in 定義.出口.items():
            if not isinstance(去處, 結束) and 去處 not in 索引:
                壞.append(f"{定義.代碼.value} 的「{標籤.value}」指向表外的 {去處.value}")
    if 壞:
        訊息 = f"階段表接不起來：{'、'.join(壞)}"
        raise ValueError(訊息)


def _檢查角色表(角色表: Mapping[階段代碼, 角色]) -> None:
    """少接一格就當場炸，不要等跑到那一階才 `KeyError`——那時 token 已經花掉了。

    **要哪些階段是從 `TDD階段表` 推導的**，不是寫死四個：寫死的話，
    下次加階段忘了回來改守衛，又回到「跑到一半才發現沒接線」。
    """
    缺 = [
        定義.代碼.value
        for 定義 in TDD階段表
        if 定義.種類 is not 種類.判準 and 定義.代碼 not in 角色表
    ]
    if 缺:
        訊息 = f"角色表少了這些階段：{'、'.join(缺)}"
        raise ValueError(訊息)


def _兩條都要綠(
    *, pytest結果: 判準結果 | tuple[判準終局, str], ruff結果: 判準結果 | tuple[判準終局, str]
) -> 判準結果:
    """`驗證重構` 兩條都要綠。**紅的那條擺證據前面**——人先看到的該是壞掉的那個。

    「跑不起來」蓋過「紅」：那不是重構弄壞了什麼，是這一步根本沒跑到。
    """
    pytest結果 = _轉成判準結果(pytest結果)
    ruff結果 = _轉成判準結果(ruff結果)
    pytest收場, pytest證據 = pytest結果.終局, pytest結果.證據
    ruff收場, ruff證據 = ruff結果.終局, ruff結果.證據
    if pytest收場 is 判準終局.紅:
        證據 = f"[pytest] {pytest證據}\n[ruff] {ruff證據}"
    else:
        證據 = f"[ruff] {ruff證據}\n[pytest] {pytest證據}"
    收場們 = (pytest收場, ruff收場)
    if any(項 is 判準終局.跑不起來 for 項 in 收場們):
        收場 = 判準終局.跑不起來
    elif all(項 is 判準終局.綠 for 項 in 收場們):
        收場 = 判準終局.綠
    else:
        收場 = 判準終局.紅
    return 判準結果(收場, 證據, pytest結果.等待毫秒 + ruff結果.等待毫秒)


def _轉成判準結果(結果: 判準結果 | tuple[判準終局, str]) -> 判準結果:
    """把注入的舊二元組判準補成沒有等待的結構化結果。"""
    if isinstance(結果, 判準結果):
        return 結果
    收場, 證據 = 結果
    return 判準結果(終局=收場, 證據=證據)


def _還在工作樹上(檔: str, 工作目錄: Path | None) -> bool:
    """改名 ＝ 刪＋加：舊路徑餵給 pytest 是 `ERROR: not found`（exit 4）＝ 結果未知。

    護欄的「動過的測試檔」把刪除也算動過（對），但已經不在工作樹上的檔不是
    pytest 收得到的目標。看不到那棵樹時（沒給、或根本不是目錄）就不判斷——
    **誠實的退化**：不知道就別亂濾，濾掉會讓驗證紅少驗一支還說驗過了。
    """
    if 工作目錄 is None or not 工作目錄.is_dir():
        return True
    return (工作目錄 / 檔).is_file()


def _只驗這輪新寫的測試(
    工廠: 指定測試判準工廠 | None,
    軌跡: tuple[步驟結果, ...],
    *,
    篩選: 測試檔篩選器,
    工作目錄: Path | None = None,
) -> tuple[判準, tuple[str, ...]] | None:
    """`驗證紅` 該用的判準：只驗測試階段動過的那幾支。做不到就回 `None`。

    **整套 suite 的非零退出不算「這一輪的測試紅了」**：repo 本來就有一支紅
    （flaky／遺留）的時候，那個非零是別人的紅，而新測試從未被證明會紅。

    兩種做不到的情況都退回全套（**誠實的退化**：照舊跑，不假裝驗過那幾支）——
    沒接工廠、或這一輪動過的檔案濾完就空了（濾掉 pytest 收不到的檔，
    以及已經不在工作樹上的舊路徑）。

    目標取的是**最近一次**測試階動過的那幾支，不是整趟的聯集（聯集只餵給
    `驗證綠` 的分類器）：測試員被退回、第二輪只改打架的既有測試時，第一輪
    那幾支多半已經被實作員弄綠，一起驗會把「這一輪的測試真的紅了嗎」稀釋
    成誤判的綠。
    """
    if 工廠 is None:
        return None
    檔們 = tuple(
        檔 for 檔 in _最近一次測試階動過的(軌跡) if 篩選(檔) and _還在工作樹上(檔, 工作目錄)
    )
    if not 檔們:
        return None
    return 工廠(檔們), 檔們


def 建TDD執行器(
    *,
    角色表: Mapping[階段代碼, 角色],
    跑判準: 判準,
    篩選指定測試: 測試檔篩選器,
    跑重構判準: 判準 | None = None,
    建指定測試判準: 指定測試判準工廠 | None = None,
) -> 執行器:
    """把角色表與機械判準接成一個執行器。

    這就是 `BaseWorkflow(task, 測試, 實作, 驗證, review)` 的形狀——但**驗證不是角色**，
    是機械判準（硬規則 4：不得讓同一個模型自寫自評）。而且它出現兩次：
    實作之前確認測試真的紅了，實作之後確認全綠了。

    `審查` 應該給**另一顆腦**——自己審自己等於沒審。這條目前是呼叫端的責任。
    """
    _檢查角色表(角色表)

    def 跑這階的判準(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> 判準結果:
        """判準階段跑哪一條：`驗證重構` 要 pytest ＋ ruff、`驗證紅` 只驗這輪新寫的、其餘全套。"""
        if 定義.代碼 is 階段代碼.驗證重構 and 跑重構判準 is not None:
            return _兩條都要綠(pytest結果=跑判準(任), ruff結果=跑重構判準(任))
        只驗這輪的 = (
            _只驗這輪新寫的測試(建指定測試判準, 軌跡, 篩選=篩選指定測試, 工作目錄=任.工作目錄)
            if 定義.代碼 is 階段代碼.驗證紅
            else None
        )
        if 只驗這輪的 is not None:
            判, 檔們 = 只驗這輪的
            結果 = _轉成判準結果(判(任))
            # 證據要指名驗了哪幾支：退回測試員時，「哪支該紅而沒紅」才可行動。
            return 判準結果(
                終局=結果.終局,
                證據=f"只驗這一輪動過的測試（{'、'.join(檔們)}）：\n{結果.證據}",
                等待毫秒=結果.等待毫秒,
            )
        return _轉成判準結果(跑判準(任))

    def 執行一步(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> 步驟結果:
        if 定義.種類 is 種類.判準:
            結果 = 跑這階的判準(定義, 任, 軌跡)
            if 結果.終局 is 判準終局.跑不起來:
                # **不是紅，是這一步根本沒跑到。** 終局標成結果未知，
                # 狀態機就會收在「結果未知」讓人去查環境，而不是回去再實作一次。
                證據 = 結果.證據
                if not 結果.等待毫秒:
                    return 步驟結果(階段=定義.代碼, 終局=終局.結果未知, 判準綠=None, 證據=證據)
                return 步驟結果(
                    階段=定義.代碼,
                    終局=終局.結果未知,
                    判準綠=None,
                    證據=證據,
                    等待毫秒=結果.等待毫秒,
                )
            return 步驟結果(
                階段=定義.代碼,
                終局=終局.成功,
                判準綠=結果.終局 is 判準終局.綠,
                證據=結果.證據,
                等待毫秒=結果.等待毫秒,
            )
        答 = 角色表[定義.代碼].做(_提示(定義, 任, 軌跡), 工作目錄=任.工作目錄)
        # 失敗時把代碼寫進證據——只給一段自由文字，下游要重建「為什麼失敗」（§4.3）。
        證據 = 答.文字 if 答.終局 is 終局.成功 else f"[{答.失敗代碼.value}] {答.文字}"
        # 審查階段的驗收權在判定上，不在「子程序有沒有跑完」上。
        結論 = 讀審查判定(答.文字) if 定義.種類 is 種類.審查 else None
        return 步驟結果(
            階段=定義.代碼,
            終局=答.終局,
            判準綠=None,
            證據=證據,
            審查結論=結論,
            花費=答.用量,
        )

    return 執行一步


def _提示(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> str:
    """給角色的提示：這次的任務 ＋ 上一步的證據（Memory）；前情與證據都用不可信圍欄包住。

    每一階通常帶的只有這裡列的幾段：任務、階段、前情、**上一步**的證據。
    伸手動測試檔退回測試員時不帶通用前情，只接檔名清單，避免把實作員的改法帶過去。
    不重播全部——重播整段歷史會讓 context 隨輪數線性膨脹。
    看階段（或看票的種類）才多帶的那幾段收在 `_看階段才帶的段落`。
    """
    提示段落 = [f"任務：{任.描述}", f"你現在的階段：{定義.名稱}"]
    if 任.前情 and not (定義.代碼 is 階段代碼.測試 and _上一步伸手動了測試(軌跡)):
        提示段落.append(f"前情（上一輪的進度，這一輪要接著做，不要從頭來）：\n{_包不可信(任.前情)}")
    if 軌跡:
        給這一階的證據 = _上一步給這一階看的證據(定義, 軌跡)
        if 給這一階的證據 is not None:
            提示段落.append(f"上一步（{軌跡[-1].階段}）的結果：\n{_包不可信(給這一階的證據)}")
    提示段落.extend(_看階段才帶的段落(定義, 任, 軌跡))
    return "\n\n".join(提示段落)


def _上一步給這一階看的證據(定義: 階段定義, 軌跡: tuple[步驟結果, ...]) -> str | None:
    """一般情況原樣帶上一步的證據；退回測試員那條路上要濾掉新測試的 `FAILED` 行。

    那幾支紅是實作員的事——把它們一起丟給測試員，等於請它去改自己剛寫的測試。

    上一步是**伸手動了測試檔**的那一步時整段不帶（回 `None`）：那份回報會原封不動地
    說「我把哪支斷言改鬆了、改成什麼」，流到測試員手上等於把作弊稿抄給它。
    測試員要看的只有檔名清單，那一段另外接（`_實作員動過測試的前情`）。
    """
    上一步證據 = 軌跡[-1].證據
    if 定義.代碼 is not 階段代碼.測試:
        return 上一步證據
    if _上一步伸手動了測試(軌跡):
        return None
    既有紅 = _上一步紅在哪些既有測試(軌跡)
    if not 既有紅:
        return 上一步證據
    return _只留既有測試的失敗行(上一步證據, frozenset(既有紅))


def _只留既有測試的失敗行(證據: str, 既有紅: frozenset[str]) -> str:
    """認得出 nodeid 的 `FAILED` 行只留既有測試那幾支；其餘的行原樣保留。

    認 nodeid 走 `失敗行的測試節點`（狀態機那支唯一入口），跟分類器同一套規則：
    帶步名前綴的 `[全測試] FAILED …::…` 也算數，抽不出 nodeid 的行不算任何測試紅。
    """
    return "\n".join(
        行 for 行 in 證據.splitlines() if (節點 := 失敗行的測試節點(行)) is None or 節點 in 既有紅
    )


def _看階段才帶的段落(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> list[str]:
    """只有某一階、或只有某一種票才接上的段落，依送出去的先後排好。

    **這幾段都不能住在系統提示裡**：系統提示一次建好、每輪不變，
    而這裡每一段都是 per-round 或 per-ticket 的。

    - 再次審查、以及退回循環裡的測試員與實作員：另外帶最近一次審查與其後的測試、實作回報。
      混合意見（`[test-design]` ＋ `[impl]`）整包退測試員時，兩階之後的實作員
      上一步是 `驗證紅`，那些 `[impl]` 條目沿著上一步流不過來，只能從這裡帶。
    - 從「全綠了嗎」紅在既有測試而被退回來的測試員：多一段那幾支是誰的前情。
    - 因為實作／重構伸手動了測試檔而被退回來的測試員：多一段被動的檔名清單
      （只有清單，不帶 diff，理由見 `_實作員動過測試的前情`）。
    - 測試員遇上「新增保證」的票：多一段固定負控登記。負控只接給測試員——
      它本來就能寫測試檔；接給實作員等於教它去撞「不准動測試檔」的護欄。
    - 實作員：這一輪的讀取策略。首輪禁跑全測試（省 token），
      被退回的那一輪反過來要它跑——它要修的正是全測試的紅。
    """
    段落: list[str] = []
    if _這一階要接審查回顧(定義, 軌跡):
        審查回顧 = _上次審查與其後回報(軌跡)
        if 審查回顧 is not None:
            段落.append(審查回顧)
    if 定義.代碼 is 階段代碼.測試:
        被退回的前情 = (_既有測試紅了的前情(軌跡), _實作員動過測試的前情(軌跡))
        段落.extend(前情 for 前情 in 被退回的前情 if 前情 is not None)
        if 任.新增保證:
            段落.append(角色提示.測試員負控段落)
    if 定義.代碼 is 階段代碼.實作:
        被退回 = bool(軌跡) and (是回頭邊(軌跡[-1].階段, 定義.代碼) or _在審查退回循環裡(軌跡))
        段落.append(角色提示.這一輪的讀取策略(被退回=被退回))
    return 段落


def _這一階要接審查回顧(定義: 階段定義, 軌跡: tuple[步驟結果, ...]) -> bool:
    """審查階每次都要；實作階與測試階只在上一步不是審查時才要。

    上一步已經是審查的話，全文早就在「上一步的結果」那段裡了，接第二份只是重複。
    """
    if 定義.代碼 is 階段代碼.審查:
        return True
    if 定義.代碼 not in (階段代碼.實作, 階段代碼.測試):
        return False
    return not 軌跡 or 軌跡[-1].階段 is not 階段代碼.審查


def _在審查退回循環裡(軌跡: tuple[步驟結果, ...]) -> bool:
    """軌跡上最近一次審查是「要求修改」——那之後的每一步都在退回循環裡。

    這跟 `狀態機.是回頭邊`（去處排在來源前面）是兩個概念：混合意見整包退測試員時，
    實作階的上一步是 `驗證紅`，不是回頭邊，但這一輪確確實實是被退回來的。
    """
    位置 = _最近一次審查的位置(軌跡)
    if 位置 is None:
        return False
    # 只讀結構化的 `審查結論`：審查階建步驟結果時就填好了，那是唯一的語意來源。
    # 沒填就是沒給，不准回頭重新解析 `證據`——那會養出第二份「什麼叫要求修改」。
    return 軌跡[位置].審查結論 is 審查判定.要求修改


def _最近一次審查的位置(軌跡: tuple[步驟結果, ...]) -> int | None:
    """軌跡上最後一個審查步的索引；沒審查過就回 `None`。"""
    return next(
        (索引 for 索引 in range(len(軌跡) - 1, -1, -1) if 軌跡[索引].階段 is 階段代碼.審查),
        None,
    )


def _上次審查與其後回報(軌跡: tuple[步驟結果, ...]) -> str | None:
    """最近一次審查的全文，加上它之後最後一份測試回報與實作回報（沒有就不接）。

    測試回報也要帶：混合意見（`[test-design]` ＋ `[impl]`）整包退測試員時，
    `[test-design]` 那幾條是**測試員**接手的，它補了什麼只寫在自己的回報裡；
    只帶實作回報的話，第二次審查對那半邊等於沒有人回報過，只好原封不動再開一次。

    只帶這幾段、不重播整段歷史：長度有界，內容跟第二次審查看到的一樣多。

    標題只列**真的接上的**那幾份回報：接了什麼就說什麼，沒接的不准出現在標題上。
    """
    上次審查索引 = _最近一次審查的位置(軌跡)
    if 上次審查索引 is None:
        return None

    上次審查 = 軌跡[上次審查索引]
    其後 = _剔掉伸手動測試的那幾步(軌跡[上次審查索引 + 1 :])
    上次審查後的測試 = _最後一份回報(其後, 階段代碼.測試)
    上次審查後的實作 = _最後一份回報(其後, 階段代碼.實作)
    內文段落: list[str] = [f"上一次審查：\n{_包不可信(上次審查.證據)}"]
    # 標題是這一段的目錄：只准列真的接上的那幾份，不然讀的人會去找一份不存在的回報。
    有的種類: list[str] = []
    if 上次審查後的測試 is not None:
        有的種類.append("測試回報")
        內文段落.append(f"其後測試回報：\n{_包不可信(上次審查後的測試.證據)}")
    if 上次審查後的實作 is not None:
        有的種類.append("實作回報")
        內文段落.append(f"其後實作回報：\n{_包不可信(上次審查後的實作.證據)}")
    標題 = "上一次審查回顧：" if not 有的種類 else f"上一次審查與其後{'、'.join(有的種類)}："
    return "\n".join([標題, *內文段落])


def _剔掉伸手動測試的那幾步(步驟們: tuple[步驟結果, ...]) -> tuple[步驟結果, ...]:
    """濾掉「不准動測試的階段動了測試檔」那幾步——整步不算數，它的回報也不准流出去。

    那份自由文字會原封不動地說「我把哪支斷言改鬆了、改成什麼」，接給測試員
    等於把作弊稿抄給它（前門 `_上一步給這一階看的證據` 已經遮了這條路）。
    """
    return tuple(步 for 步 in 步驟們 if not 伸手動了測試(步.階段, 步.動過的測試檔))


def _最後一份回報(步驟們: tuple[步驟結果, ...], 階段: 階段代碼) -> 步驟結果 | None:
    """這幾步裡最後一個屬於該階段的步驟；沒有就回 `None`。"""
    return next((步驟 for 步驟 in reversed(步驟們) if 步驟.階段 is 階段), None)


def _上一步紅在哪些既有測試(軌跡: tuple[步驟結果, ...]) -> tuple[str, ...]:
    """剛剛那一步是紅掉的 `驗證綠` 的話，它紅在哪幾支既有測試。

    不是這條路（軌跡空、上一步不是紅的 `驗證綠`、或抽不出既有紅）就回空。
    """
    if not 軌跡 or not 是紅掉的驗證綠(軌跡[-1]):
        return ()
    return 紅在哪些既有測試(軌跡[-1])


def _實作員動過測試的前情(軌跡: tuple[步驟結果, ...]) -> str | None:
    """上一步伸手動了測試檔而被退回來時，說得出被動的是哪幾個檔。不是這條路就回 `None`。

    **只帶檔名清單，不准帶它改了什麼**：把作弊稿抄給測試員，等於請測試員
    照實作員的意思把測試改鬆。
    """
    if not _上一步伸手動了測試(軌跡):
        return None
    清單 = "\n".join(f"- {檔}" for 檔 in 軌跡[-1].動過的測試檔)
    return (
        "上一步的實作／重構動了這幾個測試檔（那一步不算數，已還原到實作前快照）：\n"
        f"{清單}\n"
        "測試是驗收機制，改它是**你**的職權：這幾個檔要不要改、要怎麼改，"
        "你決定。決定完再往下走。"
    )


def _既有測試紅了的前情(軌跡: tuple[步驟結果, ...]) -> str | None:
    """從 `驗證綠` 退回測試員時要說得出「紅的這幾支是既有測試」與是哪幾支。

    不是這條路就回 `None`。
    """
    既有紅 = _上一步紅在哪些既有測試(軌跡)
    if not 既有紅:
        return None
    清單 = "\n".join(f"- {支}" for 支 in 既有紅)
    return (
        "你是從「全綠了嗎」被退回來的，而且紅的這幾支是**既有測試**"
        "（不是這一輪新寫的）：\n"
        f"{清單}\n"
        "改既有測試是測試員的事——實作員動任何測試檔都會撞護欄，所以這條退回接到你。\n"
        "先判斷：這張票是不是真的要改掉這些測試編碼的慣例？"
        "是就把它們改成新的慣例；不是就把這一輪的新測試改成不跟它們打架。"
    )


def _包不可信(資料: str) -> str:
    """把上游文字限制在固定的不可信資料圍欄內。

    這是資料邊界衛生，不是完整的提示注入防護牆；模型仍可能服從圍欄內的句子。
    """
    開始標記 = "<<<UNTRUSTED"
    結束標記 = "UNTRUSTED>>>"
    # 清除後可能接合出新標記，因此反覆清除直到沒有 marker。
    while 開始標記 in 資料 or 結束標記 in 資料:
        資料 = 資料.replace(開始標記, "").replace(結束標記, "")
    return f"{開始標記} {資料} {結束標記}"
