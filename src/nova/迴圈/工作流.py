"""工作流的執行器：照狀態機走，走到結束為止。

七欄位契約（§3.2）在這裡的落點：

| 欄位 | 這裡是什麼 |
|---|---|
| Trigger | 呼叫 `跑工作流` |
| Goal | 走到 `結束(完成)` |
| Memory | `軌跡`——每一步的結果，下一步看得到 |
| Action policy | 狀態機的轉移表，只准走表上有的路 |
| Evidence | 每步的 `步驟結果`（終局＋判準紅綠＋證據） |
| Feedback | 紅掉時退回哪個階段，由表決定 |
| **Stop rule** | `停止條件`（步數上限＋token 上限）——**缺它的不是迴圈，是成本漏洞** |

`執行一步` 是參數不是內建：高層決定需要什麼形狀，低層去符合（依賴反轉）。
所以這支 runner 的測試不必碰任何 LLM 或子程序。
"""

from dataclasses import dataclass

from nova.契約.工作流 import (
    任務,
    停止條件,
    判準,
    執行器,
    步驟結果,
    種類,
    結束,
    結束代碼,
    階段代碼,
    階段定義,
    預設停止,
)
from nova.契約.模型回應 import 終局
from nova.契約.角色 import 角色
from nova.迴圈.審查 import 讀審查判定
from nova.迴圈.狀態機 import TDD階段表, 下一步, 查階段


@dataclass(frozen=True, slots=True)
class 工作流結果:
    """走完之後的全部證據。"""

    結束: 結束
    軌跡: tuple[步驟結果, ...]


def 跑工作流(
    任務: 任務,
    *,
    執行一步: 執行器,
    階段表: tuple[階段定義, ...] = TDD階段表,
    起點: 階段代碼 = 階段代碼.測試,
    停止: 停止條件 = 預設停止,
) -> 工作流結果:
    """從起點開始走，走到結束、撞到步數上限、或花完預算為止。

    上限不是保險，是 stop rule 本身：`驗證紅` 沒紅會退回 `測試`、
    `驗證綠` 沒綠會退回 `實作`，兩條回頭邊都可能來回不停。

    **步數與 token 是兩個不同的洞。** 步數擋「來回幾次」，token 擋「花多少」——
    一步可以很貴，十二步的上限對成本沒有任何保證。

    預算是累計式的：每次回來加總，**下一次呼叫之前**擋下。擋不到「這一次會花多少」
    （那要等它回來才知道），所以最後一步一定會超出一點。誠實的上限，不是精準的上限。
    """
    del 階段表  # 目前只有一張表；留參數是為了之後換表，不是為了現在用
    軌跡: list[步驟結果] = []
    已花token = 0
    目前: 階段代碼 | 結束 = 起點
    for _ in range(停止.最多步數):
        if isinstance(目前, 結束):
            return 工作流結果(結束=目前, 軌跡=tuple(軌跡))
        if 已花token >= 停止.最多token:
            收尾 = 結束(
                結束代碼.中止,
                f"已花 {已花token} token，達到上限 {停止.最多token}，"
                f"停在「{查階段(目前).名稱}」之前（沒有預算上限的迴圈是成本漏洞）",
            )
            return 工作流結果(結束=收尾, 軌跡=tuple(軌跡))
        定義 = 查階段(目前)
        結果 = 執行一步(定義, 任務, tuple(軌跡))
        軌跡.append(結果)
        已花token += 結果.花費.總token if 結果.花費 is not None else 0
        目前 = 下一步(定義, 結果)
    if isinstance(目前, 結束):
        return 工作流結果(結束=目前, 軌跡=tuple(軌跡))
    收尾 = 結束(
        結束代碼.中止, f"超過最多步數 {停止.最多步數}，停止（沒有停止條件的迴圈是成本漏洞）"
    )
    return 工作流結果(結束=收尾, 軌跡=tuple(軌跡))


def 建TDD執行器(*, 測試: 角色, 實作: 角色, 重構: 角色, 審查: 角色, 跑判準: 判準) -> 執行器:
    """把四個零件接成一個執行器。

    這就是 `BaseWorkflow(task, 測試, 實作, 驗證, review)` 的形狀——但**驗證不是角色**，
    是機械判準（硬規則 4：不得讓同一個模型自寫自評）。而且它出現兩次：
    實作之前確認測試真的紅了，實作之後確認全綠了。

    `審查` 應該給**另一顆腦**——自己審自己等於沒審。這條目前是呼叫端的責任。
    """
    角色表: dict[階段代碼, 角色] = {
        階段代碼.測試: 測試,
        階段代碼.實作: 實作,
        階段代碼.重構: 重構,
        階段代碼.審查: 審查,
    }

    def 執行一步(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> 步驟結果:
        if 定義.種類 is 種類.判準:
            綠, 證據 = 跑判準(任)
            return 步驟結果(階段=定義.代碼, 終局=終局.成功, 判準綠=綠, 證據=證據)
        答 = 角色表[定義.代碼].做(_提示(定義, 任, 軌跡), 工作目錄=任.工作目錄)
        # 失敗時把代碼寫進證據——只給一段自由文字，下游要重建「為什麼失敗」（§4.3）。
        證據 = 答.文字 if 答.終局 is 終局.成功 else f"[{答.失敗代碼.value}] {答.文字}"
        # 審查階段的驗收權在判定上，不在「子程序有沒有跑完」上。
        結論 = 讀審查判定(答.文字) if 定義.種類 is 種類.審查 else None
        return 步驟結果(
            階段=定義.代碼,
            終局=答.終局,
            判準綠=None,
            證據=證據,
            審查結論=結論,
            花費=答.用量,
        )

    return 執行一步


def _提示(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> str:
    """給角色的提示：這次的任務 ＋ 上一步的證據（Memory）。

    只帶**上一步**，不重播全部——重播整段歷史會讓 context 隨輪數線性膨脹。
    """
    段落 = [f"任務：{任.描述}", f"你現在的階段：{定義.名稱}"]
    if 軌跡:
        上一步 = 軌跡[-1]
        段落.append(f"上一步（{上一步.階段}）的結果：\n{上一步.證據}")
    return "\n\n".join(段落)
