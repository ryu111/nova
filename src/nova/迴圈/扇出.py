"""扇出節點 runner：有界派送，固定以屏障收斂。"""

from collections.abc import Callable
from concurrent.futures import FIRST_COMPLETED, Future, ThreadPoolExecutor, wait
from dataclasses import dataclass, replace
from pathlib import Path
from time import monotonic

from nova.契約.扇出 import 分支工作, 分支結果, 扇出政策, 扇出模式, 扇出結果, 開不出工作樹
from nova.契約.節點 import (
    分支識別碼,
    節點上下文,
    節點成功,
    節點確定失敗,
    節點結果,
    節點護欄,
    結果代碼,
)


@dataclass(slots=True)
class _用量累計:
    """扇出 runner 自己持有的階段總用量。"""

    累計新鮮token: int = 0

    def 加入[輸出](self, 結果: 節點結果[輸出]) -> int:
        """記下結果的用量；確定失敗沒有用量，不計入總額。"""
        if isinstance(結果, 節點確定失敗):
            return 0
        if 結果.用量 is None:
            return 0
        花費 = 結果.用量.新鮮token
        self.累計新鮮token += 花費
        return 花費


def 執行扇出[輸入, 輸出, 依賴](
    工作: tuple[分支工作[輸入, 依賴], ...],
    *,
    執行一顆: Callable[
        [分支工作[輸入, 依賴], 節點上下文],
        節點結果[輸出],
    ],
    上下文: 節點上下文,
    政策: 扇出政策,
) -> 扇出結果[輸出]:
    """執行分支並等屏障收齊，再決定整階終局。"""
    _驗證輸入(工作, 政策)
    已回收結果: dict[分支識別碼, 節點結果[輸出]] = {}
    進行中: dict[Future[節點結果[輸出]], 分支工作[輸入, 依賴]] = {}
    下一個 = 0
    用量累計 = _用量累計()
    已呼叫 = 0
    已觸發護欄 = False
    開始 = monotonic()

    def _盡量派送() -> None:
        nonlocal 下一個, 已呼叫, 已觸發護欄
        while 下一個 < len(工作) and len(進行中) < 政策.最大並行數 and not 已觸發護欄:
            if _上限阻止再派一顆(已呼叫, 用量累計.累計新鮮token, len(進行中), 開始, 政策):
                已觸發護欄 = True
                break
            工作項 = 工作[下一個]
            下一個 += 1
            if _呼叫端開不出樹(工作項):
                continue
            未來 = 執行池.submit(
                執行一顆,
                工作項,
                _這顆分支的上下文(上下文, 工作項),
            )
            進行中[未來] = 工作項
            已呼叫 += 1

    with ThreadPoolExecutor(max_workers=max(1, 政策.最大並行數)) as 執行池:
        while 下一個 < len(工作) or 進行中:
            _盡量派送()

            if not 進行中:
                break

            本批觸發護欄 = _收回完成分支(
                進行中,
                已回收結果,
                用量累計,
                政策,
            )
            已觸發護欄 = 已觸發護欄 or 本批觸發護欄

            if monotonic() - 開始 >= 政策.最多秒:
                已觸發護欄 = True

    return _收斂(工作, 已回收結果, 已觸發護欄, 政策)


def _呼叫端開不出樹[輸入, 依賴](工作項: 分支工作[輸入, 依賴]) -> bool:
    """這顆分支是不是落在「呼叫端開樹失敗」那一格。

    是的話連派都不派：它沒有可以動手的地方，退回共用工作目錄就是假隔離。
    沒派出去的分支不會進 `已回收結果`，於是在屏障那裡是「沒有分支結果、
    只出現在缺口」——跟「跑了但失敗」（有分支結果、結果是確定失敗）分得開。
    """
    return isinstance(工作項.工作樹, 開不出工作樹)


def _這顆分支的上下文[輸入, 依賴](
    上下文: 節點上下文,
    工作項: 分支工作[輸入, 依賴],
) -> 節點上下文:
    """把分支識別碼與（若有）這顆自己的工作樹接到上下文上。

    工作樹是呼叫端開好交進來的路徑，runner 只是把分支據以工作的那個目錄
    換掉——換不掉的話所謂隔離就只是契約上多一個沒人看的欄位。

    只有路徑會換目錄：`開不出工作樹` 的分支在派送前就被跳掉了，走不到這裡。
    """
    這顆上下文 = replace(上下文, 分支=工作項.分支)
    if not isinstance(工作項.工作樹, Path):
        return 這顆上下文
    在自己樹裡的任務 = replace(這顆上下文.任務, 工作目錄=工作項.工作樹)
    return replace(這顆上下文, 任務=在自己樹裡的任務)


def _驗證輸入[輸入, 依賴](
    工作: tuple[分支工作[輸入, 依賴], ...],
    政策: 扇出政策,
) -> None:
    """拒絕無法完整執行的扇出計畫。"""
    if 政策.模式 is not 扇出模式.屏障:
        訊息 = "第一版扇出只接受屏障模式"
        raise ValueError(訊息)
    if (
        政策.最大分支數 < 0
        or 政策.最大並行數 <= 0
        or 政策.最多呼叫 < 0
        or 政策.最少成功數 < 0
        or 政策.最多秒 < 0
        or 政策.每分支最多token < 0
        or 政策.階段最多token < 0
    ):
        訊息 = "扇出政策的上限與並行數必須有效"
        raise ValueError(訊息)
    if len(工作) > 政策.最大分支數:
        訊息 = "扇出分支數超過固定上限"
        raise ValueError(訊息)
    if len({工作項.分支 for 工作項 in 工作}) != len(工作):
        訊息 = "扇出分支識別碼不可重複"
        raise ValueError(訊息)
    實際必要 = frozenset(工作項.分支 for 工作項 in 工作 if 工作項.必要)
    if 實際必要 != 政策.必要分支:
        訊息 = "扇出必要分支與分派資料不一致"
        raise ValueError(訊息)
    if len(工作) * 政策.每分支最多token > 政策.階段最多token:
        訊息 = "扇出階段總預算無法容納全部分支"
        raise ValueError(訊息)
    撞到 = _找出假獨立(工作)
    if 撞到 is not None:
        甲, 乙, 甲格, 乙格 = 撞到
        訊息 = f"分支 {甲} 與 {乙} 的寫入範圍撞在一起（{甲格} 與 {乙格}）——沒有資料依賴不等於獨立"
        raise ValueError(訊息)


def _撞在一起嗎(甲格: str, 乙格: str) -> bool:
    """兩格寫入範圍是不是同一塊地。

    **比路徑節點，不比字元前綴**：`src/nova/契約` 與 `src/nova/契約-舊`
    的字元前綴一樣中、路徑節點不中，它們是兩個不同的目錄。
    比字元的話這一格會擋到不該擋的，第一個反應就是把它關掉。

    一格是另一格的祖先也算撞：`src/nova/契約` 底下就包含
    `src/nova/契約/節點.py`，兩個分支各拿一個仍然是同一塊地。
    """
    甲節點 = tuple(Path(甲格).parts)
    乙節點 = tuple(Path(乙格).parts)
    短 = min(len(甲節點), len(乙節點))
    return 甲節點[:短] == 乙節點[:短]


def _找出假獨立[輸入, 依賴](
    工作: tuple[分支工作[輸入, 依賴], ...],
) -> tuple[分支識別碼, 分支識別碼, str, str] | None:
    """第一對寫入範圍撞在一起的分支。都不撞就回 None。

    **只回第一對，不回全部**：這是開跑前的拒絕，訊息要能讓人當場知道
    該拆哪兩個；列出全部反而要人自己找出關鍵那一對。

    沒宣告寫入範圍的分支不參與比對（空 tuple 的雙層迴圈本來就不進去），
    理由寫在 `契約/扇出.py` 的 `寫入範圍` 上。
    """
    for 甲位, 甲 in enumerate(工作):
        for 乙 in 工作[甲位 + 1 :]:
            for 甲格 in 甲.寫入範圍:
                for 乙格 in 乙.寫入範圍:
                    if _撞在一起嗎(甲格, 乙格):
                        return (甲.分支, 乙.分支, 甲格, 乙格)
    return None


def _收回完成分支[輸入, 輸出, 依賴](
    進行中: dict[Future[節點結果[輸出]], 分支工作[輸入, 依賴]],
    已回收結果: dict[分支識別碼, 節點結果[輸出]],
    用量累計: _用量累計,
    政策: 扇出政策,
) -> bool:
    """整理一批完成的分支，並更新 runner 持有的階段總額。"""
    完成, _ = wait(進行中, return_when=FIRST_COMPLETED)
    本批觸發護欄 = False
    for 未來 in 完成:
        工作項 = 進行中.pop(未來)
        結果 = 未來.result()
        已回收結果[工作項.分支] = 結果
        花費 = 用量累計.加入(結果)
        if 花費 > 政策.每分支最多token:
            本批觸發護欄 = True
        if 用量累計.累計新鮮token > 政策.階段最多token or isinstance(結果, 節點護欄):
            本批觸發護欄 = True
    return 本批觸發護欄


def _上限阻止再派一顆(
    已呼叫: int,
    已花token: int,
    進行中數: int,
    開始: float,
    政策: 扇出政策,
) -> bool:
    """判斷政策上限是否阻止再派一顆分支。"""
    預留中的分支數 = 進行中數 + 1
    return (
        已呼叫 >= 政策.最多呼叫
        or 已花token >= 政策.階段最多token
        or 已花token + 預留中的分支數 * 政策.每分支最多token > 政策.階段最多token
        or monotonic() - 開始 >= 政策.最多秒
    )


def _收斂[輸入, 輸出, 依賴](
    工作: tuple[分支工作[輸入, 依賴], ...],
    已回收結果: dict[分支識別碼, 節點結果[輸出]],
    已觸發護欄: bool,
    政策: 扇出政策,
) -> 扇出結果[輸出]:
    """整理已回收結果，再委派終局判定。"""
    已回收分支結果: list[分支結果[輸出]] = []
    成功產出 = []
    未成功分支: list[分支識別碼] = []
    必要分支未回 = False
    必要分支結果代碼: set[結果代碼] = set()
    成功數 = 0

    for 工作項 in 工作:
        結果 = 已回收結果.get(工作項.分支)
        if 結果 is None:
            未成功分支.append(工作項.分支)
            必要分支未回 |= 工作項.必要
            continue

        已回收分支結果.append(分支結果(分支=工作項.分支, 結果=結果))
        if isinstance(結果, 節點成功):
            成功數 += 1
            成功產出.append(結果.產出)
        else:
            未成功分支.append(工作項.分支)

        if 工作項.必要:
            必要分支結果代碼.add(結果.結果)

    終局 = _決定終局(
        已觸發護欄=已觸發護欄,
        必要分支未回=必要分支未回,
        必要分支結果代碼=必要分支結果代碼,
        成功數=成功數,
        政策=政策,
    )

    return 扇出結果(
        分支結果=tuple(已回收分支結果),
        成功產出=tuple(成功產出),
        缺口=tuple(未成功分支),
        終局=終局,
    )


def _決定終局(
    *,
    已觸發護欄: bool,
    必要分支未回: bool,
    必要分支結果代碼: set[結果代碼],
    成功數: int,
    政策: 扇出政策,
) -> 結果代碼:
    """依未知、護欄、確定失敗、成功的風險順序決定整階終局。"""
    if 結果代碼.結果未知 in 必要分支結果代碼:
        return 結果代碼.結果未知
    if 已觸發護欄 or 必要分支未回 or 結果代碼.護欄 in 必要分支結果代碼:
        return 結果代碼.護欄
    if 結果代碼.確定失敗 in 必要分支結果代碼 or 成功數 < 政策.最少成功數:
        return 結果代碼.確定失敗
    return 結果代碼.成功
