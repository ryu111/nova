"""成果：一次做完的工作在帳上長什麼樣。

跟 `契約.帳本` 的分工是**答的問題不同**，不是同一份資料的兩種格式：

| | 答什麼 | 顆粒 |
|---|---|---|
| 事件帳本 | 花了多少、叫了幾次、走了哪幾階 | 一次執行很多筆 |
| 成果帳本 | **這件工作做完了沒、結果是什麼** | 一次工作一筆 |

事件帳本答不出「做完了沒」——那要從軌跡自己推，而推的規則
（`3` 蓋過 `4` 之類）住在命令列那一層。所以收場與退出碼直接寫在成果上。

落盤的欄位名用 ASCII（CLAUDE.md 的跨程序 schema 欄位名例外），
給 python 呼叫端的是繁中屬性名，兩邊由 `成果轉字典` 對齊。
"""

from dataclasses import dataclass
from typing import Any

from nova.契約.遮罩 import 已經遮過了, 已遮罩文字

#: 驗收那一格落盤時的 ASCII 鍵。`_欄位對照` 與 `成果轉字典` 的分派都認這個字串，
#: 各寫一次的話改了一邊就對不上，所以只留這一份。
_驗收鍵 = "acceptance"

#: （繁中屬性名, 落盤的 ASCII 鍵, 讀不到時的預設值）。
#: 預設值的型別跟著欄位走，所以標成 `Any`——標死會逼出 `type: ignore`，
#: 而那是用規避換來的綠。
_欄位對照: tuple[tuple[str, str, Any], ...] = (
    ("執行識別碼", "run_id", ""),
    ("任務", "task", ""),
    ("收場", "outcome", ""),
    ("退出碼", "exit_code", 0),
    ("起", "started_at", ""),
    ("迄", "ended_at", ""),
    ("走了幾階", "steps", 0),
    ("總token", "tokens", 0),
    ("總成本美金", "cost_usd", None),
    ("來源", "source", ""),
    ("規則表版本", "policy_version", None),
    ("起點commit", "rollback_point", None),
    ("護欄原因", "guardrail_reason", None),
    ("驗收", _驗收鍵, None),
)


@dataclass(frozen=True, slots=True)
class 驗收紀錄:
    """一條驗收在帳上的那一格：**跑了什麼、回什麼碼**。

    **證據不進來。** 驗收指令的輸出動輒上萬行，而成果帳是給人掃的；
    證據已經印在 stderr 也進了事件帳本，抄一份到這裡只會把帳淹掉。

    指令原文一定要記：一張宣告三條驗收的票，只記「紅了」的話
    事後查不出是**哪一條**擋住的。
    """

    指令: str
    退出碼: int


@dataclass(frozen=True, slots=True)
class 成果:
    """一次工作做完之後留下的那一筆。

    `任務` 記的是**使用者自己打的那句話**（或收件檔的內容），不是模型講了什麼。
    模型輸出不進成果帳——那在事件帳本裡，遮過的。

    **任務也要先過遮罩。** 以前的理由是「它已經在 `ps` 的 args 上，
    記它沒有多開一條路」，那條理由現在站不住，而且有兩個方向：
    `ps` 的 args 是程序活著的那幾秒，`已處理/` 是躺在磁碟上直到有人刪掉；
    而**收件匣那條路根本不經過 `ps`**——題目來自一個檔案，
    所以那條理由在最常見的那條路徑上一個字都不成立。
    """

    執行識別碼: str
    任務: 已遮罩文字
    收場: str
    退出碼: int
    起: str
    迄: str
    走了幾階: int
    總token: int
    總成本美金: float | None = None
    #: 誰觸發的（`typed`／`file`／…）。**不是「誰醒來把它撈起來」**——
    #: 分不出來的話，「排程昨晚自己跑了什麼」跟「我手動派了什麼」
    #: 會混在同一本帳上，而那正是無人看管跑起來之後最需要分開的兩件事。
    來源: str = ""
    #: 這次跑的時候規則表是哪一版（內容雜湊）。**答的是「閘為什麼放行／擋下」**——
    #: 規則表天天在改，而規則變了會改變閘擋不擋得住。沒有這一欄，
    #: 一次壞掉的執行只剩「它壞了」這個結論，沒有可歸因的變數。
    規則表版本: str | None = None
    #: 起跑時工作目錄停在哪個 commit。**是起點不是終點**：要退回去的是
    #: 這次動手之前那個狀態。工作目錄不是 repo 時是 `None`，
    #: 不是空字串——「這裡沒有 commit 可退」跟「沒記到」是兩件事。
    起點commit: str | None = None
    #: 退出碼 4 是**哪一種**護欄（`契約.護欄.護欄原因` 的值）。`收場` 答不出這件事：
    #: 工作流自己撞護欄時它全寫 `guardrail`，驗收紅那條 4 它寫的卻是 `done`。
    #: 兩邊都看不出「那個 4 是怎麼來的」，而「模型每次都撞上限」與
    #: 「模型每次都在原地打轉」的修法完全相反。
    #: **沒撞護欄與沒記到都是 `None`，不是空字串**——比照 `起點commit`：
    #: 舊的成果檔沒有這一欄，塌成空字串的話「那時候還沒有這一欄」
    #: 會長得像「那次跑完沒撞到任何護欄」。
    #: 型別是 `str` 不是 `護欄原因`：帳從 JSON 讀回來就只是字串。
    護欄原因: str | None = None
    #: 這一輪跑了哪幾條驗收、綠不綠。**`None` 與空 tuple 是兩件事**：
    #: 沒宣告驗收的票（人給的）根本不會跑驗收，那一格是「沒有這個概念」，
    #: 不是「零條紅」。長得一樣的話，事後就分不出
    #: 「模型每次都撞上限」與「模型每次都說做完了但驗收不過」，
    #: 而那兩件事的修法完全相反。
    驗收: tuple[驗收紀錄, ...] | None = None


def _驗收攤平(幾條: tuple[驗收紀錄, ...]) -> list[dict[str, Any]]:
    """驗收那一格是 dataclass，JSON 塞不進去，所以一條攤成一個 dict。"""
    return [{"command": 一條.指令, "exit_code": 一條.退出碼} for 一條 in 幾條]


def _驗收讀回(幾條: list[dict[str, Any]]) -> tuple[驗收紀錄, ...]:
    """`_驗收攤平` 的反向。兩邊的 ASCII 鍵放在一起，改的時候看得到彼此。"""
    return tuple(驗收紀錄(指令=一條["command"], 退出碼=一條["exit_code"]) for 一條 in 幾條)


def 成果轉字典(一筆: 成果) -> dict[str, Any]:
    """落盤用。鍵是 ASCII，讀的人可能不是 python。

    **`None` 的欄位整格不落盤**，寫成 `null` 或空值都不行——
    讀回來的時候要分得出「沒有這個概念」與「有，但是空的」。
    """
    落盤: dict[str, Any] = {}
    for 內, 外, _ in _欄位對照:
        值 = getattr(一筆, 內)
        if 值 is None:
            continue
        落盤[外] = _驗收攤平(值) if 外 == _驗收鍵 else 值
    return 落盤


def 字典轉成果(原始: dict[str, Any]) -> 成果:
    """讀回來。**缺欄位補預設值，不炸。**

    帳是 append-only 的歷史，以前寫的那些不會回頭改；欄位是之後加的話
    舊紀錄就少那一格。這裡炸掉的話整本帳都看不了，
    而看得到「哪一次、什麼收場」已經比看不到強得多。

    **`任務` 走 `已經遮過了`**：從磁碟讀回來只是 `str`，但寫進去的時候
    過了遮罩（由 `test_使用者自己打進去的祕密也不准進成果帳` 背書）。
    型別資訊在 JSON 那一趟掉了，這裡把它接回來，並且寫下理由。
    """
    欄 = {內: 原始.get(外, 預設) for 內, 外, 預設 in _欄位對照}
    欄["任務"] = 已經遮過了(欄["任務"], 因為="從已處理的 JSON 讀回來，寫進去的時候過了遮罩")
    if 欄["驗收"] is not None:
        欄["驗收"] = _驗收讀回(欄["驗收"])
    return 成果(**欄)
