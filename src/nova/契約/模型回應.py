"""三家 LLM CLI 共用的證據 schema。

規格 §4.3：跨層傳遞一律 schema 化。自由段落會逼下游重建上游語意，
多階段之後歧義累積會改變結論——所以錯誤分類在這一層做完一次，不往下游丟原始訊息。

用 `StrEnum` 不用 `Literal`＋常數表：**識別字中文、值 ASCII**。
一個來源就沒有漂移問題（常數表與型別標註分兩處寫，遲早對不上），
而且能直接 `for 代碼 in 失敗代碼` 迭代，窮舉性測試才寫得出來。

設計決定見 `docs/設計/02-統一LLM介面.md`。
"""

from dataclasses import dataclass, field
from enum import StrEnum
from typing import Any


class 失敗代碼(StrEnum):
    """為什麼沒跑成。值用 ASCII——要跨程序流動（CLI 輸出、日誌、CI）。"""

    無 = "none"
    認證 = "auth"
    模型不存在 = "model-not-found"
    用法錯誤 = "usage"
    #: CLI 根本沒裝。**不是「模型不存在」**——那是裝好了但型號錯。
    未安裝 = "not-installed"
    #: 沙箱或權限系統擋下來的。**跟其他失敗的處置相反**：
    #: 換一顆腦沒有用，下一顆撞的是同一堵牆（同一套沙箱、同一份旗標）。
    #: 要動的是沙箱設定或授權，不是模型。
    權限被擋 = "permission-denied"
    #: 額度／配額用完，要等重置或付錢。**不是暫時限流**（那是 `上游`）：
    #: 429 等一下就好，這個等一下也沒用，但**換一家就好**——
    #: 額度是綁在 provider 上的，這正是接力鏈存在的理由。
    額度耗盡 = "quota-exhausted"
    逾時 = "timeout"
    被中斷 = "interrupted"
    上游 = "upstream"
    #: CLI 說成功、卻一個字都沒回。**不併進 `未知`**：`unknown` 什麼都可能是，
    #: 而這一種有明確的處置（唯讀下再問一次），也是帳本唯一數得出來的形狀。
    空輸出 = "empty-output"
    未知 = "unknown"


class 終局(StrEnum):
    """at-most-once 的地基：**結果未知 ≠ 確定失敗**。

    殺掉子程序時工作可能已經做了一半。把它當確定失敗，重試就會把可能做過的事
    再做一次。布林壓不住這個區別，所以是三值。
    """

    成功 = "success"
    確定失敗 = "failed"
    結果未知 = "unknown"


# 分界線是「請求出門了沒」——出門了就可能已經產生副作用。
# 寫成表不是寫成 if 鏈：加一個失敗代碼＝加一列，不是回來改判斷（開放封閉）。
# 每個 `失敗代碼` 都必須在這裡有一列，由 test_每個失敗代碼都要有明確的終局 背書。
_終局表: dict[失敗代碼, 終局] = {
    失敗代碼.無: 終局.成功,
    失敗代碼.認證: 終局.確定失敗,  # 認證就被擋，沒出門
    失敗代碼.模型不存在: 終局.確定失敗,  # 模型不存在，沒出門
    失敗代碼.用法錯誤: 終局.確定失敗,  # 旗標錯，CLI 自己就退了
    失敗代碼.未安裝: 終局.確定失敗,  # 執行檔不在，請求根本沒出門
    # 請求被拒，模型一個字都沒跑，沒有任何副作用——那正是「可以安全換下一家」的定義。
    失敗代碼.額度耗盡: 終局.確定失敗,
    # 工具在第一步就被權限系統拒絕，沒有任何動作發生；確定失敗。
    失敗代碼.權限被擋: 終局.確定失敗,
    失敗代碼.上游: 終局.結果未知,  # 429／5xx：出門了，對面做了什麼不知道
    失敗代碼.逾時: 終局.結果未知,  # 被我們殺掉，可能做了一半
    失敗代碼.被中斷: 終局.結果未知,  # 同上
    #: 請求出門了、CLI 也說成功，只是一個字都沒回——工具可能動過檔案。
    #: 重試的邊界不在這裡決定，在 `轉接.空輸出該重試`（唯讀才准）。
    失敗代碼.空輸出: 終局.結果未知,
    失敗代碼.未知: 終局.結果未知,  # 解析不出來，最保守的那一格
}


def 終局判定(代碼: 失敗代碼) -> 終局:
    """這個失敗可不可以重試？

    表裡沒有的代碼一律當結果未知——fail-closed。猜「大概可以重試」會重做副作用。

    從簡：`上游` 把 429（確定沒做）和 5xx（可能做了）壓在一起，所以連 429 都
    不准重試。要放寬就把 `上游` 拆成兩個代碼，等真的有重試迴圈嫌它太保守再拆。
    """
    return _終局表.get(代碼, 終局.結果未知)


@dataclass(frozen=True, slots=True)
class 用量:
    """一次呼叫花了多少。

    只有 claude 給成本，codex 與 agy 只有 token 數，所以 `成本美金` 可以是 None。
    **不准為了讓三家對稱而自己估算**——猜出來的成本比沒有成本更危險。
    """

    #: **不含快取讀取的那份新鮮輸入。**三家原生語意不一樣（codex 的
    #: `input_tokens` 含快取讀取、claude 的不含），對齊做在解析器裡，
    #: 進到契約就只剩這一種意思——寫新的解析器要照這個對齊。
    輸入token: int
    輸出token: int
    快取讀取token: int | None = None
    #: **真的付費的 input，而且按 1.25× 計價。**不是快取讀取的子集——
    #: 同一次呼叫兩欄都有值。只有 claude 給。
    快取建立token: int | None = None
    思考token: int | None = None
    成本美金: float | None = None

    @property
    def 新鮮token(self) -> int:
        """這次呼叫真的燒掉多少——預算與單次上限都比這個數。

        輸入（各家在解析器裡都已經扣掉快取讀取）＋輸出＋快取建立。思考 token
        三家都算在輸出裡；**快取讀取不算**，那是打折重讀的上下文，不是這次燒的。
        快取建立算，它是真的新鮮輸入而且按 1.25× 計價。
        """
        return self.輸入token + self.輸出token + (self.快取建立token or 0)


@dataclass(frozen=True, slots=True)
class 回應:
    """一次 LLM CLI 呼叫的結構化結果。

    兩件事刻意不做：

    1. **沒有 `成功` 欄位。** 三家 CLI 實測，模型拒答或答錯一律 exit 0——
       結束碼只分「跑完 vs 基礎設施壞掉」。任務成敗要由迴圈用證據判定（§3.2），
       不能由這一層給，否則就是「以模型說完成了當停止條件」。
    2. **`終局` 不是布林。** 布林會把「結果未知」壓成「確定失敗」，
       而那兩者的重試政策相反。
    """

    文字: str
    終局: 終局
    失敗代碼: 失敗代碼
    原始結束碼: int
    對話識別碼: str | None
    用量: 用量
    結構化輸出: dict[str, Any] | None = None
    #: 逃生艙：認不得的欄位不解析也要留著，下游要挖細節時才有東西可挖。
    原始輸出: tuple[dict[str, Any], ...] = field(default=())
