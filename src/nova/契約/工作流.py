"""工作流的契約：階段、步驟結果、結束。

規格 §4.3：跨層傳遞一律 schema 化。控制流程要能印進 journal，
所以階段與轉移都是**資料**，不是藏在函式裡的分支。

同 `模型回應`：全部用 `StrEnum`，識別字中文、值 ASCII。
"""

from collections.abc import Callable, Mapping
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path
from types import MappingProxyType

from nova.契約.模型回應 import 用量, 終局


class 階段代碼(StrEnum):
    """TDD 的五個階段。值跨程序流動（journal、CLI 輸出）所以是 ASCII。"""

    測試 = "test"
    驗證紅 = "verify-red"
    實作 = "impl"
    驗證綠 = "verify-green"
    #: 只清乾淨、不改行為。**做完一定要再驗一次綠**，否則「行為沒變」沒有背書。
    重構 = "refactor"
    #: 跟 `驗證綠` 長得一樣但**去處不同**——重用同一個代碼的話，
    #: 轉移函式就得記得「我是第幾次來的」，純函式當場破功。
    驗證重構 = "verify-refactor"
    審查 = "review"


class 種類(StrEnum):
    """這個階段由誰做，以及**驗收權在誰手上**。

    這三個對應 Fowler 那套分類的三格（見 docs/設計/04-載體要長什麼樣.md）：

    | 種類 | 對應 | 驗收 |
    |---|---|---|
    | `模型` | inferential guide——它去做事 | 跑完就算 |
    | `判準` | computational sensor——機械跑一條指令 | 看退出碼 |
    | `審查` | inferential sensor——另一顆腦來挑毛病 | **看它給的判定** |

    `審查` 一度被歸在 `模型` 裡，後果是「跑完就算通過」——
    見 `審查判定` 的 docstring。
    """

    模型 = "llm"
    判準 = "gate"
    審查 = "review"


class 判準終局(StrEnum):
    """判準的三種收場。**「跑不起來」不是「紅」。**

    這個型別是被一次真實的燒錢逼出來的（2026-08-30，單次 997,031 token）：
    排程在 launchd 底下跑，PATH 沒有 `uv`，判準指令 `uv run pytest -q`
    丟 `FileNotFoundError`——而當時的實作把它當成「紅」回報。

    工作流看到紅就回去「再實作一次」，實作要叫模型（最貴的一步），
    然後再驗一次、再跑不起來一次。**環境問題重跑一百次還是同一個環境**，
    但每一次重跑中間都夾著一個模型階段。

    nova 自己的診斷順序寫著 **環境 → 回饋 → 流程**：綠與紅是回饋，
    跑不起來是環境。兩種東西壓進同一個 `bool` 就是把環境問題偽裝成回饋。
    """

    綠 = "green"
    紅 = "red"
    #: 指令不存在、沒有執行權限、路徑不是目錄——**根本沒跑到**。
    跑不起來 = "unrunnable"


class 審查判定(StrEnum):
    """審查員給的結論。**沒給就是沒給，不准當成通過。**

    這個型別是被一次真實的假成功逼出來的：審查階段原本歸在 `種類.模型`，
    而模型階段的規則是「跑完就算達到期望」——所以審查員回
    「設計有重大問題，不通過」，只要 CLI 結束碼是 0，工作流照樣宣布
    「全綠且通過審查」。

    CLAUDE.md 硬規則第 4 條說不得以「模型說完成了」當停止條件。
    原本的實作比那還鬆：**它連模型有沒有說完成都不看，只看子程序有沒有跑完。**
    """

    通過 = "pass"
    要求修改 = "changes-requested"
    #: 讀不出約定的標記。fail-closed——由狀態機中止，不往下走也不重做。
    沒給結論 = "no-verdict"


class 結束代碼(StrEnum):
    """為什麼不往下走了。**三值，因為外圈要做的事不同。**

    原本只有 `完成`／`中止`，而 `中止` 把兩種相反的處境壓在一起：

    | 代碼 | 意思 | 外圈該做什麼 |
    |---|---|---|
    | `完成` | 全綠且通過審查 | 收工 |
    | `護欄` | **停止規則生效了**（預算、步數、卡住、結果未知、重構改壞行為） |
      改題目／改起點，**要不要放寬是人的決定** |
    | `中止` | 東西壞了（角色確定失敗：認證、額度、接線） | 照硬規則 6 診斷：環境 → 回饋 → 流程 |

    為什麼一定要分開：一個自動修復迴圈看到 `中止` 會去修，
    而護欄最省事的「修法」是**把上限調高**——那是自己拆掉執法點，
    跟 `--no-verify` 同一件事。分不出來的話，這個錯誤不會有人發現。
    """

    完成 = "done"
    #: 停止規則生效。**不是失敗**——是這個迴圈按設計停下來了。
    護欄 = "guardrail"
    中止 = "aborted"


@dataclass(frozen=True, slots=True)
class 任務:
    """要被做完的一件事。"""

    描述: str
    工作目錄: Path
    #: 上一輪走到哪、做了什麼。**跨 context window 的記憶就是這一欄。**
    #:
    #: 為什麼不從帳本讀：帳本記的全文是**遮過的**（有洞）而且超過上限會截斷。
    #: 那份是給人查的證據，不是給模型的記憶——餵回去會餵到殘缺的東西。
    #: 空字串代表第一輪——那時候不要硬塞一個空標題進提示，浪費 token 又誤導。
    前情: str = ""


@dataclass(frozen=True, slots=True)
class 結束:
    """工作流的終點。"""

    代碼: 結束代碼
    原因: str


@dataclass(frozen=True, slots=True)
class 步驟結果:
    """一個階段跑完的結果。

    `終局` 回答「這一步跑完了嗎」（三值）；`判準綠` 回答「機械閘是綠的嗎」——
    只有判準階段有，模型階段是 None。兩個問題分開，因為答案會不一致：
    閘跑完了（終局成功）但結果是紅的。
    """

    階段: 階段代碼
    終局: 終局
    判準綠: bool | None
    證據: str
    #: 只有審查階段有。同 `判準綠`——不適用的階段是 None。
    #: **欄位名不能跟型別名一樣**：dataclass 的 annotation 在 class 內部求值，
    #: 同名會讓 `審查判定 | None` 變成 `None | None`，當場 TypeError。
    審查結論: "審查判定 | None" = None
    #: 這一步花了多少。判準階段不叫模型，所以是 None——
    #: 補一個零上去會讓「沒花錢」跟「沒問到」長得一樣。
    花費: "用量 | None" = None


#: 預設走幾步就強制停。
#: 七個階段加三條回頭邊，最壞路徑約 16 步（測試↔驗證紅、實作↔驗證綠、審查→實作各一次）。
#: 抓 20 留一點餘裕。**加階段就要重算這個數**，不然一加就撞上限。
預設最多步數 = 20
#: 預設的 token 上限。**忘了傳不能等於沒有上限**——沒有預設的保證是懇求，不是保證。
#:
#: 這個數字**改過一次，而且是被實測打臉才改的**。
#:
#: 原本 500k 是憑估算：每次 ~60k × 至多 8 次模型呼叫。那個估算把最大的一塊算漏了
#: ——真跑兩輪量到的是：
#:
#:     重構 命令列.py（703 行）  refactor 498,053 ＋ review 555,433 = 1,053,486
#:     重命名 add → 相加（小題）  七階段全跑完               =   527,545
#:
#: **input token 佔 87～98%**，錢花在模型**讀檔案**上，而那跟題目大小、repo 大小
#: 成正比，不是跟提示長度成正比。500k 連一輪「重構＋審查」都跑不完。
#:
#: 要守的關係：預設上限至少等於一階實測成本乘上 TDD 階段數。
#: 一階實測成本出處：2026-08-30 今晚兩條線的 TDD 實測，第三階，sol-max，
#: 單階 848,184 token；848,184 × 7 = 5,937,288，預設向上取整到百萬。
#: **拉大不等於拿掉**：沒有上限的迴圈還是成本漏洞（§3.2 的 stop rule）。
預設最多token = 6_000_000


@dataclass(frozen=True, slots=True)
class 停止條件:
    """迴圈七欄位裡的 stop rule（§3.2）。缺它的不是迴圈，是成本漏洞。

    **兩個不同的洞，所以是兩個旋鈕**：步數擋「來回幾次」，token 擋「花多少」。
    一步可以很貴，光有步數上限對成本沒有任何保證。

    包成一個資料類別不是為了好看——stop rule 是契約的一部分，
    要能整包印進 journal、整包換掉，而不是散在函式簽章上的兩個 int。
    """

    最多步數: int = 預設最多步數
    最多token: int = 預設最多token


#: 不傳就是這個。frozen 且沒有可變欄位，所以共用一份是安全的
#: （ruff B008 不准把建構式寫進參數預設值，理由就是可變的預設會被共享）。
預設停止 = 停止條件()


class 出口標籤(StrEnum):
    """一個階段走完之後，**分得出來的所有收場**。

    原本表上只有「綠」「紅」兩格，另外三種收場藏在 `下一步()` 的 `if` 裡。
    **表印得出來、`if` 印不出來**——藏起來的邊只有讀原始碼才知道存在，
    規格把這個叫隱式控制流程。

    值 ASCII：控制流程要能整張印進 journal（§4.3）。
    """

    綠 = "green"
    紅 = "red"
    #: 不知道做了沒（逾時被殺、輸出解析不出來）。往下走或退回重做都可能把
    #: 已經做過的事再做一次（at-most-once，寧漏不重）。
    結果未知 = "unknown"
    #: 角色沒出門就掛了，或判準根本跑不起來。**那是環境，不是回饋。**
    確定失敗 = "failed"
    #: 只有審查階段做得出來：讀不出約定的判定標記。**不准當成通過。**
    沒給結論 = "no-verdict"


#: 每一種階段**做得出來**的出口。`階段定義` 拿它當窮舉的判準：少一格、多一格都建不出來。
#:
#: 為什麼不是每種階段都五格——多出來的那格**沒有任何結果走得到**。
#: 舊表上模型階段的「紅」就是這種假邊：`達到期望` 對模型階段一律回 True，
#: 所以「測試角色寫不出測試」那句話從來沒有人看過（真的失敗時走的是 `確定失敗`）。
#: 假邊跟隱式邊一樣會騙人，只是騙的方向相反：一個讓你看到走不到的路，
#: 一個讓你看不到走得到的路。
必要出口: Mapping[種類, frozenset[出口標籤]] = MappingProxyType(
    {
        種類.模型: frozenset({出口標籤.綠, 出口標籤.結果未知, 出口標籤.確定失敗}),
        種類.判準: frozenset({出口標籤.綠, 出口標籤.紅, 出口標籤.結果未知, 出口標籤.確定失敗}),
        #: 審查是唯一分得出「沒給結論」的種類——它的驗收權在判定上。
        種類.審查: frozenset(出口標籤),
    }
)


@dataclass(frozen=True, slots=True)
class 階段定義:
    """一個階段，以及它**每一種**收場各往哪走。

    `綠`／`紅` 指的是**達到期望與否**，不是「成功失敗」：
    `驗證紅` 期望的是紅，所以真的紅了才走 `綠` 那條出口。

    出口是**窮舉**的映射，不是兩格：轉移表的價值在於「印得出來、讀得完」，
    漏掉一種收場就等於那條邊藏回函式裡，讀表的人看不到它。
    """

    代碼: 階段代碼
    名稱: str
    種類: 種類
    #: 判準階段才有：True 期望全綠、False 期望紅。模型階段是 None。
    期望綠: bool | None
    #: 出口標籤 → 去處（下一個階段，或結束）。窮舉，由 `必要出口` 定義該有哪些。
    出口: Mapping[出口標籤, "階段代碼 | 結束"]

    def __post_init__(self) -> None:
        """出口沒窮舉就當場炸，然後把這張表凍起來。

        **錯要在建表當場炸，不要等跑到那一階**——同 `_檢查角色表` 的理由：
        那時 token 已經花掉了，而且裸 `KeyError` 說不出少的是哪一格。

        凍起來是因為表是模組層級共用的一份：改得動就等於跑到一半可以重接線，
        那正是這次要刪掉的那種看不見的行為。
        """
        該有 = 必要出口[self.種類]
        缺 = sorted(標籤.value for 標籤 in 該有 - frozenset(self.出口))
        多 = sorted(標籤.value for 標籤 in frozenset(self.出口) - 該有)
        if 缺 or 多:
            訊息 = f"{self.代碼.value} 的出口沒窮舉：缺 {缺}、多出走不到的 {多}"
            raise ValueError(訊息)
        object.__setattr__(self, "出口", MappingProxyType(dict(self.出口)))


#: 跑一個階段。收軌跡是為了讓角色看得到前面發生什麼（七欄位的 Memory）。
執行器 = Callable[[階段定義, 任務, tuple[步驟結果, ...]], 步驟結果]
#: 機械判準：跑完回 (收場, 證據)。**不是模型**——驗收權不在執行者手上。
判準 = Callable[[任務], tuple[判準終局, str]]
