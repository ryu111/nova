class 判準結果(tuple[判準終局, str]):
    """一次機械判準的結構化結果；保留舊二元組的解包與索引方式。"""

    _等待毫秒: int

    def __new__(
        cls,
        終局: 判準終局,
        證據: str,
        等待毫秒: int = 0,
    ) -> "判準結果":
        """建立結果並把等待毫秒放在二元組之外。"""
        結果 = super().__new__(cls, (終局, 證據))
        object.__setattr__(結果, "_等待毫秒", 等待毫秒)
        return 結果

    @property
    def 終局(self) -> 判準終局:
        """回傳判準終局。"""
        return self[0]

    @property
    def 證據(self) -> str:
        """回傳判準證據。"""
        return self[1]

    @property
    def 等待毫秒(self) -> int:
        """回傳拿到閘額度前的等待毫秒數。"""
        return self._等待毫秒

    def __setattr__(self, 名稱: str, 值: object) -> None:
        """拒絕改寫結果。"""
        訊息 = f"判準結果不可變：{名稱}={值!r}"
        raise AttributeError(訊息)


