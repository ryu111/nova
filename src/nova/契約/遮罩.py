"""遮罩的型別：**遮過的文字跟沒遮過的文字，在型別上要分得開。**

## 為什麼型別住這裡、函式住載體

`遮罩()` 要讀 `os.environ` 才知道哪些值是祕密——**那是載體的知識**
（把模型從圖上刪掉，環境變數還在，所以它住載體）。

但「這段字遮過了」是一個**跨層流動的事實**：成果帳、事件帳本、
收件匣的歸檔都要標記它。跨層流動的結構化證據住契約層（§4.3），
而且**契約不准 import 載體**——反過來才對。

## 決策 0002 的第一個實例

以前遮罩靠四個落盤點各自記得呼叫 `遮罩()`：

```
命令列.py   成果帳的任務
收件.py     接續票的前情
收件.py     歸檔的原始請求
記帳.py     模型回應
```

2026-08-30 發現**四個裡漏了一個**（PR #95：模型講的話遮了、
使用者自己打的那句話沒遮），而且是靠真的跑一次端到端才看見的。
repo 是 public，**洩漏一次就是永久的**——GitHub 的快取與別人的
clone 收不回來。

所以把「你必須記得的事」變成「你不得不傳的型別」：
落盤欄位收 `已遮罩文字`，餵裸 `str` 在 mypy 就紅。

## 兩道網，缺一不可

| 網 | 擋什麼 | 擋不住什麼 |
|---|---|---|
| `NewType` ＋ mypy | 忘了呼叫遮罩（最常見的那種） | 硬轉 |
| `tests/驗收/test_沒遮過的字進不了落盤點.py` | 在別的檔案裡硬轉 | — |

只有第一道的話，一句 `已遮罩文字(祕密)` 就繞過去了，而且它編得過。
"""

from dataclasses import dataclass
from typing import NewType

#: 遮過的文字。**落盤欄位一律收這個型別，不收裸 `str`。**
#:
#: 這個建構子**只准出現在本檔案裡**，由 `test_不准在遮罩以外的地方硬轉`
#: 守著。別的地方要造，走 `已經遮過了()`——那條路會逼你寫下理由。
已遮罩文字 = NewType("已遮罩文字", str)


def 已經遮過了(文字: str, *, 因為: str) -> 已遮罩文字:
    """**逃生口，而且會留下痕跡。**

    有些字確實已經遮過，只是型別資訊在路上掉了。兩個真實的例子：

    - 從磁碟讀回來的 JSON：寫進去的時候遮過，讀回來卻只是 `str`。
    - `遮罩()` 自己：它剛做完那件事，但輸出是 `str` 的運算結果。

    `因為` 是**必填**的：斷言要說得出理由。沒有它，這個函式會退化成
    一個安靜的 cast，而安靜的 cast 正是這條規則要防的東西。
    寫下來的理由會留在程式碼裡，之後 grep 得到、review 看得見。

    **空字串也不算理由。** 型別擋得住「不傳」，擋不住 `因為=""`——
    那條縫要用執行期的檢查補，不然必填只是形式。
    """
    if not 因為.strip():
        訊息 = "已經遮過了() 要說得出理由：這段字為什麼可以當成遮過的？"
        raise ValueError(訊息)
    return 已遮罩文字(文字)


@dataclass(frozen=True, slots=True)
class 遮罩結果:
    """遮完的文字，加上**遮掉幾處**。

    `遮掉幾處` 不是統計用的裝飾品：0 代表「這份是原文」，
    大於 0 代表「你看到的東西缺了幾塊」。少了它，兩者長得一樣。
    """

    文字: 已遮罩文字
    遮掉幾處: int
