"""護欄原因：撞到停止政策時「是哪一種」的那組值，三層共用。

契約（`工作流.結束`、`節點`）、迴圈（撞護欄的那幾行）與載體（收尾補上驗收紅、
落成果帳）寫的都是這一組，所以它自己一個模組，不掛在其中任何一層底下。

放這裡是因為它誰也不 import：`契約.節點` 反過來 import `契約.工作流`，
enum 留在 `節點` 的話 `結束.護欄原因` 就標不死型別（會繞成環）。

識別字中文、值 ASCII——成果帳的 JSON 就是照這個字寫的。
"""

from enum import StrEnum


class 護欄原因(StrEnum):
    """被停止政策攔下的原因——節點、工作流與收尾共用同一組值。"""

    預算 = "budget"
    步數 = "steps"
    逾時 = "timeout"
    無進展 = "stagnation"
    扇出超限 = "fanout-limit"
    輸出不合約 = "invalid-output"
    #: 不准動測試的那一階**同一輪第二次**動了測試（階段邊界發的）。第一次不收線，
    #: 只是「這一步不算數、退回測試員」；再犯才落這一格。修法是人去看那幾個檔，
    #: 不是去查扇出設定，所以不借 `fanout-limit` 那一格。
    動了測試 = "touched-tests"
    #: 重構把行為改掉了（狀態機發的）。修法是「退回上一個綠燈」，
    #: 不是去看模型回應格式，所以不借 `invalid-output` 那一格。
    重構改壞行為 = "refactor-broke-behavior"
    #: `驗證紅` 連續判成綠達門檻（狀態機發的）：這張票本來就沒有紅可看
    #: （補紀錄／補登記／重構型工作）。修法是人回去重新切題，不是叫測試員再寫一次，
    #: 跟「同一批紅一直重現」的 `stagnation` 是兩件事，所以各有各的一格。
    沒有紅可看 = "no-red-to-see"
    #: 模型說做完了、票宣告的驗收指令不同意（收尾發的）。修法是「回去重做」，
    #: 跟重構改壞行為的「退回上一個綠燈」是兩件事，所以各有各的一格。
    驗收紅 = "acceptance-failed"
