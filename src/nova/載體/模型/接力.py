"""接力：一串腦，前一顆失敗就換下一顆。

`接力腦` 本身也是一顆腦（實作 `語言模型`），所以它可以被 `角色` 持有，
也可以被套進另一條鏈——組合，不是繼承。

**最關鍵的一條規則**：能不能換下一顆，要看**權限**。

| 上一顆的終局 | 唯讀 | 可編輯 |
|---|---|---|
| 成功 | 不用換 | 不用換 |
| 確定失敗（請求沒出門） | 換 | 換 |
| **結果未知**（可能做了一半） | **換** | **不換** |

唯讀沒有副作用可以重做；可編輯可能已經改了檔案，換一顆就是做第二次。
這就是 at-most-once：寧漏不重。
"""

from collections.abc import Sequence
from dataclasses import dataclass, field, replace

from nova.契約.模型回應 import 回應, 失敗代碼, 用量, 終局
from nova.契約.角色 import 呼叫選項, 權限, 語言模型, 預設選項

_證據上限 = 3000

#: 同一顆腦連續這麼多次回同一種失敗，就當成「這個端點壞了」，不准再接力。
#: 「這一次呼叫失敗」該接力，「端點壞了」該當場停下並指名——兩者反應相反。
連續失敗上限 = 3

#: 只有端點本身的故障才會累進熔斷；額度、型號與安裝問題照舊換備援。
_端點故障代碼 = frozenset({失敗代碼.上游, 失敗代碼.逾時})


@dataclass(frozen=True, slots=True)
class 連續失敗紀錄:
    """某顆腦「同一種錯連著幾次」的計數。換一種錯就重新算。

    `原文` 記著最後那一次的錯誤全文——判定壞掉之後不會再有新的一次呼叫，
    「指名端點與原文」就只能靠這裡記著的字長出來，不准退化成「呼叫失敗」。
    """

    代碼: 失敗代碼
    次數: int
    原文: str


#: 端點健康表：端點網址（沒有網址的腦用名稱）→ 連續失敗紀錄。
#:
#: **壞的是那台服務，不是某一條鏈的物件**，所以這份表要一個工作流一份、四階共用。
#: 綁在單一鏈上的話，「每階各一次 409」只會各自累計到 1，
#: 四條線照樣一路接力燒到底——那正是出事那晚的形狀。
type 端點健康表 = dict[str, 連續失敗紀錄]


def 新端點健康表() -> 端點健康表:
    """開一份新的端點健康表。組裝點建一次，傳給同一輪的每一條接力鏈。"""
    return {}


@dataclass(frozen=True, slots=True)
class 缺席腦:
    """一顆**沒裝**的腦。被叫到就回確定失敗，讓接力換下一顆。

    存在的理由：`建立()` 會當場 `找執行檔()`，所以一串裡少裝一家，
    整條鏈在建構期就 `FileNotFoundError`——**連裝好的那家都不會被叫到**。
    接力鏈存在的理由就是「這顆不行換下一顆」，卻在建構期先自己垮了。

    回**確定失敗**不是結果未知：請求根本沒出門，沒有副作用，
    所以可以安全地換下一顆。判成結果未知的話，可編輯模式下接力當場停。
    """

    名稱: str
    原因: str

    def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
        """不會真的問任何東西。簽章要跟 `語言模型` 一樣才塞得進鏈上。"""
        del 提示, 選項
        return 回應(
            文字=self.原因,
            終局=終局.確定失敗,
            失敗代碼=失敗代碼.未安裝,
            原始結束碼=-1,
            對話識別碼=None,
            用量=用量(輸入token=0, 輸出token=0),
        )


def 可以換下一顆(終: 終局, 可以做什麼: 權限, 代碼: 失敗代碼 = 失敗代碼.未知) -> bool:
    """上一顆這樣收場，可以換下一顆重做嗎？

    純函式，這是整個接力的判斷核心——它錯了，重試就會重做副作用。

    **終局決定「能不能重做」，失敗代碼決定「重做有沒有意義」**，兩個問題不同：

    | 情況 | 能不能重做 | 重做有沒有意義 |
    |---|---|---|
    | `model-not-found` | 能（請求沒出門） | 有——下一顆可能好好的 |
    | `permission-denied` | 能 | **沒有**——下一顆撞同一堵牆 |

    權限被擋是唯一一條「能重做但不該重做」的：沙箱與權限旗標是 nova 自己組的，
    對整條鏈都一樣。換三顆腦就是白燒三次呼叫，最後回報同一件事。
    """
    if 代碼 is 失敗代碼.權限被擋:
        return False
    if 終 is 終局.確定失敗:
        return True
    if 終 is 終局.結果未知:
        return 可以做什麼 is 權限.唯讀
    return False


@dataclass(frozen=True, slots=True)
class 接力腦:
    """一串腦。照順序試，第一顆成功就停。"""

    名稱: str
    腦們: tuple[語言模型, ...]
    #: 每顆腦目前連續失敗的樣子（形狀與共用的理由見 `端點健康表`）。
    #: 同一輪的每一條鏈要拿同一份：`新端點健康表()` 建一次傳進來。
    #: 不傳就自己開一份，單獨用一條鏈的呼叫端不受影響。
    端點健康: 端點健康表 = field(default_factory=新端點健康表, compare=False)

    def __post_init__(self) -> None:
        """空的鏈會回一個假的成功——當場擋掉。"""
        if not self.腦們:
            訊息 = "接力腦至少要有一顆腦"
            raise ValueError(訊息)

    def 詢問(self, 提示: str, *, 選項: 呼叫選項 = 預設選項) -> 回應:
        """照順序試，回第一個成功的；全掛就回最後一顆並附上試過誰。

        **回傳的用量是整條鏈的總和，不是最後一顆的。** 只回最後一顆的話，
        前面幾顆燒掉的 token 在預算裡憑空消失——而 `迴圈/工作流.py` 的
        token 上限就靠這個數字累計。**算錯的上限也是成本漏洞。**
        """
        試過的腦: list[str] = []
        各次用量: list[用量] = []
        # **型號只給第一家。** 各家的模型命名空間不交集（`轉接.py` 原樣傳不翻譯），
        # 所以指名的型號對下一家一定不存在——備援會用一個不存在的型號再炸一次，
        # 而帳面上看起來像「兩家都掛了」。換家就用那家的預設。
        # 思考深度不清：那是鏈上共通的設定，清掉等於偷偷改行為。
        換家選項 = replace(選項, 模型=None)
        最新回應 = _沒問到任何一顆()
        for 序, 腦 in enumerate(self.腦們):
            健康表鍵 = getattr(腦, "網址", 腦.名稱)
            既有壞紀錄 = self._壞掉的紀錄(健康表鍵)
            if 既有壞紀錄 is not None:
                # 短路要在打出去**之前**：壞的是那台服務的旗標，
                # 多打幾次不會把它打好，只會把時間燒完。
                return _端點壞了回應(腦.名稱, 既有壞紀錄, 各次用量)
            最新回應 = 腦.詢問(提示, 選項=選項 if 序 == 0 else 換家選項)
            各次用量.append(最新回應.用量)
            if 最新回應.終局 is 終局.成功:
                self._記下成功(健康表鍵)
                return replace(最新回應, 用量=_加總用量(各次用量))
            if _端點故障嗎(最新回應):
                失敗紀錄 = self._記下失敗(健康表鍵, 最新回應.失敗代碼, 最新回應.文字)
                if _已達連續失敗上限(失敗紀錄):
                    訊息 = _端點壞了訊息(腦.名稱, 失敗紀錄)
                    return replace(最新回應, 文字=訊息, 用量=_加總用量(各次用量))
            else:
                # 不是端點故障的回答不進健康計數，也會打斷「連續」。
                self.端點健康.pop(健康表鍵, None)
            試過的腦.append(f"{腦.名稱}:{最新回應.失敗代碼.value}")
            if not 可以換下一顆(最新回應.終局, 選項.權限, 最新回應.失敗代碼):
                break
        return replace(
            最新回應,
            文字=_接力訊息(試過的腦, 最新回應.文字),
            用量=_加總用量(各次用量),
        )

    def _記下成功(self, 名稱: str) -> None:
        """這顆腦通了，把它的連續失敗計數清掉——「連續」是連續，不是總數。"""
        self.端點健康.pop(名稱, None)

    def _記下失敗(self, 名稱: str, 代碼: 失敗代碼, 原文: str) -> 連續失敗紀錄:
        """記下這顆腦又失敗一次，回傳更新後的紀錄。換一種錯就從 1 重新算。"""
        上次紀錄 = self.端點健康.get(名稱)
        連續次數 = 上次紀錄.次數 + 1 if 上次紀錄 is not None and 上次紀錄.代碼 is 代碼 else 1
        最新紀錄 = 連續失敗紀錄(代碼=代碼, 次數=連續次數, 原文=原文)
        self.端點健康[名稱] = 最新紀錄
        return 最新紀錄

    def _壞掉的紀錄(self, 名稱: str) -> 連續失敗紀錄 | None:
        """這顆腦在這之前就被判定壞掉了嗎？是的話回那筆紀錄，呼叫端不准再打出去。"""
        紀錄 = self.端點健康.get(名稱)
        return 紀錄 if 紀錄 is not None and _已達連續失敗上限(紀錄) else None


def _已達連續失敗上限(紀錄: 連續失敗紀錄) -> bool:
    """撞到上限就不是「這一次呼叫失敗」而是「端點壞了」——這條線只畫在這裡一次。"""
    return 紀錄.次數 >= 連續失敗上限


def _端點故障嗎(答: 回應) -> bool:
    """只把端點故障送進健康表；缺席腦與額度耗盡仍照原策略接力。"""
    if 答.失敗代碼 in _端點故障代碼:
        return True
    # 連線拒絕沿用既有的 `未安裝` 代碼，但本地 HTTP 訊息能辨識它。
    return 答.失敗代碼 is 失敗代碼.未安裝 and "連不上 " in 答.文字


def _沒問到任何一顆() -> 回應:
    """一顆都沒問成的墊底答案。實務上不會流出去——第一顆壞掉就先 return 了。"""
    return _接力自己生的失敗(
        "接力鏈上沒有任何一顆腦被問到", 失敗代碼.未知, 用量(輸入token=0, 輸出token=0)
    )


def _端點壞了回應(腦名稱: str, 紀錄: 連續失敗紀錄, 花過: Sequence[用量]) -> 回應:
    """判定壞掉之後那一次的答案：不打出去，但訊息與失敗代碼跟當初判定時同一類。"""
    # 花過是空的就不能交給 `_加總用量`：它會把「沒有任何一顆花過」加成 `成本美金=0`，
    # 而一個假的 0 在帳面上看起來像個真數字。
    總用量 = _加總用量(花過) if 花過 else 用量(輸入token=0, 輸出token=0)
    return _接力自己生的失敗(_端點壞了訊息(腦名稱, 紀錄), 紀錄.代碼, 總用量)


def _接力自己生的失敗(文字: str, 代碼: 失敗代碼, 花的: 用量) -> 回應:
    """接力層自己長出來的失敗答案。

    請求根本沒送出去，所以是**確定失敗**、也沒有上游的結束碼可報（`-1`）。
    """
    return 回應(
        文字=文字,
        終局=終局.確定失敗,
        失敗代碼=代碼,
        原始結束碼=-1,
        對話識別碼=None,
        用量=花的,
    )


def _端點壞了訊息(腦名稱: str, 紀錄: 連續失敗紀錄) -> str:
    """收成「端點壞了」那一句：指名是哪顆腦、哪一種錯，後面接上游原文。

    原文一定要留著——只說「呼叫失敗」的話，看訊息的人不知道要去修哪台服務。
    """
    抬頭 = f"[端點壞了 {腦名稱} 連續 {紀錄.次數} 次 {紀錄.代碼.value}，不再接力]"
    return f"{抬頭} {紀錄.原文}"[:_證據上限]


def _接力訊息(試過: Sequence[str], 原文: str) -> str:
    """全鏈都失敗那一句：照順序列出試過誰、各自收在哪一種失敗代碼。"""
    return f"[接力 {' → '.join(試過)}] {原文}"[:_證據上限]


def _加總用量(花過: Sequence[用量]) -> 用量:
    """把鏈上每一顆的用量加起來。

    **有一顆給不出來的欄位就整個不給**（`成本美金`、`快取讀取token`、`思考token`）。
    CLAUDE.md：不准為了讓三家對稱而自己估算——只有 claude 給成本，
    把「claude 那顆的成本」當成「整條鏈的成本」是低報，
    而**低報的成本比沒有成本更危險，它看起來像個數字**。

    token 數三家都給，所以直接加。`快取建立token` 是唯一的例外，
    它為什麼不套這條規則寫在 `_快取建立加總` 裡。
    """
    if len(花過) == 1:
        return 花過[0]

    def 全有才加(取: str) -> int | None:
        值們 = [getattr(用, 取) for 用 in 花過]
        return None if any(值 is None for 值 in 值們) else sum(值們)

    成本們 = [用.成本美金 for 用 in 花過]
    return 用量(
        輸入token=sum(用.輸入token for 用 in 花過),
        輸出token=sum(用.輸出token for 用 in 花過),
        快取讀取token=全有才加("快取讀取token"),
        快取建立token=_快取建立加總(花過),
        思考token=全有才加("思考token"),
        成本美金=None if any(本 is None for 本 in 成本們) else sum(成本們),  # type: ignore[arg-type]
    )


def _快取建立加總(花過: Sequence[用量]) -> int | None:
    """快取建立的 `None` 是「這家沒有這種東西」，不是「不知道」——當 0 加。

    整條鏈都沒有才留白；只要有一顆給了，就不准被別顆的 `None` 吃掉，
    否則 `新鮮token` 少報那一顆真的燒掉的量。
    """
    建們 = [用.快取建立token for 用 in 花過]
    if all(建 is None for 建 in 建們):
        return None
    return sum(建 or 0 for 建 in 建們)
