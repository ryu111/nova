"""生圖：三家裡只有 agy 有，而且非全開會**靜默假成功**。

`tests/驗收/test_真cli契約.py::test_agy生圖要全開權限檔案才進得了工作目錄`
是燒 token 量到的行為契約。這個模組把那份契約變成擋得住的規則——
契約記錄「事實是這樣」，這裡讓人違反不了。

## 兩條寫進殼裡的事實

1. **只有 agy 有 `generate_image`。** claude 與 codex 沒有，
   派給它們只會得到一段「我做不到」的散文，而終局是成功。
2. **可編輯權限下會假成功。** `generate_image` 本身會成功，但圖產在
   `~/.gemini/antigravity-cli/brain/<sid>/`——`--add-dir` 管不到那裡。
   搬進工作目錄要再跑一道 shell，那道在可編輯下被擋，
   **而 CLI 仍然回 `status: SUCCESS`、`response: ""`。**

所以權限**不是參數**，一律全開。能傳就代表能傳錯，而傳錯的樣子跟成功一模一樣。

## 驗收看檔案，不看模型說什麼

硬規則 5：不得以「模型說完成了」當停止條件。跑完之後工作目錄裡**多**了圖才算成功。
「多了」不是「有」——只看有沒有的話，第二次呼叫會被第一次的產物騙過去。

沒生出來一律降成 `結果未知`**而不是確定失敗**：圖可能已經生出來了，
只是留在 brain 目錄搬不過來。判成確定失敗會讓上層重跑，
而重跑是再生一張圖、再花一次錢。
"""

from dataclasses import dataclass, replace
from pathlib import Path

from nova.契約.模型回應 import 回應, 失敗代碼, 終局
from nova.契約.角色 import 呼叫選項, 權限, 預設逾時秒
from nova.載體.帳本 import 不記帳本, 帳本
from nova.載體.模型.記帳 import 記帳腦
from nova.載體.模型.轉接 import 家族, 建立

#: 只有這家有 `generate_image`。**不是設定項**——另外兩家不是「還沒支援」，
#: 是真的沒有這個工具。
生圖那家: 家族 = "agy"

#: 算圖的副檔名。`generate_image` 實測產出 jpg，轉檔多半轉成 png。
圖的副檔名 = frozenset({".png", ".jpg", ".jpeg", ".webp"})


@dataclass(frozen=True, slots=True)
class 生圖結果:
    """模型講的話 ＋ **真的出現在工作目錄裡的檔案**。

    兩個都給是因為它們會不一致，而不一致正是這個模組要抓的東西。
    """

    答: 回應
    圖檔: tuple[Path, ...]


@dataclass(frozen=True, slots=True)
class 生圖選項:
    """怎麼跑的那幾個旋鈕。

    **刻意不用 `呼叫選項`**：那個有 `權限` 欄位，而生圖的權限不給選
    （可編輯下會靜默假成功，見模組 docstring）。收成物件是因為
    ruff `PLR0913` 會紅，而那條規則說的是對的——一長串具名參數
    會讓呼叫端看不出漏了哪個。
    """

    執行檔: Path | None = None
    逾時秒: float = 預設逾時秒
    #: 給上一次的 `對話識別碼` 就能接著改上一張圖。
    #: **沒有「保留對話」**：agy 對話一律落地。
    續接: str | None = None


#: 不傳就是這個。frozen 且沒有可變欄位，共用一份是安全的。
預設生圖選項 = 生圖選項()


def 生圖(
    描述: str,
    *,
    工作目錄: Path,
    帳: 帳本 | None = None,
    選項: 生圖選項 = 預設生圖選項,
) -> 生圖結果:
    """叫 agy 生一張圖，並且**自己確認檔案真的在**。

    沒有 `權限` 參數是刻意的：可編輯下這條路會靜默假成功（見模組 docstring）。

    `續接` 給上一次的 `對話識別碼` 就能**接著改上一張圖**——實測有效
    （見 `tests/整合/test_生圖.py::Test續接` 的 docstring）。
    **沒有 `保留對話`**：agy 對話一律落地，多一個永遠是 True 的旗標
    只會讓人以為忘了給就續接不到。
    """
    腦 = 記帳腦(內層=建立(生圖那家, 執行檔=選項.執行檔), 帳=帳 or 不記帳本())
    本來就有 = _圖檔們(工作目錄)
    答 = 腦.詢問(
        _提示(描述, 工作目錄),
        選項=呼叫選項(
            工作目錄=工作目錄,
            權限=權限.全開,
            逾時秒=選項.逾時秒,
            續接=選項.續接,
        ),
    )
    新的 = tuple(sorted(_圖檔們(工作目錄) - 本來就有))
    if 答.終局 is 終局.成功 and not 新的:
        return 生圖結果(答=_降級(答, 工作目錄), 圖檔=())
    return 生圖結果(答=答, 圖檔=新的)


def _提示(描述: str, 工作目錄: Path) -> str:
    """要它自己把檔案搬過來。

    圖預設落在 agy 的 brain 目錄，不講就不會過來——而且它得自己想到要轉檔
    （`generate_image` 給的是 jpg）。這一段是提示不是保證，
    所以後面一定要用檔案系統驗收。
    """
    return (
        f"用 generate_image 產生：{描述}。\n"
        f"然後把產生的圖片檔複製到 {工作目錄} 底下（需要轉檔就用 sips）。\n"
        f"最後回報檔案的完整路徑與大小。"
    )


def _圖檔們(目錄: Path) -> frozenset[Path]:
    if not 目錄.is_dir():
        return frozenset()
    return frozenset(檔 for 檔 in 目錄.iterdir() if 檔.suffix.lower() in 圖的副檔名)


def _降級(答: 回應, 工作目錄: Path) -> 回應:
    """模型說成功但檔案不在——那是**結果未知**，不是確定失敗。

    原因要留在證據裡：只回一個終局的話，查的人得自己重建為什麼。
    """
    原因 = (
        f"[生圖] 模型回報成功，但工作目錄 {工作目錄} 裡沒有新的圖檔。"
        f"圖可能還留在 agy 的 brain 目錄（搬檔那道沒跑成）。"
        f"**不要自動重跑**——重跑是再生一張圖、再花一次錢。\n\n{答.文字}"
    )
    return replace(答, 終局=終局.結果未知, 失敗代碼=失敗代碼.未知, 文字=原因)
