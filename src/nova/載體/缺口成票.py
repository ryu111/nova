"""空收件匣時，從規格對照挑一個缺口落成一張票。

nova 的迴圈本來只閉在「維護」那半邊：閘紅落修理票、撞上限落接續票，
**推進票一張都不是自己生的**。這裡補的就是那個缺口——空手不再等於沒事做。

## 挑法不在這裡發明

專案自己那份目標對照（見下面的候選位置）的「所以下一批該做什麼」
自己就寫明了挑哪幾條與為什麼（「是別條缺口的前提」、「成本最低而風險最實」、
「唯一不需要新模型呼叫」）。這個模組只是**把那份文件讀出來**，
不另立第二套優先序，也**不叫模型去想一個新的點**：
硬規則二不准同一個對話自寫自評，而 nova 生票、nova 做、nova 驗那條鏈，
源頭必須追得到一份外部文件。文件不在、文件裡沒有缺口，就不挑。
"""

import re
from collections.abc import Callable
from pathlib import Path
from typing import NamedTuple

from nova.載體.健康度 import 健康度指標, 准生票嗎, 票種
from nova.載體.健康度查詢 import 查健康度指標
from nova.載體.收件 import 丟一件, 收件目錄, 時鐘

#: 目標對照住在專案裡的哪裡。**相對路徑寫死是刻意的**：
#: 它是這條鏈唯一的外部來源，可以由設定檔換掉的話就不叫外部來源了。
#:
#: 走的是「甲、約定一個與專案無關的位置」：位置由 nova 定死一組約定，
#: 任何專案照著擺一份就能被挑點——不必為了「我的目標在哪」多一個設定檔，
#: 也就不會有人把判斷邏輯偷渡進別人的設定檔裡（CLAUDE.md 的那條）。
#: 最後那一個是 nova 自己現有的那份，先留著當相容位置，
#: 免得這一格順手去搬 nova 的文件（那是另一張票）。
_目標對照候選相對路徑 = (
    Path(".nova") / "目標.md",
    Path("docs") / "目標.md",
    Path("docs") / "設計" / "13-規格做到哪了.md",
)

#: 文件裡挑下一批的那一段。段落標題以外的部分不看。
_下一批標題 = "## 所以下一批該做什麼"

#: 那一段裡「這是挑出來的一條」長什麼樣：`**一、§4.3 隔離工作區接到扇出上。**`
#: 只認帶序號的粗體開頭——同一段裡的其他粗體（例如「挑三條」那句總結）不算一條。
_一條缺口 = re.compile(r"\*\*[一二三四五六七八九十]、\s*(.+?)\s*\*\*", re.DOTALL)

#: 段落之間的空行。
_段落之間 = re.compile(r"\n\s*\n")


class _挑到的缺口(NamedTuple):
    """挑出來的那一條，以及它是從哪份目標對照挑的（出處要寫進票裡）。"""

    出處: str
    標題: str
    原文: str


class 落票結果(NamedTuple):
    """落了票，或者為什麼沒落。

    **不能只回 `Path | None`**：那樣「健康度擋下來」跟「文件裡沒缺口」
    長得一模一樣，人看不出 nova 是在背壓還是在發呆。
    """

    票: Path | None
    #: 沒落票的原因；真的落了票就是 `None`。
    擋下的理由: str | None


def 空手時落一張票(
    專案: Path,
    *,
    查指標: Callable[[Path], 健康度指標] | None = None,
) -> 落票結果:
    """收件匣空的時候呼叫：健康度全綠且挑得到缺口，才落一張票。

    **健康度閘在這個函式裡面，不在呼叫端。** `命令列.py` 有兩個呼叫點
    （`nova 跑` 空手那條、`nova 收件` 空手那條），閘擺在呼叫端就是
    「有一個忘了就等於沒有」——那正是這一格要修的形狀：
    `載體/健康度.py` 寫好了、有四項各紅一次的窮舉測試，
    **卻沒有任何人呼叫它**。

    `查指標` 從參數收進來（依賴反轉）：閘的判斷是純的，去問 `gh` 的那一半
    留在載體的另一個入口，測試才不必真的連網。

    **紅的時候往佇列丟工作，只是把紅的東西堆更高。**
    """
    # **哨兵是 `None`，不是把 `查健康度指標` 寫成預設值。** 預設值在 `def` 那一刻
    # 就綁死函式物件，走 CLI 進來的測試換不掉它——換不掉就等於這條路上的
    # 健康度永遠是真的去問 `gh`，在測試環境一律「查不到」而被背壓擋死。
    判定 = 准生票嗎((查指標 or 查健康度指標)(專案), 票種=票種.推進)
    if not 判定.放行:
        return 落票結果(票=None, 擋下的理由=判定.訊息)
    缺口 = _從目標對照挑一個缺口(專案)
    if 缺口 is None:
        return 落票結果(票=None, 擋下的理由="目標對照不在，或裡面沒有寫下一批要做什麼。")
    return 落票結果(票=丟一件(_一張票(缺口), 來源=時鐘, 目錄=收件目錄(專案)), 擋下的理由=None)


def _從目標對照挑一個缺口(專案: Path) -> _挑到的缺口 | None:
    """依序試每個約定位置，回第一份挑得出缺口的那一條；都挑不出來回 `None`。"""
    for 相對路徑 in _目標對照候選相對路徑:
        內文 = _讀得到才讀(專案 / 相對路徑)
        if 內文 is None:
            continue
        挑到的 = _文件自己挑的第一條(內文)
        if 挑到的 is not None:
            標題, 原文 = 挑到的
            return _挑到的缺口(出處=相對路徑.as_posix(), 標題=標題, 原文=原文)
    return None


def _讀得到才讀(文件: Path) -> str | None:
    """讀不到（不存在、不是檔、不是 UTF-8）就當這個位置沒有目標對照，換下一個位置。"""
    try:
        return 文件.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def _文件自己挑的第一條(內文: str) -> tuple[str, str] | None:
    """讀出文件自己挑的第一條，回（標題, 那一段原文）。文件沒挑就回 `None`。"""
    下一批那段 = _下一批那一段(內文)
    if 下一批那段 is None:
        return None
    for 段落 in _段落之間.split(下一批那段):
        原文 = 段落.strip()
        找到 = _一條缺口.match(原文)
        if 找到 is not None:
            return 找到.group(1).rstrip("。"), 原文
    return None


def _下一批那一段(內文: str) -> str | None:
    """切出「所以下一批該做什麼」到下一個二級標題之間的內容。"""
    起 = 內文.find(_下一批標題)
    if 起 < 0:
        return None
    剩下 = 內文[起 + len(_下一批標題) :]
    下一個標題 = re.search(r"^## ", 剩下, re.MULTILINE)
    return 剩下[: 下一個標題.start()] if 下一個標題 else 剩下


def _一張票(缺口: _挑到的缺口) -> str:
    """四欄齊全的票。

    **自己生的票要吃得下自己的檢查**：`丟一件` 對自主來源要求四欄齊全與
    機械驗收（`載體/收件.py`），生得出一張被自己擋下來的票是最難看的那種假綠。
    """
    return f"""# 缺口：{缺口.標題}

這一條不是這裡想出來的，是 `{缺口.出處}`
的「所以下一批該做什麼」自己挑出來的第一條。挑法與優先序都在那份文件裡。

## 輸入

- `{缺口.出處}`：這條缺口的原文與為什麼是它——

{缺口.原文}

## 輸出

把上面那條缺口補起來，並回頭更新 `{缺口.出處}`
對應那一列的現況與證據——表跟碼不同步的話，下一輪會再挑一次同一條。

## 驗收

<!--nova:驗收 uv run nova 閘 提交-->
<!--nova:驗收 uv run pytest tests/單元 tests/整合 -q-->

## 停止

- 上面兩條驗收都綠就停。
- **只做這一條缺口**：文件裡其他缺口各自是一個點，順手做會做不完。
- 撞到預算或輪次上限就交給接續票，不要在這一輪硬推。
"""
