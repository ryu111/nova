"""目標 → 規劃輸入 → 分派單 → 票：中間那條線。

`迴圈/計畫.py` 的 `執行計畫員` 與 `驗證分派單` 兩半早就寫好了，缺的是把它們
串起來的那一段。這裡就是那一段，而且只到「票」為止：**不接 CLI、不寫收件匣**。

三條規矩寫死在這條鏈上：

1. **驗證沒過不准落票。** 計畫員產出、`驗證分派單` 機械把關——模型提案、
   機械否決，不是同一個對話自寫自評（CLAUDE.md 硬規則二）。
2. **生出來的票要吃得下自己的檢查。** 四欄（輸入／輸出／驗收／停止）齊全，
   過得了 `載體/收件.py` 的 `缺哪幾欄`。生得出一張自己會擋下來的票是
   最難看的那種假綠。
3. **那一次模型呼叫要被管住。** 走 `迴圈/節點.py` 的 `單獨執行`，停止政策
   （步數、逾時、`用量` 對上 `最多token` 的預算）就在那一層生效；被護欄攔下來
   時這裡拋 `計畫員沒交出分派單`，不會靜靜當成「沒有分派單」。

**`產生器` 的角色提示與記帳不在這一層**，也不該在：它就是一次模型呼叫，
照 repo 既有的形狀由呼叫端組好再傳進來——提示由 `迴圈/角色工廠.py` 那種藍圖
決定，花費由 `載體/模型/記帳.py` 的記帳腦包在腦外面記。這條鏈只負責
「怎麼問、怎麼驗、怎麼落成票」，換一顆腦不必動這個檔（依賴反轉）。
"""

from dataclasses import dataclass

from nova.契約.分派 import 分派單, 分派單問題, 分派項目
from nova.契約.節點 import 停止政策, 節點上下文, 節點成功, 節點結果, 邊包
from nova.迴圈.節點 import 單獨執行
from nova.迴圈.計畫 import (
    來源自上下文,
    執行限制,
    工件參照,
    工作現況,
    規劃輸入,
    規劃輸入版本,
    規劃輸入結構,
    計畫員節點,
    計畫產生器,
    驗證分派單,
)


@dataclass(frozen=True, slots=True)
class 規劃票:
    """一項分派落成的一張票。

    `內容` 是執行者會讀到的那份 markdown；`項目` 是同一件事的結構化原文。
    **兩個都留**：轉成 markdown 是不可逆的，落票的人常常還要照 `分支`、`必要`、
    `前置項目` 決定排程與擺放，那些欄位在字串裡只剩人看得懂。
    """

    識別碼: str
    內容: str
    項目: 分派項目


class 分派單不合格(Exception):
    """驗證沒過——一張票都不落，並指名哪一項的哪一欄不合格。"""

    def __init__(self, 問題們: tuple[分派單問題, ...]) -> None:
        """把每一個問題的項目、診斷與代碼寫進訊息——不講哪一項哪一欄等於沒講。"""
        self.問題們 = 問題們
        每一條 = "；".join(
            f"{問題.項目 or '整張分派單'}：{問題.診斷}（{問題.代碼}）" for 問題 in 問題們
        )
        super().__init__(f"分派單沒有通過驗證，不落票——{每一條}")


class 計畫員沒交出分派單(Exception):
    """計畫員那一次呼叫沒有成功——失敗、結果未知，或被停止政策的護欄攔下。"""

    def __init__(self, 結果: 節點結果[分派單]) -> None:
        """把整個節點結果留著：是預算爆掉還是模型炸掉，呼叫端要分得出來。"""
        self.結果 = 結果
        super().__init__(f"計畫員沒有交出分派單：{結果}")


def 規劃成票(  # noqa: PLR0913 —— 每一個都是這條鏈的輸入，收成 dataclass 只是換個地方列
    目標: str,
    *,
    現況: 工作現況,
    限制: 執行限制,
    上下文: 節點上下文,
    產生器: 計畫產生器,
    可用工件: tuple[工件參照, ...] | None = None,
    架構: object | None = None,
) -> tuple[規劃票, ...]:
    """吃一句目標，回一組四欄齊全的票；驗證沒過就拋 `分派單不合格`。

    `可用工件` 不給就用 `現況.已有工件`——同一份東西沒有理由要呼叫端抄兩次，
    但「這一次只准引用其中幾件」是真的存在的收窄，所以留得掉。
    `架構` 是系統架構師那一階的產物；這一格還沒接上那一階，所以預設沒有，
    **但它是呼叫端明給的參數，不是這裡替它填的空**。
    """
    輸入 = 規劃輸入(
        目標=目標,
        現況=現況,
        限制=限制,
        可用工件=現況.已有工件 if 可用工件 is None else 可用工件,
        架構=架構,
    )
    候選 = _請計畫員出一張候選分派單(輸入, 上下文=上下文, 產生器=產生器)
    問題們 = 驗證分派單(候選, 限制=限制)
    if 問題們:
        raise 分派單不合格(問題們)
    return tuple(_一張票(項目) for 項目 in 候選.項目)


def _請計畫員出一張候選分派單(
    輸入: 規劃輸入,
    *,
    上下文: 節點上下文,
    產生器: 計畫產生器,
) -> 分派單:
    """跑那一次模型呼叫，取回**還沒驗過**的候選分派單。

    走 `單獨執行` 而不是直接呼叫計畫員，停止政策的護欄才管得到這一次呼叫；
    被攔下來時拋 `計畫員沒交出分派單`，不會靜靜當成「沒有分派單」。
    """
    結果 = 單獨執行(
        計畫員節點(),
        邊包(
            結構=規劃輸入結構,
            版本=規劃輸入版本,
            內容=輸入,
            來源=來源自上下文(上下文),
        ),
        上下文=上下文,
        # 同一個東西在這裡叫 `產生器`、在 `單獨執行` 那邊叫 `依賴`——
        # 後者是節點層的通用名（節點不知道它拿到的是哪一種相依），前者是這條鏈
        # 對它的稱呼。**不統一是刻意的**：改成 `依賴` 會讓這個檔失去「它是誰」。
        依賴=產生器,
    )
    if not isinstance(結果, 節點成功):
        raise 計畫員沒交出分派單(結果)
    return 結果.產出.內容


def _一張票(項目: 分派項目) -> 規劃票:
    """把一項分派寫成四欄齊全的票。

    `分派項目` 的每一欄都要出現在票面上：漏掉的那一欄執行者就不知道它存在，
    而票是他唯一讀得到的交代。
    """
    內容 = f"""# 分派項目：{項目.識別碼}

這張票是規劃那一層產出的，不是人手寫的：`執行計畫員` 產出分派單、
`驗證分派單` 機械檢查通過之後，才落成這一項。

## 輸入

- 節點：`{項目.節點}`
- 輸入結構：`{項目.輸入結構}`
- 前置項目：{_併成一行(項目.前置項目)}
- 分支：{f"`{項目.分支}`" if 項目.分支 else "無（會跟其他項目並行）"}
- 這一項{"必要" if 項目.必要 else "可以跳過"}

## 輸出

寫入範圍（**只准動這幾格**）：

{_一格一列(項目.寫入範圍) or "- （未宣告寫入範圍）"}

要的權限：網路{_要不要(項目.需要網路)}、編輯{_要不要(項目.需要編輯)}

## 驗收

{_驗收(項目.驗收出口)}

## 停止

{_停止列(項目.停止)}
"""
    return 規劃票(識別碼=項目.識別碼, 內容=內容, 項目=項目)


def _併成一行(幾格: tuple[str, ...]) -> str:
    """一行寫得完的清單；空的就是「無」。"""
    return "、".join(f"`{一格}`" for 一格 in 幾格) if 幾格 else "無"


def _一格一列(幾格: tuple[str, ...]) -> str:
    """一格一列的 markdown 清單；空的就是空字串，由呼叫端決定要不要補墊詞。"""
    return "\n".join(f"- `{一格}`" for 一格 in 幾格)


def _要不要(要: bool) -> str:
    """權限那一欄的兩個字。"""
    return "要" if 要 else "不要"


def _驗收(驗收出口: tuple[str, ...]) -> str:
    """驗收出口只寫成 `nova:驗收` 標記這一種形式。

    不再另外條列一份人看的清單：同一組指令寫兩遍，改了一遍沒改另一遍的時候，
    票面上會同時有兩份互相矛盾的驗收，而機器只讀得到其中一份。
    標記在 markdown 裡看不見沒關係——`收件.讀出驗收` 讀的就是它。
    """
    return "\n".join(f"<!--nova:驗收 {一條}-->" for 一條 in 驗收出口)


def _停止列(停止: 停止政策 | None) -> str:
    """把停止政策攤成四列。

    `驗證分派單` 已經擋掉沒有停止政策的項目，所以 None 這條路走不到；
    留著是因為型別上仍可能是 None，而**默默生出一張沒有停止條件的票**
    比拋錯更難查——墊詞至少會在票面上自曝。
    """
    if 停止 is None:
        return "- （未宣告停止政策）"
    return (
        f"- 最多呼叫 {停止.最多呼叫} 次\n"
        f"- 最多 {停止.最多token} token\n"
        f"- 最多 {停止.最多秒} 秒\n"
        f"- 連續 {停止.最多無進展} 次沒有進展就停"
    )
