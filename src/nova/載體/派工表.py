"""派工表：工作種類 → 腦鏈。

寫成**表**不是寫成 `if/elif`（開放封閉）：加一種工作＝加一列，
不是回來改判斷。而且表可以被窮舉測試掃過——`if` 鏈不行。

`tests/單元/test_派工表.py` 把使用者的策略逐條釘住：例行第一順位是 claude、
兩列都要有備援、例行不准用高階模型、推理一定要指名 sol；本地腦不進自動派工列的
負控在 `tests/單元/test_本地派工.py`。
改動這張表而讓那些測試變紅，代表你改掉的是**策略**不是實作細節。
"""

from nova.契約.派工 import 工作種類, 派法
from nova.載體.模型.轉接 import codex高階模型

#: 每個 `工作種類` 都必須在這裡有一列，由 `test_每個工作種類都要有派法` 背書。
#:
#: **例行為什麼從 agy 翻成 claude**：原本的前提是「agy 便宜且快」，
#: 2026-08-31 量掉了——agy 跑真任務單階 375,061／410,294 input token，
#: claude 同一份工作約 8,600，**46 倍**。原因不是 CLI 把工作區打包
#: （空目錄 13,720 vs nova 目錄 13,726，只差 6 個），是模型自己在工具迴圈裡
#: 選擇讀滿整個 repo。在 `迴圈/角色提示.py` 教會它怎麼找之前，貴的是 agy。
#: agy 留在備援：額度是分開計的，claude 耗盡時它仍然接得住。
#:
#: **推理列的備援是燒掉三輪才補的。** 排程 argv 是 `nova 工作流 --從收件匣`，
#: 兩個腦旗標都不帶，所以審查階段問這張表拿到推理那一列。那一列曾是單鏈
#: `("codex",)`，codex 額度一耗盡，每輪都會照劇本跑完前三階、燒掉幾十萬 token，
#: 然後死在 review——三輪 aborted 的死因都是它。
#: 家族名重疊不是擋下的理由（`#140`：判準是對話不是家族名）。
#:
#: 型號 `codex高階模型` 只會給鏈上第一家，`載體/模型/接力.py` 換家時清掉它——
#: 各家命名空間不交集，帶著走的話 claude 會拿到 sol 的型號名再炸一次，
#: 那種備援是假的。由 `tests/單元/test_接力腦.py::Test型號只給第一家` 背書。
#: 本地腦的審查資格檢查住在 `src/nova/載體/模型/本地.py`，命令列與門面共用。
#: local 刻意不在表上：能力邊界尚未證明適合自動派工，詳見 `docs/研究/本地腦能力邊界.md`。
_表: dict[工作種類, 派法] = {
    工作種類.例行: 派法(腦們=("claude", "agy"), 思考深度="high"),
    工作種類.推理: 派法(腦們=("codex", "claude"), 思考深度="max", 模型=codex高階模型),
}


def 怎麼派(種: 工作種類) -> 派法:
    """這種工作派給誰。

    表裡沒有就當場炸，**不猜預設**：猜錯的代價是每一次都派錯家，
    而且沒有人會發現——輸出看起來一樣，只是慢、貴、或笨。
    """
    if 種 not in _表:
        訊息 = f"派工表沒有 {種.value} 這一格"
        raise KeyError(訊息)
    return _表[種]
