"""派工表：工作種類 → 腦鏈。

寫成**表**不是寫成 `if/elif`（開放封閉）：加一種工作＝加一列，
不是回來改判斷。而且表可以被窮舉測試掃過——`if` 鏈不行。

`tests/單元/test_派工表.py` 把使用者的策略逐條釘住：例行第一順位是 agy、
例行要有備援、例行不准用高階模型、推理一定要指名 sol。
改動這張表而讓那些測試變紅，代表你改掉的是**策略**不是實作細節。
"""

from nova.契約.派工 import 工作種類, 派法
from nova.載體.模型.轉接 import codex高階模型

#: 每個 `工作種類` 都必須在這裡有一列，由 `test_每個工作種類都要有派法` 背書。
#:
#: 例行為什麼是 agy 打頭：使用者的策略是分擔 Claude 的額度，
#: agy 便宜且快。codex 當備援——兩家的失敗模式不一樣（額度、網路、模型下架），
#: 同一家排兩次不叫備援。
_表: dict[工作種類, 派法] = {
    工作種類.例行: 派法(腦們=("agy", "codex")),
    工作種類.推理: 派法(腦們=("codex",), 模型=codex高階模型),
}


def 怎麼派(種: 工作種類) -> 派法:
    """這種工作派給誰。

    表裡沒有就當場炸，**不猜預設**：猜錯的代價是每一次都派錯家，
    而且沒有人會發現——輸出看起來一樣，只是慢、貴、或笨。
    """
    if 種 not in _表:
        訊息 = f"派工表沒有 {種.value} 這一格"
        raise KeyError(訊息)
    return _表[種]
