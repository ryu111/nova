"""載入秘密：**出生前就把憑證交到子程序手上。**

排程做完之後這一格才有意義：launchd 的 job 拿到的是一份很乾淨的環境，
使用者的 shell profile 一個字都不會被讀。所以無人看管的那條路徑上，
憑證只有一個來源——**載體自己遞過去**。

「叫使用者 export 就好」在人坐在終端機前面時成立，在時鐘自己跑的時候不成立。
而**兩條路徑行為不一樣是最貴的那種 bug**：手動跑得動，排程永遠拿到 401，
然後你會去查模型、查網路、查 CLI，就是不會想到環境。

## 住專案外面

跟進度檔同一條規則：**「屬於某個專案」跟「存在那個專案裡面」是兩件事**，
存在裡面就等於交到執行者手上。而這個 repo 是 public——洩漏一次就是永久的。
所以落點是 `<狀態根>/專案/<識別>/祕密.env`，用專案當鍵不是當位置。

## fail-closed 的兩個方向

1. **看不懂就不要出生。** 半載入的祕密會讓子程序帶著缺一半的憑證跑起來，
   拿到 401 而不是「你的祕密檔第 3 行打錯了」——診斷順序整個被帶歪。
2. **權限太鬆就不要出生。** `0644` 的祕密檔在多人機器上等於沒有祕密，
   而它看起來完全正常。

## 載進去的同時要讓遮罩看得見

`遮罩` 靠鍵名的特徵猜哪些環境變數是祕密（`KEY`／`TOKEN`／`SECRET`…）。
猜得中一般情況，猜不中 `MY_THING=sk-...`。但**nova 自己載進去的東西，
是不是祕密不必猜**——所以載入時把鍵名記進 `NOVA_LOADED_SECRETS`，
`遮罩` 讀它。名單跟著資料走在同一個地方，不必另外維護一份全域狀態。
"""

import re
import stat
from collections.abc import MutableMapping
from pathlib import Path

from nova.載體.帳本 import 專案識別
from nova.載體.狀態 import 狀態根目錄

#: 祕密檔的檔名。ASCII 例外不適用——這是給人看的檔名，不是工具在讀的。
祕密檔名 = "祕密.env"

#: 載入了哪些鍵。**遮罩讀這個**，所以鍵名不准是祕密的一部分。
#: ASCII：跨程序 semantic id。
已載入的鍵環境變數 = "NOVA_LOADED_SECRETS"

#: 合法的 shell 變數名。鍵名一律 ASCII（CLAUDE.md 的 shell 變數名例外）——
#: `金鑰=x` 傳得進 `os.environ`，但子程序多半讀不到，
#: 而失敗方式是「憑證好像沒設」，查起來一樣貴。
_合法鍵 = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

#: 比這個鬆就拒絕。`0o600` ＝ 只有自己讀得到。
_最鬆的權限 = 0o600


class 看不懂的祕密檔(ValueError):
    """祕密檔有讀不懂的行。**訊息裡一律不含值。**

    錯誤訊息也會進 log；把值印出來的話，祕密檔的意義就沒了。
    """


def 祕密檔(專案: Path) -> Path:
    """這個專案的祕密住哪。**用專案當鍵，不是當位置。**

    住在專案裡面就等於交到執行者手上，而這個 repo 是 public。
    """
    return 狀態根目錄() / "專案" / 專案識別(專案) / 祕密檔名


def 讀祕密(內容: str) -> dict[str, str]:
    """`KEY=VALUE` 一行一個。空行與 `#` 註解跳過，看不懂的行當場報錯。

    吃字串不吃路徑，所以這一層是純函式——落點與權限是 `載入到` 的事。
    """
    出: dict[str, str] = {}
    for 幾, 原行 in enumerate(內容.splitlines(), start=1):
        行 = 原行.strip()
        if not 行 or 行.startswith("#"):
            continue
        鍵, 值 = _拆一行(行, 幾)
        出[鍵] = 值
    return 出


def 權限太鬆(路徑: Path) -> str | None:
    """比 `0600` 鬆就回一句原因。**這是「出生前就擋」的一半。**

    `0644` 的祕密檔在多人機器上等於沒有祕密，而它看起來完全正常——
    沒有任何症狀，直到有一天有症狀。
    """
    模式 = stat.S_IMODE(路徑.stat().st_mode)
    if 模式 & ~_最鬆的權限:
        return (
            f"{路徑} 的權限是 {模式:04o}，比 0600 鬆——別人讀得到就等於沒有祕密。"
            f"修：chmod 600 {路徑}"
        )
    return None


def 載入到(環境: MutableMapping[str, str], *, 專案: Path) -> list[str]:
    """把這個專案的祕密塞進 `環境`，回傳載入了哪些鍵。

    **檔案不存在就是沒有祕密要載**（回空的，不是錯誤）——預設關閉，
    跟熔斷與預算鎖同一條。

    **不蓋掉已經存在的**：使用者手動 `export` 的優先。反過來的話，
    「我明明 export 了為什麼沒用」會變成一個查不出來的問題。
    """
    路徑 = 祕密檔(專案)
    if not 路徑.is_file():
        return []
    太鬆 = 權限太鬆(路徑)
    if 太鬆 is not None:
        raise 看不懂的祕密檔(太鬆)
    載 = 讀祕密(路徑.read_text(encoding="utf-8"))
    進去了 = [鍵 for 鍵 in 載 if 鍵 not in 環境]
    for 鍵 in 進去了:
        環境[鍵] = 載[鍵]
    if 進去了:
        # **遮罩要看得見。** 名單跟著資料走在同一個地方，
        # 不必另外維護一份全域狀態，而且子程序也繼承得到。
        既有 = [名 for 名 in 環境.get(已載入的鍵環境變數, "").split(",") if 名]
        環境[已載入的鍵環境變數] = ",".join(dict.fromkeys([*既有, *進去了]))
    return 進去了


def _拆一行(行: str, 幾: int) -> tuple[str, str]:
    """一行 → (鍵, 值)。看不懂就報錯，而且**訊息裡不含值**。"""
    if "=" not in 行:
        訊息 = f"祕密檔第 {幾} 行看不懂：要長成 KEY=VALUE"
        raise 看不懂的祕密檔(訊息)
    # 只切第一個等號——base64 與 JWT 常常以 `=` 結尾，切斷的話憑證會靜默失效。
    鍵, _, 值 = 行.partition("=")
    鍵 = 鍵.strip().removeprefix("export ").strip()
    if not _合法鍵.match(鍵):
        訊息 = f"祕密檔第 {幾} 行的鍵名不是合法的環境變數名（只准 A-Z a-z 0-9 _，開頭不能是數字）"
        raise 看不懂的祕密檔(訊息)
    值 = _脫引號(值.strip())
    if not 值:
        訊息 = f"祕密檔第 {幾} 行的值是空的——空字串會蓋掉真的環境變數"
        raise 看不懂的祕密檔(訊息)
    return 鍵, 值


def _脫引號(值: str) -> str:
    """`A="x"` 是 shell 的寫法。留著引號的話送出去的憑證會多兩個字元。"""
    for 引 in ('"', "'"):
        if len(值) >= 2 and 值.startswith(引) and 值.endswith(引):  # noqa: PLR2004
            return 值[1:-1]
    return 值
