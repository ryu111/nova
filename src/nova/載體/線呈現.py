"""`nova 線` 的看板排版與人話呈現。"""

from nova.契約.線觀測 import 線現況

_成功退出碼 = 0
_確定失敗退出碼 = 1
_結果未知退出碼 = 3
_護欄退出碼 = 4

_退出碼說明 = {
    _成功退出碼: "成功",
    _確定失敗退出碼: "確定失敗",
    _結果未知退出碼: "結果未知（不准重跑）",
    _護欄退出碼: "護欄生效（不是壞了）",
}


def 排版(線們: tuple[線現況, ...]) -> str:
    """把查詢結果排成給人看的看板。"""
    if not 線們:
        # 防禦性分支：正常情況 工作樹們 至少回傳專案根目錄
        return "線：查不到（沒有 worktree）\n"
    return "\n\n".join(格式化一條線(線) for 線 in 線們) + "\n"


def 格式化一條線(線: 線現況) -> str:
    """一條線在看板上的那一段。"""
    return "\n".join(
        [
            f"線：{線.名字}",
            f"  在跑嗎：{_在跑的人話(線)}",
            f"  跑多久了：{_跑多久的人話(線)}",
            f"  現在在哪一階：{線.目前階段 or '查不到（事件帳本沒有可辨識的階段）'}",
            f"  上一次怎麼收的：{_上一次的人話(線)}",
            f"  工作區乾淨嗎：{_工作區的人話(線)}",
            f"  base 落後幾個 commit：{_基底的人話(線)}",
        ]
    )


def _在跑的人話(線: 線現況) -> str:
    if 線.在跑嗎 is None:
        return "查不到（無法讀取 ps）"
    return "是" if 線.在跑嗎 else "否"


def _跑多久的人話(線: 線現況) -> str:
    if 線.在跑嗎 is None:
        return "查不到（無法確認程序）"
    if 線.在跑嗎 is False:
        return "不適用（目前沒有活著的 nova 程序）"
    return f"{線.跑多久 or '查不到'}（啟動於 {線.啟動時間 or '查不到'}）"


def _上一次的人話(線: 線現況) -> str:
    if 線.上一次 is None:
        return "查不到（沒有成果帳本）"
    碼 = 線.上一次.退出碼
    說法 = _退出碼說明.get(碼, f"查不到（未定義的退出碼 {碼}）")
    if 碼 == _護欄退出碼:
        原因 = 線.護欄原因 or "查不到（現有帳本沒有記錄護欄原因）"
        return f"退出碼 {碼}：{說法}；護欄原因：{原因}"
    return f"退出碼 {碼}：{說法}"


def _工作區的人話(線: 線現況) -> str:
    if 線.未提交檔案數 is None:
        return "查不到（git status 無法讀取）"
    乾淨 = "是" if 線.未提交檔案數 == 0 else "否"
    return f"{乾淨}（{線.未提交檔案數} 個未提交檔案）"


def _基底的人話(線: 線現況) -> str:
    if 線.基底落後數 is None:
        return "查不到（沒有可確認的上游預設分支）"
    return str(線.基底落後數)
