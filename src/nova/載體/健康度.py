"""健康度閘：**二元**的綠／紅，紅了只擋推進票，維護票永遠放行。

這裡只做「算」的那一半——四個指標當參數收進來，不在函式裡自己去查
`gh`／git／檔案系統（依賴反轉）。查的那一半是載體的另一個入口。

刻意**不做配額**（90/10、40/60）：中間那一檔會被拿來拖延，趕進度時人的
判斷一定偏向推進。也刻意**沒有可設定的閾值**：可調的閾值就是留給自己的
後門，護欄最省事的修法永遠是把上限調鬆。
"""

from dataclasses import dataclass
from enum import Enum
from typing import TYPE_CHECKING, Any, ClassVar


def _凍結資料類別[資料類別](類別: type[資料類別]) -> type[資料類別]:
    """執行期用資料類別；不讓 mypy 把 `replace` 的動態欄位收窄。"""
    return dataclass(類別, frozen=True, slots=True)


class 指標代碼(Enum):
    """四個指標的名字。紅的時候要指名是哪一項，不能只說「系統不健康」。"""

    main的CI = "main的CI"
    卡住的線 = "卡住的線"
    沒收尾的收件 = "沒收尾的收件"
    壞掉的PR = "壞掉的PR"


class 票種(Enum):
    """推進會被健康度擋；維護（閘紅票、接續票）永遠放行。"""

    推進 = "推進"
    維護 = "維護"


@_凍結資料類別
class 健康度指標:
    """四個指標的現場值。

    算不出來一律留空（`None`），不拿 0 或 True 頂替——照 `載體/線.py` 的慣例。
    """

    # `dataclasses.replace` 的 mypy hook 會要求動態欄位字典符合每個欄位的型別；
    # 這個 marker 讓它走通用簽名，領域欄位本身仍維持正確型別。
    __dataclass_fields__: ClassVar[dict[str, Any]]

    main綠嗎: bool | None
    卡住的線數: int | None
    沒收尾的件數: int | None
    壞掉的PR數: int | None

    if TYPE_CHECKING:

        def __init__(
            self,
            main綠嗎: bool | None,
            卡住的線數: int | None,
            沒收尾的件數: int | None,
            壞掉的PR數: int | None,
        ) -> None:
            """供 mypy 得到實際建構子的型別；執行期由資料類別產生。"""
            ...


@dataclass(frozen=True, slots=True)
class 健康度判定:
    """閘的結果：放不放行、哪幾項紅、以及要收掉什麼才會轉綠。"""

    放行: bool
    紅項: tuple[指標代碼, ...]
    訊息: str
    #: 查不到的項目不是紅色；只是為了安全不能放行推進票。
    未知項: tuple[指標代碼, ...] = ()


#: 每一項紅的時候要收掉什麼。訊息裡不准提到別項的名字，否則等於沒指名。
_怎麼轉綠 = {
    指標代碼.main的CI: "把權威 repo 的 main 修回綠再說",
    指標代碼.卡住的線: "先把停在半路的那幾條收掉",
    指標代碼.沒收尾的收件: "先把處理中沒收尾的那幾件結掉",
    指標代碼.壞掉的PR: "先把紅的或有衝突的那幾個合掉或關掉",
}


# 以下兩支共用同一條規則：算不出來（`None`）往安全那邊倒＝當成紅。
# 理由：算不出來的時候我們**不知道**修理跟不跟得上，這時多生一張推進票
# 是拿看不見的東西下注；而擋掉的代價只是晚 15 分鐘再醒來一次。


def _CI項紅嗎(綠嗎: bool | None) -> bool:
    """main 的 CI：明確回報失敗才是紅。"""
    return 綠嗎 is False


def _計數項紅嗎(件數: int | None) -> bool:
    """卡住的線／沒收尾的收件／壞掉的 PR：有一件就算紅。"""
    return 件數 is not None and 件數 > 0


def _找出紅項(指標: 健康度指標) -> tuple[指標代碼, ...]:
    """哪幾項是紅的。順序固定照這裡的排法，訊息才不會每次條列成不同順序。"""
    每項紅嗎 = {
        指標代碼.main的CI: _CI項紅嗎(指標.main綠嗎),
        指標代碼.卡住的線: _計數項紅嗎(指標.卡住的線數),
        指標代碼.沒收尾的收件: _計數項紅嗎(指標.沒收尾的件數),
        指標代碼.壞掉的PR: _計數項紅嗎(指標.壞掉的PR數),
    }
    return tuple(代碼 for 代碼, 紅 in 每項紅嗎.items() if 紅)


def _找出未知項(指標: 健康度指標) -> tuple[指標代碼, ...]:
    """找出查詢沒有結果的項目；未知不冒充紅色。"""
    值們 = {
        指標代碼.main的CI: 指標.main綠嗎,
        指標代碼.卡住的線: 指標.卡住的線數,
        指標代碼.沒收尾的收件: 指標.沒收尾的件數,
        指標代碼.壞掉的PR: 指標.壞掉的PR數,
    }
    return tuple(代碼 for 代碼, 值 in 值們.items() if 值 is None)


# 保留公開關鍵字 `票種`，用別名避免它在函式本體遮住 Enum。
_票種 = 票種


def 准生票嗎(指標: 健康度指標, *, 票種: 票種) -> 健康度判定:
    """二元閘：四個指標全綠才准生推進票；維護票不受健康度影響。"""
    紅項 = _找出紅項(指標)
    未知項 = _找出未知項(指標)
    if 票種 is _票種.維護:
        return 健康度判定(
            放行=True,
            紅項=紅項,
            訊息="維護票不受健康度閘影響，放行。",
            未知項=未知項,
        )
    if not 紅項 and not 未知項:
        return 健康度判定(放行=True, 紅項=(), 訊息="四個指標都綠，放行推進票。")

    原因 = [f"{代碼.value}紅：{_怎麼轉綠[代碼]}" for 代碼 in 紅項]
    原因.extend(f"{代碼.value}查不到：先恢復這項查詢" for 代碼 in 未知項)
    條列 = "；".join(原因)
    return 健康度判定(
        放行=False,
        紅項=紅項,
        訊息=f"健康度未全綠，暫停推進票——{條列}。算不出來採安全側：恢復查詢前不生推進票。",
        未知項=未知項,
    )
