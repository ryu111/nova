"""收件檔出現＝一次派工。**檔案就是事件。**

路線圖觸發層那四格裡，只有這一格的副標寫著「唯一的橋」——因為檔案是唯一一種
**不綁任何一家 LLM、不綁任何一個宿主、`ls` 就看得到佇列**的事件形式。
排程到期與 MCP 派票最後都該收斂成「往收件匣丟一個檔」，不是各自長一條路。

## 為什麼收件匣不能住在工作目錄裡

理由跟進度檔同一條，但更嚴重。進度檔放錯只是讓模型替未來的自己種話；
**收件匣放錯是讓執行者自己派工給自己**——一個能寫工作目錄的模型
可以無限次觸發自己，而且每一次看起來都像是使用者丟的。

所以它跟帳本、已處理住在一起：`$XDG_STATE_HOME/nova/專案/<識別>/收件`。
歸屬是索引問題，不是存放位置問題。

## 三個狀態，三個目錄

```
收件/            還沒有人動的
收件/處理中/     收下了，還沒收尾  ← 程序被殺掉的話會留在這裡，那是誠實
已處理/          做完了，旁邊就是那次的成果 JSON
```

**收下＝把檔案移走**，靠 `rename` 的原子性宣告所有權：同一個檔只有一個
`rename` 會成功，另一個拿到 `FileNotFoundError` 然後去看下一件。
少了這一步，兩個程序會把同一件工作做兩次，而且看起來完全正常。
"""

import os
import re
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path
from secrets import token_hex

from nova.契約.遮罩 import 已遮罩文字
from nova.載體.帳本 import 專案識別
from nova.載體.狀態 import 狀態根目錄
from nova.載體.遮罩 import 遮罩

_處理中 = "處理中"

#: 誰造了這個收件檔。**ASCII：跨程序 semantic id**，會流進成果帳的 `source` 欄位被 grep。
#: 對應路線圖觸發層那四格；現在只有前兩個生得出來。
你敲, 檔案, 時鐘, 協定 = "typed", "file", "schedule", "mcp"
_認得的來源 = frozenset({你敲, 檔案, 時鐘, 協定})

#: 檔名開頭的時戳。**跟帳本的執行識別碼同一個格式**——「`ls` 就是時序」
#: 靠的是它，兩邊走散的話先進先出會靜默壞掉。
_檔名時戳 = "%Y%m%dT%H%M%SZ"

#: 檔名裡放不進去的字。題目可能有斜線、換行、引號。
_檔名不要的 = re.compile(r"[^\w]+", re.UNICODE)

#: 題目擷取幾個字當標籤。太長的檔名在 `ls` 裡會換行，反而看不出佇列。
_標籤幾個字 = 24

#: 檔名至少要有「時戳-來源」兩段才判得出來源。
_最少幾段 = 2

#: 同一件工作最多自動接續幾輪。**這是停止規則，不是設定項。**
#: 沒有它，一件永遠撞上限的工作會每 15 分鐘重排一次——永遠。
#: 迴圈那層「七欄位缺 stop rule 的不是迴圈，是成本漏洞」，這裡是同一條。
最多輪次 = 3

#: 人寫的票最多指名幾支測試。**這是停止規則，不是設定項。**
#: 跟 `最多輪次` 一樣，要放寬是人的決定，不是撞到了就調高。
指名測試上限 = 3

#: 驗收標記：`<!--nova:驗收 <指令>-->`，一條一個標記。
#: **跟接續標記是兩個不同的字串**，混用的話接續票會憑空長出一條跑不動的驗收。
#:
#: 為什麼是指令不是自然語言：自然語言的「驗收」要模型判斷做到沒有，
#: 而 CLAUDE.md 的硬規則第 2 條不准以「模型說完成了」當停止條件。
#: 指令回 0 就是綠、非 0 就是紅，**執行者違反不了**。
_驗收標記 = re.compile(r"<!--nova:驗收\s+(.+?)\s*-->")

#: 新增保證標記：`<!--nova:新增保證-->`，開票的人宣告「這張票要多做一次固定負控」。
#: 抄 `<!--nova:驗收 ...-->` 的形狀，理由也同一條：**判準從票上的資料來，
#: 不從模型的自覺來**。沒有這個標記就是沒有——純重構、純文件的票不准被
#: 要求補負控，否則每張票都多付一次成本。
_新增保證標記 = "<!--nova:新增保證-->"

#: 沒有人在現場的來源。**這兩種的票做完之後沒有人會看**，
#: 下一輪直接接著做——那時候「做完了」跟「做壞了」長得一模一樣。
#:
#: `你敲` 與 `檔案` 不在裡面是刻意的：那兩種是他打字或 cp 進來的，
#: 人就在現場，驗收是他自己看。逼他每次寫驗收指令只會讓他改走別條路，
#: 於是這道閘等於不存在。
_自主來源 = frozenset({時鐘, 協定})

#: 一個「完整的點」要有的四欄（`docs/設計/10-目標長什麼樣.md`）：
#: 輸入讀什麼、輸出寫到哪、驗收怎麼算綠、撞到什麼要停。**缺一欄不准派。**
_四欄 = ("輸入", "輸出", "驗收", "停止")

#: 欄位長成 markdown 標題：`## 輸入`。幾個井字不管，前後空白不管。
#: 欄名直接從 `_四欄` 接出來——寫死第二份的話，加一欄只改一處，
#: 另一處靜靜漏掉那一欄，而測試會全綠。
_一欄標題 = re.compile(rf"^\s*#+\s*({'|'.join(_四欄)})\s*$", re.MULTILINE)
#: 指名一支測試的形狀：`<路徑>/tests/甲.py::test_乙`，尾巴的 `[…]` 是參數化那一格。
#: `tests/` 與 `test/` 兩種目錄名都認；**只認 `::test_` 不認 `::Test`**——
#: class 形式是「順便會紅的既有測試」的指法，不是開票的人指名要跑的那幾支。
#: 開頭的 lookbehind 擋掉從別的字中間切進來的比對：`前綴.tests/甲.py::test_乙`
#: 不會被切出半條路徑，另算成一支。
_指名測試形狀 = re.compile(
    r"""
    (?<![\w.-])
    (
        /?(?:[\w.-]+/)*tests?/
        (?:[\w.-]+/)*
        [\w.-]+\.py::test_\w+
        (?:\[[^\]\r\n]*\])?
    )
    """,
    re.VERBOSE,
)


class 票太大(ValueError):
    """人寫的票指名太多支測試。"""

    def __init__(self, 那幾支: tuple[str, ...]) -> None:
        """保留超限票的完整指名，讓呼叫端能列出退件理由。"""
        self.那幾支 = 那幾支
        super().__init__(
            f"票指名了 {len(那幾支)} 支測試，超過上限 {指名測試上限}：{'、'.join(那幾支)}"
        )


def 缺哪幾欄(內容: str) -> tuple[str, ...]:
    """這張票缺了四欄裡的哪幾欄，照 `_四欄` 的順序。

    **一欄都沒寫的票不算缺**：閘紅票、手敲的一句話都是那樣長的，
    要求它們補四欄只會讓既有的自主來源全部派不出去。
    寫了一部分才算「打算寫成一個點」，那時候就要寫齊——
    半套的點比沒有點更貴，執行者會以為自己讀到了全部的交代。
    """
    有的 = {找到.group(1) for 找到 in _一欄標題.finditer(內容)}
    if not 有的:
        return ()
    return tuple(欄 for 欄 in _四欄 if 欄 not in 有的)


def 讀出驗收(內容: str) -> tuple[str, ...]:
    """票裡宣告的驗收指令，照原文順序。**沒有就是空的，不是錯誤。**

    順序不排序：排序會把「先跑快的」這種安排靜默打亂。
    只留 strip 之後還有東西的——`<!--nova:驗收 -->` 是一張看起來有、
    其實沒有的票，放行的話它會變成最貴的那種假綠。
    """
    每一條 = (找到.group(1).strip() for 找到 in _驗收標記.finditer(內容))
    return tuple(一條 for 一條 in 每一條 if 一條)


def _剝掉參數化尾巴(指名: str) -> str:
    """去掉 pytest 參數化的尾巴，讓同一支測試只算一次。"""
    return 指名.split("[", 1)[0]


def 指名的測試(內容: str) -> tuple[str, ...]:
    """讀出票裡指名的測試，去重後照原文順序回傳。

    只讀一般票文；判準輸出的 `FAILED` 行與 class 形式的指稱不算指名。
    參數化尾巴會先去掉，讓同一支測試只算一次。
    """
    已見: set[str] = set()
    指名清單: list[str] = []
    for 行 in 內容.splitlines():
        if 行.strip().startswith("FAILED"):
            continue
        for 找到 in _指名測試形狀.finditer(行):
            測試 = _剝掉參數化尾巴(找到.group(1))
            if 測試 in 已見:
                continue
            已見.add(測試)
            指名清單.append(測試)
    return tuple(指名清單)


def _擋下超過指名測試上限(內容: str, 來源: str) -> None:
    """人寫的票超過指名上限就退件；自主來源不查票身。"""
    if 來源 in _自主來源:
        return
    那幾支 = 指名的測試(內容)
    if len(那幾支) <= 指名測試上限:
        return
    raise 票太大(那幾支)


def 要驗收嗎(來源: str) -> bool:
    """這個來源的票沒帶驗收就不准派。判準是**誰在現場**，不是任務難不難。"""
    return 來源 in _自主來源


def _擋下殘缺的自主票(內容: str, 來源: str) -> None:
    """自主來源的票不完整就不准派。缺驗收、缺四欄都擋在開跑前。

    兩道檢查同一條理由（**沒有人在現場**），所以放同一個地方；
    人手丟的票整段跳過——他自己看。
    """
    if not 要驗收嗎(來源):
        return
    if not 讀出驗收(內容):
        訊息 = (
            f"來源 {來源!r} 的票沒有帶驗收——自主派工沒有人在現場，"
            "缺了機械驗收就等於缺停止條件。用 <!--nova:驗收 <指令>--> 補上"
        )
        raise ValueError(訊息)
    缺的 = 缺哪幾欄(內容)
    if 缺的:
        訊息 = (
            f"來源 {來源!r} 的票缺了這幾欄：{'、'.join(缺的)}——"
            "自主派工沒有人在現場，缺欄的票執行者不知道要讀什麼、寫到哪、撞到什麼該停。"
            "用 `## <欄名>` 補上"
        )
        raise ValueError(訊息)


#: 接續票的分隔線：上面是原本的題目，下面是上一輪走到哪。
#: 走 HTML 註解形式是刻意的——它在 markdown 裡看不見，
#: 而手丟進來的檔案不會剛好打出這一串。
_接續標記 = re.compile(r"<!--nova:接續 輪次=(\d+)[^>]*-->")


@dataclass(frozen=True, slots=True)
class 收件單:
    """收下來的一件工作。

    `名稱` 是原始檔名（去掉副檔名），拿來當這次工作的人看得懂的標籤；
    `處理中路徑` 是它現在的位置——完成的時候要從那裡搬走。
    """

    名稱: str
    任務: str
    處理中路徑: Path
    #: 誰造了這個收件檔（`typed`／`file`／…）。**不是「誰醒來把它撈起來」**——
    #: 排程把一個手丟的檔案做掉，那一件的來源仍然是檔案。
    來源: str = 檔案
    #: 上一輪走到哪。空的就是第一輪，那是絕大多數。
    前情: str = ""
    #: 這是第幾輪。手丟的檔案沒有標記，一律算第 1 輪——
    #: **不能因為讀不到就炸掉或算成第 0 輪**。
    輪次: int = 1
    #: 這件工作要跑哪些指令才算做完。**只從題目讀，不從前情讀**——
    #: 前情是模型講的話，讓它算數的話模型可以在自己的輸出裡
    #: 寫一條穩過的驗收，替未來的自己把閘關掉。
    #:
    #: 空的是正常狀態：人在現場的票不必帶驗收（`要驗收嗎`）。
    驗收: tuple[str, ...] = ()
    #: 這張票要多做一次固定負控登記（硬規則 4）。**跟 `驗收` 一樣只從題目讀**——
    #: 前情是模型自己的輸出，讓它算數的話模型可以在前情裡把票升級成
    #: 「新增保證」，替下一輪多開一次寫測試檔的許可。
    新增保證: bool = False


def 收件目錄(專案: Path | None = None) -> Path:
    """收件匣住哪。跟帳本、已處理是同一個專案資料夾底下的三個目錄。"""
    底 = 狀態根目錄()
    return 底 / "收件" if 專案 is None else 底 / "專案" / 專案識別(專案) / "收件"


def 處理中目錄(目錄: Path) -> Path:
    """回傳收件匣裡暫時收下、尚未收尾的目錄。"""
    return 目錄 / _處理中


def 丟一件(題目: str, *, 來源: str, 目錄: Path | None = None) -> Path:
    """把一句話落成一個收件檔，回傳它的位置。**這是「你敲」變成事件的那一步。**

    檔名長成 `<時戳>-<來源>-<標籤>-<亂碼>.md`：時戳讓 `ls` 就是時序（先進先出
    靠的是它），來源讓成果帳分得出是誰觸發的，亂碼讓同一秒敲兩次不會互相蓋掉。
    """
    if 來源 not in _認得的來源:
        訊息 = f"不認得的來源 {來源!r}——只准 {sorted(_認得的來源)}"
        raise ValueError(訊息)
    內容 = 題目.strip()
    if not 內容:
        訊息 = "題目是空的，派不出工"
        raise ValueError(訊息)
    _擋下超過指名測試上限(內容, 來源)
    _擋下殘缺的自主票(內容, 來源)
    return _落一個檔(內容 + "\n", 標籤用=內容, 來源=來源, 在哪=目錄 or 收件目錄())


def 接著排(單: 收件單, *, 前情: str, 上一輪: str = "", 目錄: Path | None = None) -> Path | None:
    """撞到上限停下來的那件，排回收件匣讓下一次醒來接著做。

    **回 None ＝ 輪次用完了**，那時候不排。呼叫端要讓人看得見——
    靜靜不排的話，「做不完」跟「做完了」在 `nova 狀態` 上長得一模一樣。

    **前情要過遮罩。** 進度檔可以不遮，因為路徑是使用者自己挑的
    （他知道那份內容能不能公開）；接續票的路徑是 **nova 自己挑的**，
    而收件匣跟已處理同一級，都是躺在磁碟上直到有人刪掉的東西。
    實測過模型會把祕密原封不動講回來，而前情正是模型講的話。

    **來源沿用原本的**：來源是「誰造了這件事」的血緣，不是「誰把它撿起來」
    ——你敲的那件接續之後還是你敲的，不另立第五個 semantic id。
    """
    if 單.輪次 >= 最多輪次:
        return None
    內容 = _接續票內容(單.任務, 前情=遮罩(前情).文字, 輪次=單.輪次 + 1, 上一輪=上一輪)
    return _落一個檔(內容, 標籤用=單.任務, 來源=單.來源, 在哪=目錄 or 收件目錄())


def _接續票內容(題目: str, *, 前情: 已遮罩文字, 輪次: int, 上一輪: str) -> str:
    """組接續票的內容。**存在的理由是型別**，不是為了短。

    `接著排` 本來直接寫 f-string——而 **f-string 不會讓型別流過去**：
    把 `遮罩(前情).文字` 換成 `前情`，mypy 一個字都不會說。
    收成參數之後，忘了遮就在 mypy 紅（決策 0002）。
    """
    return (
        f"{題目}\n\n"
        f"<!--nova:接續 輪次={輪次} 上一輪={上一輪}-->\n"
        f"上一輪撞到上限停下，這一輪接著做，不要從頭來。\n\n{前情}\n"
    )


def _落一個檔(內容: str, *, 標籤用: str, 來源: str, 在哪: Path) -> Path:
    """真正寫檔的那一步。丟一件與接著排共用，**檔名規則只有一份**。

    **這裡刻意收裸 `str`，不要「修好」它。** 收件匣的票是**輸入**，
    要原封不動餵回模型；遮掉的話模型看到的是 `[遮罩:…]`，題目就殘了。
    要遮的是**紀錄**（`已處理/` 的歸檔、帳本），那條路走 `_寫下遮過的`。
    分錯邊的代價不對稱：輸入遮掉只是看不懂，紀錄漏遮是永久外洩。
    """
    在哪.mkdir(parents=True, exist_ok=True)
    當下 = datetime.now(UTC).strftime(_檔名時戳)
    標籤 = _檔名不要的.sub("-", 標籤用)[:_標籤幾個字].strip("-") or "工作"
    落點 = 在哪 / f"{當下}-{來源}-{標籤}-{token_hex(3)}.md"
    落點.write_text(內容, encoding="utf-8")
    return 落點


def _拆接續(內容: str) -> tuple[str, str, int]:
    """(題目, 前情, 輪次)。**沒有標記就是手丟的第一輪**，不是錯誤。"""
    找到 = _接續標記.search(內容)
    if 找到 is None:
        return 內容.strip(), "", 1
    return 內容[: 找到.start()].strip(), 內容[找到.end() :].strip(), int(找到.group(1))


def 誰造的(檔名: str) -> str:
    """從檔名讀出來源。讀不出來就是**檔案**——那是手丟進去的，而那也是一種來源。

    判準要夠緊：第一段是時戳、第二段是認得的來源。鬆的話一個剛好叫
    `2026-typed-x.md` 的手丟檔會被標成你敲。
    """
    段 = 檔名.split("-")
    if len(段) < _最少幾段 or 段[1] not in _認得的來源:
        return 檔案
    try:
        datetime.strptime(段[0], _檔名時戳).replace(tzinfo=UTC)
    except ValueError:
        return 檔案
    return 段[1]


def _按檔名列出檔案(在哪: Path) -> list[Path]:
    """一個目錄裡的檔案，**按檔名排**。

    目錄不存在就是空的——第一次跑的時候本來就還沒有。
    只看檔案不看子目錄：`處理中/` 就住在旁邊，掃到它會變成無限迴圈。
    """
    if not 在哪.is_dir():
        return []
    return sorted((路 for 路 in 在哪.iterdir() if 路.is_file()), key=lambda 路: 路.name)


def 待處理(目錄: Path | None = None) -> list[Path]:
    """還沒有人動的那些，**先丟的排前面**。目錄不存在就是空的。"""
    return _按檔名列出檔案(目錄 or 收件目錄())


#: 收下多久還沒收尾就當它卡住了。理由寫在 `卡住的()` 的 docstring。
_預設多久算卡住 = timedelta(minutes=30)


@dataclass(frozen=True, slots=True)
class 卡住的一件:
    """`處理中/` 裡一件收下了、卻沒收尾的殘骸。**唯讀的一張快照。**

    `收下時間` 走檔案 mtime 不走檔名時戳：檔名時戳是「這張票什麼時候被造出來」，
    而卡住要問的是「它什麼時候被收下」——排程票可能躺了三天才被撿起來。
    """

    檔名: str
    收下時間: datetime
    卡了多久: timedelta
    #: 原本的題目，**不含前情**——前情是模型上一輪講的話，
    #: 混進來人會以為那是他自己交代的事。
    題目: str


class 卡住清單(list[卡住的一件]):
    """卡住的那些，外加**跳過幾個讀不動的**。

    跳過幾個不是「出事才有」的欄位：它永遠拿得到，否則呼叫端要先問有沒有。
    清單上兩件、實際上三件的差距，正是「看起來沒事」與「真的沒事」之間唯一的線索。
    """

    def __init__(self, 那些: list[卡住的一件], *, 跳過幾個: int = 0) -> None:
        """收下那些卡住的，外加跳過幾個讀不動的。"""
        super().__init__(那些)
        self.跳過幾個 = 跳過幾個


def 卡住的(目錄: Path | None = None, *, 多久算卡住: timedelta = _預設多久算卡住) -> 卡住清單:
    """`處理中/` 裡收下了卻沒收尾的那些，**按檔名排**——只為了每次查的順序一樣。

    **這一格唯讀：一個檔都不搬、不刪、不改。** 自動清理是危險操作——殘骸代表
    一件做到一半的工作，副作用可能已經發生，要不要清是人的決定。查詢順手清掉的話，
    人會失去「這件到底做到哪」的唯一線索，而且是在他還不知道發生過什麼的時候失去。

    `多久算卡住` 預設 30 分鐘（`_預設多久算卡住`），理由是門檻要擋得住正在跑的那件：
    不然每次查都會看到正在跑的工作，人就會學會忽略這份清單。
    工作長度跟自己的不一樣就改它。

    目錄不存在回空的——第一次跑的時候本來就還沒有 `處理中/`，那不是異常。
    讀不動的（權限、被刪到一半）跳過，但**數得出跳過幾個**。
    """
    當下 = datetime.now(UTC)
    那些: list[卡住的一件] = []
    跳過幾個 = 0
    for 路 in _按檔名列出檔案(處理中目錄(目錄 or 收件目錄())):
        一件 = _讀殘骸快照(路, 當下=當下)
        if 一件 is None:
            跳過幾個 += 1
        elif 一件.卡了多久 >= 多久算卡住:
            那些.append(一件)
    return 卡住清單(那些, 跳過幾個=跳過幾個)


def _讀殘骸快照(路: Path, *, 當下: datetime) -> 卡住的一件 | None:
    """把 `處理中/` 的一個檔看成一張快照。**讀不動就是 None**，那是要被數的那種。

    這裡不判斷夠不夠久：門檻是呼叫端的政策，快照只講事實。
    分開之後，「跳過幾個」數的永遠是讀不動的，不會混進「還沒卡住的」。
    """
    內容 = _讀得到嗎(路)
    if 內容 is None:
        return None
    收下時間 = datetime.fromtimestamp(路.stat().st_mtime, UTC)
    題目, _前情, _輪次 = _拆接續(內容)
    return 卡住的一件(檔名=路.name, 收下時間=收下時間, 卡了多久=當下 - 收下時間, 題目=題目)


def 收下一件(目錄: Path | None = None) -> 收件單 | None:
    """拿走最前面那一件。沒有東西可拿就回 None。

    **收下＝移走。** 不移走的話，下一輪會再拿到同一件，而副作用會做第二次。
    空白內容的檔案跳過但**不移走**——它派不出工，而移走會讓使用者以為做過了。
    """
    在哪 = 目錄 or 收件目錄()
    for 候選 in 待處理(在哪):
        單 = _搶下來(候選, 在哪)
        if 單 is not None:
            return 單
    return None


def 搶下這一件(候選: Path, 目錄: Path | None = None) -> 收件單 | None:
    """指名搶某一件，搶不到回 None。**派工要的是「我剛落的那張」。**

    `收下一件` 拿的是佇列最前面那一張——派工用它的話，佇列上還有別人在等的
    時候會派到不相干的票，而使用者以為他派的是自己剛給的那個檔。
    所有權宣告仍然是同一個 rename（`_搶下來`），不是第二套。
    """
    return _搶下來(候選, 目錄 or 收件目錄())


def 完成一件(單: 收件單, *, 執行識別碼: str, 已處理: Path) -> Path:
    """把原始請求搬到成果旁邊，回傳它的新位置。

    **成果要對得回請求**：成果帳本說「這件收在護欄」，你要看得到當初丟進來的
    是什麼。兩邊靠執行識別碼配對，跟事件帳本同一條規則。
    """
    已處理.mkdir(parents=True, exist_ok=True)
    落點 = 已處理 / f"{執行識別碼}.收件"
    # **原文也要過遮罩。** 「原文」的意思是「當初丟進來的是什麼」，
    # 不是「連憑證一起留一份」——而 `已處理/` 是躺在磁碟上直到有人刪掉的東西。
    _寫下遮過的(落點, 遮罩(單.任務).文字)
    單.處理中路徑.unlink(missing_ok=True)
    return 落點


def _寫下遮過的(落點: Path, 文字: 已遮罩文字) -> None:
    """歸檔用的唯一落盤入口。**型別是這個函式存在的全部理由。**

    `write_text` 收 `str`，所以忘了遮罩它一個字都不會說。收成
    `已遮罩文字` 之後，忘了遮就在 mypy 紅——由
    `test_收件的落盤只准走遮過的那個入口` 守著沒有第二條路。
    """
    落點.write_text(文字, encoding="utf-8")


def _搶下來(候選: Path, 收件: Path) -> 收件單 | None:
    """用 `rename` 宣告所有權。搶不到（別人先拿走）就回 None。"""
    內容 = _讀得到嗎(候選)
    if 內容 is None or not 內容.strip():
        return None
    處理中 = 處理中目錄(收件)
    處理中.mkdir(parents=True, exist_ok=True)
    目標 = 處理中 / f"{os.getpid()}-{候選.name}"
    try:
        候選.rename(目標)
    except OSError:
        return None  # 別人先搶到了，或檔案剛好被拿走
    題目, 前情, 輪次 = _拆接續(內容)
    return 收件單(
        名稱=候選.stem,
        任務=題目,
        # **餵 `題目` 不是 `內容`**：`_拆接續` 已經把前情切掉了，
        # 而前情是模型的輸出。整份掃的話模型種得進驗收。
        驗收=讀出驗收(題目),
        # 同上：**只掃 `題目`**。掃 `內容` 的話模型在自己的前情裡寫一句
        # `<!--nova:新增保證-->` 就替下一輪多開一次寫測試檔的許可。
        新增保證=_新增保證標記 in 題目,
        處理中路徑=目標,
        來源=誰造的(候選.name),
        前情=前情,
        輪次=輪次,
    )


def _讀得到嗎(路徑: Path) -> str | None:
    """讀不動的不算一件，但**也不移走**——移走等於把使用者丟進來的東西弄丟。"""
    try:
        return 路徑.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None
