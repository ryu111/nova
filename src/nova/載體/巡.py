"""巡：吃「專案 ＋ 現在」，算出哪些接續票該被叫醒、哪些是孤兒、哪些只給人看。

## 為什麼判定要跟發射分開

接續票帶得動 `不早於`，收件匣在時刻之前不放行——**但沒有人定期醒來去看它
到期了沒**。票躺著，時鐘走過去，什麼都沒發生。

補上「醒來」這件事的第一半是**判定**：候選只從 git 登記正向推，四個集合純算
出來，一條線都不發射、一個模型都不叫、樹裡一個檔都不改。判定是純函式才驗得動
——「不早於還沒到」與「到了」的差別只是參數上的一個 `datetime`，測試自己把
時鐘翻面就好，不必等十五分鐘、也不必去戳真的排程。

## 為什麼候選只從 git 登記正向推

glob 狀態根目錄會撿到早就收掉的樹留下來的收件匣，寫死 `nova-wt-` 前綴則是把
命名慣例當成資料來源。**`工作樹們` 是唯一那份登記**，路徑已經不存在但登記還在
的樹也要列進來——那正是孤兒的第一種來源。

## 為什麼「查不到在不在跑」不等於「沒在跑」

`是否在跑` 是三態：True／False／`None`（清查不到）。`None` 當作沒在跑的話，巡
就會在一棵**可能正在跑**的樹上叫醒同一張票，兩個工作流搶同一棵樹。拿 flock 當
替代也不行：拿不到鎖那條路照樣會把 `狀態.json` 覆寫成 busy，把剛寫進去的
`resume_not_before` 洗掉。所以三態裡只有 False 能放行。
"""

import re
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from enum import Enum, auto
from pathlib import Path

from nova.契約.線觀測 import 程序清查
from nova.載體.工作樹觀測 import 工作樹們
from nova.載體.帳本 import 預設帳本目錄
from nova.載體.收件 import _檔名時戳, 待處理, 收件目錄, 處理中目錄
from nova.載體.程序觀測 import 是否在跑

__all__ = ["一輪判定", "巡一輪", "候選票", "最久可接", "能不能叫"]

#: 接續票躺多久就不再自動叫。**這是停止規則，不是設定項。**
#: 接續票是給十五分鐘後的時鐘的；躺超過一天的那些是「時鐘沒在跑那段」的殘留，
#: 一次叫醒會把幾十張陳年的票同時發射出去。過期的只列給人看，
#: 不叫、也不標孤兒——要不要接是人的決定。
最久可接 = timedelta(hours=24)

#: 接續標記整段：`<!--nova:接續 輪次=2 上一輪=… 不早於=…-->`。
#: `收件._接續標記` 只挖得出輪次，這裡要的是欄位那一整串。
_接續標記 = re.compile(r"<!--nova:接續\s+([^>]*?)\s*-->")

#: 標記裡的一格 `鍵=值`。值不含空白（時戳與執行識別碼都是）。
_一格 = re.compile(r"(\S+?)=(\S*)")


class _歸屬(Enum):
    """一張票歸到哪一堆。

    **只在這個模組內部流通**，出口是 `一輪判定` 的欄位，不是這幾個名字。
    前三個是回得出去的集合，後三個是不叫的三種理由——過期要報數、
    還沒到與樹沒放行連數都不必報，差別只在 `巡一輪` 怎麼接。
    """

    到期 = auto()
    孤兒 = auto()
    首輪票 = auto()
    過期 = auto()
    還沒到 = auto()
    #: 樹正在跑，或清查不到它在不在跑——三態裡只有 False 能放行。
    樹沒放行 = auto()


@dataclass(frozen=True, slots=True)
class 候選票:
    """收件匣裡的一張票，連同它屬於哪棵派工樹。

    **樹要跟著票走**：發射那一半（23-2）要在對的樹上叫醒它，
    只回一串路徑的話呼叫端得再倒推一次歸屬，而那正是會推錯的地方。
    """

    票: Path
    樹: Path


@dataclass(frozen=True, slots=True)
class 一輪判定:
    """巡一輪算出來的四個集合，加上要印給人看的話。

    集合分四個而不是「叫／不叫」兩個：不叫的三種理由完全不同——孤兒接的是
    舊世界、首輪票是人手放的、殘骸是上一個程序被殺掉留下的——混成一堆的話
    人看不出該對哪一種動手。
    """

    到期: tuple[候選票, ...]
    孤兒: tuple[候選票, ...]
    首輪票: tuple[候選票, ...]
    殘骸: tuple[候選票, ...]
    訊息們: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class _接續:
    """票上那一行接續標記讀出來的欄位。

    `不早於` **原封不動留成字串**：寫票那一端（22a-2 的 `接著排`）落的是帶時區的
    ISO，放行與否交給 `_時候到了嗎` 一處判。在這裡先解成 `datetime` 的話，
    形狀對不上就解出 `None`、被當成「沒有不早於」，時間門形同不存在。
    """

    上一輪: str
    不早於: str


def 能不能叫(在跑: bool | None) -> bool:
    """三態裡只有 `False` 能放行。

    `None` 是「清查不到」，不是「沒在跑」——當成沒在跑就會在一棵可能正在跑的
    樹上叫醒同一張票。這一行看起來可以簡化成 `not 在跑`，那正是它被固定負控
    守著的原因（`tests/負控/登記們/巡判定.py`）。
    """
    return 在跑 is False


def _讀接續(內容: str) -> _接續 | None:
    """票上的接續標記。**沒有標記就是人手放的第一輪**，不是錯誤。"""
    找到 = _接續標記.search(內容)
    if 找到 is None:
        return None
    欄位 = dict(_一格.findall(找到.group(1)))
    return _接續(上一輪=欄位.get("上一輪", ""), 不早於=欄位.get("不早於", ""))


def _時候到了嗎(不早於: str, *, 現在: datetime) -> bool:
    """這張票可以動了嗎。`不早於` 是空的（絕大多數的票）就一律可以。

    形狀是**寫票那一端落下來的帶時區 ISO**（22a-2 的 `接著排(不早於=…)`），所以
    這裡用 `fromisoformat` 讀，不是用檔名那套 `%Y%m%dT%H%M%SZ`——拿檔名格式去解
    ISO 會解不動、被當成「沒給不早於」，時間門就形同不存在。
    讀不動的時戳、還有沒帶時區的時戳都當「可以」：時間門的職責是**擋等時刻的
    那幾張**，不是把一格壞掉的票鎖死。22a-2 的 `收件.時候到了嗎` 落地之後，
    這一份就該換成 import 它。
    """
    if not 不早於:
        return True
    try:
        時刻 = datetime.fromisoformat(不早於)
    except ValueError:
        return True
    if 時刻.tzinfo is None:
        return True
    return 現在 >= 時刻


def _檔名時刻(票: Path) -> datetime | None:
    """從檔名第一段讀落檔時刻。

    **讀不出來就回 `None`**（那張不算過期）——壞掉的一格不該把整張票變成看不見。
    """
    try:
        return datetime.strptime(票.name.split("-")[0], _檔名時戳).replace(tzinfo=UTC)
    except ValueError:
        return None


def _帳本最新那筆(樹: Path) -> str:
    """那棵樹帳本目錄裡最新的執行識別碼。一本都沒有就回空字串。

    識別碼開頭是時戳，所以檔名排序就是時序（跟 `ls` 就是佇列同一條）。
    """
    目錄 = 預設帳本目錄(樹)
    if not 目錄.is_dir():
        return ""
    帳們 = sorted(路.stem for 路 in 目錄.glob("*.jsonl"))
    return 帳們[-1] if 帳們 else ""


def 巡一輪(專案: Path, *, 現在: datetime, 清查: 程序清查 | None) -> 一輪判定:
    """算出這一輪的四個集合。**只判定，不動手。**

    ```
    派工樹  = 工作樹們(專案)[1:]                  ← 去掉主工作區
    候選票  = ⋃ 待處理(收件目錄(樹))
    孤兒    = 樹路徑不存在 ∪ 帶標記 ∧ 上一輪 ≠ 該樹帳本最新那筆
    首輪票  = 沒有接續標記                         ← 只列不叫：人手放的，人手起
    到期    = 帶標記 ∧ 上一輪＝最新 ∧（沒有 不早於 ∨ 不早於 ≤ 現在）
            ∧ 檔名時戳距今 ≤ 最久可接 ∧ 是否在跑(樹) is False
    ```

    `現在` 收成參數不去讀時鐘：吊在時鐘上的判定驗不動，測試要自己把時刻翻面。
    """
    分堆: dict[_歸屬, list[候選票]] = {_歸屬.到期: [], _歸屬.孤兒: [], _歸屬.首輪票: []}
    殘骸: list[候選票] = []
    訊息們: list[str] = []
    過期 = 0

    for 樹, _ in 工作樹們(專案)[1:]:
        匣 = 收件目錄(樹)
        殘骸 += [候選票(票=路, 樹=樹) for 路 in 待處理(處理中目錄(匣))]
        在跑 = 是否在跑(樹, 清查)
        最新 = _帳本最新那筆(樹)
        for 票 in 待處理(匣):
            歸 = _歸到哪(票, 樹在=樹.exists(), 最新=最新, 現在=現在, 在跑=在跑)
            if 歸 in 分堆:
                分堆[歸].append(候選票(票=票, 樹=樹))
            elif 歸 is _歸屬.過期:
                過期 += 1
            elif 在跑 is None:
                # 剩下的兩種理由裡，只有「清查不到」要說出來：時刻還沒到是
                # 講好的等待，查不到卻是巡看不見現場，人得知道它被跳過了。
                訊息們.append(f"{樹.name}：查不到在不在跑，這一輪不叫")

    訊息們 += _數給人看(殘骸=殘骸, 過期=過期)
    return 一輪判定(
        到期=tuple(分堆[_歸屬.到期]),
        孤兒=tuple(分堆[_歸屬.孤兒]),
        首輪票=tuple(分堆[_歸屬.首輪票]),
        殘骸=tuple(殘骸),
        訊息們=tuple(訊息們),
    )


def _歸到哪(
    票: Path,
    *,
    樹在: bool,
    最新: str,
    現在: datetime,
    在跑: bool | None,
) -> _歸屬:
    """一張票歸到哪一堆。**判定的全部條件都在這裡**，呼叫端只負責分派。

    順序不能換：孤兒要先判，因為一張接舊世界的票就算時刻早就到了也不准叫。
    """
    接續 = _讀接續(票.read_text(encoding="utf-8", errors="replace"))
    if not 樹在 or (接續 is not None and 接續.上一輪 != 最新):
        return _歸屬.孤兒
    if 接續 is None:
        return _歸屬.首輪票
    if not _時候到了嗎(接續.不早於, 現在=現在):
        return _歸屬.還沒到
    if _太久沒動(票, 現在=現在):
        return _歸屬.過期
    return _歸屬.到期 if 能不能叫(在跑) else _歸屬.樹沒放行


def _太久沒動(票: Path, *, 現在: datetime) -> bool:
    """檔名時戳距今超過 `最久可接`。時戳讀不出來就當它沒過期。"""
    落檔 = _檔名時刻(票)
    return 落檔 is not None and 現在 - 落檔 > 最久可接


def _數給人看(*, 殘骸: list[候選票], 過期: int) -> list[str]:
    """殘骸與過期只報數，不動手。

    `處理中/` 是上一個程序被殺掉留下的誠實現場，動它等於把證據擦掉；
    過期的票要不要接是人的決定，不是巡的。
    """
    話: list[str] = []
    if 過期:
        話.append(f"過期 {過期} 張（躺超過 {int(最久可接.total_seconds() // 3600)} 小時），不叫")
    if 殘骸:
        樹在 = sum(1 for 一張 in 殘骸 if 一張.樹.exists())
        話.append(f"殘骸 {len(殘骸)} 張（樹在 {樹在}／樹不在 {len(殘骸) - 樹在}），不動")
    return 話
