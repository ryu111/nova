#: 接續票躺多久就不再自動叫。**這是停止規則，不是設定項。**
#: 接續票是給十五分鐘後的時鐘的；躺超過一天的那些是「時鐘沒在跑那段」的殘留，
#: 一次叫醒會把幾十張陳年的票同時發射出去。過期的只列給人看，
#: 不叫、也不標孤兒——要不要接是人的決定。
最久可接 = timedelta(hours=24)

#: 接續標記整段：`<!--nova:接續 輪次=2 上一輪=… 不早於=…-->`。
#: `收件._接續標記` 只挖得出輪次，這裡要的是欄位那一整串。
_接續標記 = re.compile(r"<!--nova:接續\s+([^>]*?)\s*-->")

#: 標記裡的一格 `鍵=值`。值不含空白（時戳與執行識別碼都是）。
_一格 = re.compile(r"(\S+?)=(\S*)")


class _歸屬(Enum):
    """一張票歸到哪一堆。

    **只在這個模組內部流通**，出口是 `一輪判定` 的欄位，不是這幾個名字。
    前三個是回得出去的集合，後三個是不叫的三種理由——過期要報數、
    還沒到與樹沒放行連數都不必報，差別只在 `巡一輪` 怎麼接。
    """

    到期 = auto()
    孤兒 = auto()
    首輪票 = auto()
    過期 = auto()
    還沒到 = auto()
    #: 樹正在跑，或清查不到它在不在跑——三態裡只有 False 能放行。
    樹沒放行 = auto()


@dataclass(frozen=True, slots=True)
class 候選票:
    """收件匣裡的一張票，連同它屬於哪棵派工樹。

    **樹要跟著票走**：發射那一半（23-2）要在對的樹上叫醒它，
    只回一串路徑的話呼叫端得再倒推一次歸屬，而那正是會推錯的地方。
    """

    票: Path
    樹: Path


@dataclass(frozen=True, slots=True)
class 一輪判定:
    """巡一輪算出來的四個集合，加上要印給人看的話。

    集合分四個而不是「叫／不叫」兩個：不叫的三種理由完全不同——孤兒接的是
    舊世界、首輪票是人手放的、殘骸是上一個程序被殺掉留下的——混成一堆的話
    人看不出該對哪一種動手。
    """

    到期: tuple[候選票, ...]
    孤兒: tuple[候選票, ...]
    首輪票: tuple[候選票, ...]
    殘骸: tuple[候選票, ...]
    訊息們: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class _接續:
    """票上那一行接續標記讀出來的欄位。

    `不早於` **原封不動留成字串**：寫票那一端（22a-2 的 `接著排`）落的是帶時區的
    ISO，放行與否交給 `_時候到了嗎` 一處判。在這裡先解成 `datetime` 的話，
    形狀對不上就解出 `None`、被當成「沒有不早於」，時間門形同不存在。
    """

    上一輪: str
    不早於: str


def 能不能叫(在跑: bool | None) -> bool:
    """三態裡只有 `False` 能放行。

    `None` 是「清查不到」，不是「沒在跑」——當成沒在跑就會在一棵可能正在跑的
    樹上叫醒同一張票。這一行看起來可以簡化成 `not 在跑`，那正是它被固定負控
    守著的原因（`tests/負控/登記們/巡判定.py`）。
    """
    return 在跑 is False


def _讀接續(內容: str) -> _接續 | None:
    """票上的接續標記。**沒有標記就是人手放的第一輪**，不是錯誤。"""
    找到 = _接續標記.search(內容)
    if 找到 is None:
        return None
    欄位 = dict(_一格.findall(找到.group(1)))
    return _接續(上一輪=欄位.get("上一輪", ""), 不早於=欄位.get("不早於", ""))


def _時候到了嗎(不早於: str, *, 現在: datetime) -> bool:
    """這張票可以動了嗎。`不早於` 是空的（絕大多數的票）就一律可以。

    形狀是**寫票那一端落下來的帶時區 ISO**（22a-2 的 `接著排(不早於=…)`），所以
    這裡用 `fromisoformat` 讀，不是用檔名那套 `%Y%m%dT%H%M%SZ`——拿檔名格式去解
    ISO 會解不動、被當成「沒給不早於」，時間門就形同不存在。
    讀不動的時戳、還有沒帶時區的時戳都當「可以」：時間門的職責是**擋等時刻的
    那幾張**，不是把一格壞掉的票鎖死。22a-2 的 `收件.時候到了嗎` 落地之後，
    這一份就該換成 import 它。
    """
    if not 不早於:
        return True
    try:
        時刻 = datetime.fromisoformat(不早於)
    except ValueError:
        return True
    if 時刻.tzinfo is None:
        return True
    return 現在 >= 時刻


def _檔名時刻(票: Path) -> datetime | None:
    """從檔名第一段讀落檔時刻。

    **讀不出來就回 `None`**（那張不算過期）——壞掉的一格不該把整張票變成看不見。
    """
    try:
        return datetime.strptime(票.name.split("-")[0], _檔名時戳).replace(tzinfo=UTC)
    except ValueError:
        return None


def _帳本最新那筆(樹: Path) -> str:
    """那棵樹帳本目錄裡最新的執行識別碼。一本都沒有就回空字串。

    識別碼開頭是時戳，所以檔名排序就是時序（跟 `ls` 就是佇列同一條）。
    """
    目錄 = 預設帳本目錄(樹)
    if not 目錄.is_dir():
        return ""
    帳們 = sorted(路.stem for 路 in 目錄.glob("*.jsonl"))
    return 帳們[-1] if 帳們 else ""


def 巡一輪(專案: Path, *, 現在: datetime, 清查: 程序清查 | None) -> 一輪判定:
    """算出這一輪的四個集合。**只判定，不動手。**

    ```
    派工樹  = 工作樹們(專案)[1:]                  ← 去掉主工作區
    候選票  = ⋃ 待處理(收件目錄(樹))
    孤兒    = 樹路徑不存在 ∪ 帶標記 ∧ 上一輪 ≠ 該樹帳本最新那筆
    首輪票  = 沒有接續標記                         ← 只列不叫：人手放的，人手起
    到期    = 帶標記 ∧ 上一輪＝最新 ∧（沒有 不早於 ∨ 不早於 ≤ 現在）
            ∧ 檔名時戳距今 ≤ 最久可接 ∧ 是否在跑(樹) is False
    ```

    `現在` 收成參數不去讀時鐘：吊在時鐘上的判定驗不動，測試要自己把時刻翻面。
    """
    分堆: dict[_歸屬, list[候選票]] = {_歸屬.到期: [], _歸屬.孤兒: [], _歸屬.首輪票: []}
    殘骸: list[候選票] = []
    訊息們: list[str] = []
    過期 = 0

    for 樹, _ in 工作樹們(專案)[1:]:
        匣 = 收件目錄(樹)
        殘骸 += [候選票(票=路, 樹=樹) for 路 in 待處理(處理中目錄(匣))]
        在跑 = 是否在跑(樹, 清查)
        最新 = _帳本最新那筆(樹)
        for 票 in 待處理(匣):
            歸 = _歸到哪(票, 樹在=樹.exists(), 最新=最新, 現在=現在, 在跑=在跑)
            if 歸 in 分堆:
                分堆[歸].append(候選票(票=票, 樹=樹))
            elif 歸 is _歸屬.過期:
                過期 += 1
            elif 在跑 is None:
                # 剩下的兩種理由裡，只有「清查不到」要說出來：時刻還沒到是
                # 講好的等待，查不到卻是巡看不見現場，人得知道它被跳過了。
                訊息們.append(f"{樹.name}：查不到在不在跑，這一輪不叫")

    訊息們 += _數給人看(殘骸=殘骸, 過期=過期)
    return 一輪判定(
        到期=tuple(分堆[_歸屬.到期]),
        孤兒=tuple(分堆[_歸屬.孤兒]),
        首輪票=tuple(分堆[_歸屬.首輪票]),
        殘骸=tuple(殘骸),
        訊息們=tuple(訊息們),
    )


def _歸到哪(
    票: Path,
    *,
    樹在: bool,
    最新: str,
    現在: datetime,
    在跑: bool | None,
) -> _歸屬:
    """一張票歸到哪一堆。**判定的全部條件都在這裡**，呼叫端只負責分派。

    順序不能換：孤兒要先判，因為一張接舊世界的票就算時刻早就到了也不准叫。
    """
    接續 = _讀接續(票.read_text(encoding="utf-8", errors="replace"))
    if not 樹在 or (接續 is not None and 接續.上一輪 != 最新):
        return _歸屬.孤兒
    if 接續 is None:
        return _歸屬.首輪票
    if not _時候到了嗎(接續.不早於, 現在=現在):
        return _歸屬.還沒到
    if _太久沒動(票, 現在=現在):
        return _歸屬.過期
    return _歸屬.到期 if 能不能叫(在跑) else _歸屬.樹沒放行


def _太久沒動(票: Path, *, 現在: datetime) -> bool:
    """檔名時戳距今超過 `最久可接`。時戳讀不出來就當它沒過期。"""
    落檔 = _檔名時刻(票)
    return 落檔 is not None and 現在 - 落檔 > 最久可接


def _數給人看(*, 殘骸: list[候選票], 過期: int) -> list[str]:
    """殘骸與過期只報數，不動手。

    `處理中/` 是上一個程序被殺掉留下的誠實現場，動它等於把證據擦掉；
    過期的票要不要接是人的決定，不是巡的。
    """
    話: list[str] = []
    if 過期:
        話.append(f"過期 {過期} 張（躺超過 {int(最久可接.total_seconds() // 3600)} 小時），不叫")
    if 殘骸:
        樹在 = sum(1 for 一張 in 殘骸 if 一張.樹.exists())
        話.append(f"殘骸 {len(殘骸)} 張（樹在 {樹在}／樹不在 {len(殘骸) - 樹在}），不動")
    return 話


#: 這台機器同時最多幾條線。本地腦一條 3.8 GB，四條就把記憶體吃光。
#: **停止規則，不是旗標也不是設定項**——調得動的門檻第一次擋到人就會被調大。
最多同時線數 = 4

#: 一次醒來最多叫幾條。跟配額取小的那一個才是這一輪真的會發射的數量。
一次最多喚醒 = 2


def _在底下(路: Path, 上層: Path) -> bool:
    """`路` 是不是在 `上層` 底下（含自己）。兩邊都先 resolve 才比得準。"""
    try:
        路.resolve().relative_to(上層.resolve())
    except ValueError:
        return False
    return True


def 載體不在專案底下(專案: Path) -> bool:
    """自檢 (a)：**執行中的這份 nova 的原始碼**不在 `專案` 底下。

    比的是 `nova.__file__`，不去 import 主工作區的 nova——真的載入它就等於
    讓被巡的那棵樹決定巡自己怎麼跑。
    """
    return not _在底下(Path(nova.__file__), 專案)


def 自己的樹乾淨嗎() -> bool:
    """自檢 (c)：巡自己站的那棵樹沒有未提交的東西。

    **查不到也算不乾淨**：查不到就是看不見現場，那時候發射等於閉著眼睛動別人的樹。
    """
    return 未提交檔案數(Path.cwd()) == 0


def _自檢不過的理由(專案: Path) -> str | None:
    """三道自檢，擋得下就回一句話。**話裡要指名是哪個路徑害的**——

    只說「不能在主工作區跑」的話，人看不出該去修 cwd 還是修這支 nova 是哪裡來的。
    """
    if not 載體不在專案底下(專案):
        return f"這份 nova 的原始碼就在 {專案} 底下：巡不能拿主工作區的自己去跑"
    if _在底下(Path.cwd(), 專案):
        return f"現在就站在 {專案} 裡（cwd={Path.cwd()}）：巡要在自己的樹上跑"
    if not 自己的樹乾淨嗎():
        return f"巡自己的樹（{Path.cwd()}）不乾淨或查不到，這一輪不跑（要巡的是 {專案}）"
    return None


def 這次的配額(專案: Path) -> int:
    """這一輪最多發射幾條：`最多同時線數 − 在跑的線數`，跟 `一次最多喚醒` 取小。

    在跑的**只數 `在跑嗎 is True`**：`None` 是「清查不到」，把它算成在跑會讓巡在
    清查失靈的那天一條都不敢叫。
    """
    在跑 = sum(1 for 線 in 查並行現況(專案) if 線.在跑嗎 is True)
    return min(一次最多喚醒, 最多同時線數 - 在跑)


#: 轉給 `工作流` 之前要剝掉的帶值旗標：`--專案` 只有巡認得，
#: `--工作目錄` 等一下會補一份指到票自己那棵樹，留著舊的就會有兩份。
_剝掉這幾格帶值的 = ("--專案", "--工作目錄")

#: 同樣那幾格寫成 `--專案=值` 時的樣子（一格就帶著值，沒有下一格要跳）。
_剝掉這幾格的等號寫法 = tuple(f"{名}=" for 名 in _剝掉這幾格帶值的)

#: 轉給 `工作流` 之前要剝掉的開關旗標：`--演練` 只有巡認得。
_剝掉這幾格開關的 = ("--演練",)


def _剝掉巡自己的旗標(原argv: list[str]) -> list[str]:
    """拿掉 `--專案 <值>`／`--工作目錄 <值>`（含 `=` 寫法）與 `--演練`。

    帶值的旗標分兩格寫的時候，值跟在後面那一格，所以要記著「下一格是它的值」
    再一起跳過；沒記的話那個值會被當成 `工作流` 的位置參數送過去。
    """
    留下: list[str] = []
    下一格是值 = False
    for 格 in 原argv:
        if 下一格是值:
            下一格是值 = False
            continue
        if 格 in _剝掉這幾格帶值的:
            下一格是值 = True
            continue
        if 格 in _剝掉這幾格開關的 or 格.startswith(_剝掉這幾格的等號寫法):
            continue
        留下.append(格)
    return 留下


def _子命令在第幾格(原argv: list[str]) -> int:
    """`巡` 這個子命令真正落在第幾格。

    daemon 醒來的那一行是 `nova --根目錄 <樹> 巡 --專案 …`：`--根目錄` 是頂層旗標，
    合法而且必須留在子命令前面，所以不能假設 `巡` 就在第一格。值剛好是「巡」兩個字
    的旗標（例如 `--帳本目錄 巡`）不算——那一格的前一格是旗標。
    找不到就回長度，等於「後面沒有東西要轉」。
    """
    for 第幾格, 格 in enumerate(原argv):
        前一格 = 原argv[第幾格 - 1] if 第幾格 else ""
        if 格 == "巡" and not 前一格.startswith("-"):
            return 第幾格
    return len(原argv)


def _轉成工作流的argv(一張: 候選票) -> list[str]:
    """把自己的 argv 轉成那條線要跑的 `工作流`。

    **只換子命令那一格**（值剛好叫「巡」的旗標不准跟著被改，`--根目錄` 這種頂層
    旗標原樣留在子命令前面）、剝掉
    `--專案`／`--演練`／舊的 `--工作目錄`，加上
    `--從收件匣 --收件檔 <票> --工作目錄 <樹>`；`--喚醒來源` 與一輪的旗標原樣帶過去。
    走 `sys.argv` 而不是重組參數（跟 `_丟到背景` 同一條理由）：重組會漏掉旗標，
    而漏掉的那次剛好就是最難查的那次。

    `--收件檔` 指名選中的那一張：那棵樹的收件匣裡可能還躺著判定說「不准叫」的
    孤兒票，不指名的話子程序照檔名先拿到的就是它。
    """
    巡自己的參 = sys.argv[1:]
    這一格 = _子命令在第幾格(巡自己的參)
    子命令前面的 = 巡自己的參[:這一格]
    子命令後面的 = 巡自己的參[這一格 + 1 :] if 這一格 < len(巡自己的參) else []
    轉過去的 = _剝掉巡自己的旗標(子命令後面的)
    return [
        *子命令前面的,
        "工作流",
        *轉過去的,
        "--從收件匣",
        "--收件檔",
        str(一張.票),
        "--工作目錄",
        str(一張.樹),
    ]


def _叫醒(一張: 候選票, *, 專案: Path) -> Path:
    """在那張票自己的樹上發射一條 `工作流`，回傳它的輸出檔。

    **不走 `_背景起一條線`**：那是派工的形狀（它要開新樹、要搶票），
    喚醒接的是既有的樹與既有的票。
    """
    輸出檔 = 備好背景輸出目錄(專案) / f"{一張.樹.name}.md"
    with 輸出檔.open("a", encoding="utf-8") as 手:
        發射背景程序(_轉成工作流的argv(一張), 輸出=手, 在哪跑=一張.樹, 環境=os.environ.copy())
    return 輸出檔


def _記下這一輪(判定: 一輪判定, *, 叫了: int) -> None:
    """巡自己那一筆狀態。**住 `狀態根/巡/`，不是任何專案底下**——

    巡不屬於它巡的任何一個專案，寫進某個專案的 `狀態.json` 會把那個專案
    上一輪工作流的事實蓋掉。
    """
    寫下現況(
        現況(
            上次醒來=datetime.now(UTC).isoformat(),
            上次結果=巡過了,
            上次退出碼=放行,
            上次理由=(
                f"叫了 {叫了} 條、孤兒 {len(判定.孤兒)} 張、"
                f"首輪 {len(判定.首輪票)} 張、殘骸 {len(判定.殘骸)} 張"
            ),
        ),
        路徑=狀態根目錄() / "巡" / 狀態檔名,
    )


def _這一輪要叫誰(專案: Path) -> tuple[一輪判定, list[候選票]]:
    """判定 ＋ 這一輪配額之內、檔名時戳最早的那幾張。

    排序是巡的責任，不是呼叫端剛好給對了順序：檔名第一段是時戳，所以
    照檔名排就是照落票的先後。
    """
    判定 = 巡一輪(專案, 現在=datetime.now(UTC), 清查=找nova程序())
    # 在跑的線數可以超過上限（人手動起的線不受巡管），那時配額算出來是負的，
    # 而負數餵給切片會從尾巴倒數回來——變成「越滿越叫」。夾在 0 才是「一條都不叫」。
    配額 = max(0, 這次的配額(專案))
    return 判定, sorted(判定.到期, key=lambda 一張: 一張.票.name)[:配額]


def _跑一輪(專案: Path, *, 演練: bool) -> int:
    """算出這一輪要叫誰，然後叫（`--演練` 只印不叫）。"""
    判定, 要叫 = _這一輪要叫誰(專案)
    for 一句 in 判定.訊息們:
        sys.stdout.write(f"{一句}\n")
    if 演練:
        for 一張 in 要叫:
            sys.stdout.write(f"會叫：{一張.票.name}（樹 {一張.樹}）\n")
        return 放行
    for 一張 in 要叫:
        sys.stdout.write(f"叫醒 {一張.票.name}：輸出寫在 {_叫醒(一張, 專案=專案)}\n")
    _記下這一輪(判定, 叫了=len(要叫))
    return 放行


def 子命令_巡(參數: argparse.Namespace) -> int:
    """`nova 巡`：三道自檢 → 單例鎖 → 把到期的接續票叫醒。

    自己的 HEAD 每次醒來都印出來：巡是背景跑的，出事時人手上唯一的線索
    就是這一行說的「當時跑的是哪一版」。
    """
    專案 = Path(參數.專案)
    sys.stdout.write(f"巡自己的 HEAD：{目前commit(Path.cwd()) or '查不到'}\n")
    理由 = _自檢不過的理由(專案)
    if 理由 is not None:
        sys.stderr.write(f"{理由}\n")
        return 阻擋
    try:
        with 只准一個(狀態根目錄() / "巡.鎖"):
            return _跑一輪(專案, 演練=參數.演練)
    except 拿不到鎖 as 忙:
        # 上一輪還在巡就安靜讓開（0）：巡本來就會在忙的時候醒來，
        # 把它印成錯誤的話 log 會被永遠不會有人修的錯誤塞滿。
        sys.stderr.write(f"{忙}\n")
        return 放行
