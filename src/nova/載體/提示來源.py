"""提示從哪來：**argv 是唯一會被 shell 展開的通道，長提示不准走它。**

## 為什麼不能靠偵測

2026-08-30 派研究時，提示直接寫在雙引號字串裡，而裡面有反引號：

```
uv run nova 問 --用 codex "…請看 `docs/設計/` 底下…"
                                  ^^^^^^^^^^^ zsh 當成命令替換
```

替換之後那段字**完全消失**，nova 收到的是一份看起來正常的短提示——
它無從分辨「本來就沒有那段」跟「那段被吃掉了」，**沒有任何殘跡**。
程序照樣啟動、照樣燒完整的 token，然後交出一份對著殘缺題目寫的答案。
（同一批裡另一份是當場 parse error，那反而便宜——**無聲的那種才貴**。）

所以偵測不可能，只能**改通道**。

## 三條路，優先權寫死在這裡

| 來源 | 經過 shell 解析嗎 | 什麼時候用 |
|---|---|---|
| `--提示檔` | **不** —— nova 自己開檔 | 長的、多行的、有反引號的 |
| stdin | **不** —— nova 自己讀管線 | 從別的指令接過來 |
| argv | **會** —— 這就是危險的那條 | 人在終端機打的一句話 |

argv 的判準是「換行或太長」，因為那兩件事都代表**這是組出來的，不是人打的**。

**這條規則不精確是刻意的**：`"$(cat 檔)"` 其實安全，但 nova 站在邊界上
分不出安全的組法與危險的組法，而被擋下來的那個用法有一個嚴格更好的替代。

## 呼叫端不得不明講

`讀提示` 的兩個關鍵字**都是必填**（`提示檔` 可以是 `None`，但要傳）。
給預設值的話，忘了接 `--提示檔` 的子命令會安靜地只剩下危險的那條路，
而那正是這個模組要防的事。
"""

import sys
from collections.abc import Sequence
from pathlib import Path

#: argv 提示的長度上限。**這不是安全邊界，是「人打得出來嗎」的門檻。**
#: 超過就代表它是組出來的，而組出來的東西應該走檔案。
最長的argv提示 = 2000


class 提示走錯路(ValueError):
    """提示走了會被 shell 展開的通道，而且它長得像組出來的。"""


def argv太危險(文字: str) -> str | None:
    """走 argv 安不安全。回**拒絕的理由**，安全就回 `None`。純函式。

    理由要能照做：兩條安全的路都講出來，而且說得出為什麼——
    不講原因的話，下一個人會以為這是任意的限制然後想辦法繞過。
    """
    if "\n" not in 文字 and len(文字) <= 最長的argv提示:
        return None
    哪裡不對 = "有換行" if "\n" in 文字 else f"超過 {最長的argv提示} 字"
    return (
        f"這段提示{哪裡不對}，看起來是組出來的而不是打出來的，不准走 argv。\n"
        "  為什麼：argv 會被 shell 展開，提示裡的反引號與 $() 會被吃掉，"
        "而且**吃掉之後沒有殘跡**——nova 收到一份殘缺的題目卻看不出來，"
        "照樣燒完整的 token（2026-08-30 真的發生過）。\n"
        "  改走這兩條其中一條（都不經過 shell 解析）：\n"
        "    nova 問 --提示檔 題目.md ...\n"
        "    cat 題目.md | nova 問 ...        # stdin"
    )


def 讀提示(*, argv片段: Sequence[str], 提示檔: str | None) -> str:
    """把三條路收斂成一個字串。**兩個關鍵字都是必填。**

    `提示檔` 允許 `None`，但**必須傳**——給預設值的話，
    忘了接 `--提示檔` 的子命令會安靜地只剩下危險的那條路。
    這是型別在替我們記事情，不是靠人記得。

    優先權：`--提示檔` > argv > stdin。給了檔案就不看 argv——
    兩個都給是呼叫端搞錯了，而**安靜地挑一個**會讓他不知道自己搞錯。
    """
    if 提示檔 is not None:
        return Path(提示檔).read_text(encoding="utf-8")
    文字 = " ".join(argv片段)
    if not 文字:
        return sys.stdin.read()
    不行 = argv太危險(文字)
    if 不行 is not None:
        raise 提示走錯路(不行)
    return 文字
