"""進度檔：讓一輪工作流的進度活得比程序久。

跟 `載體/階段記帳.py` 是同一個形狀的兩個包裝（**照抄，還沒到抽共用的時候**——
三次法則要第三個才抽），但回答的是不同的問題：

| 這一層寫 | 回答的問題 | 記不記全文 |
|---|---|---|
| `記帳執行器` | 走到哪、紅還是綠、花多少 | 記回應，但**遮過且會截斷** |
| `進度執行器` | 它當時**做了什麼** | 記 |

所以兩個都要。帳本的全文是**遮過的**（有洞）而且超過上限會截斷，
拿去當前情餵回模型會餵到殘缺的東西——帳本是給人查的證據，不是給模型的記憶。
下一輪要接得上，需要的正好是後者。

**進度檔是使用者指定的路徑**，不是 nova 自己找地方寫——內容有模型全文，
放哪裡由知道那份內容能不能公開的人決定。
"""

from pathlib import Path

from nova.契約.工作流 import 任務, 執行器, 步驟結果, 階段定義

#: 一步寫多少字。太長會讓下一輪的提示膨脹回原本要解決的問題。
一步上限 = 4000


def 檢查進度檔位置(檔: Path, 工作目錄: Path) -> None:
    """進度檔不准住在工作目錄底下。**fail-closed，不是警告。**

    真跑七階段才發現的：放在工作目錄裡，模型會讀它、照抄格式、往裡面接一段
    自己的摘要。同一階段同一題目，只差進度檔的位置——

        在裡面 → nova 寫的段落數 2（多出來那段是模型寫的）
        在外面 → 1

    為什麼不能只是髒：進度檔下一輪會被當成 `前情` 餵回模型。
    **執行者可以在載體的記憶裡種東西給未來的自己看。**
    那是宿主反轉最不該破的一格——連狀態都住在執行者手上，就沒有殼了。

    為什麼不是警告：警告會被忽略，而且忽略的那次剛好就是被種東西的那次。

    子目錄一樣要擋（模型動得到整棵樹），路徑要先解析成絕對的
    ——`./進度.md` 跟工作目錄比字串永遠不相等，那等於沒擋。
    """
    絕對檔 = 檔.resolve()
    絕對目錄 = 工作目錄.resolve()
    if 絕對目錄 in 絕對檔.parents:
        訊息 = (
            f"進度檔 {絕對檔} 在工作目錄 {絕對目錄} 底下——模型動得到它，"
            f"會把自己的話寫進去，而那份東西下一輪會被當成前情餵回去。放到工作目錄外面。"
        )
        raise ValueError(訊息)


def 進度執行器(內層: 執行器, 檔: Path) -> 執行器:
    """包住一個執行器，每跑完一階就把證據**附加**到檔案。

    **跑完就寫，不要等整輪結束**——被殺掉的那一輪正是最需要進度的一輪。
    附加不是覆寫：覆寫的話，最後一階把前面全洗掉，等於只記得一步。

    寫檔失敗不擋工作流：進度是**加速器**，不是保證。
    寫不出來頂多下一輪從頭來，把整輪弄死才是更大的損失。
    """

    def 執行一步(定義: 階段定義, 任: 任務, 軌跡: tuple[步驟結果, ...]) -> 步驟結果:
        結果 = 內層(定義, 任, 軌跡)
        綠 = "" if 結果.判準綠 is None else f"（判準{'綠' if 結果.判準綠 else '紅'}）"
        一段 = (
            f"\n## {定義.代碼.value} · {定義.名稱}{綠}\n"
            f"終局：{結果.終局.value}\n\n{結果.證據[:一步上限]}\n"
        )
        try:
            with 檔.open("a", encoding="utf-8") as 手:
                手.write(一段)
        except OSError:  # noqa: S110 —— 進度是加速器，寫不出來不該把整輪弄死
            pass
        return 結果

    setattr(執行一步, "__wrapped__", 內層)  # noqa: B010 —— 保留內層執行器供解包
    return 執行一步


def 讀進度(檔: Path) -> str:
    """讀不到就回空字串——**第一輪沒有進度檔，那不是錯誤**。"""
    try:
        return 檔.read_text(encoding="utf-8")
    except OSError:
        return ""
