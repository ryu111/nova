"""同一類失敗第二次出現就指出來——不要等人自己撞到。

`docs/設計/09-接下來往哪走.md` 第 2 階的判準：「同一類失敗第二次出現 →
自動落票／落一支探針」。`載體/閘紅成票.py` 做掉了閘紅那半，模型失敗那半沒有：
一顆腦連續在同一階摔、工具回合用完、輸出解析不出來，現在只留在帳本裡沒人回頭看。

這個檔只做**唯讀查詢**：讀跨專案帳本，挑出同一類出現兩次以上的失敗。
**不落票、不碰收件匣**——落票是下一格，那條路要先想清楚
「同一類失敗的票怎麼去重」（`閘紅成票.py` 用機器鍵去重）。
"""

from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from nova.契約.帳本 import 事件種類
from nova.載體.帳本讀取 import 讀原始事件, 跨專案盤點

#: 幾次算「重複」。**第一次是雜訊，第二次才是模式。**
#:
#: 1 等於每個失敗都算重複——失敗是 TDD 的正常狀態，清單當天就淹掉；
#: 3 以上等於同一顆腦要摔滿三次才有人知道，而第三次通常已經有人先撞到了。
重複門檻 = 2


@dataclass(frozen=True, slots=True)
class 一類重複失敗:
    """一類反覆出現的失敗。

    鍵是階段＋失敗代碼＋供應商，**不含執行識別碼與時間戳**——含了的話
    每一筆都是獨一無二的，「第二次」永遠不會發生，這整份查詢等於死程式碼。
    """

    階段: str
    失敗代碼: str
    供應商: str
    次數: int
    #: 貢獻這一類的執行識別碼們。一次執行最多貢獻一次，所以長度等於 `次數`。
    執行們: tuple[str, ...]


def 找出重複失敗(狀態根: Path) -> list[一類重複失敗]:
    """掃跨專案帳本，回傳出現次數達 `重複門檻` 的失敗類別。

    帳本不存在、或每一類都只摔過一次時回空清單——「還沒有帳」不是錯誤，
    全新的機器上狀態目錄根本不存在。
    """
    return [
        一類重複失敗(
            階段=階段,
            失敗代碼=失敗代碼,
            供應商=供應商,
            次數=len(執行們),
            執行們=tuple(執行們),
        )
        for (階段, 失敗代碼, 供應商), 執行們 in _每類摔過的執行們(狀態根).items()
        if len(執行們) >= 重複門檻
    ]


def _每類摔過的執行們(狀態根: Path) -> dict[tuple[str, str, str], list[str]]:
    """跨專案帳本 → 每一類失敗各是被哪幾次執行貢獻的。

    同一個執行識別碼只記一次：一次執行最多貢獻一次，所以清單長度就是次數。
    （不同專案的帳本可能撞到同名的執行識別碼，所以這裡仍要擋一次。）
    """
    每類的執行們: dict[tuple[str, str, str], list[str]] = {}
    for _, 檔 in 跨專案盤點(狀態根).執行們:
        執行識別碼 = 檔.stem
        for 鍵 in _這次執行摔過的類別(檔):
            執行們 = 每類的執行們.setdefault(鍵, [])
            if 執行識別碼 not in 執行們:
                執行們.append(執行識別碼)
    return 每類的執行們


def _這次執行摔過的類別(檔: Path) -> set[tuple[str, str, str]]:
    """一本帳 → 這次執行摔過哪幾類。

    **回集合**是為了讓接力鏈只算一次：接力（`接力第幾顆`／`attempt`）是同一件事的
    重試，算成三次的話第一次執行就直接過門檻，門檻等於沒有。
    """
    return set(_順著讀出的失敗類別(檔))


def _順著讀出的失敗類別(檔: Path) -> Iterator[tuple[str, str, str]]:
    """走一遍事件，把失敗的呼叫配上它所在的階段。

    呼叫事件自己不帶階段，階段要靠外層那對 `stage_started`／`stage_finished`
    圈出來，所以只能順著讀。
    """
    目前階段 = ""
    for 事 in _讀得動的事件(檔):
        種類 = 事.get("event")
        if 種類 == 事件種類.階段開始.value:
            目前階段 = str(事.get("stage", ""))
        elif 種類 == 事件種類.階段結束.value:
            目前階段 = ""
        elif 種類 == 事件種類.呼叫結束.value and 事.get("outcome") == "failed":
            yield (目前階段, str(事.get("failure_code", "")), str(事.get("family", "")))


def _讀得動的事件(檔: Path) -> list[dict[str, Any]]:
    """讀不動的整本跳過。

    盤點已經濾過撈不到的檔，但檔可能在盤點之後被換掉或權限變了——
    一本讀不動就讓整份查詢炸掉，等於一次磁碟意外就把狀態列弄紅。
    """
    try:
        return 讀原始事件(檔)
    except OSError:
        return []
