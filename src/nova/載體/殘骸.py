"""逾時不該等於全損：給被委派的 CLI 一個檔案邊做邊寫，死了還有屍體可以驗。

## 為什麼需要這個

實測 `gpt-5.6-sol` 跑同一個大題目，25 分鐘一次、60 分鐘一次，
**兩次都是 0→0 token**。nova 判「結果未知」是對的，但我們對
「它到底做到哪了」一無所知——連「有沒有開始」都不知道。

原因是**輸出只有一條路**：stdout，而且要整個跑完才吐。那條路被砍斷，
前面幾十分鐘的工作就一起消失。

給它一個檔案邊做邊寫，這條路就多一個出口。逾時之後那個檔案就是證據。

## 兩條不准弄混的規則

1. **有屍體不等於做完了。** 撿回殘骸**不改終局**——它還是結果未知，
   還是不准自動重跑。改成成功就是拿半成品當成品。
2. **殘骸是補充不是取代。** 原本的失敗訊息才說得出「為什麼死的」，
   殘骸只說得出「死之前做到哪」。兩個都要留。

## 從簡

只做 `nova 問` 這條路。工作流那條每一步都可以留殘骸，但那要先想清楚
「哪一步的殘骸算數」，還沒到那個時候。
"""

from dataclasses import replace
from pathlib import Path

from nova.契約.模型回應 import 回應, 終局

#: 殘骸最多帶回多少字。屍體可能是一個很大的 log，
#: 整個塞進回應會把終端機洗掉——而且真正有用的通常在開頭。
殘骸上限 = 12_000


def 加上寫檔指示(提示: str, 輸出檔: Path) -> str:
    """在原本的提示後面補一段「邊做邊寫」。

    **原本的提示留在最前面**：指示塞在前面會讓模型把它當成主要任務。

    「邊做邊寫」那句是整個機制的關鍵——最後才寫的話，逾時一樣什麼都沒有。
    這是提示不是保證（模型可以不理），所以撿回來的東西一律當「可能不完整」。
    """
    return (
        f"{提示}\n\n"
        f"---\n"
        f"另外：請把你的進度與結論**邊做邊寫**進 {輸出檔}。\n"
        f"每查到一件事就先寫進去，不要等全部做完才寫——"
        f"這個工作可能會被逾時中斷，寫進去的部分才留得下來。"
    )


def 撿回殘骸(答: 回應, 輸出檔: Path) -> 回應:
    """沒跑成的話，把它寫下的東西併進證據。

    成功的時候不動——它已經正常回答了，再接一次只會讓同一段話出現兩次。
    """
    if 答.終局 is 終局.成功:
        return 答
    return replace(答, 文字=_併起來(答.文字, _讀殘骸(輸出檔), 輸出檔))


def _讀殘骸(輸出檔: Path) -> str:
    try:
        內容 = 輸出檔.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    return 內容 if 內容.strip() else ""


def _併起來(原本: str, 殘: str, 輸出檔: Path) -> str:
    """殘骸接在原本的診斷後面。

    沒有殘骸也要明講——空輸出會讓人以為是 nova 壞了，
    而事實是「它什麼都沒寫」。那兩件事的下一步不一樣。
    """
    if not 殘:
        return f"{原本}\n\n[殘骸] {輸出檔} 沒有留下任何東西——它連一個字都還沒寫。".lstrip()
    片段 = 殘[:殘骸上限]
    尾 = "" if len(殘) <= 殘骸上限 else f"\n……（殘骸共 {len(殘)} 字，已截斷）"
    return f"{原本}\n\n[殘骸] 這是它被中斷之前寫進 {輸出檔} 的東西：\n{片段}{尾}".lstrip()
