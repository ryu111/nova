"""契約 → 一頁 HTML。**這個檔不碰世界**：字串進、字串出。

版面是設計稿定的，住在旁邊的 `模板.html`；這裡只做四件事：

* **代換**：一律 `substitute()`，不用 `safe_substitute()`——少一個變數要當場炸。
  安靜地留下 `${…}` 的話，畫面上會出現一個「看起來像模板」的格子而沒人會查。
* **跳脫**：所有字串值過 `html.escape`。票標題與護欄原因是自由文字。
* **三值**：契約裡沒有的格子由模板自己喊「未接線」（這裡碰不到它）；
  契約有、這次查不到的（`None`）由這裡渲染成「查不到」。
  **兩者共用樣式、用 `title` 分開**——長得一樣的話，
  人會把沒接線的格子當成「今天剛好是 0」。
* **模板裡不准有資料之外的陳述**：圖上一段佔多寬、結論句講哪一種失敗，
  都是**陳述句**，只是一個長成圖形、一個長成文字。寫死在模板上的話，
  畫面會拿設計稿當天的比例與當天排第一那個碼，陳述今天的事——
  而每個數字都是對的，所以沒有一個「未接線」或「少一格」的檢查會響。
  所以它們在模板上是 `${…}`，值由這裡算（`_佔比`、`_第一名處置`）。

模板引擎是標準庫的 `string.Template`，不加相依。要的只有代換加三種重複列。
"""

