def _算出來的每一格(一份: 儀表板) -> dict[str, str]:
    """圖上一段佔多寬、排第一那個失敗碼的處置句——**模板上不准寫死，值在這裡算**。"""
    收 = 一份.收件匣
    可見度 = 一份.可見度
    票的去處滿格 = _票的去處滿格(收)
    return {
        "收件匣_等著佔比": _佔比(收.等著, 票的去處滿格),
        "收件匣_處理中佔比": _佔比(收.處理中, 票的去處滿格),
        "收件匣_已完成佔比": _佔比(收.已完成, 票的去處滿格),
        "可見度_本專案佔比": _佔比(可見度.本專案token, 可見度.全部token),
        "可見度_其餘佔比": _佔比(可見度.全部token - 可見度.本專案token, 可見度.全部token),
        "失敗碼_第一名處置": _第一名處置(一份.失敗碼們),
    }


def _佔比(這一段: int, 滿格: int, *, 小數位: int = 1) -> str:
    """一段圖形佔多寬。**滿格是 0 的時候給 0%**——分不出比例就不畫，不假裝有一段。"""
    return f"{這一段 / 滿格 * 100:.{小數位}f}%" if 滿格 else "0%"


def _票的去處滿格(收: 收件匣) -> int:
    """收件匣那條圖形的滿格量：**等著＋處理中＋已完成**。

    「讀不動」不進分母：那一格數的是「這幾張連讀都讀不動」，不是票的一個去處，
    算進去的話三段加起來會少一截，而那一截什麼都不代表。
    """
    return 收.等著 + 收.處理中 + 收.已完成


