"""契約 → 一頁 HTML。**這個檔不碰世界**：字串進、字串出。

版面是設計稿定的，住在旁邊的 `模板.html`；這裡只做三件事：

* **代換**：一律 `substitute()`，不用 `safe_substitute()`——少一個變數要當場炸。
  安靜地留下 `${…}` 的話，畫面上會出現一個「看起來像模板」的格子而沒人會查。
* **跳脫**：所有字串值過 `html.escape`。票標題與護欄原因是自由文字。
* **三值**：契約裡沒有的格子由模板自己喊「未接線」（這裡碰不到它）；
  契約有、這次查不到的（`None`）由這裡渲染成「查不到」。
  **兩者共用樣式、用 `title` 分開**——長得一樣的話，
  人會把沒接線的格子當成「今天剛好是 0」。

模板引擎是標準庫的 `string.Template`，不加相依。要的只有代換加三種重複列。
"""

import html
import re
from importlib.resources import files
from string import Template

from nova.契約.儀表板 import 一家用量, 一條線, 一階, 儀表板, 失敗碼

#: 沒接線／查不到共用的樣式，`title` 是唯一的分辨點。
_查不到 = '<span class="未接線" title="契約有這格、這次查不到">查不到</span>'

#: 重複列放在同一個 `模板.html` 的 `<template id="…">` 裡，代換前整段拆掉。
#: 留在主模板裡的話，它們的 `${…}` 會讓 `substitute()` 炸。
_片段 = re.compile(r'<template id="(?P<名>[^"]+)">(?P<內文>.*?)</template>\n?', re.DOTALL)

#: 這條線此刻真的有一個程序在跑。**只給 `在跑嗎 is True` 的那幾列**——
#: 收工的線也閃著綠點的話，人會一直等一個三個小時前就結束的東西。
_活著 = '<span class="活">{名字}</span>'

#: 每一段重複列該有哪幾格，**窮舉**。
#: 這張表在渲染任何一列之前就對過一次——沒有線在跑的那一天一列都不渲染，
#: 靠「渲染的時候才發現」的話，整段重複列從模板上不見了也踩不到。
_重複列該有的格: dict[str, frozenset[str]] = {
    "線列": frozenset(
        {
            "名字",
            "路徑",
            "票標題",
            "目前階段",
            "在跑嗎",
            "跑了幾秒",
            "啟動時間",
            "退出碼",
            "未提交檔案數",
            "護欄原因",
            "七階們",
        }
    ),
    "階格": frozenset({"階段", "終局", "判準綠"}),
    "各家列": frozenset({"供應商", "次數", "token", "佔比", "佔比條寬", "平均每次"}),
    "失敗碼列": frozenset({"代碼", "次數", "佔比條寬"}),
}


class _繁中模板(Template):
    """`string.Template` 預設的變數名只吃 ASCII，繁中變數名要自己放寬。"""

    idpattern = r"[^\W\d]\w*"


def 渲染(一份: 儀表板, 模板原文: str | None = None) -> str:
    """一份儀表板 → 一頁純靜態 HTML。不連外、沒有 JS。

    `模板原文` 不給就是出貨的那一份。給的話是「模板少一格」那條線的唯一縫。
    """
    主原文, 片們 = _拆模板(模板原文)
    格們 = _每一格(一份) | _三種列(片們, 一份)
    _對過每一格("模板", 主原文, set(格們))
    return _繁中模板(主原文).substitute(格們)


def _對過每一格(話頭: str, 原文: str, 該有: set[str]) -> None:
    """這一段模板引用的格子要跟契約**兩邊都對得上**，對不上就當場炸。

    `substitute()` 只擋「模板要、映射沒給」，反過來它靜默放行——模板上少掉一格，
    畫面就安靜地少一個數字，沒有例外也沒有警告。所以**兩個方向都要擋**。

    **用 `get_identifiers()` 不自己寫 regex**：`string.Template` 認 `${名}` 也認 `$名`，
    只數大括號那一種的話 `$錯字` 會漏掉；而跳脫過的 `$$` 是字面的錢號不是變數，
    自己數會把設計稿標頭那個 `US$` 當成一格而炸掉合法的模板。

    `話頭` 直接接上「少了／多了」，帶名字的呼叫端要自己留好空白。
    """
    用到的 = set(_繁中模板(原文).get_identifiers())
    _差幾格就炸(f"{話頭}少了", 該有 - 用到的)
    _差幾格就炸(f"{話頭}多了", 用到的 - 該有)


def _差幾格就炸(話頭: str, 差的: set[str]) -> None:
    """模板與契約對不上就當場炸，訊息帶上差的是哪幾格。一格不差就什麼都不做。"""
    if 差的:
        話 = f"{話頭}這幾格：{'、'.join(sorted(差的))}"
        raise KeyError(話)


def _每一格(一份: 儀表板) -> dict[str, str]:
    """單獨一個值的那些格子。**一格一個變數名**，模板上少一個就當場炸。"""
    return {
        "產生時間": _字(一份.產生時間),
        "工作目錄": _字(一份.工作目錄),
        "目前commit": _字(一份.目前commit),
        "總token": _數(一份.總token),
        "總成本美金": _成本(一份.總成本美金),
        "算不出成本的執行數": _數(一份.算不出成本的執行數),
        "呼叫次數": _數(一份.呼叫次數),
        "繞過次數": _數(一份.繞過次數),
        "在跑的線": _數(一份.在跑的線),
        "退出碼_成功": _數(一份.退出碼.成功),
        "退出碼_確定失敗": _數(一份.退出碼.確定失敗),
        "退出碼_未知": _數(一份.退出碼.未知),
        "退出碼_護欄": _數(一份.退出碼.護欄),
        "退出碼_其他": _數(一份.退出碼.其他),
        "收件匣_等著": _數(一份.收件匣.等著),
        "收件匣_處理中": _數(一份.收件匣.處理中),
        "收件匣_已完成": _數(一份.收件匣.已完成),
        "收件匣_讀不動": _數(一份.收件匣.讀不動),
        "工作樹數": _數(一份.工作樹數),
        "可見度_本專案token": _數(一份.可見度.本專案token),
        "可見度_全部token": _數(一份.可見度.全部token),
        "可見度_專案鍵總數": _數(一份.可見度.專案鍵總數),
        "可見度_有內容的專案鍵": _數(一份.可見度.有內容的專案鍵),
        "可見度_跳過的檔": _數(一份.可見度.跳過的檔),
        "負控_登記檔數": _數(一份.負控.登記檔數),
        "負控_紀錄檔數": _數(一份.負控.紀錄檔數),
        "負控_閘規則數": _數(一份.負控.閘規則數),
        "負控_階段數": _數(一份.負控.階段數),
    }


def _三種列(片們: dict[str, _繁中模板], 一份: 儀表板) -> dict[str, str]:
    """會重複的三種列。列數是零的時候就是空字串——空表比假的一列誠實。"""
    # 失敗碼那張表的滿格量。一個碼都沒有的時候是 0，那一天連一列都不渲染。
    最常見的次數 = max((一個.次數 for 一個 in 一份.失敗碼們), default=0)
    return {
        "線列們": "".join(_一列線(片們, 條) for 條 in 一份.線們),
        "各家列們": "".join(_一列家(片們, 家) for 家 in 一份.各家),
        "失敗碼列們": "".join(_一列失敗碼(片們, 碼, 最常見的次數) for 碼 in 一份.失敗碼們),
    }


def _拆模板(模板原文: str | None) -> tuple[str, dict[str, _繁中模板]]:
    """讀模板，把重複列拆成各自的 `Template`，主模板不留 `<template>`。"""
    原文 = 模板原文 if 模板原文 is not None else _出貨的模板()
    內文們 = {一段["名"]: 一段["內文"] for 一段 in _片段.finditer(原文)}
    _重複列少了格子就炸(內文們)
    return _片段.sub("", 原文), {名: _繁中模板(內文) for 名, 內文 in 內文們.items()}


def _重複列少了格子就炸(內文們: dict[str, str]) -> None:
    """該有幾段重複列、每段該有哪幾格，是**模板自己的事，不是那一次資料的事**。

    所以在渲染任何一列之前就對一次：資料剛好是空的那一天，
    整張表從模板上不見了、或多打一個 `${錯字}` 照樣要炸——
    那一次 `substitute()` 一次都不會被呼叫，靠它擋是擋不到的。
    """
    for 名, 該有 in _重複列該有的格.items():
        if 名 not in 內文們:
            話 = f"模板少了整段重複列：{名}"
            raise KeyError(話)
        _對過每一格(f"重複列 {名} ", 內文們[名], set(該有))


def _出貨的模板() -> str:
    """套件資源裡的那一份。"""
    return files("nova.載體.儀表板").joinpath("模板.html").read_text(encoding="utf-8")


def _一列線(片們: dict[str, _繁中模板], 條: 一條線) -> str:
    """線表的一列，附上那條線的七階時間軸。"""
    return 片們["線列"].substitute(
        名字=_名字(條),
        路徑=_字(條.路徑),
        票標題=_字(條.票標題),
        目前階段=_字(條.目前階段),
        在跑嗎=_在跑嗎(條.在跑嗎),
        跑了幾秒=_秒(條.跑了幾秒),
        啟動時間=_字(條.啟動時間),
        退出碼=_數(條.退出碼),
        未提交檔案數=_數(條.未提交檔案數),
        護欄原因=_字(條.護欄原因),
        七階們="".join(_一格階(片們, 階) for 階 in 條.七階) or "還沒有階段紀錄",
    )


def _一格階(片們: dict[str, _繁中模板], 階: 一階) -> str:
    """七階時間軸上的一格。"""
    return 片們["階格"].substitute(
        階段=_字(階.階段),
        終局=_字(階.終局),
        判準綠=_判準綠(階.判準綠),
    )


def _一列家(片們: dict[str, _繁中模板], 家: 一家用量) -> str:
    """各家用量的一列。**佔比的字面與條寬是同一個數**：條長跟數字對不上就是在騙人。"""
    百分比 = f"{家.佔比 * 100:.1f}%"
    return 片們["各家列"].substitute(
        供應商=_字(家.供應商),
        次數=_數(家.次數),
        token=_數(家.token),
        佔比=百分比,
        佔比條寬=百分比,
        平均每次=_數(家.平均每次),
    )


def _一列失敗碼(片們: dict[str, _繁中模板], 碼: 失敗碼, 最多: int) -> str:
    """失敗碼那張表的一列。**條長是拿最常見那個碼當滿格量出來的**，不是畫著好看的。"""
    return 片們["失敗碼列"].substitute(
        代碼=_字(碼.代碼),
        次數=_數(碼.次數),
        佔比條寬=f"{碼.次數 / 最多 * 100:.0f}%" if 最多 else "0%",
    )


def _名字(條: 一條線) -> str:
    """線的名字。**真的在跑的那幾條才套 `.活`**（設計稿那顆會呼吸的綠點）。

    收工的線、問不到的線都不給——一頁綠點閃著、其實三個小時前就結束了的話，
    人會繼續等它。
    """
    名 = _字(條.名字)
    return _活著.format(名字=名) if 條.在跑嗎 is True else 名


def _字(值: str | None) -> str:
    """字串值：`None` 是「查不到」，有值就跳脫。**一律跳脫**，沒有例外。"""
    return _查不到 if 值 is None else html.escape(值)


def _數(值: int | None) -> str:
    """計數：`None` 是「查不到」，不是 0。"""
    return _查不到 if 值 is None else str(值)


def _成本(值: float | None) -> str:
    """成本：查不到就說查不到，**不准渲染成 0**。"""
    return _查不到 if 值 is None else f"{值:.2f}"


def _秒(值: int | None) -> str:
    """已跑多久。解不動 `etime` 的時候是「查不到」。"""
    return _查不到 if 值 is None else f"{值} 秒"


def _在跑嗎(值: bool | None) -> str:
    """在跑／收工了／查不到，三值各自有話說。"""
    return _查不到 if 值 is None else ("在跑" if 值 else "收工了")


def _判準綠(值: bool | None) -> str:
    """判準綠不綠。**沒有紀錄是「查不到」不是「紅」**——沒問到不等於失敗。"""
    return _查不到 if 值 is None else ("綠" if 值 else "紅")
