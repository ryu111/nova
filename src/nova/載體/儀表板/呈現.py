class _繁中模板(Template):
    """`string.Template` 預設的變數名只吃 ASCII，繁中變數名要自己放寬。"""

    idpattern = r"[^\W\d]\w*"


def 渲染(一份: 儀表板, 模板原文: str | None = None) -> str:
    """一份儀表板 → 一頁純靜態 HTML。不連外、沒有 JS。

    `模板原文` 不給就是出貨的那一份。給的話是「模板少一格」那條線的唯一縫。
    """
    主原文, 片們 = _拆模板(模板原文)
    格們 = _每一格(一份) | _三種列(片們, 一份)
    _對過每一格("模板", 主原文, set(格們))
    return _繁中模板(主原文).substitute(格們)


def _對過每一格(話頭: str, 原文: str, 該有: set[str]) -> None:
    """這一段模板引用的格子要跟契約**兩邊都對得上**，對不上就當場炸。

    `substitute()` 只擋「模板要、映射沒給」，反過來它靜默放行——模板上少掉一格，
    畫面就安靜地少一個數字，沒有例外也沒有警告。所以**兩個方向都要擋**。

    **用 `get_identifiers()` 不自己寫 regex**：`string.Template` 認 `${名}` 也認 `$名`，
    只數大括號那一種的話 `$錯字` 會漏掉；而跳脫過的 `$$` 是字面的錢號不是變數，
    自己數會把設計稿標頭那個 `US$` 當成一格而炸掉合法的模板。

    `話頭` 直接接上「少了／多了」，帶名字的呼叫端要自己留好空白。
    """
    用到的 = set(_繁中模板(原文).get_identifiers())
    _差幾格就炸(f"{話頭}少了", 該有 - 用到的)
    _差幾格就炸(f"{話頭}多了", 用到的 - 該有)


def _差幾格就炸(話頭: str, 差的: set[str]) -> None:
    """模板與契約對不上就當場炸，訊息帶上差的是哪幾格。一格不差就什麼都不做。"""
    if 差的:
        話 = f"{話頭}這幾格：{'、'.join(sorted(差的))}"
        raise KeyError(話)


def _每一格(一份: 儀表板) -> dict[str, str]:
    """主模板上的所有格子。**一格一個變數名**，模板上少一個就當場炸。

    分兩堆：契約上原樣搬過來的一格一個數字，與這裡算出來的圖形比例、結論句。
    """
    return _契約的每一格(一份) | _算出來的每一格(一份)


